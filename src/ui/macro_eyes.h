// ── ГЛАЗА КАРТЫ — ПРЕДСТАВЛЕНИЕ, И ТОЛЬКО ОНО (M-244a) ────────────────────
// Глайд спрайта между клетками. Истина мира — клетка (MacroCell) плюс целая
// доля (CellSub, кванты 1/256 клетки, M-244); этот буфер — «интерполяция
// картинки между тиками» (единственный законный float по ЗАКОНУ КАЛИБРОВКИ,
// и это место говорит о себе вслух). Симуляция его не читает НИКОГДА; в сейв
// он не идёт — прежний носитель MacroVisual ЕХАЛ в сейв, то есть float жил в
// состоянии мира, и M-244a его убил. M-425 добил последний его осколок —
// колонку темпа. 6 × f32 × 16384 = 384 КиБ, КЭШ (десятки мегабайт бесплатны,
// DOD п.2; а главное — ни один из этих байт не состояние мира).
//
// Файл нарочно без ImGui: закон глайда — чистая математика над колонками
// store, и его свидетель (macro_npc_ai_parity_test) собирается хедлесс.
#pragma once

#include "bus/store.h"
#include <array>

namespace sm::ui {

struct MacroEyeCache {
    // false → ближайший тик сажает каждый глаз ровно на цель (мир родился
    // или загружен — глайдить от прежнего мира нечестно и незачем).
    bool primed = false;
    std::array<float, kUnifiedCap> x;
    std::array<float, kUnifiedCap> y;
    // ТЕМП ГЛАЙДА МЕРЯЕТ САМ ГЛАЗ (M-425). Прежде его держала колонка МИРА
    // `MacroNpcRuntime::visualSpeed` — float в состоянии мира, ехавший в сейв
    // побайтово, с комментарием «cells/real s», то есть нарушавший ЗАКОН
    // КАЛИБРОВКИ и ЗАКОН ТИПА п.5 разом. Перепись читателей дала приговор:
    // читателей МИРА — НОЛЬ, читателей представления — два (этот глайд и
    // отладочная печать). Значит величина не мира, и дом ей здесь.
    //
    // И меряется она ЧЕСТНЕЕ прежнего: колонка делила путь на ПРЕДПОЛАГАЕМЫЙ
    // период думки, а глаз делит на реально прошедшее между двумя сменами
    // цели — поэтому темп верен и когда сквад думал не по расписанию.
    std::array<float, kUnifiedCap> speed;
    std::array<float, kUnifiedCap> lastTx;
    std::array<float, kUnifiedCap> lastTy;
    std::array<float, kUnifiedCap> sinceMove;
};

// Провести глаза к целям (клетка + доля) с темпом, который кэш меряет сам —
// тот же закон, что жил в tick_macro_npc_visuals@macro/npc_ai.cpp до M-244a:
// телепорт-бэкстоп 6 клеток, мёртвый/невалидный глаз садится на цель.
void tick_macro_eyes(const MacroStore& st, MacroEyeCache& eyes,
                     int mapW, int mapH, float dt);

} // namespace sm::ui
