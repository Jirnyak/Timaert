// S26): сквад несёт его колонкой (ecs/components.h), а СТРОКА РЕЕСТРА МЕСТА
// им объявляет, кого она поднимает (macro/place_registry.h). Жил он в
// npc_ai.h, и оттуда реестр его взять не мог — npc_ai.h зависит от реестра
// через state.h. Копия enum'а была бы ровно тем «вторым словарём», который
// этот проект выпалывает; поэтому один заголовок на обоих.
#pragma once
#include <cstddef>
#include <cstdint>
#include <iterator>   // std::size — счёт порядка выдачи выводится, не пишется

namespace sm {

// ── ТИП СКВАДА: КТО ЭТОТ СКВАД — {тип, объект} ────────────────────────────
// Вердикт владельца 2026-09-21, дословно: «сквад должен знать, кто он — типа
// ТИПЫ сквадов: артели, корованы, города, сборщики, патрули, лорды; это надо
// сделать системным, потому что тип задаёт поведение аи агента».
//
// ЭТО НЕ НОВАЯ СИСТЕМА, А ДОВЕДЁННАЯ СТАРАЯ. Здесь стоял `ErrandVerb` —
// «глагол поручения», — и он УЖЕ был колонкой типа сквада: в правильном месте
// (рантайм сквада), с правильным писателем (аукцион ротации) и с правильным
// параметром (`errandObject`). Не хватало ровно закона: тип не спрашивали
// первым, поэтому на вопрос «что этот сквад делает» отвечали ЧЕТЫРЕ словаря —
// колонка `ai` каталога тел, строка стола анкет, наличие путевых точек, и
// сам глагол, спрятанный ВЕТКОЙ ВНУТРИ `ai_gatherer` (пятая машина внутри
// первой). Теперь дверь одна: `dispatch` спрашивает тип, и только
// нетипизированный сквад падает на каталог тел.
//
// ПОЧЕМУ ТИП, А НЕ ГЛАГОЛ (CANON S2 «Протокол двух миров»): каталог тел
// (`kNpcTypeDefs`) принадлежит МИКРОМИРУ — это его тела и его поведение. Что
// делает СКВАД на карте — вопрос макромира, и отвечать на него обязана
// макро-колонка. «Глагол» звучал как «занятие на сегодня» и потому не мешал
// макромиру подглядывать в мобную строку; «тип» этого не позволяет.
//
// ТИП СЕГОДНЯ ВОЛАТИЛЕН, И ЭТО НЕ ДЕФЕКТ ФОРМЫ. Артель каждый день проходит
// пере-аукцион и может сменить занятие: вчера копала, сегодня везёт. Строгое
// разделение («деревни добывают, города торгуют» — владелец 2026-09-21) это
// ЗАМОРОЗИТ: деревенская строка сможет получить только `Artel`, городская —
// только `Caravan`, и решать будет СТРОКА РЕЕСТРА, а не суточная рулетка.
// Тогда тип станет стойким и будет ставиться при рождении.
// ── ОДНА ОСЬ НА ВСЕ СКВАДЫ, И МЕСТА НА НЕЙ ЖЕ (M-90 ломтик E шаг 3а) ──────
// Вердикт владельца 2026-09-30: «теперь за всё отвечает squad type / сквад
// это только что он делает»; 2026-10-01: «мы верзаем вообще всё про
// ландмарки, у нас теперь сквады только». Поэтому ось `PlaceType` здесь
// и УМЕРЛА — не переехала рядом, а СЛИЛАСЬ (имя дожило алиасом до ломтика F
// и умерло с вектором): место есть неподвижный сквад, и спрашивать «какого
// он рода» второй осью больше нечем.
//
// ПОРЯДОК ЗНАЧЕНИЙ — МЕСТА ПЕРВЫМИ, И НОМЕРА ИХ СДВИГАЮТСЯ СВОБОДНО. Здесь
// стояло «их номера не сдвинулись» как довод формы — он УМЕР 2026-10-24
// вместе с заселением столицы: ЗАКОН ЛЕСТНИЦЫ п.3 говорит прямо, что
// «дописать в хвост, чтобы сохранённый ординал не переехал» есть мёртвый
// довод, а сейв ограничением не является вовсе (§10). Три таблицы,
// ключуемые этой осью (`kPlaces@src/macro/place_registry.h`,
// `kPlaceSheets@src/macro/characters.h`, `kSquadDraw@src/ui/squad_draw.h`),
// держатся не неподвижностью номеров, а `rows_in_enum_order` — страж
// ловит разъезд ключа со строкой в тот же компиляторный заход, и именно он
// поймал все четыре таблицы, когда `Capital` встала первой.
// Платим нулевыми строками на таблицу — пустотой, а не кривизной
// (ФРЕЙМ п.4): `place_def` остаётся ПОЛНОЙ функцией над своим ключом, без
// гейта «а это вообще место?». Гейт был бы вторым вопросом о типе, то есть
// вторым словарём в ветке.
//
// У `kSquadDraw` нулевых строк БОЛЬШЕ НЕТ (слияние проходов карты
// 2026-10-19): её подвижные роды несут свои размеры и порог зума, потому что
// карта рисует их ОДНИМ проходом с местами. Пустота там держала не экономию,
// а второй проход рисовки — и ушла вместе с ним.
//
// НОЛЬ ТЕПЕРЬ ОДИН И ЗОВЁТСЯ `None`. Здесь стоял `ByKind` («спроси каталог
// тел»), а в реестре мест — `SquadType::None`; после слияния это ОДНО
// значение, и двух имён у него быть не может. Оставлено `None`, потому что
// `ByKind` называл не значение, а ОТКАЗ системы отвечать — ту самую «точку
// течи границы миров» (CANON S2), которая по вердикту владельца уходит
// вместе с генезисными одиночками.
enum class SquadType : std::uint8_t {
    // ТИП НЕ НАЗНАЧЕН. Для места это «тут никто не живёт»; для подвижного
    // сквада — «спроси каталог тел», и ровно эта ветка есть ЕДИНСТВЕННАЯ
    // ОСТАВШАЯСЯ ТОЧКА ТЕЧИ ГРАНИЦЫ МИРОВ (CANON S2), названная здесь
    // нарочно, чтобы не считаться законом. Сюда падают сквады без
    // макро-источника поведения: генезисные одиночки и квестовая цель. С их
    // сносом (порция Б-6) ветка умирает, и макромир перестаёт читать `ai`.
    None = 0,

    // ── НЕПОДВИЖНЫЕ: что СТОИТ и живёт на клетке ──────────────────────────
    // Их строка реестра несёт зону, глиф, цвет, свечение, крю, рацион и
    // фауну; подвижные роды ниже этих колонок не имеют и честно нулевые.
    // Вопрос рода «это МЕСТО» — у самой оси (ниже, squad_archetype == Place):
    // роды неподвижных идут сплошным отрезком 1..9, и это закреплено
    // static_assert-ом при предикате.
    //
    // СТОЛИЦА ПЕРВОЙ — ЗАКОН ГЕНЕРАЦИИ п.6 («столицы (для каждой фракции в
    // игре) вокруг них фичи городов вокруг городов фичи деревень»): порядок
    // оси есть порядок, которым мир рождается. Прежде столица была ГОРОДОМ
    // БЕЗ СЮЗЕРЕНА — то есть родом, выведенным из ОТСУТСТВИЯ ребра связи, а
    // не названным колонкой; теперь у неё своя строка (вердикт владельца
    // №7 2026-10-22). Ординалы 1..8 съехали на 2..9: ЗАКОН ЛЕСТНИЦЫ п.3 —
    // «новая строка встаёт В СВОЮ ГРУППУ», «дописать в хвост, чтобы
    // сохранённый ординал не переехал» есть мёртвый довод (§10).
    Capital = 1,
    City = 2,
    Village = 3,
    Spire = 4,
    Ruin = 5,
    Lair = 6,
    Shrine = 7,
    Mine = 8,
    Tower = 9,

    // ── ПОДВИЖНЫЕ: что сквад ДЕЛАЕТ ───────────────────────────────────────
    // Артель: добывает. Объект = строка таблицы целей kGathererDefs.
    Artel = 10,
    // Корован: рейс сбыта. Объект = ординал рынка.
    // Имя не «Sell», потому что это не занятие на день, а КТО ОН: у города
    // корован — единственная торговая сущность мира (род NPCType::Caravan
    // умер в v106, караван оказался сквадом, притворившимся видом).
    Caravan = 11,
    // Сборщик: идёт ВНИЗ к вассалу-должнику. Объект = ординал вассала.
    // Свой номер, а не переиспользованный патрульный, — как и было решено
    // при сносе патруля (2026-09-21).
    Collector = 12,

    // ── ПЕРСОНАЛИИ: архетип Hero, и дракон его ЗАСЕЛЯЕТ ───────────────────
    // Вердикт владельца №7 (2026-10-22): «ось рода: +Capital, +Dragon;
    // архетип Hero заселяется драконом». До него `Hero` стоял ПУСТЫМ
    // архетипом — строкой перечисления, на которую не указывал ни один род,
    // то есть ярусом без группировки (ЗАКОН ЛЕСТНИЦЫ п.5). Дракон его
    // закрывает: он не место (не стоит), не работник (не возит), и не
    // безликий кочевник — у него полная анкета, как у лорда.
    //
    // ПОЧЕМУ ИМЕННО ДРАКОН ПЕРВЫЙ — ОН ПРИБОР, А НЕ КОНТЕНТ: критерий
    // приёмки эпика назван владельцем там же — «будет ли он есть крестьян
    // эмерджентно». Род, чьё поведение не задано ни одной веткой движка,
    // есть проверка того, что модульная думка вообще работает.
    //
    // СТРОКА СУЩЕСТВА У НЕГО СВОЯ И ДРУГАЯ (ЗАКОН ДВУХ ТАБЛИЦ): здесь — чем
    // сквад ЗАНЯТ в макромире, а `NPCType::Dragon@src/tables/npc.h` — чем он
    // ДЕРЁТСЯ и ВОПЛОЩАЕТСЯ. Два разных вопроса, два разных словаря.
    Dragon = 13,

    Count,
};

// ── АРХЕТИП РОДА — РОЛЬ В МИРЕ, ВЫВЕДЕННАЯ ИЗ ТИПА ──────────────────────
// (вердикт владельца 2026-10-09; идея принесена текстом Gemini — «Четыре
// системных архетипа роли в мире … Связка squadType → SquadArchetype
// задаётся чистой табличной функцией. Рассинхрон исключён компилятором»;
// решение формы делегировано агенту, синтез записан в CANON «АРХЕТИП РОДА».)
// В памяти анкеты архетип НЕ хранится — ноль новых байт: полная constexpr-
// функция оси рода, таблицы-спутника нет (DOD п.9).
//
// ЗАКОН УПОТРЕБЛЕНИЯ: архетип законен КЛЮЧОМ таблиц и семян (округа
// навигации, генерация, выбор ИИ-модуля) и ЗАПРЕЩЁН ГЕЙТОМ в проходе
// симуляции — ранний выход «Place не ест / не думает» есть тот же дефект,
// что гейты рода M-233 п.5, и переименование предиката его не легализует.
// Place — якорь округ навигации ПО ОПРЕДЕЛЕНИЮ; флага anchorsNav нет.
//
// Шрам предшественника (M-90 шаг 5) живёт и здесь: ответ «кто ты» даёт ось
// рода, НИКОГДА строка существа — тело места носит нулевую строку (Peasant),
// и аукцион, судивший «кто артель» по строке существа, растворял тела
// городов (squadType 1 → 11 за один rotate).
enum class SquadArchetype : std::uint8_t {
    Place,   // неподвижный центр мира: стоит на клетке, сеет округу путей
    Worker,  // экономический челнок: артель, корован, сборщик
    Roamer,  // кочевник по полям — ПУСТ до эпика ИИ (бандиты, патрули, стаи)
    Hero,    // персоналия с полной анкетой — ПУСТА до эпика ИИ (лорды, игрок)

    Count,   // не значение; счёт для таблиц, ключуемых архетипом
             // (`kArchetypeDraw@src/ui/squad_draw.h` — групповые законы
             // представления). Выведенный счёт вместо ручного — ЗАКОН
             // СЛОВАРЯ п.3; `squad_archetype` его не возвращает никогда.
};

inline constexpr SquadArchetype squad_archetype(SquadType t) {
    switch (t) {
        case SquadType::Capital:
        case SquadType::City:
        case SquadType::Village:
        case SquadType::Spire:
        case SquadType::Ruin:
        case SquadType::Lair:
        case SquadType::Shrine:
        case SquadType::Mine:
        case SquadType::Tower:     return SquadArchetype::Place;
        case SquadType::Artel:
        case SquadType::Caravan:
        case SquadType::Collector: return SquadArchetype::Worker;
        case SquadType::Dragon:    return SquadArchetype::Hero;
        // None — точка течи границы миров (см. шапку оси): бестиповый ходок.
        // До сноса течи (порция Б-6) он кочевник без лица — ближайшая
        // правда; Roamer-модулей это НЕ заводит, их ещё нет.
        case SquadType::None:      return SquadArchetype::Roamer;
        case SquadType::Count:     break;  // не значение; метка ради -Wswitch
    }
    return SquadArchetype::Roamer;
}
// Отрезки — предпосылка деривации, и она под компилятором, а не под памятью
// ревьюера: вставка рода в середину оси красит сборку ЗДЕСЬ. Так и вышло при
// заселении столицы — оба ассерта покраснели раньше, чем успел соврать хоть
// один читатель оси.
static_assert(SquadType::Capital == SquadType(1)
                  && SquadType::Tower == SquadType(9)
                  && SquadType::Artel == SquadType(10)
                  && SquadType::Collector == SquadType(12)
                  && SquadType::Dragon == SquadType(13),
              "неподвижные роды — сплошной отрезок 1..9, работники 10..12, "
              "персоналии с 13: squad_archetype читает ось, а не список имён");
static_assert(squad_archetype(SquadType::Capital) == SquadArchetype::Place
                  && squad_archetype(SquadType::Tower) == SquadArchetype::Place
                  && squad_archetype(SquadType::Artel) == SquadArchetype::Worker
                  && squad_archetype(SquadType::Dragon) == SquadArchetype::Hero
                  && squad_archetype(SquadType::None) != SquadArchetype::Place,
              "Place — ровно неподвижный отрезок; Hero заселён драконом; "
              "None местом не бывает");

// (`kPlaceKindCount` УМЕР 2026-10-18 — СИРОТА С НУЛЁМ ЧИТАТЕЛЕЙ ВО ВСЁМ
//  ДЕРЕВЕ, включая тесты. Выведенный счёт — форма правильная, но DOD п.9
//  требует у строки НАЗВАННОГО читателя, а его не было ни одного: счёт
//  неподвижных родов никто не спрашивал. Понадобится — выведется той же
//  одной строкой из той же оси.)

// Приоритет владения спорной клеткой (CANON S9): порядок выдачи родов И ЕСТЬ
// один закон «чьей считается клетка, на которой стоят двое» — тот же, что был
// у старого обхода трёх векторов (города, потом деревни, потом шпили). Живёт
// У ОСИ, потому что это закон РОДА, а не обходчика: его читают и обход мест,
// и ответ каркаса «кто здесь живёт» (settlement_at@src/macro/squad_index.h),
// и переписывать его дважды — два спеллинга одного закона. Сегодня порядок
// совпадает с номерами оси 1..9 — это СОВПАДЕНИЕ значений, а не тождество
// законов: ось упорядочена «места первыми ради таблиц», приоритет —
// «города раньше шпилей», и разъехаться им закон разрешает.
inline constexpr SquadType kPlaceYieldOrder[] = {
    // Столица старше города по ТОМУ ЖЕ закону, по которому город старше
    // деревни: спорная клетка достаётся старшему поселению.
    SquadType::Capital,
    SquadType::City, SquadType::Village, SquadType::Spire,
    SquadType::Ruin, SquadType::Lair, SquadType::Shrine,
    SquadType::Mine, SquadType::Tower,
};
// Порядок выдачи обязан быть ПОЛНЫМ по неподвижному отрезку, иначе место
// нового рода стало бы невидимым для `for_each_place_view` и каркасного
// ответа «кто здесь живёт» — молча, без единой красной строки. Счёт
// выводится из оси, а не пишется рукой (ЗАКОН СЛОВАРЯ п.3).
static_assert(std::size(kPlaceYieldOrder)
                  == std::size_t(SquadType::Artel) - 1u,
              "порядок выдачи покрывает ВЕСЬ неподвижный отрезок 1..9: "
              "новый род места = его строка здесь, иначе он невидим");


} // namespace sm
