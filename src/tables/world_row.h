// 2026-09-22; наряд M-73, шаг 1 эпика единой таблицы объектов).
//
// Всякая строка мира — предмет или существо — несёт ОДИН сквозной номер:
//
//   предметы   [0, world_item_rows())
//   существа   [world_item_rows(), world_row_count())
//
// Имена в коде НЕ переезжают: `NPCType::Peasant` остаётся собой, предметный
// ординал остаётся индексом каталога. Сдвиг базы живёт ЗДЕСЬ, в двери, и
// только здесь — контейнер хранит строку мира, а спрашивает её всегда через
// эти функции.
//
// ЛОВУШКА, НАЗВАННАЯ КАНОНОМ ЗАРАНЕЕ: граница диапазона ВЫВОДИТСЯ из размера
// каталога (`world_row_is_item@src/tables/items.cpp`), вписанная константа
// была бы возвратом второго словаря. Поэтому здесь нет ни одного литерала.
//
// Авторских таблиц внутри по-прежнему две (kCatalog предметов, kNpcTypeDefs
// существ) — это удобство авторинга, а не второй словарь: на вопрос «что за
// строка мира N» отвечает ровно эта дверь, одна на проект (вердикт владельца
// 2026-09-24: «технически это единая таблица объектов»).
//
// ── ПОЧЕМУ АДРЕС ЖИВЁТ В `tables/`, А ОПЕРАЦИИ — В `macro/` (M-292,
// 2026-10-20) ────────────────────────────────────────────────────────────
// Эти двери переехали сюда из `macro/world_row.h`, и шов переезда — не
// вкус, а §11: ОБЕ половины пространства суть ТАБЛИЦЫ (`tables/items.h`,
// `tables/npc.h`), то есть вопрос «какого рода строка N и как она
// называется» отвечается общим слоем и ничего из состояния мира не знает.
// Там, в `macro/world_row.h`, остались ровно операции над КОНТЕЙНЕРОМ
// (`Inventory` — род 2 фрейма, состояние): им мир нужен по существу.
//
// Купил переезд ОДИН адрес: `value_of@src/tables/items.cpp` — дверь вопроса
// «сколько стоит объект» — обязана отвечать за обе половины (вердикт
// владельца 2026-10-20: «это тупа стоимость у сущчества как у предмета»), а
// значит ей нужен сдвиг базы. Выходов без переезда было два, и оба
// запрещённые: включить `macro/` из `tables/` (§11) или написать сдвиг
// базы второй раз — что запрещает шапка выше.
#pragma once
#include <cstdint>

#include "tables/items.h"   // world_row_is_item, ItemDef — половина предметов
#include "tables/npc.h"     // NPCType, NpcTypeDef — половина существ

namespace sm {

// Граница диапазонов — размер предметного каталога, посчитанный, не вписанный.
inline std::uint16_t world_item_rows() noexcept {
    return std::uint16_t(item_catalog().size());
}
inline std::uint16_t world_row_count() noexcept {
    return std::uint16_t(world_item_rows()
                         + std::uint16_t(NPCType::Count));
}

// world_row_is_item живёт У КАТАЛОГА (items.h/items.cpp): граница — размер
// его собственной таблицы, и контейнеру она нужна для закона размещения.
// Здесь — только вторая половина вопроса.
inline bool world_row_is_creature(std::uint16_t row) noexcept {
    return row >= world_item_rows() && row < world_row_count();
}

// Туда: род → строка мира.
inline std::uint16_t world_row_of_item(int itemOrdinal) noexcept {
    return std::uint16_t(itemOrdinal);
}
inline std::uint16_t world_row_of_creature(NPCType t) noexcept {
    return std::uint16_t(world_item_rows() + std::uint16_t(t));
}

// Обратно: строка мира → род. Fail-closed на чужом диапазоне: предмету — −1,
// существу — NPCType::Count; молча «почти правильного» ответа не бывает.
inline int item_of_world_row(std::uint16_t row) noexcept {
    return world_row_is_item(row) ? int(row) : -1;
}
inline NPCType creature_of_world_row(std::uint16_t row) noexcept {
    return world_row_is_creature(row)
        ? NPCType(row - world_item_rows())
        : NPCType::Count;
}

// ── КАК НАЗЫВАЕТСЯ СТРОКА МИРА — ОДНА ДВЕРЬ НАД ЕДИНОЙ ТАБЛИЦЕЙ ──────────
// Владелец, дословно (2026-10-20): «у нас же единая система сквадов теперь у
// них инвентарь обобщён и там и прмдеты и юниты (и таблца едина объектов)
// потому что лошади они могут быть и как юнит и как предмет и тд».
//
// Таблица объектов едина СНИЗУ — один ординал, один контейнер, — но СПРОСИТЬ
// У НЕЁ ИМЯ было нельзя: имён существовало два, и оба частные
// (`item_def_at(row)->id` для предметов, `npc_def(t).label` для существ).
// Отсюда и дефект, который видел игрок: читатель СМЕШАННОГО списка обязан был
// выбрать половину, и вкладка `Inventory` панели субъекта шла по ВСЕМ слотам
// через предметную дверь — на строке существа та возвращает `nullptr`, и в
// городе печаталось «? x6272», то есть 6272 крестьянина гарнизона, названные
// вопросительным знаком (кадр, 2026-10-20).
//
// Теперь вопрос «как называется строка N» имеет ОДИН ответ, и он здесь — там
// же, где живёт вопрос «какого она рода». Fail-closed: строка вне обоих
// диапазонов миру не принадлежит, и дверь говорит это вслух, а не
// притворяется предметом.
//
// ДВЕРЕЙ ДВЕ, ПОТОМУ ЧТО ВОПРОСОВ ДВА, И ОДНА ИЗ НИХ ОТВЕЧАЛА ЗА ОБА (правка
// M-292, 2026-10-20). `world_row_label` отдавала `def->id` у предмета и
// `npc_def(t).label` у существа — то есть у двух половин одного вопроса
// читались РАЗНЫЕ колонки: авторский ключ против человеческого имени. На
// вкладке это выглядело как «wpn_sword» рядом с «Peasant», а прилавку нужны
// обе колонки сразу (заголовок — имя, подстрока — ключ), и выбрать было не из
// чего. Теперь колонка у каждой двери одна и та же по обе стороны границы.
inline const char* world_row_label(std::uint16_t row) noexcept {
    if (world_row_is_item(row)) {
        const ItemDef* def = item_def_at(int(row));
        return def ? def->name : "?";
    }
    if (world_row_is_creature(row)) {
        return npc_def(creature_of_world_row(row)).label;
    }
    return "?";
}
inline const char* world_row_id(std::uint16_t row) noexcept {
    if (world_row_is_item(row)) {
        const ItemDef* def = item_def_at(int(row));
        return def ? def->id : "?";
    }
    if (world_row_is_creature(row)) {
        return npc_def(creature_of_world_row(row)).id;
    }
    return "?";
}

// Строка принадлежит миру вообще — предмет ИЛИ существо. Это и есть гейт
// всякого читателя СМЕШАННОГО контейнера (прилавок, сумка, сетка): прежде он
// спрашивал «есть ли предметная строка» (`item_def_at`), и половина
// контейнера для него не существовала (M-292).
inline bool world_row_exists(std::uint16_t row) noexcept {
    return row < world_row_count();
}

} // namespace sm
