// АРХЕТИП ОБЪЕКТА — ВТОРАЯ СТУПЕНЬ ЛЕСТНИЦЫ ОБЪЕКТЫ → АРХЕТИПЫ → ТИПЫ →
// СТРОКИ (наряд M-295, замысел — CANON S29).
//
// Отдельная шапка по той же причине, что у `squad_type.h`: ось называют ДВОЕ —
// предметная половина каталога (`tables/items.h`) и половина существ
// (`tables/npc.h`), — а копия перечисления в каждой была бы ровно тем вторым
// словарём, который проект выпалывает. Зависимостей у файла нет вовсе, поэтому
// включить его может кто угодно по обе стороны границы миров.
//
// ── ПОЧЕМУ ОДНА ОСЬ НА ОБЕ ПОЛОВИНЫ ───────────────────────────────────────
// Вердикт владельца 2026-10-20, дословно: «тогда не надо делить вообще на
// предметы и существ - надо сразу делать ОБЪЕКТЫ -> АРХЕТИПЫ(тут всфяике
// гуманоиды повозки оружие броня и как раз разилчие живой не живой тут) ->
// ТИПЫ»; и о форме: «это получается DOD классы и наследование но через такую
// ДОД систему именно и плоские массивы».
//
// До этой оси ОДНА ступень лестницы была названа в коде ДВАЖДЫ и разными
// словами: `ItemType` (8 родов предметной половины) и `NpcNature` (3 рода
// существной). Обе умерли здесь — не переехали рядом, а СЛИЛИСЬ (§5 п.14:
// форма владельца подразумевает снос, прикрутить своё рядом со старым
// запрещено).
//
// ── ВВЕРХ КОЛОНКА, ВНИЗ ОТРЕЗОК ───────────────────────────────────────────
// Наследование здесь есть НОЛЬ в колонке со смыслом «спроси уровень выше», и
// ни виртуальных функций, ни указателей на родителя. Вверх: строка несёт ТИП
// (`tables/object_type.h`), тип несёт АРХЕТИП. Вниз: «все строки архетипа»
// есть НЕПРЕРЫВНЫЙ ДИАПАЗОН ординалов, а не фильтр по колонке, — и
// непрерывность прибита компилятором там, где видна авторская таблица
// (`items.cpp` для вещей, `npc.h` для существ).
//
// ── ПОРЯДОК ЗНАЧЕНИЙ НЕ ВКУС, А ПРЕДПОСЫЛКА ВЫВОДА ────────────────────────
// Пространство строк мира устроено так: сперва предметный каталог, потом
// каталог существ (`tables/world_row.h`). Значит ось обязана идти ТЕМ ЖЕ
// порядком — вещи первыми, воплощаемые хвостом, — иначе «отрезок архетипа»
// перестанет быть диапазоном. Два следствия стоят под `static_assert` ниже:
//   · ВОПЛОЩАЕМЫЕ — СПЛОШНОЙ ХВОСТОВОЙ ОТРЕЗОК, поэтому вопрос «воплощается
//     ли» есть ОДНО сравнение, а не список имён;
//   · `Misc` — ПОСЛЕДНИЙ СРЕДИ ВЕЩЕЙ. Его отрезок определён ОТРИЦАНИЕМ («ни
//     одна система выше этой вещи не служит»), то есть высказывания о мире он
//     не несёт; стой он в середине, каждый новый архетип вещи раздвигал бы
//     свалку. Новый архетип вещи дописывается ПЕРЕД `Misc`.
#pragma once
#include <cstdint>

namespace sm {

// ВОПЛОЩАЕМОСТЬ — НЕ «ЖИВОЙ», И ЭТО НЕ ПРИДИРКА К СЛОВУ: нежить воплощается
// телом ровно так же, как крестьянин, и считается головой инвентаря ровно так
// же. Вопрос, на который отвечает хвостовой отрезок, — «воплощается телом в
// субмире и считается головой в контейнере», и ответ на него у `Void` ДА.
enum class ObjectArchetype : std::uint8_t {
    // ── ВЕЩИ: то, что лежит в контейнере предметом ─────────────────────────
    Weapon   = 0,   // чем бьют: строка несёт кубы, тип урона и свой навык
    Armor    = 1,   // что надевают: две колонки защиты (процент и блок)
    Potion   = 2,   // ЧТО ПОТРЕБЛЯЮТ ЗА ЭФФЕКТ — зелья, свитки, жезлы
                    // (вердикт владельца 2026-10-20: «potion обобщить до
                    // консумабле типа там будут свитки и тд всё что влияет на
                    // ресуры анкеты … буквально свитки жезлы пошны»); тип под
                    // этим архетипом так и зовётся — `consumable`
    Food     = 3,   // ЧТО ПОТРЕБЛЯЮТ ЗА СЫТОСТЬ: здесь живёт голодная строка
                    // лестницы нужд (econ_day.h hunger_commodity_ordinal)
    Material = 4,   // РЕСУРСЫ: из них крафтят, их добывают поля ресурсов
    Goods    = 5,   // ТОРГОВАЯ КОРЗИНА: то, что мир производит и чего хочет
                    // по лестнице нужд. У ВЕЩИ ОДНА РОЛЬ (вердикт владельца
                    // 2026-10-20, дословно: «так даже лучше чтобы не было
                    // предметов с двумя ролями … товары комфорта они длчя
                    // другого не используются … торговые товары сразу
                    // понятно»), поэтому уход строки из `Goods` в свой архетип
                    // ЧЕСТНО выводит её из корзины комфорта — это смысл
                    // переезда, а не его побочный эффект
    Currency = 6,   // ДЕНЬГИ: род вещи, а не флаг на товаре. Ничего
                    // «денежного» архетип не включает — платёж по-прежнему
                    // идёт плотностью стоимости, и монета выигрывает
                    // арифметикой веса, а не родом
    Vehicle  = 7,   // ПОВОЗКИ: первый потребитель объект-модулей (M-296) —
                    // предел обоза даёт модуль типа, сводящий число повозок с
                    // числом живых спин, а непряжённая остаётся грузом в свои
                    // честные килограммы каталога
    Misc     = 8,   // ЧЕСТНОЕ ПРОЧЕЕ, и ПОСЛЕДНЕЕ среди вещей (см. шапку)

    // ── ВОПЛОЩАЕМЫЕ: то, что лежит в контейнере головой ───────────────────
    // СОСТАВ — ВЕРДИКТ ВЛАДЕЛЬЦА 2026-10-20, и он назвал его сам, поправив
    // наряд: «нужно архетипы сущесвут расшириь»; затем «гуманоид это фолк да я
    // не прав / все орки в монстер»; итогом — «ФОЛК / МОНСТЕР / АНИМАЛ
    // /ЛАЙВСТОК / ВОИД такие вот архнтипв».
    //
    // ПЯТЬ, А НЕ ТРИ, И ЭТО НЕ ПЕРЕИМЕНОВАНИЕ `NpcNature`. Старая колонка
    // делила существ на народ / живность / нежить, то есть `Fauna` была
    // свалкой «все нелюди кроме нежити»: в ней лежали дракон и кролик, гоблин
    // и овца. Ось разумности разбирает эту свалку.
    Folk      = 9,   // НАСЕЛЕНИЕ МЕСТ: только эти души составляют население,
                     // размножаются и заселяют пустой город. Имя `Humanoid`
                     // ОТКЛОНЕНО владельцем в пользу `Folk` (ЗАКОН ИМЕНИ:
                     // архетип отвечает «народ ли», а не «человекообразен
                     // ли», и двери `is_folk_kind` уже звались так же)
    Monster   = 10,  // РАЗУМНАЯ НЕЧЕЛОВЕЧЕСКАЯ ТВАРЬ. Ось — РАЗУМ, НЕ РУКИ, и
                     // это дословная поправка владельца: «дракон это будет
                     // монстер типа это будут не по смылсу рук а по
                     // разумности - монстры они обладают разумом (огры троли
                     // гоблины драконы и тд)»
    Animal    = 11,  // «дефолт животные нашего мира кролики волки» (владелец)
    Livestock = 12,  // «скот и ваще любые домашние животные» (владелец). СПИНА
                     // ЭТОМУ АРХЕТИПУ НЕ ПРИНАДЛЕЖИТ — его же поправка,
                     // дословно: «но спина это не их механика спина есть у
                     // всего по таблице объектов», поэтому `haulMult` остаётся
                     // колонкой ВСЯКОЙ строки, и модуль скота её не получает
    Void      = 13,  // «для всякой хтони и демонов» (владелец). Отдельный
                     // архетип, а не тип внутри зверья — вердикт 2026-10-20:
                     // «про нежить да будет у них особый модуль но это не
                     // „модуль воедения“ не путайте аи модули сквадов и модули
                     // объктов (их особенноси и механики)»

    Count,           // не значение; выведенный счёт для таблиц, ключуемых
                     // архетипом (ЗАКОН СЛОВАРЯ п.3 — ручной `kCount = 14`
                     // рядом с осью был бы вторым словарём)
};

// ВОПЛОЩАЕТСЯ ЛИ ЭТОТ АРХЕТИП ТЕЛОМ — ОДНО СРАВНЕНИЕ, НОЛЬ ХРАНИМЫХ БАЙТ.
// Выведенный предикат над отрезком, а не колонка: колонка «воплощаем» была бы
// вторым ответом на вопрос, на который ось отвечает сама (DOD п.9).
inline constexpr bool object_embodied(ObjectArchetype a) {
    return a >= ObjectArchetype::Folk && a < ObjectArchetype::Count;
}

// ПЕРВЫЙ ВОПЛОЩАЕМЫЙ АРХЕТИП — ИМЯ ГРАНИЦЫ, а не литерал у каждого читателя.
inline constexpr ObjectArchetype kFirstEmbodiedArchetype = ObjectArchetype::Folk;

// СКОЛЬКО АРХЕТИПОВ У ВЕЩЕЙ — выведено из той же границы. Читатель назван:
// матрица весов ролла аффиксов (`kAffixDefs@src/tables/items.cpp`) обязана
// высказаться о КАЖДОМ архетипе ВЕЩИ и ни о одном воплощаемом — строка
// существа до двери выдачи аффиксов не доходит вовсе, у неё нет `ItemDef`.
inline constexpr int kThingArchetypeCount = int(kFirstEmbodiedArchetype);

// ── СТЕНА ПОД КОМПИЛЯТОРОМ: ПРЕДПОСЫЛКИ ВЫВОДА, А НЕ ПАМЯТЬ РЕВЬЮЕРА ──────
// Вставка архетипа в середину оси красит сборку ЗДЕСЬ, а не роняет мир молча.
static_assert(ObjectArchetype::Misc == ObjectArchetype(8)
                  && ObjectArchetype::Folk == ObjectArchetype(9)
                  && ObjectArchetype::Void == ObjectArchetype(13)
                  && int(ObjectArchetype::Count) == 14,
              "вещи — отрезок 0..8 со свалкой Misc ПОСЛЕДНЕЙ, воплощаемые — "
              "сплошной хвост 9..13: и предикат, и диапазоны строк читают ОСЬ, "
              "а не список имён");
static_assert(!object_embodied(ObjectArchetype::Weapon)
                  && !object_embodied(ObjectArchetype::Vehicle)
                  && !object_embodied(ObjectArchetype::Misc)
                  && object_embodied(ObjectArchetype::Folk)
                  && object_embodied(ObjectArchetype::Monster)
                  && object_embodied(ObjectArchetype::Animal)
                  && object_embodied(ObjectArchetype::Livestock)
                  && object_embodied(ObjectArchetype::Void),
              "воплощаемость — ровно хвостовой отрезок: вещь телом не встаёт, "
              "а нежить встаёт (воплощаемость это НЕ «живой»)");
static_assert(kThingArchetypeCount == 9,
              "девять архетипов вещи — столько колонок обязана назвать строка "
              "матрицы весов аффиксов");

} // namespace sm
