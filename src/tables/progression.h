// ── КРИВАЯ ПРОГРЕССИИ — ОДНА НА ВЕСЬ МИР ───────────────────────────────────
//
// Здесь живёт ЛЕСТНИЦА: порог уровня и делитель цены убитого. Файл НЕ знает ни
// анкеты, ни строк существ, ни мира — он чистая арифметика над целым, и потому
// лежит в общем слое, который видят ОБА мира (§11).
//
// ПОЧЕМУ КРИВАЯ УЕХАЛА ИЗ ШИНЫ (2026-11-03). Она жила в `src/bus/anketa.h`, а
// новым читателем стала цена убитого — `npc_xp_reward@src/tables/npc.h`. Слой
// `src/tables/` шину включать НЕ МОЖЕТ (§11: tables → core и только), значит
// либо кривая переезжает сюда, либо в дереве появляется её вторая копия. Второй
// копии не бывает (DOD п.6), поэтому переезд.
//
// ФОРМА ЦЕЛАЯ, И ЭТО НЕ ПЕРЕКАЛИБРОВКА. Прежнее тело считало
// `int(1000.0 * level * (0.1 * level + 1.0))` — через double. Тождественно
// `100·L² + 1000·L`, и на всей лестнице 1..255 обе формы дают БИТ В БИТ одно и
// то же (старший порог 6 757 500 представим в double точно). Целая форма
// выбрана по ЗАКОНУ ТИПА: величина симуляции ходит в целых, а float —
// пограничный тип, нужный железу и континууму, не кривой опыта.
#pragma once

#include <array>
#include <cstddef>
#include <cstdint>

namespace sm {

// ── ВЕРХ ЛЕСТНИЦЫ И ЕДИНСТВЕННАЯ ДВЕРЬ, САЖАЮЩАЯ ЧИСЛО НА ЕЁ СТУПЕНЬ ───────
//
// ВЕРХ — 255, И ЭТО НЕ ВКУС, А ШИРИНА НОСИТЕЛЕЙ. Уровень головы инвентаря едет
// байтом (`ItemRef::level@src/tables/items.h`), тело толпы — байтом, опасность
// клетки — байтом (`ZoneLayer@src/macro/zones.h`). Одна лестница на все четыре
// вопроса (вердикт владельца 2026-11-03: «у нас есть УЖЕ ЗОНЫ СЛОЖНОСТИ И ТИРЫ
// ПРЕДМЕТОВ … они уже u8 255 НА ЭТОМ И РЕШИЛИ»), значит её верх есть верх байта.
//
// У ОДНОГО ЧИСЛА БЫЛО ДВА ИМЕНИ, И ВТОРОЕ УМЕРЛО ЗДЕСЬ (M-382). Рядом жил
// `kMaxSoldierLevel` в `tables/army.h` — те же 255, тот же вывод, своя копия
// прозы; его собственная шапка уже признавала единство («та же лестница дальше
// ведёт зоны сложности и дроп по уровню»), то есть второе имя было не второй
// величиной, а вторым СПЕЛЛИНГОМ первой. Рода «уровень солдата» в игре нет
// (ЗАКОН АНКЕТЫ: сквад есть «что он делает»), поэтому выжило имя ЛЕСТНИЦЫ.
constexpr int kMaxTier = 255;

// ОДНА ДВЕРЬ НА ВОПРОС «КАКАЯ ЭТО СТУПЕНЬ», И ЭТО КЛАМП-СТРАЖ, А НЕ КОСТЫЛЬ
// (ЗАКОН КЛАМПА): она охраняет ОБЛАСТЬ ОПРЕДЕЛЕНИЯ — таблица порогов ниже имеет
// ровно 256 ступеней, и индекс вне неё есть UB, а не «подрезанное поведение».
// Пол 1, а не 0, — высказывание: нулевой ступени у лестницы нет, и цена первой
// ступени не ноль (вердикт владельца о поле лестницы: «чтобы чтото было»).
//
// ЧЕТЫРЕ СПЕЛЛИНГА СВЕДЕНЫ К ЭТОМУ ОДНОМУ (M-382, перепись): `normalize_soldier_level`
// в `tables/army.h` (пол 1, потолок своим именем капа), и три рукописных тройных
// условия — в `exp_at_level` и `exp_value_of_level` здесь же и в `creature_tier`
// в `tables/npc.h`. Вопрос у всех четырёх был ОДИН, и это DOD п.6: разойтись им
// ничто не мешало, а один из четырёх уже разошёлся — у цены убитого потолка не
// было вовсе, только пол.
constexpr int clamp_to_ladder(int level) {
    if (level < 1) return 1;
    return level > kMaxTier ? kMaxTier : level;
}

// ПОРОГ СЛЕДУЮЩЕГО УРОВНЯ. Квадратичный закон: вклад в базу и вклад в
// множитель растут линейно по уровню, их произведение — парабола, и порог
// обязан идти с ней в лад, иначе гринд инфлирует (замер прежней линейной
// награды: убийств ровни на уровень 110 → 1100 на дистанции 1..100).
//
// ПОТОЛОК СЧИТАН: на уровне 255 порог равен 6 757 500, а СУММА всех порогов
// лестницы — 581 850 498, то есть кумулятивный опыт влезает в `std::uint32_t`
// с запасом 3 713 116 797 — это 337 556 убийств твари тира 100 ПОСЛЕ
// максимального уровня. Нагриндить переполнение невыразимо на практике.
constexpr int exp_to_next_level(int level) {
    const int L = level < 0 ? 0 : level;
    return 100 * L * L + 1000 * L;
}

// ДЕЛИТЕЛЬ ЦЕНЫ УБИТОГО — ДИЗАЙН-ВЫСКАЗЫВАНИЕ, А НЕ КАЛИБРОВКА (вердикт
// владельца 2026-11-03: «я настаиваю на 100 … делитель это однозначно уже
// да»). Сто значит «УРОВЕНЬ СТОИТ СТО УБИЙСТВ РАВНОГО ПРОТИВНИКА», и число
// СОКРАЩАЕТСЯ тождественно: цена ровни есть `exp_to_next_level(L)/100`, порог
// есть `exp_to_next_level(L)`, значит убийств на уровень выходит ровно сто — на
// ВСЕЙ дистанции, без калибровки по уровням.
// И ДЕЛИТЕЛЬ ДЕЛИТ КРИВУЮ БЕЗ ОСТАТКА — ЭТО СВОЙСТВО, А НЕ СОВПАДЕНИЕ: порог
// есть `100·(L² + 10L)`, то есть сотня стоит в нём множителем. Поэтому цена
// ровни выходит ровно `L² + 10L`, а отношение «порог / цена» равно СТА точно,
// на каждой ступени лестницы, без округлений. Двигая делитель, помни: число,
// не делящее сотню, вернёт в закон остаток и сломает тождество.
constexpr int kKillsPerLevel = 100;

// ЦЕНА УБИТОГО В ОПЫТЕ. Вход — УРОВЕНЬ убитого: у аватара настоящий (анкета),
// у головы инвентаря — ТИР ЕЁ СТРОКИ (ЗАКОН ДВУХ ТАБЛИЦ: у объекта анкеты нет,
// и уровень объекта есть тир). Одна дверь на оба случая — ветки по роду убитого
// здесь нет и быть не может.
constexpr int exp_value_of_level(int level) {
    const int L = clamp_to_ladder(level);
    return exp_to_next_level(L) / kKillsPerLevel;
}

// ТИР — АВТОРСКОЕ ЧИСЛО, И ВЫВОДИТЬ ЕГО ИЗ МОЩИ ЗАПРЕЩЕНО.
//
// Здесь стояла пара `isqrt_round`/`tier_of_power`, считавшая `тир = √(hp×dps)`.
// Она СНЕСЕНА в тот же день, 2026-11-03, вердиктом владельца: ✓ «мы же решили
// отказаться ваще от мощи и умножения хп на дпс … у нас же просто таблица
// объектов и написан тир моба»; и о предмете: ✓ «мне кажется лучше тир число
// ВСЁ РАВНО ОН НУЖЕН ДЛЯ ВЕСОВ зон».
//
// ПОЧЕМУ ВЫВОД БЫЛ НЕВЕРЕН — ОН НЕ ВИДИТ ПОЛОВИНЫ СТРОКИ. Владелец предупредил
// об этом прямо, ещё обсуждая свидетеля монотонности: ✓ «могут быть твари мало
// хп куча резистов и огромнвй урон не умничай где нюансы есть». `hp × удар /
// период` не знает ни резистов (`Defense::armor` по восьми родам урона), ни
// блока, ни дальнобойности, ни правил — значит стеклянная пушка получала бы
// низкий тир, а жирный безобидный мешок высокий. Тир есть ВЫСКАЗЫВАНИЕ автора
// «насколько эта тварь высоко в мире», и формулой оно не заменяется.
//
// ЧТО ТИР ЕСТЬ ПО СУЩЕСТВУ: одна шкала 0..255 на три РАЗНЫХ вопроса — опасность
// клетки, высота твари, ценность вещи. Едина она не потому, что три вещи
// тождественны, а потому, что мир их СОПОСТАВЛЯЕТ: `danger_match_weight` сводит
// клетку с тварью, `affix_power` — клетку с вещью. Сопоставление и есть причина
// единиц.
//
// Носитель тира твари — колонка её строки (`src/tables/npc.h`), и читается она
// одной дверью `head_xp_reward` там же.

// ── УРОВЕНЬ — ВЫВОД ИЗ НАКОПЛЕННОГО ОПЫТА, А НЕ ХРАНИМОЕ ЧИСЛО ─────────────
//
// Вердикт владельца 2026-11-03, дословно: ✓ «а может раз мы опыт всё равно
// храним убрать кап у скровня и вообще его убрать а сделать уровнеь вычислимым?
// типа опыт по сути и есть уровнь через квадратичную формулу»; и о том, что
// этим нельзя потерять: ✓ «просто важно едисннственое это тчобы левел апы
// давались после перехода вехи уровня».
//
// Хранимый уровень был ДУБЛЕМ ВЫВОДИМОГО — того же рода, что поле `expToNext`,
// которое однажды давало даровой уровень с первой победы (`SCARS.md`
// «анкета-три-носителя»). Теперь в анкете лежит ОДНО число — кумулятивный опыт,
// — а уровень есть обратная функция кривой.
//
// ПОРОГИ ТАБЛИЦЕЙ, ПОИСК ДВОИЧНЫЙ: 256 × 4 Б = 1 КиБ в rodata, восемь
// сравнений на вопрос, ноль флоатов, ноль делений. Таблица выводится из той же
// `exp_to_next_level`, то есть разъехаться с кривой не может по построению.
inline constexpr auto kExpAtLevel = [] {
    std::array<std::uint32_t, std::size_t(kMaxTier) + 2> t{};
    for (int L = 1; L <= kMaxTier; ++L)
        t[std::size_t(L) + 1] =
            t[std::size_t(L)] + std::uint32_t(exp_to_next_level(L));
    return t;
}();

// ПОТОЛОК ОПЫТА ВЫВЕДЕН, А НЕ НАЗНАЧЕН: сумма всех порогов лестницы равна
// 581 850 498, то есть кумулятив влезает в `std::uint32_t` с запасом ×7.
static_assert(kExpAtLevel[std::size_t(kMaxTier)] < 0xFFFFFFFFu / 7u,
              "кумулятивный опыт обязан влезать в u32 с запасом на хвост "
              "сверх максимального уровня");

// КАП ЛЕСТНИЦЫ ПЕРЕСТАЛ БЫТЬ ЧИСЛОМ — ОН ЕСТЬ ДЛИНА ЭТОЙ ТАБЛИЦЫ. Выше неё
// уровень не растёт, и это не кламп поведения, а край шкалы: носители уровня в
// дереве байтовые (`ItemRef::level@src/tables/items.h`, тело толпы), опасность
// клетки тоже байт.
constexpr int level_of_exp(std::uint32_t exp) {
    int lo = 1, hi = kMaxTier;
    while (lo < hi) {
        const int mid = (lo + hi + 1) / 2;
        if (kExpAtLevel[std::size_t(mid)] <= exp) lo = mid; else hi = mid - 1;
    }
    return lo;
}

// ОПЫТ, НАКОПЛЕННЫЙ ВНУТРИ ТЕКУЩЕЙ СТУПЕНИ — то, что рисует полоса. Прежде это
// и лежало в поле `exp`, потому что уровень вычитал порог; теперь вычитание
// делает читатель, а запись остаётся монотонной.
constexpr std::uint32_t exp_within_level(std::uint32_t exp) {
    return exp - kExpAtLevel[std::size_t(level_of_exp(exp))];
}

// ОПЫТ, КОТОРЫМ ОПЛАЧЕНА ДАННАЯ СТУПЕНЬ — вход для авторских анкет: строка
// называет РАНГИ, а её опыт выводится из того уровня, который эти ранги
// оплачивает (вердикт владельца: ✓ «А уровень = прокачка»).
constexpr std::uint32_t exp_at_level(int level) {
    return kExpAtLevel[std::size_t(clamp_to_ladder(level))];
}

// ── БЮДЖЕТ УРОВНЯ: 5-5-5 НА СОЗДАНИИ, 1-1-1 ЗА УРОВЕНЬ (CANON S14) ─────────
// Выданное — функция УРОВНЯ, потраченное — функция САМОГО ЛИСТА, доступное их
// разность. Поэтому ни один из четырёх счётчиков не хранится: хранить их значило
// бы держать четыре величины, выводимые из двух уже хранимых.
constexpr int kCreationBudget = 5;

constexpr int granted_attribute_points(int level) {
    return kCreationBudget + (level < 1 ? 0 : level - 1);
}
constexpr int granted_skill_points(int level) {
    return level < 1 ? 0 : level - 1;
}
// УЧЕНИЙ РОВНО ПЯТЬ НА ВСЮ ЖИЗНЬ, И ЭТО НЕ ОПЕЧАТКА: `try_level_up` никогда не
// выдавала шестого, а CANON S14 говорит «стартовая пятёрка — это ВЫУЧИВАНИЯ в
// ранг 1, не поинты». Мир учит скиллам СОБЫТИЕМ, а не уровнем.
constexpr int granted_learn_picks(int /*level*/) { return kCreationBudget; }
constexpr int granted_perk_points(int level) {
    return kCreationBudget + (level < 1 ? 0 : level - 1);
}

} // namespace sm
