// КОНТУР СТРОКИ МИРА — ЗАКОН, КОТОРЫЙ СУДИТ КОМПИЛЯТОР.
//
// Владелец, дословно (наряд M-169): «надо сделать так чтобы новый код не мог
// насрать СТРОГО ТЕХНИЧЕСКИ уже а не какимито словами чтобы ложило компиляцию и
// все знали все видели кто насрал и как». Этот заголовок и есть та стена:
// строка мира, в которую заложили вектор, строку, карту, умный указатель,
// функтор или виртуальный метод, ПЕРЕСТАЁТ СОБИРАТЬСЯ, и сообщение называет тип
// поимённо.
//
// ПОЧЕМУ КОНТУР ПО ТИПУ, А НЕ ЗАПРЕТ ПО СЛОВУ. Текстовый бан `std::vector` в
// файле-сущности был предложен и ЗАБРАКОВАН ЗАМЕРОМ (M-169): в `macro/squad.h`
// семь вхождений слова — и все семь ложные, это параметры функций
// (`const std::vector<SoldierRecord>&`) и локальные черновики в телах. Закон
// говорит о том, что лежит ВНУТРИ СТРУКТУРЫ; текстовый бан — о том, что
// написано В ФАЙЛЕ. Правило, врущее 7 из 7 на первом же файле, учит ровно
// одному — обходу переносом сигнатуры. `is_trivially_copyable` спрашивает
// ЧЛЕНЫ и обойти себя не даёт ни одним написанием: ни один heap-контейнер
// стандартной библиотеки тривиально копируемым не бывает.
//
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ, И КАКОЙ ЗАКОН ЗА КАЖДЫМ:
//   · `is_trivially_copyable`   — DOD §4 п.1 и §12: строка обязана пережить
//     `memcpy` и лечь в сейв БЕЗ собственного сериализатора. Это же условие
//     ловит heap-контейнер членом — то, ради чего контур и заводился;
//   · `is_standard_layout`      — раскладка предсказуема, значит `sizeof` и
//     смещения можно называть числом (DOD §4 п.10), а сейв-пакет — выкладывать
//     байтами (§10: своего формата у сейва нет, он идёт пакетами);
//   · `!is_polymorphic`         — §12 «никаких виртуалов на горячих данных».
//     vtable кладёт в строку указатель, свой у каждого процесса: такую строку
//     нельзя ни сохранить, ни переслать пакетом;
//   · `is_trivially_destructible` — уничтожение строки есть освобождение слота
//     (ЗАКОН ДВУХ МИРОВ п.4: «исчезновение тела — ЗАНУЛЕНИЕ СЛОТА»), а не обход
//     деструкторов; массив на 16384 слота не может позволить себе обратного.
//
// ЗАМЕР НА ДЕНЬ ПОСТРОЙКИ (M-169, 351 тип в `macro/ecs/sub/content`):
// тривиально копируемы 306, полиморфных **0**, наследований **0**,
// `new`-выражений во всём `src/` **два** (оба — документированный
// `reset(new T)` из шрама заголовка, §5 п.13). То есть контур не вычищает ООП —
// его в дереве уже нет; контур ЗАМОРАЖИВАЕТ ДОСТИГНУТЫЙ НОЛЬ. Это и есть его
// работа: вчистить один раз умеет и ревью, а не пустить обратно — только
// компилятор.
//
// ГДЕ КОНТУР ОБЯЗАН СТОЯТЬ, РЕШАЕТ НЕ ЭТОТ ФАЙЛ. Заголовки-строки перечислены в
// `tests/arch_guard_test.cpp`, и он же краснеет, если в таком заголовке завели
// структуру БЕЗ контура: иначе стена обходилась бы молча — новым типом.
//
// Цена включения O(1): один `<type_traits>` и ни одного тела (§5 п.13).
#pragma once
#include <type_traits>

// Контур без закрепления размера. Размер строки растёт с каждой законной
// колонкой, и требовать его числом здесь значило бы делать каждое расширение
// двухфайловой правкой — то есть тормозить развитие, что тесту запрещено
// (§8 ЗАКОН НУЛЕВОЙ п.7).
#define TIMAERT_ROW(T)                                                         \
    static_assert(std::is_trivially_copyable_v<T>,                             \
                  #T ": строка мира обязана переживать memcpy и ложиться в "   \
                     "сейв без своего сериализатора (AGENTS §4 DOD п.1). "     \
                     "Её сломал член, который тривиально копируемым не "       \
                     "бывает: vector, string, map, unique_ptr, shared_ptr, "   \
                     "function. Вместо него — плоский массив с именованным "   \
                     "капом и явным счётом.");                                 \
    static_assert(std::is_standard_layout_v<T>,                                \
                  #T ": у строки мира раскладка обязана быть предсказуемой "   \
                     "(AGENTS §4 DOD п.10, §10 СЕЙВ). Ломают ссылка членом, "  \
                     "смешанные public/private данные и наследование.");       \
    static_assert(!std::is_polymorphic_v<T>,                                   \
                  #T ": виртуальных на горячих данных не бывает (AGENTS §12). "\
                     "vtable кладёт в строку указатель процесса — такую "      \
                     "строку нельзя ни сохранить, ни отправить пакетом.");     \
    static_assert(std::is_trivially_destructible_v<T>,                         \
                  #T ": исчезновение строки есть ЗАНУЛЕНИЕ СЛОТА, а не обход " \
                     "деструкторов (AGENTS §3 ЗАКОН ДВУХ МИРОВ п.4).");        \
    static_assert(true, "")

// Контур с закреплённым размером — для строк, чей `sizeof` НАЗВАН вслух (в
// доке, в шапке, в реестре). DOD §4 п.10 дословно: «у структуры, чей размер
// назван, размер закрепляется `static_assert(sizeof)`» — куплено двумя шапками,
// обещавшими 36 и 72 байта при настоящих 92 и 80.
#define TIMAERT_ROW_BYTES(T, BYTES)                                            \
    TIMAERT_ROW(T);                                                            \
    static_assert(sizeof(T) == (BYTES),                                        \
                  #T ": размер этой строки НАЗВАН числом, и он разъехался. "   \
                     "Либо колонка добавлена осознанно — поправь число здесь " \
                     "и там, где оно названо; либо в раскладке дыра "          \
                     "выравнивания (AGENTS §4 DOD п.2: узкие поля пакуются "   \
                     "ВМЕСТЕ).");                                              \
    static_assert(true, "")
