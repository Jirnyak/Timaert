// ЕДИНЫЙ КАП МАКРОМИРА — 16384 (2^14): сквады-анкеты, округа навигации и Пул
// Входов меряются ОДНИМ числом, и имя у него одно. ТЕЛА СУБМИРА ЗДЕСЬ БОЛЬШЕ
// НЕ ЖИВУТ: у сцены свой кап `kMaxSubObjects@src/sub/caps.h` = 65536 (2^16 =
// мощность u16-индекса слота), поднятый вердиктом владельца 2026-10-09 («в
// субмире кап нужен макс большой потому что там будут кучи объектов снарядов
// большие сражения трупы пропы деревья из полей»). Конфликт двух вердиктов
// решает ДАТА: цитаты ниже — от 2026-10-06, когда одно число ещё служило
// обоим, и в части ТЕЛ они СНЯТЫ. «16к тел субмира» есть ошибка, названная
// владельцем прямо 2026-10-13: «кап 64к объектов субмира, 16к сеилинг это
// ошибка». Вердикт владельца
// 2026-10-06, дословно: «я могу быть реалистом и уменьшить кап сквадов до 16к
// (и единый кап будет — нпц/мобов в субмире 16к — сквадов 16к — карта путей
// 16к зон»; подтверждён 2026-10-09: «единый кап 16к давай единый это
// техническое на что мы ориентируемся». ОТМЕНЯЕТ вердикт 2026-09-25 о
// `kMacroEntityCap = 32768` (двойной запас) и закрывает двойное имя популяции
// (`kWorldSquads` 16384 против `kMacroEntityCap` 32768); оба имени мертвы.
//
// Контрфакт назван и принят (CANON «ЕДИНЫЙ КАП 16384»): пик замера за 512
// дней — 12.8k слотов = 78 % от 16384 при недобавленных родах сквадов. Принято
// потому, что отказ рождения ГРОМКИЙ (`store_birth@src/macro/store.h` печатает
// отказ в stderr и возвращает невалидный хэндл): день, когда кап кончится,
// будет НАЗВАН, а не угадан, а поднять потолок — одно число (ЗАКОН КАПА).
// Развязка «округа ≠ место» НЕ делается — отменена тем же разделом канона
// (владелец: «нет лучше единый кап»; «так что 16к золотая констнат всеобщая
// оставляем в микромире тела / в макромире сквады / и места окрестности
// путей»).
//
// Вывод числа у каждого потребителя СВОЙ, и они сошлись в одном — потому кап
// и един, а не «совпал»:
//   · СКВАДЫ МАКРОМИРА: замысел «до 16к агентов»; места делят кап одним
//     массивом — место есть неподвижный сквад (M-90);
//   · ОКРУГА НАВИГАЦИИ: производное — округа рождается на место, место есть
//     сквад, округ не бывает больше, чем сквадов (`nav_bake@src/macro/nav_field.cpp`).
//
// Живёт в отдельном крошечном заголовке, а не в `core/stacks.h`, потому что
// перепись стеков тянет `macro/*`, а субмиру включать macro/ запрещено
// (ЗАКОН ДВУХ МИРОВ); цена включения этого файла — O(1), ноль тел.
#pragma once

#include <cstddef>

namespace sm {

inline constexpr std::size_t kUnifiedCap = 16384u;
static_assert(kUnifiedCap != 0 && (kUnifiedCap & (kUnifiedCap - 1)) == 0,
              "степень двойки: маска вместо деления, один кап на симуляцию и рендер");

}  // namespace sm
