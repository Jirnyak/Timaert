// ЗАКОН ТРЁХ ДВЕРЕЙ ВЫЧИТАНИЯ (AGENTS §3, четыре инженерных закона, №2) —
// НОСИТЕЛЬ. Андерфлоу беззнакового — дюп из воздуха: `uint16 wood = 5;
// wood -= 10;` кладёт на склад 65 531 дерева, молча и навсегда. Голое
// `-=`/`a - b` над беззнаковой ВЕЛИЧИНОЙ симуляции (склад, инвентарь,
// экономика, поле) запрещено; вычитание ходит одной из трёх дверей, и
// ВЫБОР ДВЕРИ ЕСТЬ ВЫСКАЗЫВАНИЕ О ЗАКОНЕ МЕСТА:
//   sub_sat   — насыщение в ноль: износ, прочность, угасание следа — где
//               «ниже нуля» физически не бывает;
//   try_spend — всё или ничего, при нехватке величина НЕ трогается:
//               покупка, рецепт, жалованье — где полуплатёж есть ложь;
//   drain     — взять сколько есть и ВЕРНУТЬ ФАКТ: жатва, рубка, выемка
//               жилы, грабёж — где мир отдаёт остаток честно.
//
// ДОМ — core/: двери нужны обоим мирам (пулы, склады, поля), таблицам и
// приборам; цена включения O(1), ноль тел (§5 п.13). До 2026-10-09 дверей
// НЕ СУЩЕСТВОВАЛО ВОВСЕ (0 вызовов на всё дерево при 57 голых `-=` в
// macro/sub) — закон жил прозой и проецировался; семантика drain при этом
// уже была доменно (`bleed_flock@src/macro/world_row.h` возвращает факт) —
// доменные двери ОСТАЮТСЯ, они строятся НА этих или выражают тот же закон
// своим контрактом.
//
// ЗНАКОВОЙ ДВЕРИ НЕТ СОЗНАТЕЛЬНО (ЗАКОН ТИПА п.2): величина, законно
// ходящая в минус (репутация, золото), вычитается голым минусом — её
// отрицательное значение ИНФОРМАЦИЯ, а не авария. Стена на этом стоит
// компилятором: инстанс двери знаковым типом не собирается.
#pragma once

namespace sm {

// Насыщение в ноль. [[nodiscard]]: выброшенный результат значит «вычли и
// забыли», то есть голое вычитание под другим именем.
template <class T>
[[nodiscard]] constexpr T sub_sat(T a, T b) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    return a > b ? T(a - b) : T(0);
}

// Всё или ничего: при нехватке баланс НЕ трогается. Возврат — ФАКТ оплаты;
// игнорировать его нельзя — молча несработавший платёж и есть полуложь,
// которую дверь существует запрещать.
template <class T>
[[nodiscard]] constexpr bool try_spend(T& balance, T cost) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    if (balance < cost) return false;
    balance = T(balance - cost);
    return true;
}

// Взять сколько есть и вернуть ФАКТ: «срубили 3, осталось 1 — взято 1».
template <class T>
[[nodiscard]] constexpr T drain(T& stock, T want) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    const T taken = stock < want ? stock : want;
    stock = T(stock - taken);
    return taken;
}

}  // namespace sm
