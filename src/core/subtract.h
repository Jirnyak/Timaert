// ЗАКОН ТРЁХ ДВЕРЕЙ ВЫЧИТАНИЯ (AGENTS §3, четыре инженерных закона, №2) —
// НОСИТЕЛЬ. Андерфлоу беззнакового — дюп из воздуха: `uint16 wood = 5;
// wood -= 10;` кладёт на склад 65 531 дерева, молча и навсегда. Голое
// `-=`/`a - b` над беззнаковой ВЕЛИЧИНОЙ симуляции (склад, инвентарь,
// экономика, поле) запрещено; вычитание ходит одной из трёх дверей, и
// ВЫБОР ДВЕРИ ЕСТЬ ВЫСКАЗЫВАНИЕ О ЗАКОНЕ МЕСТА:
//   sub_sat   — насыщение в ноль: износ, прочность, угасание следа — где
//               «ниже нуля» физически не бывает;
//   try_spend — всё или ничего, при нехватке величина НЕ трогается:
//               покупка, рецепт, жалованье — где полуплатёж есть ложь;
//   drain     — взять сколько есть и ВЕРНУТЬ ФАКТ: жатва, рубка, выемка
//               жилы, грабёж — где мир отдаёт остаток честно.
//
// ДОМ — core/: двери нужны обоим мирам (пулы, склады, поля), таблицам и
// приборам; цена включения O(1), ноль тел (§5 п.13). До 2026-10-09 дверей
// НЕ СУЩЕСТВОВАЛО ВОВСЕ (0 вызовов на всё дерево при 57 голых `-=` в
// macro/sub) — закон жил прозой и проецировался; семантика drain при этом
// уже была доменно (`bleed_flock@src/bus/world_row.h` возвращает факт) —
// доменные двери ОСТАЮТСЯ, они строятся НА этих или выражают тот же закон
// своим контрактом.
//
// ЗНАКОВОЙ ДВЕРИ НЕТ СОЗНАТЕЛЬНО (ЗАКОН ТИПА п.2): величина, законно
// ходящая в минус (репутация, золото), вычитается голым минусом — её
// отрицательное значение ИНФОРМАЦИЯ, а не авария. Стена на этом стоит
// компилятором: инстанс двери знаковым типом не собирается.
//
// ── ВТОРАЯ ПОЛОВИНА СТЕНЫ: `Qty` (2026-11-08, вердикт владельца) ──────────
// Владелец, дословно: «ну тогда надо универсльно для всеъ безнаковых
// вычитаний проверку разрешон ли заворот если да то норм если запрещон то
// получается нижний кламп или что там»; и о форме: «но както надо обобщенно
// системно сделать наиболее в духе проекта».
//
// СВОЙСТВО «ЗАВОРОТ РАЗРЕШЁН» — ЭТО ТИП, И ПРОЕКТ ТАК УЖЕ РЕШИЛ, ПРОСТО НА
// ПОЛПУТИ. ЗАКОН ТИПА п.2 говорит: знаковый — если величина ЗАКОННО бывает
// отрицательной; беззнаковый — если это счёт или ординал. То есть «можно ли
// уйти ниже нуля» уже отвечено выбором типа, и двери выше достраивают
// половину стены (знаковым типом они не собираются). Недостроена вторая:
// у сырого `uint16` оператор минус отвечает «заворот разрешён = ДА» для
// величины, чей закон говорит НЕТ. Язык отвечает за нас, и отвечает неверно.
//
// `Qty<T>` отвечает верно: `+` есть, сравнения есть, а `-` и `-=` УДАЛЕНЫ.
// Вычесть можно только дверью, и дверь вернёт то, что положено её случаю.
// Это не флаг, не ведомость и не прогон: нарушение становится НЕСОБИРАЕМЫМ —
// лучшая форма свидетеля (§8 п.6), ровно тот приём, которым ФРЕЙМ п.7 ставит
// стену канала (запрещённое не существует для компилятора).
//
// ЧТО ЭТА ФОРМА УБИВАЕТ: текстовый храповик на `a - b` не строится НИКОГДА
// (1747 вхождений на 1515 строках, почти все законные int/float — он был бы
// налогом на всякое выражение, §8 п.7); белый список `-=` тает до нуля по
// мере перевода величин вместо того, чтобы вечно стоять запретом роста;
// рантайм-флаг и ведомость «величина → заворот?» не заводятся вовсе — обе
// были бы вторым ответом на вопрос, на который отвечает тип (DOD п.6).
//
// ЕДИНСТВЕННОЕ, ЧТО МОГЛО БЫ МОЛЧА УБИТЬ ВСЮ СТЕНУ, — НЕЯВНОЕ ПРИВЕДЕНИЕ К
// СЫРОМУ ТИПУ: умей `Qty` сам превращаться в `uint16`, и `a - b` снова
// собирается, а мы имеем стену, которой нет, при полной уверенности, что она
// есть. Поэтому носитель ЗАКРЫТ, а выход наружу один и названный — `get()`.
// Остаток честно: автор, написавший `a.get() - b.get()`, обходит стену — но
// это ДЕЛИБЕРАТНЫЙ акт с именем двери в строке, а закон заведён против
// МОЛЧАЛИВОГО случая, и смысл стены ровно в том, чтобы случайное стало
// невыразимым.
//
// ФОРМА — POD: тривиально копируем, стандартной раскладки, `sizeof` равен
// исходному под `static_assert`. Значит величина мира, одетая в `Qty`, ложится
// в сейв теми же байтами и не раздувает раскладку ни на бит.

#pragma once

#include <compare>
#include <type_traits>

namespace sm {

template <class T>
struct Qty {
    static_assert(T(0) < T(-1),
                  "`Qty` одевает БЕЗЗНАКОВУЮ величину симуляции; знаковой "
                  "минус законен голым (ЗАКОН ТИПА п.2)");

    constexpr Qty() noexcept = default;
    constexpr explicit Qty(T raw) noexcept : v_(raw) {}

    // ЕДИНСТВЕННЫЙ ВЫХОД НАРУЖУ, И ОН НАЗВАН. Неявного приведения нет
    // сознательно — см. шапку: оно вернуло бы голый минус через чёрный ход.
    [[nodiscard]] constexpr T get() const noexcept { return v_; }

    // Рост законен голым: прибавление беззнакового не рождает дюпа из
    // воздуха — потолок типа есть вопрос ШИРИНЫ (ЗАКОН ТИПА п.1), а не
    // вопрос заворота вниз, против которого стоит этот тип.
    constexpr Qty& operator+=(Qty b) noexcept { v_ = T(v_ + b.v_); return *this; }
    friend constexpr Qty operator+(Qty a, Qty b) noexcept { a += b; return a; }

    // ВОТ ОНА, СТЕНА — И ОНА ЕСТЬ ОТСУТСТВИЕ, А НЕ `= delete`. Первая
    // редакция объявляла оба оператора удалёнными: ошибка в коде выходила
    // красивее («selected deleted operator»). Но тогда стену НЕЛЬЗЯ
    // УТВЕРДИТЬ: clang считает выбор удалённой перегрузки внутри
    // `requires` ТВЁРДОЙ ошибкой, а не невыполненным требованием, то есть
    // `static_assert(!requires{a - b;})` не собирается вовсе. Стена, о
    // которой свидетель не может высказаться, — ровно то, против чего §8
    // п.6; поэтому минуса здесь просто НЕТ, и `requires` отвечает «не
    // собралось бы» чисто. Неявного приведения нет (см. ниже), значит
    // встроенный оператор тоже не подхватится — кандидата нет ни одного.

    friend constexpr auto operator<=>(Qty, Qty) noexcept = default;
    friend constexpr bool operator==(Qty, Qty) noexcept = default;

  private:
    T v_{};
};


// Насыщение в ноль. [[nodiscard]]: выброшенный результат значит «вычли и
// забыли», то есть голое вычитание под другим именем.
template <class T>
[[nodiscard]] constexpr T sub_sat(T a, T b) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    return a > b ? T(a - b) : T(0);
}

// Всё или ничего: при нехватке баланс НЕ трогается. Возврат — ФАКТ оплаты;
// игнорировать его нельзя — молча несработавший платёж и есть полуложь,
// которую дверь существует запрещать.
template <class T>
[[nodiscard]] constexpr bool try_spend(T& balance, T cost) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    if (balance < cost) return false;
    balance = T(balance - cost);
    return true;
}

// Взять сколько есть и вернуть ФАКТ: «срубили 3, осталось 1 — взято 1».
template <class T>
[[nodiscard]] constexpr T drain(T& stock, T want) noexcept {
    static_assert(T(0) < T(-1),
                  "дверь вычитания — для БЕЗЗНАКОВЫХ величин симуляции; "
                  "знаковой величине минус законен голым (ЗАКОН ТИПА п.2)");
    const T taken = stock < want ? stock : want;
    stock = T(stock - taken);
    return taken;
}

// ── ТЕ ЖЕ ТРИ ДВЕРИ ДЛЯ `Qty` — ТОТ ЖЕ ЗАКОН, ОДЕТЫЙ В ТИП ────────────────
// Перегрузки, а не вторая реализация: тело каждой есть вызов её же сырого
// близнеца выше, поэтому разойтись им невыразимо (DOD п.9, разряд А).
template <class T>
[[nodiscard]] constexpr Qty<T> sub_sat(Qty<T> a, Qty<T> b) noexcept {
    return Qty<T>{sub_sat(a.get(), b.get())};
}

template <class T>
[[nodiscard]] constexpr bool try_spend(Qty<T>& balance, Qty<T> cost) noexcept {
    T raw = balance.get();
    if (!try_spend(raw, cost.get())) return false;
    balance = Qty<T>{raw};
    return true;
}

template <class T>
[[nodiscard]] constexpr Qty<T> drain(Qty<T>& stock, Qty<T> want) noexcept {
    T raw = stock.get();
    const T taken = drain(raw, want.get());
    stock = Qty<T>{raw};
    return Qty<T>{taken};
}

}  // namespace sm
