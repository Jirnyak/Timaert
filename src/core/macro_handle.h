// ── MacroHandle — ссылка на макро-сквад {слот, ID рождения} (M-220) ───────
// ЕДИНОЕ ПРАВИЛО обоих миров (вердикт владельца 2026-10-05: «можно хранить
// не только номер слота потому что это опасно а ещё … ID и тогда тривиально
// мой дом в слоте айди такое слот такое - проверка ой там уже не то айи -
// дома нет»; «ну и это ID должно быть uint32 естественно»). Слот — только
// АДРЕС O(1); id — только ИДЕНТИЧНОСТЬ: ординал единого эмитента (выдаёт
// дверь рождения store_birth, с 1). Ссылка жива, пока spawnId слота
// совпадает с её id — протухание судит ID, не поколение (колонка
// generation умерла этим же шагом). id == 0 — «никого» (закон
// нуля-ординала); слот-дефолт kMacroNoSlot — сентинел АДРЕСА для сырых
// слотов (ЗАКОН УЗКОГО ИНДЕКСА: кап 16384 оставляет последнее значение u16
// свободным) — у «никого» нет ни адреса, ни личности. Родня
// ObjRef@src/sub/objects.h: та же форма, но ДРУГОЙ тип — адресные
// пространства миров компилятор не смешает (ЗАКОН АДРЕСА п.5).
//
// ПЕРЕЕХАЛ macro/ → core/ ломтём 3 эпика фрейма: ссылка — форма АДРЕСА,
// и локальный фрейм (src/bus/) несёт её родом 2, не включая macro/.
// Файл нарочно НИЩИЙ (<cstdint> и всё): его включают и ecs/components.h
// (MacroOrigin несёт хэндл через шов миров), и сознательно лёгкий конверт
// macro_world.h (BattleFact носит {слот, ID} полями) — тащить туда полный
// ecs-слой запрещено его же шапкой. Двери хэндла — macro/store.h.
#pragma once
#include <cstdint>

namespace sm {

inline constexpr std::uint16_t kMacroNoSlot = 0xFFFFu;
struct MacroHandle {
    std::uint16_t slot = kMacroNoSlot;
    std::uint32_t id   = 0;
    friend constexpr bool operator==(const MacroHandle&,
                                     const MacroHandle&) = default;
};
static_assert(sizeof(MacroHandle) == 8,
              "ссылка макромира — 8 Б (u16 + pad + u32), форма ObjRef");

} // namespace sm
