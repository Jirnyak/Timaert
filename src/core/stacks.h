// Род штабеля — чем адресуется строка.
enum class StackKind : std::uint8_t {
    ByCell,      // клеткой тора: поле над миром
    ByOrdinal,   // ординалом сущности
    Catalog,     // строкой закона, известной на сборке
    Scalars,     // единственный экземпляр: состояние мира
};

// ОДНА СТРОКА ПЕРЕПИСИ = ОДНА АЛЛОКАЦИЯ, а не одна система. Правило записано
// вслух, потому что групповая строка и есть тот способ, которым перепись
// однажды промолчала: «навигация» одним пунктом прячет шесть колонок по
// клетке и четыре таблицы по округе, и ни одну из них нельзя ни сложить, ни
// сверить. Три колонки `PathCostData` — три строки; два канала следа — две.
struct StackRow {
    const char* name;        // как штабель зовут в мире
    const char* rowType;     // тип ОДНОЙ строки
    StackKind   kind;
    std::size_t rowBytes;    // sizeof одной строки
    // ПОТОЛОК СТРОК, И ОН ЕСТЬ У КАЖДОГО ШТАБЕЛЯ, включая каталог: у каталога
    // потолок И ЕСТЬ его длина, выведенная `std::size` из самой таблицы.
    // (Здесь стояло «0 = каталог» — ложь, которую держал только комментарий:
    // свидетель `stack_census_test` запрещает нулевой потолок с первого дня,
    // и ровно поэтому каталожных строк не было заведено ни одной.)
    std::size_t cap;
};

// ── ПОТОЛКИ МИРА ─────────────────────────────────────────────────────────
// Клеток на карте и популяции мира — два числа, из которых считается всё
// остальное. Клетки живут здесь, потому что перепись — единственное место,
// где они умножаются на размеры строк; кап популяции здесь НЕ объявляется —
// он ЕДИНЫЙ на оба мира и живёт в `kUnifiedCap@src/core/caps.h` (вердикт
// владельца 2026-10-06; слияние имён — эта половина M-106 — закрыто 2026-10-09: `kWorldSquads`
// и `kMacroEntityCap` умерли в одно имя). Сквады и МЕСТА делят кап одним
// массивом (M-90: место есть неподвижный сквад; `kWorldLandmarks` умер
// ломтиком F — отдельного потолка мест не существует).
inline constexpr std::size_t kWorldCells  = 1024u * 1024u;

// ПОТОЛОК ОКРУГ НАВИГАЦИИ — ПРОИЗВОДНЫЙ ОТ ЕДИНОГО КАПА (вердикт владельца
// 2026-10-06: округа рождается на МЕСТО, а место есть сквад — округ не бывает
// больше, чем сквадов). Округа рождается на КАЖДОЕ живое место
// (`nav_bake@src/macro/nav_field.cpp`: `regionLandmarkId.push_back(lm.id)` на
// каждый не-None ландмарк); единственный гейт в коде — отказ запекаться при
// `R >= kNavNoRegion` (65535), то есть предел ТИПА, а не предел мира.
// Перепись пишет правду о цене: четыре таблицы графа КВАДРАТИЧНЫ по капу
// (3 ГиБ по капу против ~40 МиБ на замеренном мире). Числом это стоит здесь
// затем, чтобы было ВИДНО: сам граф — отдельный эпик после полировки систем
// (вердикт владельца 2026-09-28: «там надо BFS и связные окрестности»), и
// худеть его переписью ЗАПРЕЩЕНО; развязка «округа ≠ место» тоже НЕ делается
// (владелец: «нет лучше единый кап» — округи входят в золотую константу).
inline constexpr std::size_t kNavRegionCap = kUnifiedCap;

// СТРОКА ГЛАДКОЙ ПАМЯТИ МАКРО-СКВАДОВ — СУММА КОЛОНОК, А НЕ ЛИТЕРАЛ.
// `MacroStore` (macro/store.h) сюда включить нельзя: он сам включает этот
// файл ради `kUnifiedCap`. Поэтому цена слота считается здесь из тех же
// типов, из которых он сложен, а СХОДИМОСТЬ с настоящим `sizeof(MacroStore)`
// закреплена `static_assert`-ом на той стороне (`store.h`) — перепись и
// структура не могут разъехаться молча ни в одну сторону.
inline constexpr std::size_t kMacroStoreRowBytes =
    sizeof(ecs::MacroSpawnId) + sizeof(ecs::MacroCell) + sizeof(ecs::NPCKind)
    + sizeof(ecs::MacroVisual) + sizeof(ecs::NpcCharacter)
    + sizeof(ecs::SquadName)          // имя анкеты (ход 2, вердикт 3)
    + sizeof(ecs::NpcLevel) + sizeof(ecs::NpcTraits) + sizeof(ecs::Pools)
    + sizeof(ecs::MacroNpcRuntime) + sizeof(SpellBook) + sizeof(AgentMemory)
    + sizeof(ecs::SquadUpkeep)
    + sizeof(Wellbeing)               // благополучие анкеты (M-90 флип)
    + sizeof(Interests)               // связи любых сквадов (M-90 флип)
    + sizeof(ecs::NpcInventory)
    + sizeof(CharacterSheet) + sizeof(ecs::SquadOrders)
    + sizeof(ecs::BodyEquipment) + sizeof(ecs::DesignCharacterTag)
    + sizeof(std::uint8_t)            // playerFlag — флажок игрока (5б)
    + sizeof(std::uint8_t)            // dead — байт судьбы
    + sizeof(std::uint16_t)           // generation — поколение слота
    + sizeof(std::uint8_t)            // alive — занятость
    + sizeof(std::uint16_t);          // freeSlots — стек свободных

// СКОЛЬКО РЯДОВ РЕАЛЬНО ВЫДЕЛЯЮТ СВОЁ ПОЛЕ ШРАМОВ. Не десять: ряд-НОСИТЕЛЬ
// (лес и шесть жил) держит живое состояние в своём контейнере, и
// allocate_world_fields его пропускает (`if (carrierRead) continue`). Значит
