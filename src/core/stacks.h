// ── СТОРОЖ (2): РАЗМЕР КОНТЕЙНЕРА — ЛОВУШКА НА КОСТЫЛЬ ───────────────────
// Пришитое к этим структурам поле двигает sizeof, и сборка краснеет. Именно
// так нарушение инварианта становится ВИДНЫМ, а не обнаруживается через год.
// 2026-09-24, слияние M-71: пул дезертиров стал единым контейнером
// (SoldierSquad 3076 → Inventory 40960), отсюда 11576 → 49456
// (−4: с SoldierSquad ушёл его хвостовой счётчик с паддингом).
// 2026-09-26, снос мёртвой таблицы энкаунтеров: из `GameSubState` ушли три
// колонки без читателя — `eventId` и `enemyId` (по 24 Б, `std::string`) и
// `pendingEncounterIdx` (4 Б), итого 52 Б плюс 4 Б выравнивания = −56,
// отсюда 49456 → 49400. Сторож сработал ровно как задуман: снос колонки
// покраснел здесь, а не всплыл через год (§8 ЗАКОН НУЛЕВОЙ п.6 — лучшая
// форма свидетеля есть нарушение, которое невозможно собрать).
// 2026-09-29, M-106 1е кластер 5: +8 Б — игрок стал двумя packed-хэндлами
// мира (`playerSquadBits`/`playerFlagBits`, по 4 Б без паддинга: соседние
// u32); с 5б оба поля — КЭШИ колонок анкеты (playerFlag, spawnId).
// 2026-09-30, M-37: −8 Б — `nextLandmarkOrdinal` умер (u32 + 4 Б
// выравнивания): ординалы мест выдаёт ЕДИНЫЙ эмитент субъектов
// `nextMacroSpawnOrdinal`, выдача с 1, 0 навсегда «никто» (закон
// нуля-ординала, AGENTS ЗАКОН СЛОВАРЯ И ОРДИНАЛА п.6).
// 2026-09-30, ход 2 ломтик C: РОД 6 стал строками — RelationMatrix (5696)
// умер в FactionState (793096: 64 строки по 104 + пул феодальных рёбер
// 32768×24 + счёт и штамп), 49400 → 836800. Пул — на месте трёх колонок
// дани КАЖДОГО места (закон «дань — система фракций»).
// 2026-09-30, ход 2 ломтик E шаг 2: −64 Б — `worldLedger` (WorldLedger:
// цена на строку + день) умер вместе с ведомостями мест, из которых
// считался. Мировое среднее было ЧИСЛОМ, выведенным сезонным проходом по
// всем местам; его место заняла АБСОЛЮТНАЯ СТОИМОСТЬ строки каталога —
