// ПЕРЕПИСЬ ШТАБЕЛЕЙ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ НАПИСАНО, ИЗ ЧЕГО СДЕЛАН МИР.
//
// ИНВАРИАНТ ШТАБЕЛЯ (владелец, 2026-09-22). Состояние мира есть набор
// ШТАБЕЛЕЙ — непрерывных массивов ОДИНАКОВЫХ структур, адресуемых ординалом.
// Легальных форм ровно три, и все три — один и тот же штабель под разными
// именами:
//
//   ПО КЛЕТКЕ    — поле над миром: буквально число в каждой клетке тора;
//   ПО ОРДИНАЛУ  — сущности: сквады, существа, предметы;
//   КАТАЛОГ      — строки законов: спеллы, скиллы, рецепты, рода, ресурсные
//                  ряды. Неизменяемый штабель, известный на сборке.
//
// Плюс ровно одно исключение, названное вслух: СКАЛЯРЫ МИРА — день, сид,
// размер карты, счётчики-выдатчики ординалов. Их один явный блок, и он тоже
// числится здесь.
//
// ДОБАВЛЕНИЕ КОНТЕНТА РАЗРЕШЕНО ДВУМЯ ХОДАМИ И НИКАКИМИ ДРУГИМИ:
//   1) новая СТРОКА в существующий штабель (новое существо, спелл, рецепт);
//   2) новый ШТАБЕЛЬ той же формы (новый ресурс = новое поле над миром).
// Служебный вектор, хеш, одиночное число сбоку, поле, пришитое к чужой
// структуре, — НАРУШЕНИЕ. Владелец дословно: «если я захочу новый ресурс оно
// не сможет никак его добавить кроме как новое поле потому что другое сразу
// сломает ИНВАРИАНТ».
//
// ── ПОЧЕМУ ЭТО ФАЙЛ КОДА, А НЕ РАЗДЕЛ ДОКУМЕНТА ──────────────────────────
// Потому что документ не ловит. Здесь стоят ДВА рода сторожей, и оба
// компиляторные:
//
//   (1) РАЗМЕР СТРОКИ каждого штабеля закреплён `static_assert`. Раздулась
//       строка — красная сборка, и картина памяти не может разойтись с прозой
//       молча (она уже расходилась: шапка обещала «~36 bytes», правда была 96).
//
//   (2) РАЗМЕР САМОГО КОНТЕЙНЕРА закреплён тоже. Это и есть ловушка на
//       костыль: пришил служебный вектор к `GameState` — `sizeof` уехал,
//       сборка красная, и прятать это некуда. Ни один костыль не может
//       встать молча.
//
// Меняешь форму сознательно — правишь число ЗДЕСЬ, и правка видна в дифе
// отдельной строкой. Это и есть «полный контроль, что делаем».
//
// Картина мира словами живёт в SKELETON.md; здесь — та же картина числами,
// которые проверяет компилятор.
#pragma once

#include "ecs/components.h"
#include "macro/deposit_layer.h"
#include "macro/features.h"
#include "macro/macro_world.h"
#include "macro/resource_field.h"
#include "macro/state.h"
#include "macro/tree_layer.h"

#include <cstddef>
#include <cstdint>

namespace sm {

// Род штабеля — чем адресуется строка.
enum class StackKind : std::uint8_t {
    ByCell,      // клеткой тора: поле над миром
    ByOrdinal,   // ординалом сущности
    Catalog,     // строкой закона, известной на сборке
    Scalars,     // единственный экземпляр: состояние мира
};

struct StackRow {
    const char* name;        // как штабель зовут в мире
    const char* rowType;     // тип ОДНОЙ строки
    StackKind   kind;
    std::size_t rowBytes;    // sizeof одной строки
    std::size_t cap;         // потолок строк (0 = каталог, размер = его длина)
};

// ── ПОТОЛКИ МИРА ─────────────────────────────────────────────────────────
// Клеток на карте и сквадов в мире — два числа, из которых считается всё
// остальное. Живут здесь, потому что перепись — единственное место, где они
// умножаются на размеры строк.
inline constexpr std::size_t kWorldCells  = 1024u * 1024u;
inline constexpr std::size_t kWorldSquads = 16384u;

// ── СТОРОЖ (1): РАЗМЕР СТРОКИ ────────────────────────────────────────────
// Каждое число выведено из формы строки, а не замерено «как вышло». Разъехался
// вывод с правдой — компилятор говорит об этом здесь, а не проза где-то.
static_assert(sizeof(ecs::MacroNpcRuntime) == 92,
              "строка марша: 92 Б × 16384 = 1.44 МиБ");
static_assert(sizeof(ecs::Pools) == 36, "строка полос");
static_assert(sizeof(ecs::MacroVisual) == 12, "строка вида");
static_assert(sizeof(ecs::NpcCharacter) == 12, "строка лица");
static_assert(sizeof(ecs::NpcInventory) == 9216,
              "инвентарь сущности: 256 стаков");
static_assert(sizeof(ecs::SquadRoster) == 3144,
              "ростер = инвентарь существ (CANON S4)");
static_assert(sizeof(ResourceGrid) == 72, "заголовок поля над миром");
static_assert(sizeof(FeatureLayer) == 32, "заголовок слоя фич");
static_assert(sizeof(TreeLayer) == 40, "заголовок слоя леса");

// ── СТОРОЖ (2): РАЗМЕР КОНТЕЙНЕРА — ЛОВУШКА НА КОСТЫЛЬ ───────────────────
// Пришитое к этим структурам поле двигает sizeof, и сборка краснеет. Именно
// так нарушение инварианта становится ВИДНЫМ, а не обнаруживается через год.
static_assert(sizeof(GameState) == 11576,
              "состояние мира: новое поле здесь = нарушение инварианта "
              "штабеля, пока не заведено строкой переписи");
static_assert(sizeof(MacroWorld) == 120,
              "конверт мира — только указатели на штабеля, ничего своего");
static_assert(sizeof(DepositLayer) == 504,
              "слой жил: шесть полей + параметры рождения");
static_assert(sizeof(ResourceFields) == 720,
              "одиннадцать полей над миром, по заголовку на ряд");
// ЛАНДМАРК ЗАКРЕПЛЁН НЕ ЗАТЕМ, ЧТОБЫ ЕГО БЕРЕЧЬ, А ЗАТЕМ, ЧТОБЫ ВИДЕТЬ.
// Он ПОДЛЕЖИТ СНОСУ ЦЕЛИКОМ (наряд M-90, вердикт владельца 2026-09-22:
// «УНИЧТОЖИТЬ ЛАНДМАРКОВ ТОЖЕ НЕ ДОЛЖНО БЫТЬ МЫ УЖЕ ДАВНО ПЕРЕШЛИ НА ЕДИНУЮ
// СИСТЕМУ СКВАДОВ»): это второй штабель сущностей рядом со сквадами, и он
// держит число клетки (`population`) внутри своей записи вместо поля над
// миром. До сноса — пусть хотя бы не растёт молча.
static_assert(sizeof(Landmark) == 13728,
              "ПОДЛЕЖИТ СНОСУ (M-90): второй штабель сущностей");

// ── ПЕРЕПИСЬ ─────────────────────────────────────────────────────────────
// Ряд данных, а не ряд слов: по нему печатается картина памяти, и по нему же
// сверяется, что ни один штабель не забыт.
inline constexpr StackRow kStacks[] = {
    // ШТАБЕЛЯ ПО КЛЕТКЕ — поля над тором. Новый ресурс приходит СЮДА строкой.
    {"поля ресурсов", "std::int32_t", StackKind::ByCell, 4,
     kWorldCells * std::size_t(ResourceFieldId::Count)},
    {"жилы", "std::int32_t", StackKind::ByCell, 4,
     kWorldCells * kDepositKindCount},
    {"фичи", "std::uint8_t", StackKind::ByCell, 1, kWorldCells},
    {"числа фич (слой разработки)", "std::int32_t", StackKind::ByCell, 4,
     kWorldCells},
    {"лес", "std::uint16_t", StackKind::ByCell, 2, kWorldCells},

    // ШТАБЕЛЯ ПО ОРДИНАЛУ — сущности. ОДИН ШТАБЕЛЬ НА КОЛОНКУ (вердикт
    // владельца 2026-09-22): обход одной колонки не тащит остальные в кэш.
    {"марш сквада", "ecs::MacroNpcRuntime", StackKind::ByOrdinal,
     sizeof(ecs::MacroNpcRuntime), kWorldSquads},
    {"инвентарь сквада", "ecs::NpcInventory", StackKind::ByOrdinal,
     sizeof(ecs::NpcInventory), kWorldSquads},
    {"ростер сквада", "ecs::SquadRoster", StackKind::ByOrdinal,
     sizeof(ecs::SquadRoster), kWorldSquads},
    {"полосы сквада", "ecs::Pools", StackKind::ByOrdinal,
     sizeof(ecs::Pools), kWorldSquads},

    // СКАЛЯРЫ МИРА — единственный экземпляр, названное исключение.
    {"состояние мира", "GameState", StackKind::Scalars, sizeof(GameState), 1},
};

inline constexpr std::size_t kStackCount =
    sizeof(kStacks) / sizeof(kStacks[0]);

} // namespace sm
