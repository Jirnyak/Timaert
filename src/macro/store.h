// 712 884 240.
// 2026-10-11, перепись сирот (вердикт владельца «снести»): 715 849 736 →
// 713 621 512, **−2 228 224 Б = −2.125 МиБ** — колонка `memory`
// (`AgentMemory`, 136 Б × кап) уничтожена вместе со всем своим заголовком.
// Она была 99 % мёртвых байт макро-состояния и мертва была ПО ДВЕРЯМ, а не
// по грепу: `recall` имел НОЛЬ прод-вызовов — никто никогда не вспоминал, —
