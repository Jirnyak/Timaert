// Колонка на компоненту; порядок — от горячих к холодным не важен (SoA:
// каждая колонка — свой сплошной блок), список отсортирован по смыслу.
// dead — БАЙТ СУДЬБЫ, не занятость слота: мёртвый сквад стоит трупом до
// слива (AI-2), занятость держит служебный alive.
// playerFlag — «этот сквад (с этой анкетой) — игрок» (вердикт владельца
// 2026-09-29: «У НАС СИСТЕМА ИГРЫ ЧТО ЕСТЬ СКВАДЫ С АНКЕТАМИ И ЭТО ВСЁ и
// поэтому смена сквада это просто смена флажка»; и 2026-10-12: «игрок это
// не более чем тип/флаг который получает инпут»). Ровно один слот с 1 на
// КАЖДЫЙ из двух битов — инвариант держат двери ниже; GameState несёт КЭШИ
// (playerFlagRef/playerSquadRef), будущий стратегический скролл сквадов —
// ещё один звонящий той же двери.

// Обёртка флажка шириной в байт, а не голый u8: селектор колонки store_col
// ключуется ТИПОМ (одна колонка — один тип, список один), и второй голый
// u8 рядом с dead был бы переопределением специализации.
//
// ДВА БИТА — ДВА РАЗНЫХ ВОПРОСА, И ЭТО НЕ ДВА ОТВЕТА НА ОДИН (DOD п.6):
//  · on   — «КЕМ Я НА КАРТЕ СЕЙЧАС». ДВИЖЕТСЯ: на вселённого лорда, домой
//           при пробуждении. Дверь — transfer_player_flag.
//  · home — «КТО ОРИГИНАЛ», обратный адрес одержимости и признак «это ЕГО
//           запись» для свипа, рисовки, владения листом. НЕ ДВИЖЕТСЯ: ставится
//           один раз при рождении. Дверь — mark_player_home.
// Жили они порознь и неровно: `on` колонкой, а «кто оригинал» —
// ЗАРЕЗЕРВИРОВАННЫМ ОРДИНАЛОМ-ЛИТЕРАЛОМ 0x7FFFFFFF (ecs::kPlayerSquadOrdinal,
// M-255), из-за которого игрок был единственной сущностью мира с
// идентичностью-литералом, а загрузка искала его дом СКАНОМ по ординалу.
// Оба оправдания литерала были пусты: столкновения не бывает и без резерва
// (эмитент nextMacroSpawnOrdinal монотонен и ординалы не переиспользует), а
// «найти его после загрузки» делает колонка. Теперь ординал игрока выдаёт
// тот же эмитент, что всякому скваду, а оба вопроса стоят колонками рядом.
struct PlayerFlag {
    std::uint8_t on;
    std::uint8_t home;
};

