// разошлась с оригиналом на `c191fa06` (2026-09-28, M-162): снос `viewSize`
// прошёл по шейдеру и по игре и НЕ ПРОШЁЛ по харнессу, а позже добавленные
// `mapStyle` и `navView` вернули обеим раскладкам один и тот же РАЗМЕР — 56
// байт. Поэтому `static_assert(sizeof(Push) == 56)` харнесса молчал 41 день,
// хотя всё от `zoom` и ниже было сдвинуто на 8 байт: шейдер читал бы `zoom`
// из ширины кадра, а `navView` — из `elapsed`, то есть отладочный вид полей
// навигации включался бы сам через секунду после старта.
//
// УРОК, КОТОРЫЙ ЭТОТ ФАЙЛ И ЕСТЬ: `static_assert` над СВОЕЙ копией — это
// константа против своего же литерала (§8 п.4), и власти над чужим
// артефактом у неё нет. Единственная форма, в которой «байт в байт»
// невыразимо нарушить, — ОДИН тип: харнесс пушит ровно ту структуру, что
// игра. GLSL остаётся отдельным артефактом, и его согласие держат два
// свидетеля сразу: `sizeof` ниже (размер) и построение пайплайна в самом
// gpu_smoke на ШИПУЕМОМ шейдере (валидатор Vulkan ругается на несовпадение
// размера push-блока), — но разъехаться ДВУМ НАШИМ написаниям больше негде,
// потому что написание одно.
//
// Цена включения O(1) по капам мира (§5 п.13): один POD, ноль тел, ноль
// зависимостей кроме размерного контракта.
#pragma once

#include <cstddef>

namespace sm {

// std140/std430 push-constant block — must match shaders/macro.frag `Push`.
struct MacroPush {
    // `viewSize` стоял здесь вторым именем ОДНОЙ величины: и он, и
    // `resolution` получали `ext.width/height`, а шейдер делил на первое,
    // чтобы умножить на второе. Параллельные константы одной величины
    // сводятся к одной (ЗАКОН КОНСТАНТ), выжил делитель `gl_FragCoord` —
    // он честно называет кадровый буфер. Снос поля из СЕРЕДИНЫ блока
    // безопасен именно потому, что ниже всё заполняется ПО ИМЕНИ: пропуск
    // не компилируется, а не связывается молча (шрам сессии 31).
    float resolution[2];
    float mapSize[2];
    float cam[2];
    float zoom;
    float seaLevel;
    float seed;
    float timeOfDay;
    float nightDarken;
    float elapsed;  // real seconds — drives haze flow / water shimmer
    float mapStyle; // 0 = the living world; 1 = the CHART (map page document)
    // ОТЛАДОЧНЫЙ ВИД ПОЛЕЙ НАВИГАЦИИ: 0 = мир, 1 = КАТЕГОРИЯ, 2 = СКАЛЯР.
    // Шейдеру передаётся способ РАСКРАСКИ, а не смысл величины (смысл знает
    // только `encode_nav_field` в `vk_macro_renderer.cpp`) — иначе имя
    // подсистемы мира попало бы в рендер, а поток обязан идти строго вниз.
    float navView;
};

// 24 байта трёх vec2 + 8 скаляров по 4 = 56. Число стоит ОДИН раз и рядом со
// структурой, потому что оно есть факт РАСКЛАДКИ, а не настройка.
static_assert(sizeof(MacroPush) == 56,
              "push-блок macro.frag — 56 Б; правка полей обязана править и "
              "shaders/macro.frag, иначе шейдер читает чужие байты");

}  // namespace sm
