// ИНТЕРЕСЫ СУБЪЕКТА — ОДИН РЕЕСТР НА ВСЕ СВЯЗИ МАКРОМИРА.
//
// Вердикт владельца 2026-09-21, дословно: «давай универсально у всех
// макро-сквадов универсально будет система какая-то ИНТЕРЕСЫ (это другие
// сквады) — там могут быть и вассальная; в будущем будут друзья-лорды или
// наоборот враги, и как раз они могут все храниться в этом реестре»; и
// отдельно: «эту систему отношений тогда в принципе можно вассальную
// феодальную систему ввести к ней — тогда отдельная феодальная система не
// нужна, она будет частным случаем отношений».
//
// ЧТО ЭТО ЗАМЕНЯЕТ. Феодальное ребро было ПОЛОВИНОЙ системы отношений,
// написанной отдельно: у места стояла одна колонка «кому я плачу»
// (suzerainLandmarkId), а вторая половина канона S24 — «каждый узел знает
// прямых подчинённых» — существовала как отдельный производный индекс
// vassalHead/vassalNext, у которого не случилось ни одного читателя
// (problems §55). Здесь обе половины — одна таблица, и писатель у них один.
//
// ── ФОРМА: 8 БАЙТ, ЧЕТЫРЕ ВОПРОСА, НИ ОДНОГО ЛИШНЕГО ──────────────────────
// Форма согласована с владельцем построчно 2026-09-21; ниже записано, что
// было отвергнуто и почему, чтобы следующий не «дополнил» её обратно.
//
//   КТО     `object` — ординал субъекта;
//   ТИП     `stance` — чем он мне приходится (роль в структуре);
//   СИЛА    `value`  — насколько отношение крепкое, −127…127;
//   СРОК    `term`   — сколько дней ему осталось, 0 = бессрочно.
//
// ОТВЕРГНУТО И ПОЧЕМУ:
//   • колонка `kind` («чьё это пространство ординалов: место или сквад») —
//     владелец: «если у нас ландмарки и сквады сливаются в одну систему, то
//     выглядит, что не нужно». Она и есть плата за НЕДОСЛИТОСТЬ: сегодня
//     Landmark::id и MacroSpawnId::index — два независимых счётчика, и
//     колонка узаконила бы это расхождение. Пока в реестре одни МЕСТА,
//     ординал однозначен сам по себе. УСЛОВИЕ, ПОД КОТОРЫМ ЭТО ОСТАЁТСЯ
//     ВЕРНЫМ (problems §56): сквад входит в реестр ТОЛЬКО после слияния
//     пространств ординалов — иначе ординалы столкнутся молча;
//   • колонка `detail` («долг, обещание, цена вопроса») — не отвечает ни на
//     один названный вопрос: долг дани лежит по ПОЗИЦИЯМ товаров
//     (titheOwedGoods[15]), и одним int32 он не выражается. Владелец:
//     «детали убрать, это мутное»;
//   • колонка `sinceDay` («с какого дня это отношение») — это ИСТОРИЯ, а на
//     неё уже отвечает летопись (chronicle.h: WorldFact несёт субъект,
//     объект и день). Владелец: «а сама дата, когда это было сделано, — это
//     в истории». Вместо неё взят СРОК, см. ниже;
//   • значения `Friend`/`Enemy` как отдельные ТИПЫ рядом с отрицательной
//     силой — это был бы второй ответ на один вопрос (S26). Тип отвечает
//     «кем приходится», сила — «насколько»; вражда и дружба различаются
//     ЗНАКОМ силы, а тип у них может быть один.
#pragma once

#include <cstdint>

namespace sm {

// ── ЗАКОН ДИАПАЗОНА (владелец, 2026-09-21) ───────────────────────────────
// Дословно: «про −100…100 это ОШИБКА, надо −127…127, очевидно, иначе не весь
// диапазон; у нас везде степени двойки и все диапазоны». Граница шкалы
// берётся по ГРАНИЦЕ ТИПА, а не по круглому десятичному числу: «сто»
// выглядит осмысленно и не значит ничего, а 127 — это ровно то, что несёт
// байт. Закон записан в CANON S26 и распространяется на всякую шкалу мира.
//
// ШКАЛА СИММЕТРИЧНА, И ЭТО СТОИТ ОДНОГО ЗНАЧЕНИЯ. int8 даёт −128…127;
// зеркальность «настолько же враг, насколько друг» важнее лишней единицы,
// поэтому силой считается только −127…127.
// `−128` ЗАРЕЗЕРВИРОВАН ВЛАДЕЛЬЦЕМ под особое значение («будем для чего-то
// особого использовать»), и смысл ему ещё НЕ НАЗНАЧЕН. Это не «свободный
// байт»: не занимать его без вердикта и не «чинить» асимметрию шкалы.
inline constexpr int kRelationMax = 127;
inline constexpr int kRelationMin = -kRelationMax;
inline constexpr int kRelationReserved = -128;
static_assert(kRelationMin == -127 && kRelationMax == 127,
              "шкала отношений симметрична по границе int8 (владелец)");

// ТИП ОТНОШЕНИЯ. Значения заводятся ТОЛЬКО вместе со своим читателем
// (AGENTS §9) — вердикт владельца того же дня: «только те, у кого сегодня
// есть читатель». Друзья и враги придут своей механикой; их место здесь
// занято не будет, пока они не появятся.
enum class Stance : std::uint8_t {
    None = 0,   // пустая запись — и ТОЛЬКО она: занятые лежат плотно
    // Феодальная пара. Хранится С ОБОИХ КОНЦОВ (CANON S24: «каждый узел
    // знает ТОЛЬКО прямых подчинённых и сюзерена») и пишется ОДНОЙ дверью,
    // которая ставит зеркальную роль сама, — как RelationMatrix держит свою
    // симметрию одним set_relation. Именно отсутствие такой двери и оставило
    // канон S24 недостроенным на год.
    Suzerain,   // этот субъект — МОЙ сюзерен: я плачу ему дань
    Vassal,     // этот субъект — МОЙ вассал: я собираю с него дань
};

// Зеркало типа: чем Я прихожусь тому, кому ОН приходится вот этим.
inline constexpr Stance mirror_stance(Stance s) {
    switch (s) {
    case Stance::Suzerain: return Stance::Vassal;
    case Stance::Vassal:   return Stance::Suzerain;
    case Stance::None:     break;
    }
    return Stance::None;
}

struct Interest {
    // КТО. Ординал субъекта; см. отвергнутую колонку `kind` в шапке —
    // пространство сегодня одно, потому что в реестре одни места.
    std::int32_t  object = -1;
    // СРОК В ДНЯХ — счётчик, а не дата (владелец: «СРОК, типа в днях, очень
    // чисто, как counter, просто число дней, и оно меняется со временем,
    // может например подниматься — то есть дни как РЕСУРС; это сразу и
    // перемирие, и контракты»).
    //
    // 0 = БЕССРОЧНО. И это не исключение в законе тика, а его следствие:
    // тикают только ненулевые, а запись, чей срок дотикал до нуля, СНИМАЕТСЯ
    // в тот же миг. Поэтому у живой записи ноль не может ВОЗНИКНУТЬ — он
    // только присваивается вечной связи. Владелец назвал эту ловушку сам
    // («чтобы перемирие, которое 1, потом 0, не стало вечным»); ветки
    // «если вечное — не убавляй» здесь нет, а значит нет и правила с
    // исключением.
    std::uint16_t term = 0;
    std::uint8_t  stance = std::uint8_t(Stance::None);
    // СИЛА — «насколько отношение приоритетно и влияет контекстно на
    // поведение» (владелец). Читатель придёт своей механикой: названный
    // владельцем пример — «крепкий вассал платит больше дань», и это
    // расширение ЯВНО отложено («можно расширяемо НЕ СЕЙЧАС»).
    std::int8_t   value = 0;
};
static_assert(sizeof(Interest) == 8,
              "запись интереса — 8 Б ровно: 8 штук в кеш-линию, ноль дырок");

// Сколько связей субъект держит одновременно. ЧИСЛО НАЗВАНО ВЛАДЕЛЬЦЕМ
// 2026-09-21 («128 — это отлично»), а не выведено: у места вассалов бывает
// полтора десятка, остальное — запас под друзей и врагов замысла.
inline constexpr int kMaxInterests = 128;

// ХРАНЕНИЕ ПЛОТНОЕ И БЕЗ СЧЁТЧИКА — идиом Inventory (256 слотов, счётчика
// нет): занятые записи лежат подряд от нуля, первая пустая закрывает обход.
// Снятие затыкает дыру последней занятой, поэтому дырок не бывает вовсе.
struct Interests {
    Interest slots[kMaxInterests]{};
};
static_assert(sizeof(Interests) == kMaxInterests * 8,
              "реестр = 1024 Б на субъект: 32 МиБ по капу мест (AGENTS п.10)");

// Сколько связей занято: обход до первой пустой — дырок в форме нет.
inline int interests_count(const Interests& r) {
    int n = 0;
    while (n < kMaxInterests
           && r.slots[n].stance != std::uint8_t(Stance::None)) {
        ++n;
    }
    return n;
}

// Найти связь с этим субъектом; nullptr — связи нет.
inline Interest* interest_find(Interests& r, int object) {
    for (int i = 0; i < kMaxInterests; ++i) {
        if (r.slots[i].stance == std::uint8_t(Stance::None)) break;
        if (r.slots[i].object == object) return &r.slots[i];
    }
    return nullptr;
}
inline const Interest* interest_find(const Interests& r, int object) {
    return interest_find(const_cast<Interests&>(r), object);
}

// Поставить или обновить связь ОДНОГО конца. Зеркальный конец ставит дверь
// уровня мира (state.h) — здесь её нет намеренно: эта единица трансляции
// знает форму, но не знает, где живут другие субъекты.
// Возвращает false, только если реестр полон, — и это честный отказ,
// а не тихая потеря связи.
inline bool interest_set(Interests& r, int object, Stance stance,
                         int value, int term) {
    if (object < 0 || stance == Stance::None) return false;
    const std::int8_t v = std::int8_t(
        value < kRelationMin ? kRelationMin
                             : (value > kRelationMax ? kRelationMax : value));
    const std::uint16_t t = std::uint16_t(term < 0 ? 0 : (term > 0xFFFF
                                                          ? 0xFFFF : term));
    if (Interest* slot = interest_find(r, object)) {
        slot->stance = std::uint8_t(stance);
        slot->value = v;
        slot->term = t;
        return true;
    }
    const int n = interests_count(r);
    if (n >= kMaxInterests) return false;
    r.slots[n] = Interest{object, t, std::uint8_t(stance), v};
    return true;
}

// Снять связь: дыру затыкает последняя занятая запись (плотность — часть
// формы, на ней стоит обход «до первой пустой»).
inline bool interest_clear(Interests& r, int object) {
    Interest* slot = interest_find(r, object);
    if (!slot) return false;
    const int last = interests_count(r) - 1;
    *slot = r.slots[last];
    r.slots[last] = Interest{};
    return true;
}

// ДЕНЬ СРОКА. Зовётся раз в день на субъект: ненулевой срок убавляется, и
// дотикавшая до нуля связь СНИМАЕТСЯ — см. закон в комментарии к `term`.
// Возвращает число снятых связей (звать его некому, пока сроков в мире нет;
// дверь существует вместе со своим законом, а не вместо него).
inline int interests_tick_day(Interests& r) {
    int expired = 0;
    for (int i = interests_count(r) - 1; i >= 0; --i) {
        if (r.slots[i].term == 0) continue;          // бессрочная
        if (--r.slots[i].term != 0) continue;
        interest_clear(r, r.slots[i].object);
        ++expired;
    }
    return expired;
}

}   // namespace sm
