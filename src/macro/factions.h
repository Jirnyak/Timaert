// ── СТРОКА ФРАКЦИИ ───────────────────────────────────────────────────────
struct FactionRow {
    // Плоские чары; 24 длиннее любого id реестра (прецедент прежнего
    // kMaxIdLen). Пустая строка = слот не занят.
    char id[24] = {};
    // Цвет реестра (ARGB) — колонка строки, чтобы будущая рантайм-фракция
    // несла свой цвет тем же местом, что реестровая.
    std::uint32_t color = 0;
    // ОТНОШЕНИЯ — КОЛОНКОЙ СВОЕЙ СТРОКИ (вердикт: «каждая фаркция хранит
    // отношения с другими»). Одна шкала мира -127..127 (граница ТИПА);
    // симметрия — ЗАКОН: пишет только set_relation, обе строки разом.
    std::int8_t rel[kMaxFactions] = {};
    std::uint8_t used = 0;
};
static_assert(sizeof(FactionRow) == 96,
              "24 id + 4 цвет + 64 отношений + 1 клеймо + 3 паддинга");

struct FactionState {
    FactionRow rows[kMaxFactions] = {};
    // Сезон, за который начисление дани уже прошло (-1 = никогда): один
    // штамп на мир, потому что граница сезона одна и проход один
    // (`tithe_daily_@src/macro/world_tick.cpp`).
    std::int32_t titheSeasonAssessed = -1;
};
static_assert(sizeof(FactionState) == 96 * 64 + 4,
              "строки (6144) + штамп сезона (4) = 6148 Б");

// ── ДВЕРИ СТРОК ──────────────────────────────────────────────────────────

// Заполнить реестровые строки. Зовётся при создании мира и после загрузки:
// скомпилированный реестр — истина id/цвета своих строк, сейв не может
// «разобъявить» фракцию, с которой игра собрана.
inline void claim_registry_rows(FactionState& f) {
    for (int i = 0; i < kFactionCount; ++i) {
        FactionRow& r = f.rows[i];
        std::snprintf(r.id, sizeof r.id, "%s", kFactionDefs[i].id);
        r.color = kFactionDefs[i].color;
        r.used = 1;
        r.rel[i] = std::int8_t(kRelationMax);   // сам себе — верх шкалы
    }
}

// Слот по id: только реестр (рантайм-имена уничтожены вердиктом).
inline FactionSlot faction_slot(const FactionState&, const char* id) {
    if (!id || id[0] == '\0') return kNoFactionSlot;
    const int reg = faction_index(id);
    return reg >= 0 ? reg : kNoFactionSlot;
}

// Отношение по слотам — горячая форма: два чтения массива, ноль строк.
inline int relation_of(const FactionState& f, FactionSlot a, FactionSlot b) {
    if (a < 0 || b < 0 || a >= kMaxFactions || b >= kMaxFactions) {
        return 0;     // fail-closed: неразмещённая фракция нейтральна
    }
    if (a == b) return kRelationMax;   // верх шкалы, а не круглое число
    return int(f.rows[a].rel[b]);
}

// ВРАЖДЕБНОСТЬ ПО СЛОТАМ — ОДИН ПОРОГ НАД ОДНОЙ МАТРИЦЕЙ, И ОН ВЫПИСАН
// ЗДЕСЬ, рядом с матрицей, которую судит. Внутри симуляции живут только
// числа (ЗАКОН СЛОВАРЯ), поэтому горячий вопрос «враг ли он» задаётся
// ОРДИНАЛАМИ: два чтения массива, ноль строк. Строковая форма
// (`factions_hostile@src/macro/state.h`) переводит имя в ординал на ГРАНИЦЕ и
// делегирует сюда — порог живёт в дереве однажды, а не дважды.
//
// Крайние значения отвечает сам `relation_of`, второй ветки им не нужно:
// слот вне реестра (включая `kNoFaction` = 0xFFFF) даёт 0 — нейтрален, а
// сам себе даёт верх шкалы — своей фракции не враг никогда.
//
// ЗАПЕЧЁННОЙ КОПИИ ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО (вердикт владельца 2026-10-21:
// «отношения фракций однозначно динамические и могут меняться»). Биты,
// снятые с матрицы заранее, отвечали бы прошлым отношением — а матрица
// стоит одного чтения байта, то есть экономить на ней нечего.
inline bool factions_hostile(const FactionState& f, FactionSlot a,
                             FactionSlot b) {
    return relation_of(f, a, b) < kHostileThreshold;
}

// Симметричная запись — ЕДИНСТВЕННЫЙ способ сдвинуть отношение: одна дверь
// пишет ОБЕ строки, невзаимного отношения народов не бывает (вердикт «у
// фракций все равны и чистая симметрия»).
inline void set_relation(FactionState& f, FactionSlot a, FactionSlot b,
                         int value) {
    if (a < 0 || b < 0 || a >= kMaxFactions || b >= kMaxFactions || a == b) {
        return;
    }
    // Одна шкала мира: кламп по границе ТИПА (страж упаковки в int8).
    const int v = value < kRelationMin ? kRelationMin
                                       : (value > kRelationMax ? kRelationMax
                                                               : value);
    f.rows[a].rel[b] = std::int8_t(v);
    f.rows[b].rel[a] = std::int8_t(v);
}

// СДВИГ ОТНОШЕНИЯ ПО ОРДИНАЛАМ — ЕДИНСТВЕННАЯ ДВЕРЬ ПОСТУПКА (вердикты
// владельца 2026-11-03, дословно: «да это надо обобщить … потому что игрок
// ничем не особенен»; «любой воплощённый аватар сквада (игрок частный случай)
// будет менять репутацию в матрицы фракий (его и чужая)»).
//
// ЗАПИСЬ ПАРНАЯ, А АСИММЕТРИЧЕН ЗДЕСЬ АКТ. Отношения фракций СИММЕТРИЧНЫ по
// закону — «у фракций все равны и чистая симметрия», — и пишет обе строки
// одна дверь (`set_relation` выше). Асимметрия живёт в ПОСТУПКЕ, и это
// тоже слова владельца: «фракция не может бить сама никого но она владеет».
// Поэтому стороны здесь названы АКТОРОМ (чей аватар ударил) и ВЛАДЕЛЬЦЕМ
// задетого (чьё знамя носил тот, кого задели), хотя число ложится одно на обе
// строки: имена сторон объясняют, КТО спросил, а не что у отношения две
// половины. Второго числа «моё к нему» у пары не существует.
//
// СВОЙ ОТКАЗ У ЭТОЙ ДВЕРИ РОВНО ОДИН — НУЛЕВОЙ СДВИГ НЕ ПОСТУПОК, и его не
// судит больше никто. Два ОСТАЛЬНЫХ отказа здесь НЕ ПОВТОРЯЮТСЯ сознательно:
// и ординал вне реестра (включая `kNoFaction` и всякий протухший байт), и
// пару «сам себе» отвергают УЖЕ ОБА конца этой строки — чтение
// (`relation_of`: вне реестра 0, диагональ — верх шкалы) и запись
// (`set_relation`: тот же предикат перед обеими колонками). Дублировать их
// тут значило бы завести второй ответ на один вопрос (DOD п.6), а стоит он
// там, где живёт сама матрица: это свойство МАТРИЦЫ, а не поступка. Цена
// отказа названа: одержимый лорд, ударивший своего же земляка, фракцию с
// собой не ссорит, и держит это диагональ, а не гейт поступка.
//
// ЗАМЕР, НАЗВАВШИЙ ДУБЛЬ ЧИСЛОМ (мутации свидетеля `avatar_standing_test`):
// снос гейта ЗДЕСЬ — зелёный 30/30, снос `a == b` в `set_relation` — тоже
// зелёный 30/30, снос ОБОИХ — КРАСНЫЙ 2/30. То есть нужен ровно один, и
// наблюдаемого различия между ними нет — выбор дома решён законом, не вкусом.
inline void add_faction_standing(FactionState& f, FactionSlot actor,
                                 FactionSlot owner, int delta) {
    if (delta == 0) return;
    set_relation(f, actor, owner, relation_of(f, actor, owner) + delta);
}

