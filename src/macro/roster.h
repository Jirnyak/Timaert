#pragma once

#include "macro/commodity.h"   // kCommodityCount — ширина счёта харча

#include <cstdint>

namespace sm {

// СЛИЯНИЕ M-71 (2026-09-24): существа больше НЕ живут здесь — они лежат
// строками мира в ЕДИНОМ контейнере владельца (Inventory, закон двух
// областей — items.h; двери — macro/world_row.h). Ростер остался ОБВЯЗКОЙ
// СЧЕТОВ над тем же контейнером: кто здесь есть — спрашивают у контейнера
// (creature_heads / creature_heads_range / души по entityId != 0), чем
// владелец должен — здесь.
struct Roster {
    // ── СЧЁТ СОДЕРЖАНИЯ (CANON S10 «у всякого, кто кормит, есть счёт») ───
    // ХАРЧ — строка лестницы, поэтому он живёт в товарных ординалах и
    // гасится ТОЙ ЖЕ дверью econ_pay_debt, что счёт места: добыча привезла —
    // часть съелась в тот же день.
    std::int32_t needDebt[kCommodityCount] = {};
    // ПЛАТА — стоимость, у неё своя колонка и своя дверь (pay_value_dense),
    // и платится она ЧАСТИЧНО: кромка «всё или ничего» умерла вместе с 1/8.
    std::int64_t wageDebt = 0;
};
// РАЗМЕР ЗАКРЕПЛЁН (AGENTS п.10): счёт харча 15 × 4 = 60 + выравнивание 4 +
// плата 8. Слоты существ (3 076 Б) уехали в единый контейнер слиянием M-71.
static_assert(sizeof(Roster) == 72,
              "ростер = счёт харча (60 + пад 4) + плата (8)");

} // namespace sm
