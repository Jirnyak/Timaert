#pragma once

#include "macro/army.h"        // SoldierSquad — инвентарь существ
#include "macro/commodity.h"   // kCommodityCount — ширина счёта харча

#include <cstdint>

namespace sm {

struct Roster {
    // КТО ЗДЕСЬ ЕСТЬ. Стакуется по закону предметов (S4): одинаковое в один
    // слот, скрученное — в свой. Место, армия, артель, пул и игрок носят
    // ОДИН этот контейнер.
    SoldierSquad squad{};
    // ── СЧЁТ СОДЕРЖАНИЯ (CANON S10 «у всякого, кто кормит, есть счёт») ───
    // ХАРЧ — строка лестницы, поэтому он живёт в товарных ординалах и
    // гасится ТОЙ ЖЕ дверью econ_pay_debt, что счёт места: добыча привезла —
    // часть съелась в тот же день.
    std::int32_t needDebt[kCommodityCount] = {};
    // ПЛАТА — стоимость, у неё своя колонка и своя дверь (pay_value_dense),
    // и платится она ЧАСТИЧНО: кромка «всё или ничего» умерла вместе с 1/8.
    std::int64_t wageDebt = 0;

    int souls() const { return squad.size(); }
    bool empty() const { return squad.empty(); }
};
// РАЗМЕР ЗАКРЕПЛЁН (AGENTS п.10). Это ВТОРАЯ по весу структура мира после
// инвентаря: 3 144 Б несёт и каждый сквад, и каждое место (гарнизон = тот же
// ростер), то есть 49 МиБ по капу сквадов + 98 МиБ по капу мест. Почти всё —
// `slots[256]` (3 076 Б), и они лежат целиком даже у сквада-одиночки: это
// НАМЕРЕННАЯ форма (AGENTS п.2), а не недосмотр.
static_assert(sizeof(Roster) == 3144,
              "ростер = 256 слотов (3076) + счёт харча (60) + плата (8)");

} // namespace sm
