// Здесь лежит ФОРМА, а не закон: инвентарь существ плюс его счёт содержания.
// Суд границы сезона — одна дверь на все ростеры мира, и он живёт отдельно
// (macro/roster_window.h), чтобы этот заголовок оставался лёгким: его тянет
// ecs/components.h, то есть почти каждая единица трансляции игры.
//
// ЧТО ЭТИМ УБИТО (2026-09-21): у места стояли `garrison` + `garrisonDebt` +
// `garrisonWageDebt`, у сквада — `squad` + `needDebt` + `wageDebt`, поле в
// поле одно и то же, и ДВЕ копии закона над ними. Копии уже разошлись в
// четырёх местах (кто считается ртом, полцены дома, скидка фуражира, и
// гарнизон дезертировал МОЛЧА — мимо ведомости душ). Второй ответ на один
