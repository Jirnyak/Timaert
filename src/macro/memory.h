// ПАМЯТЬ МИРА — ОДНА ДВЕРЬ, ОДИН ГОРИЗОНТ (CANON S19.2, владелец 2026-09-21).
//
// У мира есть величины, которые ПОМНЯТ и забывают: средний склад, под который
// начисляется дань; поле угрозы, копящее чужие смерти; поле запаха, копящее
// следы. До этой двери каждая помнила по-своему — свой горизонт (сезон / 8
// дней / 4 дня) и своё НАПИСАНИЕ: разностная EMA у дани, «полураспад раз в N
// дней» у полей. Два написания одного закона — ровно то, что запрещает S26.
//
// ── ГОРИЗОНТ ОДИН, И ОН РАВЕН СЕЗОНУ ─────────────────────────────────────
// Владелец, дословно: «всё в 1 сезон, не надо херни — мы снова усложним;
// лучше всё сезонами делить». Довод не в опрятности: сезон — это такт
// ПЕРЕНОРМИРОВКИ и ИТОГА («что за эти 32 дня накопилось и произошло в мире,
// типа веха»), поэтому память мира И ЕСТЬ накопленное за веху. Горизонт не
// выбран рядом с сезоном — он сезону РАВЕН, и долей у него нет.
//
// Отсюда же смерть второго написания: форма «полураспад раз в N дней» сезон
// выразить НЕ МОЖЕТ. Память = 1.44 × полураспад, значит «память ровно сезон»
// просит полураспада 22 дня, а 22 не делит 32 — поле поехало бы по фазе
// относительно границы, и ответ зависел бы от того, в какой день спросили.
// Дневной шаг с горизонтом 2^5 дней такого недостатка не имеет: вся лестница
// времени мира степень двойки (день 2^13 тиков, сезон 2^5 дней, год 2^2
// сезона), поэтому шаг точен, а фаза не уезжает никогда.
//
// ── ПАМЯТЬ ХРАНИТСЯ ПРЕДМАСШТАБИРОВАННОЙ, И ЭТО ЗАКОН ────────────────────
// Величина в поле — это значение, УМНОЖЕННОЕ на горизонт; наружу она выходит
// сдвигом. Иначе целочисленный шаг от разницы, меньшей горизонта, равен нулю,
// и у памяти появляется МЁРТВАЯ ЗОНА размером в горизонт: она молчит и при
// этом выглядит работающей.
//
// ЦЕНА ЭТОГО ЗАКОНА УЖЕ ЗАПЛАЧЕНА ТРИЖДЫ — все три поймано 2026-09-21:
//   · дань: склад мельче 32 единиц держал среднее РОВНО НОЛЬ вечно, то есть
//     вся лестница комфорта не облагалась никогда (в мире 21 инструмент на
//     1860 мест), а реальная ставка вместо 1/8 была 0 % у мелких и 12.1 % у
//     крупных — «1/8 со всего» в каноне было неправдой;
//   · поле угрозы: округа со слабой угрозой не диффундировала НИКОГДА
//     (`per = (t>>3)/deg` обнулялся при t < 8·deg);
//   · поле запаха: слабый след не расползался (`per` обнулялся при t < 64).
// Ни один из трёх не выглядел поломкой: поле жило, значения менялись, тесты
// были зелёными. Мёртвая зона — это молчание, а не падение.
//
// ── ДВА ГЛАГОЛА ВХОДА, И ПУТАТЬ ИХ НЕЛЬЗЯ ────────────────────────────────
// Ядро одно, входа два, и они отвечают на РАЗНЫЕ вопросы о мире:
//   · СЛЕЖЕНИЕ (memory_track) — на входе УРОВЕНЬ: склад, цена, население.
//     Память сходится к уровню и отвечает «чем ты обычно располагаешь».
//   · НАКОПЛЕНИЕ (memory_accumulate) — на входе ИМПУЛЬС: смерть, след,
//     сделка. Память сходится к «темп источника × горизонт» и отвечает
//     «сколько всего случилось недавно».
// Математически это одно: track(x) ≡ accumulate(x / горизонт). Именно
// поэтому дверь ОДНА — но глагол обязан называться, иначе следующий читатель
// скормит уровню импульсную форму и получит величину в 32 раза не ту.
#pragma once

#include <cstdint>

#include "macro/seasons.h"   // kDaysPerSeason — горизонт всякой памяти мира

namespace sm {

// Горизонт памяти = сезон. Не «примерно сезон» и не «сезон/4»: см. закон выше.
inline constexpr int kMemoryHorizonDays = kDaysPerSeason;
inline constexpr int kMemoryShift = 5;
static_assert(1 << kMemoryShift == kMemoryHorizonDays,
              "горизонт памяти мира ЕСТЬ сезон, и сдвиг обязан быть его "
              "логарифмом — иначе предмасштабирование врёт в 2^k раз");

// Хранимая память. ШИРИНА ПО РАСЧЁТУ (ЗАКОН ТИПА): поле держит значение,
// умноженное на 32, а самое крупное значение мира — счёт предмета на складе
// (std::int32_t, потолок 2.1e9). 2.1e9 × 32 = 6.8e10 в int32 не помещается
// по построению, значит 64 бита здесь не запас «на всякий», а арифметическая
// необходимость. Знаковая: шаг слежения — ВЫЧИТАНИЕ, и у падающего уровня
// разница законно отрицательна.
using WorldMemory = std::int64_t;

// СЛЕЖЕНИЕ за уровнем: память подтягивается к сегодняшнему значению на
// 1/горизонт разницы. Равновесие — ровно уровень (без смещения вниз, которое
// давала непредмасштабированная форма).
inline void memory_track(WorldMemory& mem, std::int64_t level) {
    mem += level - (mem >> kMemoryShift);
}

// НАКОПЛЕНИЕ импульсов: сегодняшний импульс входит целиком, вчерашний
// забывается на 1/горизонт. Равновесие — «темп × горизонт».
inline void memory_accumulate(WorldMemory& mem, std::int64_t impulse) {
    mem += (impulse << kMemoryShift) - (mem >> kMemoryShift);
}

// Значение памяти наружу. Единственный законный способ её прочитать: сырое
// поле — это значение × горизонт, и всякий, кто сравнит его с величиной мира
// напрямую, ошибётся ровно в 32 раза.
inline std::int64_t memory_value(WorldMemory mem) {
    return mem >> kMemoryShift;
}

}  // namespace sm
