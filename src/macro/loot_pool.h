//
// Вердикт владельца 2026-09-28, дословно: «только чистая стоимость потом
// режиссёр будет уже сам решать типа есть таблица обхектов там у всего уже
// есть стоимость». Значит пул лута есть ОДНО ЧИСЛО — казна теневого мира, —
// а эта дверь есть его единственный расходный конец: ей дают БЮДЖЕТ и
// КОНТЕКСТ, она возвращает стаки и говорит, сколько стоимости потратила.
//
// ЧЕГО ЭТА ДВЕРЬ НЕ ЗНАЕТ, И ЭТО ЗАКОН АГНОСТИЧНОСТИ, А НЕ НЕДОДЕЛКА:
// чей это бюджет (казна пула, награда квеста, посев места), кто получатель
// (сундук, труп, сумка игрока) и в какой сцене дело. Слой выше — редактор:
// он решает СКОЛЬКО дать и КУДА положить, и держит эти числа у себя.
// Поэтому в сигнатуре стоит `int budgetValue`, а не `GameState&` и не
// `std::int64_t& pool`: списание казны делает тот, у кого казна.
//
// ГДЕ ЭТА ДВЕРЬ ЖИВЁТ И ПОЧЕМУ ЗДЕСЬ. Она есть функция над ОБЩЕЙ ТАБЛИЦЕЙ
// ОБЪЕКТОВ (AGENTS, ГЕНЕРАЛЬНАЯ СХЕМА: таблицы лежат по обе стороны и шиной
// НЕ едут), поэтому стоит рядом с таблицей. Макро-число она не читает ни
// одно — значит субмир, когда ПАКЕТНАЯ ШИНА принесёт ему казну родом 4,
// позовёт её, не заводя ни одной нитки в макромир.
#pragma once
#include "macro/anketa.h"

#include <cstdint>

namespace sm {

// КОНТЕКСТ ВЫДАЧИ — то, что говорят о МЕСТЕ выдачи системы мира.
//
// Растёт ПОЛЕМ, а не аргументом: погода, тёмное поле, живой склад места
// припишутся сюда, и ни одна сигнатура звонящего не изменится — та же
// идиома, что у `MacroWorld`. Это и была причина завести структуру вместо
// трёх аргументов (замысел владельца 2026-08-27: «контекст от таблицы мобов
// × зоны сложности (0..255) × богатство ландмарка/экономика, и расширяемо»).
//
// СЮДА ПЕРЕЕХАЛ `CorpseLootContext`, у которого во всём дереве не было ни
// одного читателя: он и был этой структурой, только осиротевшей — контекст
// без двери, которая его читает.
struct LootContext {
    // Байт опасности клетки (`macro/zones.h`, континуум 0..255) — РОД 3
    // пакета (поле над тором). Глухой угол мира платит богаче, и это не
    // погребённый автолевелинг CANON S12: множится то, что вещь СТОИТ, а
    // не тело, которое её несёт.
    std::uint8_t danger = 0;
    // Богатство места, стоящего на клетке (`landmark_registry` wealthMul;
    // 1.0 = чистое поле) — РОД 2 пакета (анкета сквада; место есть
    // неподвижный сквад).
    float wealthMul = 1.0f;
    // Уровень контекста — он же лестница дропа («существо уровня N сыплет
    // вещи ~того же уровня»). Все три колонки сходятся в ОДНОЙ двери силы
    // аффиксов (`affix_power`), второго вывода «насколько богата вещь» не
    // существует.
    int level = 0;
};

// ВЫДАТЬ ВЕЩЕЙ НА `budgetValue` СТОИМОСТИ. Возвращает ПОТРАЧЕННУЮ стоимость —
// ФАКТ, а не обещание (ЗАКОН ТРЁХ ДВЕРЕЙ ВЫЧИТАНИЯ, дверь `drain`: взять
// сколько есть и вернуть правду). Звонящий списывает со своей казны ровно
// возвращённое, поэтому стоимость сохраняется точно и при полном контейнере,
// и при пустом каталоге, и при нулевом бюджете.
//
// Потраченное всегда ≤ `budgetValue`: остаток, который режиссёр не сумел
// разместить, остаётся у звонящего, а не сгорает.
int loot_issue(int budgetValue, const LootContext& ctx, RngFn rng,
               Inventory& into);

} // namespace sm
