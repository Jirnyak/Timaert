// Распад: threat >>1 раз в N дней. 8 — стартовая ручка дубль-прогона:
// смерть крестьянина (30) гаснет в ноль за ~40 дней — чуть дольше интереса
// Died-строки летописи (32 дня), сезон страха на округу.
inline constexpr int kThreatDecayDays = 8;

// Диффузия: 1/8 значения округи в день уходит соседям, поровну на ребро
// (мембраны текут одинаково; изрезанная округа течёт сильнее — у неё больше
// мембран, и это физика, не баг).
inline constexpr int kThreatDiffusionShift = 3;

// Стоимость погибшей души — строка НАЙМА (upkeep × 30, npc.h): дом хоронит
// крестьян, и Died-факт несёт только счёт тел, так что душа оценивается
// гражданской строкой. Уточнение по родам погибших — если замер попросит.
inline int threat_soul_price() {
    return npc_def(NPCType::Peasant).hireGold;
}

// Угроза округи; 0 — поле пусто или округа вне графа (легальный ноль S6).
inline std::uint32_t threat_of(const NavWorld& nv, std::uint16_t region) {
    return std::size_t(region) < nv.threat.size()
               ? nv.threat[std::size_t(region)] : 0u;
}

// ХУДШАЯ округа маршрута from→to по пешей таблице routeNext — страх платит
// самый опасный перегон, не среднее. Цепочка ≤ 16 переходов (диаметр графа
// живых миров меньше; обрыв цепочки честно возвращает уже увиденный
// максимум).
inline std::uint32_t threat_on_route(const NavWorld& nv, std::uint16_t from,
                                     std::uint16_t to) {
    const std::size_t R = nv.regionLandmarkId.size();
    if (nv.threat.size() != R || std::size_t(from) >= R
        || std::size_t(to) >= R)
        return 0u;
    std::uint32_t worst = threat_of(nv, to);
    std::uint16_t r = from;
    for (int hop = 0; hop < 16; ++hop) {
        worst = std::max(worst, threat_of(nv, r));
        if (r == to) break;
        const std::uint16_t next = nv.routeNext[std::size_t(r) * R + to];
        if (next == kNavUnreached || next == r) break;
        r = next;
    }
    return worst;
}

