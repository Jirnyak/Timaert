// ── ЭТИ ДВЕРИ УЕДУТ В AI-МОДУЛИ РОДОВ, И ОБОБЩАТЬ ИХ ЗАПРЕЩЕНО ───────────
// Вердикт владельца 2026-10-06, дословно: «про паству ты снова какуюто шизу
// пишешь / замысел простой - ПО ТИПУ типаы уже есть и это будет в АИ модуле
// - город в аи модуле городу будет смо треть на поле фич своей клетки и там
// это число опля фич (единое поле ресурсов фич) ЭТО ПОПУЛЯЦИЯ ГОРОДА! по
// смыслу внтури его модуля!!! по анаолгии деревня тоже ЭТО DOD инкапсуляция
// агностичные модули НИКАКИХ ПАСТВ СИСТЕМ НЕТ РОСТ ГОРОДА ЭТО АИ МОДУЛЬ
// ГОРОДА! ТАКЖЕ КАК И ДЕРЕВНИ И ТД!»; и о классах: «у нас нет никаких
// неподвидных это просто сквады с анкетами».
//
// ЧТО ЭТО ЗНАЧИТ ЗДЕСЬ: общей системы населения над ВСЕМИ сквадами нет и не
// должно быть. Есть единое поле фич над миром, и СМЫСЛ числу задаёт ТОТ, КТО
// ЕГО ЧИТАЕТ: модуль города, глядя на число фичи СВОЕЙ клетки, читает его как
// свою популяцию, модуль артели этого вопроса себе не задаёт. Значит двери
// ниже — не «система мира», а СОДЕРЖИМОЕ модулей города и деревни, которое
// пока лежит общим кодом (эпик M-72/M-235, CANON «НЕПОДВИЖНЫХ НЕТ»).
//
// ОТСЮДА ПРЯМОЙ ЗАПРЕТ: НЕ ОБОБЩАТЬ их на подвижные роды. Подвижный сквад
// на клетке лишь СТОИТ, и число поля под ним — чужое: прочитать его как «его
// население» значит приписать коровану паству деревни, через которую он
// проходит. Лечится это не правкой двери, а её ПЕРЕЕЗДОМ в модуль; обобщить
// общую дверь значит укрепить ту самую «систему паствы», которой нет.
// (Прежде здесь стоял довод через колонку `bornPopBase` — она УНИЧТОЖЕНА
// вместе с гарнизоном, и довод, опирающийся на мёртвую колонку, был бы
// гниющим свидетелем: AGENTS ЗАКОН ИМЕНИ п.1.)
//
// ── ДУШИ МЕСТА: ДВА ВОПРОСА, ДВА НОСИТЕЛЯ (переворот населения, вердикты
// владельца 2026-09-30) ──────────────────────────────────────────────────
//   souls_home  — кто стоит ДОМА: ГОЛОВЫ в инвентаре места (стаками; один
//                 вид — один стак). Они едят со склада, стоят у станков, из
//                 них поднимаются сквады, ими место обороняется («оборона
//                 места = вся толпа — ЭТО НОРМАЛЬНО»). Человеческие души,
//                 не головы вообще: лошадь в стойле — имущество.
//   (ВТОРОЙ ДВЕРИ, `souls_flock`, БОЛЬШЕ НЕТ — надгробие ниже.)
// Колонка Landmark::population умерла с переворотом v122 у всех родов.
inline int souls_home(const MacroStore& st, std::uint16_t slot) {
    return count_human_souls(st.inventory[slot].inv);
}
// ── ЗДЕСЬ ЖИЛА `souls_flock`, И ОНА УНИЧТОЖЕНА КАК ЛИШНЯЯ СИСТЕМА ───────
//
// Вердикт владельца 2026-10-26: «да лишняя система сноси».
//
// ЧЕМ ОНА БЫЛА: мировой дверью, объявлявшей число поля фич под клеткой
// «паствой ЭТОГО СКВАДА». Её подпись брала СЛОТ — и в этом вся улика: она
// утверждала, будто у сквада есть атрибут популяции. Его нет. У сквада есть
// ИНВЕНТАРЬ (его люди — `souls_home` выше) и есть КЛЕТКА, под которой лежит
// число поля ресурсов фич (род 3).
//
// ПОЧЕМУ ЭТО БЫЛА СИСТЕМА, КОТОРОЙ НЕ ДОЛЖНО БЫТЬ (владелец, дословно):
// «сквады у нас все одинаковые по виду структуры на форме байтов, у них нет
// служебных битов костылей, где хранить например число популяции для закона
// роста, зато есть поля фич и закон агностичный что сквады могут двигаться /
// взаимодействовать / менять мир (работать) — вот поэтому через закон работы
// сквад может по своему модулю менять число поля фич под собой (например
// рост популяции)». Трёх систем — гладкий массив сквадов, поля фич, закон
// работы — достаточно; `souls_flock` была ЧЕТВЁРТОЙ.
//
// И ТОЛКОВАТЕЛЬ ЗАКОНЕН ТОЛЬКО ВНУТРИ МОДУЛЯ (владелец): «пришёл на фичу,
// там есть поле с числом, а поскольку тип фичи город и над ней стоит сквад
// город — то это его популяция, и я делаю из этого выводы в поведении своём
// — ЭТО ВСЁ ВНУТРИ МОДУЛЯ например другого сквад типа». Наружу, мировой
// дверью, такого толкователя быть не должно.
//
// ПЕРЕПИСЬ, НА КОТОРОЙ ВЫНЕСЕН ПРИГОВОР: **13 вызовов в `src/`**, и НИ ОДИН
// не спрашивал того, что дверь обещала. Все тринадцать читают ЧИСЛО ПОЛЯ ПО
// КЛЕТКЕ: два — закон работы (рост города в дне, выбор цели ходоком), два —
// ведомость стока и колонка пакета, четыре — представление, четыре —
// свидетель-смоук. Довод за снос поэтому НЕ «мало читателей», а «ни один
// читатель не спрашивает обещанного».
//
// ЧЕМ ЗАМЕНЕНА: `worked_read@src/macro/state.h` по КЛЕТКЕ — канонической
// дверью поля, чья собственная шапка говорит тот же закон («there is one of
// it, and the feature on the cell says what its number means»). Четырнадцатой
// двери не заведено ни одной. Повтор идиомы «клетка слота → число» на
// тринадцати сайтах ЗАКОНЕН прямо (DOD п.5: «модульность бьёт DRY, похожий
// код — НОРМА; дефект — СЦЕПЛЕНИЕ»), и когда придут модули родов (ломоть 5б,
// M-235), эти чтения ПЕРЕЕДУТ в них без изменения смысла — второй миграции
// семантики не будет.

// ── ПОСЕЛИТЬ ДУШИ — ОДНА ДВЕРЬ НА ВСЯКОЕ ИХ ПОЯВЛЕНИЕ (v122) ─────────────
// «Место получило души» есть ОДНО событие мира, а носителей у него ДВА:
// паства (worked-число фичи) и домашние головы (инвентарь). Писать их
// порознь значит завести двух писателей одной величины — и оно уже было
// написано порознь в пяти местах (генезис города, генезис деревни, шпиль,
// руина, рост дня, запись-назад субмира). Здесь они сходятся в одну строку.
//
// ВОЗВРАЩАЕТ ФАКТ: сколько душ реально ВСТАЛО. Контейнер вправе отказать
// (кап областей), и паства растёт ровно на вставших — иначе число копило бы
// призраков, которых ни одна дверь не найдёт.
//
// ЗДЕСЬ СТОЯЛА ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ РАЗВИЛКИ, И ОНА СНЕСЕНА С НЕЙ (M-320):
// «у данжа паства и есть головы, поэтому worked не трогается — под FT_Spire
// там живёт СПЕЛЛ». Утверждение было верным, но его субъект исчез: данж
// сквадом больше не является, и поселить души в шпиль некому. Заселение
// данжа — дело ЕГО СОБСТВЕННОГО модуля (CANON S28, механизм 2), а не этой
// двери; сюда приходят только сквады, у которых паства есть число их клетки.
inline int settle_souls(GameState& gs, MacroStore& st, std::uint16_t slot,
                        int souls) {
    if (souls <= 0) return 0;
    Inventory& store = st.inventory[slot].inv;
    const int stood = raise_flock_into_container(store, souls);
    if (stood > 0) {
        const auto& c = st.cell[slot];
        worked_add(gs, ecs::cell_x(c, gs.mapW), ecs::cell_y(c, gs.mapW),
                   stood);
    }
    return stood;
}

