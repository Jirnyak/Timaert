// ── ПОСЕЛИТЬ ДУШИ — ОДНА ДВЕРЬ НА ВСЯКОЕ ИХ ПОЯВЛЕНИЕ (v122) ─────────────
// «Место получило души» есть ОДНО событие мира, а носителей у него ДВА:
// паства (worked-число фичи) и домашние головы (инвентарь). Писать их
// порознь значит завести двух писателей одной величины — и оно уже было
// написано порознь в пяти местах (генезис города, генезис деревни, шпиль,
// руина, рост дня, запись-назад субмира). Здесь они сходятся в одну строку.
//
// ВОЗВРАЩАЕТ ФАКТ: сколько душ реально ВСТАЛО. Контейнер вправе отказать
// (кап областей), и паства растёт ровно на вставших — иначе число копило бы
// призраков, которых ни одна дверь не найдёт.
//
// ЗДЕСЬ СТОЯЛА ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ РАЗВИЛКИ, И ОНА СНЕСЕНА С НЕЙ (M-320):
// «у данжа паства и есть головы, поэтому worked не трогается — под FT_Spire
// там живёт СПЕЛЛ». Утверждение было верным, но его субъект исчез: данж
// сквадом больше не является, и поселить души в шпиль некому. Заселение
// данжа — дело ЕГО СОБСТВЕННОГО модуля (CANON S28, механизм 2), а не этой
// двери; сюда приходят только сквады, у которых паства есть число их клетки.
inline int settle_souls(GameState& gs, MacroStore& st, std::uint16_t slot,
                        int souls) {
    if (souls <= 0) return 0;
    Inventory& store = st.inventory[slot].inv;
    const int stood = raise_flock_into_container(store, souls);
    if (stood > 0) {
        const auto& c = st.cell[slot];
        worked_add(gs, ecs::cell_x(c, gs.mapW), ecs::cell_y(c, gs.mapW),
                   stood);
    }
    return stood;
}

// СКОЛЬКО ДУШ МЕСТО МОЖЕТ ДЕРЖАТЬ В ПОЛЕ — половина всех своих.
//
// Считается от ПАСТВЫ (дома + во всех сквадах места), а не от одного
// населения: «половина населения» по оставшимся дома сходилась бы к тому,
// что в поле рано или поздно уходят ВСЕ (половина от половины от половины —
// ряд сходится к единице), и «дома больше, чем в поле» переставало бы
// выполняться уже на третьем рейсе. По пастве это ровно одно и то же число в
// день, когда в поле нет никого, и честный потолок во все остальные дни.
inline constexpr int kFieldShareShift = 1;   // 1/2 — вердикт владельца
static_assert(kFieldShareShift == 1,
              "поле = половина паствы: число названо владельцем, а не выведено");

// `afield` — души ВСЕХ сквадов этого места (и стоящих дома, и ушедших),
// `standingSouls` — из них те, что стоят дома Idle: ими место распоряжается
// сегодня заново, поэтому они возвращаются в пул как свободные руки.
inline int field_pool(const GameState& gs, const MacroStore& st,
                      std::uint16_t slot, int afield, int standingSouls) {
    // Число поля фич под клеткой УЖЕ знает про ушедших (worked = дома + в
    // поле): слагаемое `afield` умерло, как и обещал его комментарий;
    // параметр остался мерой «уже в дороге». Читается ПО КЛЕТКЕ — M-320
    // снёс `souls_flock`, бравшую слот.
    const auto& fpc = st.cell[slot];
    const int flock = worked_read(gs, ecs::cell_x(fpc, gs.mapW),
                                  ecs::cell_y(fpc, gs.mapW));
    const int cap = flock >> kFieldShareShift;
    const int marched = afield - standingSouls;      // уже в дороге
    const int free = cap - marched;
    // Больше, чем есть свободных тел, не поднять ни при каком потолке.
    return std::clamp(free, 0, souls_home(st, slot) + standingSouls);
}

