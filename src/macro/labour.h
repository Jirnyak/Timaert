//
// ЧЕМ ОН БЫЛ: `field_pool` — мировая дверь, бравшая СЛОТ и объявлявшая число
// поля фич под его клеткой «паствой ЭТОГО СКВАДА», а затем применявшая к ней
// правило «половина может уйти в поле» (`kFieldShareShift`). Улика та же, что
// у снесённой M-320 `souls_flock`, и ровно в том же месте подписи: слот на
// входе есть утверждение, будто у сквада есть АТРИБУТ популяции. Его нет — у
// сквада есть инвентарь (`souls_home` выше) и есть клетка, под которой лежит
// число поля (род 3). Сверх того дверь ТОЛКОВАЛА это число наружу, мировым
// кодом, а толкователь законен только внутри модуля (владелец 2026-10-26).
//
// ПЕРЕПИСЬ, НА КОТОРОЙ ВЫНЕСЕН ПРИГОВОР: **НОЛЬ вызовов** — ни в `src/`, ни в
