// Вердикт владельца 2026-09-21 (CANON S4 «Рождение сквада — один закон, а не
// девять»): «нас пункт решает, сколько он может позволить людей в поле
// АБСТРАКТНО В ЦЕЛОМ, и потом из этого уже снаряжаются сквады»; мера названа
// дословно — «просто половину населения может поднять сквадами и всё».
//
// ПОЧЕМУ ПРОКОРМ В ЭТОТ СЧЁТ НЕ ВХОДИТ (владелец, тот же день): «прокорм
// вообще не надо считать, потому что уже система, что город тоже сквад, и
// прокорм в любом случае будет — в поле, не в поле, это уже не важно». Рот
// ест одинаково с обеих сторон границы места, поэтому склад решает, сколько
// душ ЖИВЁТ, а не где они стоят; взять его и сюда значило бы заплатить тем же
// харчем дважды — ровно тот «второй словарь», который канон запрещает (S26).
//
// ЧТО ЭТОТ ЗАКОН УБИВАЕТ, ПОИМЁННО:
//   • `pop >> labourShift` — доля с потолка, три разных прочтения в npc_ai;
//   • гейт отлучки «дома должно быть больше, чем в поле» — он и есть половина,
//     сказанная вторым голосом (следствие, а не отдельное правило);
//   • два литерала `20` в двух файлах (world_tick, npc_spawn) — их перевод
//     идёт своей порцией, дверь для них уже здесь.
// `labourShift` в реестре ОСТАЁТСЯ, но только для станков города — сколько
// душ стоит у верстака (kHeadsPerCityWorker), а это другой вопрос.
#pragma once

#include <algorithm>

#include "macro/npc.h"     // природа строки: кто есть народ (kNpcNature)
#include "macro/state.h"   // Landmark — чьи это души

namespace sm {

// ── ДУШИ МЕСТА: ДВА ВОПРОСА, КОТОРЫЕ МИР ЗАДАВАЛ ОДНИМ ЧИСЛОМ ────────────
// `Landmark::population` отвечает сегодня обоим, и половине читателей поэтому
// врёт. Вопросы разные:
//   souls_home  — кто стоит ДОМА: они едят со склада места, стоят у станков,
//                 из них набираются сквады, их считает спрос рынка;
//   souls_flock — ВСЯ паства места, включая ушедших в поле: ею меряется рост,
//                 размер города в субмире, потолок табуна и пул рук.
// Город, у которого полпаствы в артелях, сегодня РАСТЁТ как маленький и
// РИСУЕТСЯ маленьким — это и есть цена склейки.
//
// СЕЙЧАС ОБЕ ДВЕРИ ВОЗВРАЩАЮТ ОДНО И ТО ЖЕ ЧИСЛО, байт в байт: этот шаг
// только РАЗВОДИТ ЧИТАТЕЛЕЙ ПО СМЫСЛУ под зелёной сюитой, поведения не
// меняя. Смысл им даст переворот (население = паства, души дома = ростер
// места), и тогда правка будет ровно в этих двух телах, а не в 85 местах.
inline int souls_home(const Landmark& lm) { return lm.population; }
inline int souls_flock(const Landmark& lm) { return lm.population; }

// СКОЛЬКО ДУШ МЕСТО МОЖЕТ ДЕРЖАТЬ В ПОЛЕ — половина всех своих.
//
// Считается от ПАСТВЫ (дома + во всех сквадах места), а не от одного
// населения: «половина населения» по оставшимся дома сходилась бы к тому,
// что в поле рано или поздно уходят ВСЕ (половина от половины от половины —
// ряд сходится к единице), и «дома больше, чем в поле» переставало бы
// выполняться уже на третьем рейсе. По пастве это ровно одно и то же число в
// день, когда в поле нет никого, и честный потолок во все остальные дни.
inline constexpr int kFieldShareShift = 1;   // 1/2 — вердикт владельца
static_assert(kFieldShareShift == 1,
              "поле = половина паствы: число названо владельцем, а не выведено");

// `afield` — души ВСЕХ сквадов этого места (и стоящих дома, и ушедших),
// `standingSouls` — из них те, что стоят дома Idle: ими место распоряжается
// сегодня заново, поэтому они возвращаются в пул как свободные руки.
inline int field_pool(const Landmark& lm, int afield, int standingSouls) {
    // Паства СПРАШИВАЕТСЯ ДВЕРЬЮ: после переворота `souls_flock` уже будет
    // знать про ушедших, и слагаемое `afield` здесь честно умрёт — вместе с
    // ежедневным сканом всех сущностей мира, который его считает.
    const int population = souls_flock(lm);
    const int flock = population + afield;
    const int cap = flock >> kFieldShareShift;
    const int marched = afield - standingSouls;      // уже в дороге
    const int free = cap - marched;
    // Больше, чем есть свободных тел, не поднять ни при каком потолке.
    return std::clamp(free, 0, population + standingSouls);
}

}   // namespace sm
