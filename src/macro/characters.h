// Параметры агенды — маленькая структура с ДЕФОЛТАМИ: новое поле агенды
// аппендится сюда и не трогает старые строки (designated-инициализация).
struct DesignAgenda {
    // Маршрут «дом ↔ ближайший ландмарк этого рода» для Waypoints-моделей:
    // ординал SquadType, −1 = маршрута нет. Абсолютные клетки в строке
    // невозможны — мир процедурен, поэтому строка называет РОД цели, а
    // спавн-дверь резолвит её из контекста, как find_valid_spawn.
    std::int8_t routeToNearest = -1;
    // (`radiusCells` СНЕСЁН 2026-11-02, ломоть 6 M-72: поводок дракона —
    //  ВНУТРИ его модуля (вердикт владельца 2026-10-10 «5) внутри модуля»),
    //  константой kDragonLeashCells@src/macro/squad_ai/dragon.cpp; агенда
    //  радиуса была вторым носителем того же числа.)
};

// Дом анкеты: ландмарк рода homeType — N-й по порядку (homeIndex ≥ 0,
// заворот по счёту) или СЛУЧАЙНЫЙ сидом мира (homeIndex < 0); ряд можно
// сузить префиксом фракции ландмарка (homeFactionPrefix, nullptr = любой:
// «случайный варварский город» = City + "barbarian"). Когда homeType ==
// SquadType::None — прямая клетка cellX/cellY.
struct DesignCharacterDef {
    const char*  id;        // authoring-ключ (летопись, консоль) — не рантайм
    const char*  name;      // авторское имя (текст владельца — ДОСЛОВНО)
    NPCType      body;      // строка реестра как есть: спрайт/комбат/апкип;
                            // контекст выбирает строку, не скейлит (S12)
    std::int16_t level;     // −1 = дефолт строки + бросок
    // РОД СКВАДА персоны (ломоть 6 M-72): типизированный род думает МОДУЛЕМ
    // своей строки kAiModuleRows, и колонка behaviour у него не читается.
    // None = бестиповый — думает лестницей None-строки (течь, сузит Б-6).
    SquadType    type;
    // ЛИСТ — ЕДИНОЙ СИСТЕМОЙ, БЕЗ ОСОБОГО ПУТИ (вердикт владельца
    // 2026-10-18, дословно: «авторед это просто одна из анкет то есть не
    // ннадо особую систему это единая система просто дод типа будут
    // добавляться»). Здесь жили `bool authoredSheet` и `CharacterSheet
    // sheet` — флаг плюс колонка-спутник, то есть ВТОРОЙ путь рождения
    // анкеты рядом с общим. Мертвы они были буквально: `authoredSheet =
    // true` не ставила НИ ОДНА из пяти строк, и ветка за ними была
    // недостижима с рождения. Анкета дизайн-персонажа выводится из его
    // колонок (`body` + `level`) той же дверью, что у всякого сквада, —
    // а добавляться будут СТРОКИ, не механика.
    // Строка ОДНОГО реестра фракций (authoring-ключ); nullptr = фракция
    // ДОМА (царь варварского города — их человек, чей бы город ни выпал).
    const char*  factionId;
    SquadType homeType;  // None = клетка ниже / вершина
    std::int16_t homeIndex; // N-й ландмарк рода; < 0 = случайный сидом.
                            // При homePeak — ординал ВЕРШИНЫ (0 = высшая).
    const char*  homeFactionPrefix;  // nullptr = род без фильтра фракции
    // Дом — ВЕРШИНА ГОРНОГО МАССИВА (владелец: «рандом центр горного
    // массива — самая высокая клетка»): homeType = None, спавн-дверь
    // резолвит homeIndex-ю из высочайших клеток карты с разносом, и она
    // же становится ЛОГОВОМ (слово памяти модуля, dragon_lair) для дракона.
    bool         homePeak;
    std::int16_t cellX, cellY;
    AIBehaviour  behaviour; // какая модель думает (лестница effective_behaviour)
    DesignAgenda agenda;
};

