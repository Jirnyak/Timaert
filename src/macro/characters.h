// ── ДЕФОЛТ АНКЕТЫ РОДА (владелец, 2026-09-18) ─────────────────────────────
//
// «У всего в макромире — ландмарки, сквады, лорды — есть анкета: у генерик
// вещей вроде городов и сквадов генерик анкета, у лордов и царя-крестьянина
// просто более детальная, с именем» (дословно). Одна на РОД, не на
// экземпляр: «ландмарки — деревни, города и столицы — потом будут иметь
// каждый по одной анкете, и там мы зададим скиллы и что они умеют». Поэтому
// она живёт здесь константой и НЕ едет в сейв.
//
// ЧТО ОНА РЕШАЕТ СЕГОДНЯ: какие рецепты роду открыты (econ_day.h kRecipes —
// ремесло + ранг). Деревня не чеканит не потому, что она деревня, а потому
// что её кузнечный ранг ноль. Стены по виду больше нет — есть руки.
// ── ТАБЛИЦА РОЖДЕНИЯ РОДА: КАК СКВАД ЭТОГО ТИПА РОЖДАЕТСЯ ПО ДЕФОЛТУ ──────
// (вердикт владельца 2026-11-02, дословно: «в таблице типа как рождается по
// дефолту что в инвентаре и тд (это кстати тоже нужно чтобы был дефолт
// наполнение генерик паков в будущем например всяки банды и тд чтобы у них
// были генерик статы и инвентарь … то есть 3 однозначно нужно».)
//
// МЕХАНИЗМ ПРИ ЭТОМ ОДИН И НЕ ЗДЕСЬ: рождает сквад ЕДИНАЯ дверь системы
// сквадов (store_birth / глагол пульта spawn), а эта таблица — её ДАННЫЕ:
// дефолт анкеты рода плюс амбар рождения. Генерация (прото-политика
// фракций) и живой мир (город рожает артель своим модулем) — ЗВОНЯЩИЕ одной
// и той же двери; «сквада мира» не существует. Бывшая `kPlaceSheets` (стол
// анкет мест) обобщена этой таблицей — ломоть 5б M-235, 2026-11-02.
struct SquadBirthRow {
    // Дефолт анкеты рода: нули = род не умеет ничего (честный случай руин
    // и логов, не дыра). Личность поверх дефолта — дело рождающего модуля.
    CharacterSheet sheet{};
    // Амбар рождения («born mid-life»): дней бюджета комфорта в амбаре и
    // множитель сырьевых буферов. Дефолты деревенские: сквад, про который
    // ничего не сказано, рождается скромно, а не богато. Числа БАЛАНС.
    std::uint8_t seedComfortDays = 8;
    std::uint8_t seedRawMult = 2;
};

inline constexpr std::array<SquadBirthRow, std::size_t(SquadType::Count)>
kSquadBirth = [] {
    // ── УМОЛЧАНИЯ ПОЛЕЙ ПРИМЕНЯЮТСЯ У НАЗВАННОГО ОБЪЕКТА, А НЕ У МАССИВА ──
    // Здесь стояло просто `a{}`, и это была ДЫРА, которую нашёл первый
    // работающий Windows-свидетель (2026-11-09): под GCC
    // `std::array<SquadBirthRow, N> a{}` не протаскивает умолчания ПОЛЕЙ
    // (`seedComfortDays = 8`, `seedRawMult = 2`) и зануляет их, а clang
    // применяет. Диагноз дословно: «the comparison reduces to '(0 == 8)'».
    // Цена была не стилевая: эти числа ЧИТАЕТ экономика
    // (`seed_rooted_inventory@src/macro/econ_day.cpp` берёт дни и множитель),
    // и шапка структуры объявляет умолчание НАМЕРЕННЫМ — «сквад, про который
    // ничего не сказано, рождается скромно». То есть под GCC нулём рождались
    // бы ВСЕ рода, кроме города, а не одна деревня.
    //
    // Источник числа остаётся ОДИН — умолчания полей структуры (DOD п.6: два
    // места для одного ответа разъехались бы молча). Меняется лишь то, ГДЕ
    // они применяются: у именованного объекта `def{}`, где агрегатная
    // инициализация обязана их взять по языку, а не у `std::array`, про
    // который компиляторы разошлись.
    std::array<SquadBirthRow, std::size_t(SquadType::Count)> a{};
    const SquadBirthRow def{};
    for (SquadBirthRow& r : a) r = def;
    CharacterSheet& city = a[std::size_t(SquadType::City)].sheet;
    // Город умеет ВСЁ, чем сегодня живёт экономика, и чеканит: кузнечный
    // ранг дотягивается до монетной строки (kRecipes minRank 30).
    city.skills[SkillId::Blacksmith] = 30;
    city.skills[SkillId::Tailoring]  = 30;
    city.skills[SkillId::Masonry]    = 30;
    city.skills[SkillId::Alchemy]    = 10;
    // ТОРГОВАЯ СИЛА МЕСТА (CANON S25, «лавки не существует — есть две
    // макросущности»): у города она ВЫШЕ, чем у деревенской артели, потому
    // что торг — его ремесло; ровно это и означает «город наценивает». Сила
    // = харизма × торговля через одно производное (attributes.h), так что
    // числа здесь — не наценка, а АНКЕТА, из которой она выводится.
    // Городской торг: харизма 10 при ранге 30 (те же 30, что у его ремёсел
    // — торговать город умеет как кузнечить).
    city.attributes[AttributeId::Cha] = 10;
    city.skills[SkillId::Trade]       = 30;
    // Город рождается с СЕЗОНОМ комфорта и одинарным сырьём (перенесено из
    // булева параметра seed_rooted_inventory один в один, M-281-родня).
    a[std::size_t(SquadType::City)].seedComfortDays = 32;
    a[std::size_t(SquadType::City)].seedRawMult = 1;
    CharacterSheet& village = a[std::size_t(SquadType::Village)].sheet;
    // ДЕРЕВНЯ ПРОИЗВОДИТ ПО ТОЙ ЖЕ МОДЕЛИ, И МЕНЬШЕ — ЭМЕРДЖЕНТНО (владелец,
    // 2026-09-21, дословно: «пусть деревня тоже производит, просто чеканить
    // монеты не может — типа крутой рецепт, не хардкод, а потолок по скилам;
    // а город может; и деревня производит по той же модели, то есть единая
    // система — а меньше она будет производить эмерджентно, потому что в ней
    // меньше население, чем в городе, на порядок»).
    //
    // ПОЭТОМУ РЕМЕСЛЕННЫЕ РАНГИ ДЕРЕВНИ РАВНЫ ГОРОДСКИМ. Ранг в этой системе
    // — это ДОПУСК к строке рецепта (recipe_known), а не темп: сколько работы
    // покупает бар, решает число рабочих юнитов — на них делится цена акта
    // (`act_sp_price@src/tables/econ_laws.h`). Значит разница городов и
    // деревень выходит из ОДНОГО различия — числа душ, — и её не надо
    // назначать вторым числом здесь.
    //
    // ЧТО ЭТО ЧИНИТ. После сноса хлеба (2026-09-20) у деревни оставалось
    // поварское ремесло рангом 10, а в kRecipes не осталось НИ ОДНОЙ его
    // строки — деревня не производила ровно ничего, и дневной выпуск
    // крутился вхолостую для ~1700 поселений каждый день. Мир умел одно: растить
    // еду. Замер дня 61: пища 28 469 593, кирпичи 18 942, ткань 1 466,
    // ИНСТРУМЕНТЫ 5 — на весь мир. Само ремесло вырезано 2026-09-28 (M-148):
    // рецепта у него не могло появиться никогда, значит и ранга ему не нужно.
    village.skills[SkillId::Tailoring]  = 30;
    village.skills[SkillId::Masonry]    = 30;
    village.skills[SkillId::Alchemy]    = 10;
    // КУЗНЕЧНЫЙ РАНГ — ЕДИНСТВЕННОЕ РЕМЕСЛЕННОЕ РАЗЛИЧИЕ, И ОНО ВЫВЕДЕНО ИЗ
    // ТАБЛИЦЫ РЕЦЕПТОВ, А НЕ НАЗНАЧЕНО: 20 — это высший ранг кузнечной
    // строки НИЖЕ монетной (украшения 20 против чеканки 30, econ_day.h
    // kRecipes). То есть деревенская кузница умеет всё, кроме монетного
    // двора, — ровно вердикт владельца, записанный числом, которое сдвинется
    // само, если сдвинется таблица. Сторожит это свидетель (econ_v1_test):
    // каталог рецептов и стол анкет — разные единицы трансляции, и
    // компилятору эта связь недоступна.
    village.skills[SkillId::Blacksmith] = 20;
    // ТОРГОВАЯ СИЛА остаётся ниже городской, и это ДРУГОЙ закон, не ремесло
    // (CANON S25): торг — ремесло города, «город наценивает» означает именно
    // это. Поэтому в городе крестьянин уступает в цене, а у себя дома с
    // заезжим караваном — уже нет: разница считается ОБЕИМИ анкетами.
    village.attributes[AttributeId::Cha] = 5;
    village.skills[SkillId::Trade]       = 10;
    // СТОЛИЦА УМЕЕТ ТО ЖЕ, ЧТО ГОРОД, И ЭТО КОПИЯ ПО ПОСТРОЕНИЮ, А НЕ ПО
    // НЕВНИМАТЕЛЬНОСТИ: анкета города и есть «полный набор ремёсел, какой
    // сегодня знает экономика», выше потолка просто нет. Писать её вторым
    // столбиком цифр значило бы завести ВТОРОЕ место, где живёт один и тот
    // же ответ (DOD п.6), и первая же правка городских рангов разъехалась
    // бы со столичными молча. Присвоение держит их едиными под
    // компилятором; разойдутся они в день, когда у столицы появится своё
    // ремесло, — и тогда это будет СТРОКА различия, а не копия.
    a[std::size_t(SquadType::Capital)] = a[std::size_t(SquadType::City)];
    // Руин, логов, шпилей и башен ремесло не касается — их анкета в нулях,
    // и это честный случай, а не дыра: место, которое не умеет ничего.
    return a;
}();

inline constexpr const SquadBirthRow& squad_birth(SquadType t) {
    return kSquadBirth[std::size_t(t) < std::size_t(SquadType::Count)
                               ? std::size_t(t) : 0];
}

// АМБАР РОЖДЕНИЯ СТОИТ ГДЕ ОБЕЩАНО — ПОД КОМПИЛЯТОРОМ (пин переехал сюда
// вместе с колонками из реестра мест). Числа БАЛАНСНЫЕ и менять их можно;
// менять ВМЕСТЕ с этой строкой.
static_assert(
    squad_birth(SquadType::City).seedComfortDays == 32
        && squad_birth(SquadType::City).seedRawMult == 1
        && squad_birth(SquadType::Village).seedComfortDays == 8
        && squad_birth(SquadType::Village).seedRawMult == 2,
    "амбар рождения: город — сезон комфорта и одинарное сырьё, деревня — "
    "восемь дней и двойное");

inline constexpr std::int16_t kDesignCharacterCount =
    std::int16_t(sizeof(kDesignCharacterDefs) / sizeof(kDesignCharacterDefs[0]));

// Строка по ординалу тега — nullptr на мусорный ординал (запись из чужого
// будущего сейва каталожный закон объявляет невозможной, но дверь честная).
inline constexpr const DesignCharacterDef* design_character(std::int16_t ord) {
    return ord >= 0 && ord < kDesignCharacterCount
        ? &kDesignCharacterDefs[ord] : nullptr;
}

