// ── АНКЕТЫ МЕСТ (владелец, 2026-09-18) ────────────────────────────────────
//
// «У всего в макромире — ландмарки, сквады, лорды — есть анкета: у генерик
// вещей вроде городов и сквадов генерик анкета, у лордов и царя-крестьянина
// просто более детальная, с именем» (дословно). Сквады это УЖЕ умеют —
// squad.h sheet_of: владеемый CharacterSheet-компонент у именованного, иначе
// генерик-бросок от строки и уровня. Не умели только МЕСТА, и вот их анкета.
//
// Одна на РОД, не на экземпляр: «ландмарки — деревни, города и столицы —
// потом будут иметь каждый по одной анкете, и там мы зададим скиллы и что
// они умеют». Поэтому она живёт здесь константой и НЕ едет в сейв — ни байта
// на 32 тысячи мест, ни бампа kSaveVersion.
//
// ЧТО ОНА РЕШАЕТ СЕГОДНЯ: какие рецепты месту открыты (econ_day.h kRecipes —
// ремесло + ранг). Деревня не чеканит не потому, что она деревня, а потому
// что её кузнечный ранг ноль. Стены по виду больше нет — есть руки.
//
// Столицы отдельным родом ещё не существует (LandmarkType её не знает;
// столица сегодня — город без сюзерена), так что её строка придёт вместе с
// родом. Незаполненный род = анкета в нулях: место, которое не умеет ничего,
// — честный случай, а не дыра.
inline constexpr std::array<CharacterSheet, std::size_t(LandmarkType::Count)>
kLandmarkSheets = [] {
    std::array<CharacterSheet, std::size_t(LandmarkType::Count)> a{};
    CharacterSheet& city = a[std::size_t(LandmarkType::City)];
    // Город умеет ВСЁ, чем сегодня живёт экономика, и чеканит: кузнечный
    // ранг дотягивается до монетной строки (kRecipes minRank 30).
    city.skills[SkillId::Cooking]    = 30;
    city.skills[SkillId::Blacksmith] = 30;
    city.skills[SkillId::Tailoring]  = 30;
    city.skills[SkillId::Masonry]    = 30;
    city.skills[SkillId::Alchemy]    = 10;
    // ТОРГОВАЯ СИЛА МЕСТА (CANON S25, «лавки не существует — есть две
    // макросущности»): у города она ВЫШЕ, чем у деревенской артели, потому
    // что торг — его ремесло; ровно это и означает «город наценивает». Сила
    // = харизма × торговля через одно производное (attributes.h), так что
    // числа здесь — не наценка, а АНКЕТА, из которой она выводится.
    // Городской торг: харизма 10 при ранге 30 (те же 30, что у его ремёсел
    // — торговать город умеет как кузнечить).
    city.attributes[AttributeId::Cha] = 10;
    city.skills[SkillId::Trade]       = 30;
    CharacterSheet& village = a[std::size_t(LandmarkType::Village)];
    // ДЕРЕВНЯ ПРОИЗВОДИТ ПО ТОЙ ЖЕ МОДЕЛИ, И МЕНЬШЕ — ЭМЕРДЖЕНТНО (владелец,
    // 2026-09-21, дословно: «пусть деревня тоже производит, просто чеканить
    // монеты не может — типа крутой рецепт, не хардкод, а потолок по скилам;
    // а город может; и деревня производит по той же модели, то есть единая
    // система — а меньше она будет производить эмерджентно, потому что в ней
    // меньше население, чем в городе, на порядок»).
    //
    // ПОЭТОМУ РЕМЕСЛЕННЫЕ РАНГИ ДЕРЕВНИ РАВНЫ ГОРОДСКИМ. Ранг в этой системе
    // — это ДОПУСК к строке рецепта (recipe_known), а не темп: темп считает
    // econ_produce_day из населения (пул рук pop/kHeadsPerCityWorker и КПД
    // log2(pop)/4). Значит разница городов и деревень выходит из ОДНОГО
    // различия — числа душ, — и её не надо назначать вторым числом здесь.
    //
    // ЧТО ЭТО ЧИНИТ. После сноса хлеба (2026-09-20) у деревни оставалось
    // ремесло Cooking 10, а в kRecipes не осталось НИ ОДНОЙ строки на
    // Cooking — деревня не производила ровно ничего, и econ_produce_day
    // крутился вхолостую для ~1700 мест каждый день. Мир умел одно: растить
    // еду. Замер дня 61: пища 28 469 593, кирпичи 18 942, ткань 1 466,
    // ИНСТРУМЕНТЫ 5 — на весь мир.
    village.skills[SkillId::Cooking]    = 30;
    village.skills[SkillId::Tailoring]  = 30;
    village.skills[SkillId::Masonry]    = 30;
    village.skills[SkillId::Alchemy]    = 10;
    // КУЗНЕЧНЫЙ РАНГ — ЕДИНСТВЕННОЕ РЕМЕСЛЕННОЕ РАЗЛИЧИЕ, И ОНО ВЫВЕДЕНО ИЗ
    // ТАБЛИЦЫ РЕЦЕПТОВ, А НЕ НАЗНАЧЕНО: 20 — это высший ранг кузнечной
    // строки НИЖЕ монетной (украшения 20 против чеканки 30, econ_day.h
    // kRecipes). То есть деревенская кузница умеет всё, кроме монетного
    // двора, — ровно вердикт владельца, записанный числом, которое сдвинется
    // само, если сдвинется таблица. Сторожит это свидетель (econ_v1_test):
    // каталог рецептов и стол анкет — разные единицы трансляции, и
    // компилятору эта связь недоступна.
    village.skills[SkillId::Blacksmith] = 20;
    // ТОРГОВАЯ СИЛА остаётся ниже городской, и это ДРУГОЙ закон, не ремесло
    // (CANON S25): торг — ремесло города, «город наценивает» означает именно
    // это. Поэтому в городе крестьянин уступает в цене, а у себя дома с
    // заезжим караваном — уже нет: разница считается ОБЕИМИ анкетами.
    village.attributes[AttributeId::Cha] = 5;
    village.skills[SkillId::Trade]       = 10;
    // Руин, логов, шпилей и башен ремесло не касается — их анкета в нулях,
    // и это честный случай, а не дыра: место, которое не умеет ничего.
    return a;
}();

inline constexpr const CharacterSheet& landmark_sheet(LandmarkType t) {
    return kLandmarkSheets[std::size_t(t) < std::size_t(LandmarkType::Count)
                               ? std::size_t(t) : 0];
}

inline constexpr std::int16_t kDesignCharacterCount =
    std::int16_t(sizeof(kDesignCharacterDefs) / sizeof(kDesignCharacterDefs[0]));

// Строка по ординалу тега — nullptr на мусорный ординал (запись из чужого
// будущего сейва каталожный закон объявляет невозможной, но дверь честная).
inline constexpr const DesignCharacterDef* design_character(std::int16_t ord) {
    return ord >= 0 && ord < kDesignCharacterCount
        ? &kDesignCharacterDefs[ord] : nullptr;
}

