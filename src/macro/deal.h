// ОДИН ГЛАГОЛ ОБМЕНА МИРА — `deal` (вердикт владельца 2026-10-22 п.3,
// дословно — CANON «ВЕРДИКТЫ СЕССИИ 2026-10-22»: обмен и перенос — ОДИН
// глагол; перенос = сделка с пустым встречным лотом; лот несёт НАМЕРЕНИЕ
// «до N», дверь клампит до исполнимого — исток, вместимость, покрытие — и
// исполняет АТОМАРНО; ЦЕНА — закон звонящего, «VALUE fairness is the
// caller's law»).
//
// ПЕРЕНОС АГНОСТИЧЕН, И ДУШ ДВЕРЬ НЕ ЗНАЕТ (вердикт владельца 2026-10-23,
// дословно — CANON при п.3 вердиктов 2026-10-22): «перенос инвентаря должен
// быть агностичным … ему самом всё равно люди это или предметы - это
// перенос обхектов - смысл этих переносов ложиться на внутренность аи
// модулей»; «паства это только ответ АИ модуля (город/деревня/стлица)».
// Значит: дверь переносит ОБЪЕКТЫ, и только; пара «голова+число фичи»
// (паства) — ответственность ИИ-модуля поселения, а до модулей (ломти 4–5)
// её пишут прежние звонящие (`flock_left_home` у найма/прилавка UI).
// Подсистемы «на архетип» не существует: ЗАКОН КОНТЕЙНЕРА уже положил души
// и предметы в ОДНИ слоты, и различие областей разруливают двери самого
// контейнера.
//
// ПОЧЕМУ ВХОД — СЛОТЫ СКВАДОВ, А НЕ ГОЛЫЕ `Inventory&`: долг места.
// Приход в место гасит его счёт СРАЗУ (CANON S10), и счёт стороны дверь
// читает по её слоту — у ходока он стоит нулями, и гашение молчит само,
// без ветки по роду.
//
// ЧЕМ ЭТА ДВЕРЬ УБИЛА СВОИХ ПРЕДШЕСТВЕННИКОВ (перепись 2026-10-22:
// независимых реализаций «взять у A, отдать B» было ОДИННАДЦАТЬ):
// `barter_swap` — её прямой предок (идиома «копии и коммит целиком» —
// отсюда); `haul_between` — его латентный дюп (возврат `remove_of`
// выбрасывался) здесь невыразим: сделка исполняется целиком на копиях или
// мир не тронут; `hire_npc` — скретч-кошелёк и ручной откат умерли в
// exact-лот; `deliver_bag_home`/`creatures_move`/`creatures_add` — частные
// случаи пустого встречного лота.
#pragma once
#include <cstdint>
#include <limits>
#include <span>

#include "macro/econ_day.h"   // EconFactSink: приход в место гасит долг СРАЗУ (CANON S10)
#include "tables/items.h"     // item_def_at/item_mass_g — кламп массы прибытия

namespace sm {

struct MacroStore;
struct Inventory;

// «ПРЕДЕЛА НЕТ» — ИМЕНОВАННЫМ ЧИСЛОМ, А НЕ ЛИТЕРАЛОМ (переехало из
// npc_ai.h вместе со смертью haul_between). Приёмник сделки на рынке есть
// СКЛАД МЕСТА, а у склада спины нет вовсе: обоз — свойство анкеты, которая
// идёт, а место не идёт никуда. Вывод числа физический: `int64` держит
// 9.2·10¹⁸ г, то есть предел заведомо недостижим любым контейнером
// (1024 слота × `int32` счёт × 64 кг самой тяжёлой строки каталога
// ≈ 1.4·10¹⁴ г), и минимум клампа его просто никогда не выбирает.
inline constexpr std::int64_t kNoCarryLimitG =
    std::numeric_limits<std::int64_t>::max();

// Масса ЕДИНИЦЫ строки каталога для клампа спины (переехало из npc_ai.cpp,
// M-298). У существа строки предмета нет вовсе (item_def_at честно отдаёт
// nullptr) — такая строка весит здесь КИЛОГРАММ (1000 г), и это НЕ ВЫВОД, а
// СОХРАНЁННОЕ поведение: число делит живые рейсы, и права сдвинуть его у
// наряда обмена нет. Делитель никогда не ноль по построению: разрешённую
// строку держит выше нуля страж `item_mass_g` (items.cpp отказывает сборке
// на строке с нулевой массой), а неразрешённая отдаёт 1000.
inline std::int64_t unit_mass_g(const ItemDef* d) noexcept {
    return d ? std::int64_t(item_mass_g(*d)) : 1000;
}

// «Любой стак строки» — закон узкого индекса: «нет слота» есть ПОСЛЕДНЕЕ
// значение типа, не −1 (слот 0 — законный элемент контейнера).
inline constexpr std::uint16_t kDealAnyStack =
    std::numeric_limits<std::uint16_t>::max();

// Строка лота — НАМЕРЕНИЕ, после сделки несёт ФАКТ.
struct DealLine {
    std::int32_t  want  = 0;   // намерение «до N» единиц
    std::int32_t  done  = 0;   // ФАКТ — пишет дверь (0 при отказе сделки)
    std::uint16_t def   = 0;   // строка каталога у ИСТОКА
    // конкретный стак истока (протухший — факт 0, не чужой груз: s.def
    // сверяется) или kDealAnyStack — любые стаки строки, старые первыми
    std::uint16_t slot  = kDealAnyStack;
    // 0 = едет как есть; иначе прибывает ЭТОЙ строкой — подмена строки
    // лотом (вердикт п.3: перевод душ дом↔артель без рукописного
    // перерождения); идентичность стака (seed/affixes/entityId) едет как есть
    std::uint16_t asDef = 0;
    // 1 = «ровно N»: факт ниже намерения отказывает ВСЕЙ сделке (закон
    // торгового экрана — staged-монеты против протухшего товара не едут)
    std::uint8_t  exact = 0;
};
// Узкие поля упакованы вместе, итог прибит (DOD п.2): 4+4+2+2+2+1 = 15 → 16.
static_assert(sizeof(DealLine) == 16, "lot line is 16 bytes packed");

// Факт обеих половин — в самих строках (done); здесь — сводка и вердикт.
struct DealFact {
    int  unitsAB = 0;      // единиц уехало A → B
    int  unitsBA = 0;      // единиц уехало B → A
    bool settled = false;  // коммит был (хоть одна единица уехала)
};

// Сделка: лоты обеих половин клампятся до исполнимого (исток, слоты и
// спина приёмника, exact-покрытие) и исполняются ЦЕЛИКОМ на копиях —
// отказ любой exact-строки откатывает всё, мир не тронут. Капы массы —
// закон звонящего (остаток ноги ходока; у склада места спины нет —
// kNoCarryLimitG). Долг места гасится приходом (CANON S10) у обеих сторон.
DealFact deal(MacroStore& st,
              std::uint16_t a, std::uint16_t b,
              std::span<DealLine> fromA, std::span<DealLine> fromB,
              std::int64_t massCapToB = kNoCarryLimitG,
              std::int64_t massCapToA = kNoCarryLimitG,
              EconFactSink sink = nullptr, void* user = nullptr);

// Встречный лот ПО ЗАКОНУ ПЛОТНОСТИ — цена остаётся законом звонящего:
// та же дверь `densest_value_slot`, какой платит весь мир, только она
// СТЕЙДЖИТ строки, а не снимает их. Последняя строка может переплатить
// (бартерный закон: отданное покрывает взятое). Строки выходят exact —
// платёж едет целиком или сделка не состоится. Покрыто меньше запроса
// (тощая сумка, кончились строки лота) — судит звонящий по `value`.
struct StagedValue {
    int value = 0;   // покрытая стоимость (может превысить запрос последней строкой)
    int lines = 0;   // занято строк лота
};
StagedValue stage_value_lines(const Inventory& inv, int value,
                              std::span<DealLine> out);

} // namespace sm
