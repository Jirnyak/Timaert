// ВЕРДИКТ ВЛАДЕЛЬЦА 2026-11-08 (M-433 п.1), дословно: подпись «вывести из
// существующего контента». Значит ни четырнадцати новых player-facing слов, ни
// таблицы-спутника по ординалу фичи (DOD п.9 «ГДЕ КОЛОНКЕ ЖИТЬ»): подпись есть
// ВЫВОД из уже авторских колонок, и разойтись с источником она не может ПО
// ПОСТРОЕНИЮ — правка `yieldItem` шахты или `label` рода переписывает подпись в
// тот же миг.
//
// ЧТО ЗДЕСЬ СТОЯЛО ДО ЭТОЙ ДВЕРИ: `feature_name` — switch по роду фичи внутри
// `src/ui/macro_overlay.cpp`, то есть словарь, спрятанный в UI (ЗАКОН СТРОКИ
// КАТАЛОГА). Из восемнадцати родов слово в нём имели ТРИ (дорога, грунтовка,
// мост), а четырнадцать возвращали ПУСТУЮ СТРОКУ — поимённо и сознательно,
// правкой того же дня, которая сделала switch исчерпывающим: молчание стало
// явным, но осталось молчанием. Восемнадцатый, `FT_None`, пуст ПО ЗАКОНУ: на
// клетке не построено ничего, и подписывать нечего.
//
// ТРИ КОЛОНКИ ОТВЕЧАЮТ, В ПОРЯДКЕ УБЫВАНИЯ КОНКРЕТНОСТИ, И КАЖДАЯ УЖЕ ЖИВА СО
// СВОИМ ЧИТАТЕЛЕМ — ни одна не заведена ради подписи:
//   1) `kind` — чей род ставит этот байт → `label` его строки `kSquadKinds`
//      («Capital», «City», «Village», «Spire», «Ruin»). Это НЕ дубль строки,
//      которую тултип печатает рядом: та несёт ИМЯ ЭКЗЕМПЛЯРА сквада
//      (колонка `name` сквада, «Kingsford»), а эта — его РОД;
//   2) `yieldItem` — что с фичи берут → `name` строки каталога у шести шахт
//      («Clay», «Iron Ore», «Stone», «Silver Ore», «Copper Ore», «Gold Ore»)
//      и у льна («Fibre»);
//   3) `numberRow` — чей ряд реестра несёт её число → умолчание выхода этого
//      ряда, предметом или СУЩЕСТВОМ. Сегодня так отвечает одно пастбище: его
//      число есть стадо, а умолчание ряда `Livestock` — конь-душа («Horse»).
//
// ЦЕНА НАЗВАНА ВЛАДЕЛЬЦЕМ ЗАРАНЕЕ, И ОНА ПРИНЯТА: слова выходят ТЕХНИЧНЫМИ
// («Iron Ore» на клетке железной шахты), и перепишет их владелец СТРОКОЙ
// каталога, а не механикой. Вывод тем и хорош, что переписывается строкой.
//
// ЧТО ЭТА ДВЕРЬ НЕ ОТВЕЧАЕТ, И ЭТО НАЗВАНО ВСЛУХ: пашня (`FT_Field`) остаётся
// без подписи, потому что выводить её НЕ ИЗ ЧЕГО — её `numberRow` есть `Count`
// НАМЕРЕННО (стоячий хлеб живёт шрамом ряда `Wheat`, а не полем чисел фич —
// `feature_def.h`), `yieldItem` у неё пуст по той же причине, а рода она не
// несёт. Колонки, которая назвала бы её культуру, у строки нет ни одной, и
// выдумать её значило бы написать то самое новое слово.
//
// ПОЧЕМУ ДОМ ЗДЕСЬ, А НЕ У СТРОКИ (`tables/feature_def.h`): клаузе 3 нужен ряд
// реестра, то есть ИЗМЕНЯЕМОЕ СОСТОЯНИЕ МИРА, которого нейтральный слой не
// видит и видеть не должен (§11). А почему своим файлом, а не в
// `macro/features.h`: цену заголовка платит КАЖДЫЙ ВКЛЮЧИВШИЙ (§5 п.13), а
// каталоги предметов и существ — два самых тяжёлых стола дерева; включателей у
// подписи ровно два (тултип карты и её свидетель), и пусть платят они.
#pragma once
#include "macro/resource_field.h"   // ряд реестра и его умолчание выхода
#include "tables/feature_def.h"     // строка фичи: kind · yieldItem · caption
#include "tables/items.h"           // имя предмета — `ItemDef::name`
#include "tables/npc.h"             // имя существа — `NpcTypeDef::label`
#include "tables/squad_type.h"      // подпись рода — `SquadKindRow::label`

namespace sm {

// Имя строки каталога по её авторскому ключу; nullptr = ключа нет или он не
// резолвится. Строка живёт НА ГРАНИЦЕ (ЗАКОН СЛОВАРЯ п.1: авторинг и UI) —
// звонят сюда из тултипа, не из тика.
inline const char* feature_yield_name(const char* id) {
    const ItemDef* def = id ? item_def_at(item_index(id)) : nullptr;
    return def ? def->name : nullptr;
}

inline const char* feature_caption(FeatureType f) {
    const FeatureDef& d = feature_def(f);
    if (d.caption) return d.caption;                 // авторский остаток: ленты
    if (d.kind != SquadType::None)                   // (1) пять поселений
        return squad_kind(d.kind).label.data();
    if (const char* item = feature_yield_name(d.yieldItem))
        return item;                                 // (2) шесть шахт и лён
    if (d.numberRow != ResourceFieldId::Count) {     // (3) пастбище
        const ResourceFieldDef& row = resource_field_def(d.numberRow);
        if (row.yieldCreature != NPCType::Count)
            return npc_def(row.yieldCreature).label;
        if (const char* item = feature_yield_name(row.yieldItem)) return item;
    }
    return "";   // выводить не из чего — и это ЗНАЧЕНИЕ, а не отказ
}

} // namespace sm
