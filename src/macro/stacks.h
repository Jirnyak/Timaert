// Род штабеля — чем адресуется строка.
enum class StackKind : std::uint8_t {
    ByCell,      // клеткой тора: поле над миром
    ByOrdinal,   // ординалом сущности
    Catalog,     // строкой закона, известной на сборке
    Scalars,     // единственный экземпляр: состояние мира
};

// ОДНА СТРОКА ПЕРЕПИСИ = ОДНА АЛЛОКАЦИЯ, а не одна система. Правило записано
// вслух, потому что групповая строка и есть тот способ, которым перепись
// однажды промолчала: «навигация» одним пунктом прячет шесть колонок по
// клетке и четыре таблицы по округе, и ни одну из них нельзя ни сложить, ни
// сверить. Три колонки `PathCostData` — три строки; два канала следа — две.
struct StackRow {
    const char* name;        // как штабель зовут в мире
    const char* rowType;     // тип ОДНОЙ строки
    StackKind   kind;
    std::size_t rowBytes;    // sizeof одной строки
    // ПОТОЛОК СТРОК, И ОН ЕСТЬ У КАЖДОГО ШТАБЕЛЯ, включая каталог: у каталога
    // потолок И ЕСТЬ его длина, выведенная `std::size` из самой таблицы.
    // (Здесь стояло «0 = каталог» — ложь, которую держал только комментарий:
    // свидетель `stack_census_test` запрещает нулевой потолок с первого дня,
    // и ровно поэтому каталожных строк не было заведено ни одной.)
    std::size_t cap;
};

// ── ПОТОЛКИ МИРА ─────────────────────────────────────────────────────────
// Клеток на карте и популяции мира — два числа, из которых считается всё
// остальное. Клетки живут здесь, потому что перепись — единственное место,
// где они умножаются на размеры строк; кап популяции здесь НЕ объявляется —
// он ЕДИНЫЙ на оба мира и живёт в `kUnifiedCap@src/core/caps.h` (вердикт
// владельца 2026-10-06; слияние имён — эта половина M-106 — закрыто 2026-10-09: `kWorldSquads`
// и `kMacroEntityCap` умерли в одно имя). Сквады и МЕСТА делят кап одним
// массивом (M-90: место есть неподвижный сквад; `kWorldPlaces` умер
// ломтиком F — отдельного потолка мест не существует).
inline constexpr std::size_t kWorldCells  = kWorldCellCap;   // core/caps.h

// ПОТОЛОК ОКРУГ НАВИГАЦИИ — ПРОИЗВОДНЫЙ ОТ ЕДИНОГО КАПА (вердикт владельца
// 2026-10-06: округа рождается на МЕСТО, а место есть сквад — округ не бывает
// больше, чем сквадов). Округа рождается на КАЖДЫЙ укоренённый сквад
// (`nav_bake@src/macro/nav_field.cpp` обходит их по оси архетипа); гейт «род
// не None» СНЕСЁН, и файл сноса сам это пишет — бестиповых мест в популяции
// не бывает, а обход по архетипу и есть ответ оси рода. Единственный живой
// гейт — отказ запекаться при `R >= kNavNoRegion` (65535), то есть предел
// ТИПА, а не предел мира.
// Перепись пишет правду о цене: четыре таблицы графа КВАДРАТИЧНЫ по капу
// (3 ГиБ по капу против ~40 МиБ на замеренном мире). Числом это стоит здесь
// затем, чтобы было ВИДНО: сам граф — отдельный эпик после полировки систем
// (вердикт владельца 2026-09-28: «там надо BFS и связные окрестности»), и
// худеть его переписью ЗАПРЕЩЕНО; развязка «округа ≠ место» тоже НЕ делается
// (владелец: «нет лучше единый кап» — округи входят в золотую константу).
inline constexpr std::size_t kNavRegionCap = kUnifiedCap;

// СТРОКА ГЛАДКОЙ ПАМЯТИ МАКРО-СКВАДОВ — СУММА КОЛОНОК, А НЕ ЛИТЕРАЛ.
// Цена слота считается здесь из тех же типов, из которых сложен `MacroStore`,
// а СХОДИМОСТЬ с настоящим `sizeof(MacroStore)` закреплена `static_assert`-ом
// в конце этого файла — перепись и структура не могут разъехаться молча ни в
// одну сторону. Инверсия включения умерла с переездом стора на шину (M-171,
// ломоть 2б-II): он брал кап ТРАНЗИТОМ отсюда, теперь — из `core/caps.h`
// прямо, и перепись включает стор, а не наоборот.
inline constexpr std::size_t kMacroStoreRowBytes =
    sizeof(ecs::MacroSpawnId) + sizeof(ecs::MacroCell) + sizeof(ecs::NPCKind)
    // (колонка CellSub умерла 2026-11-02: доля — СКВАДНАЯ величина и живёт
    //  внутри MacroNpcRuntime, на месте умершего float-банка moveBudget)
    + sizeof(ecs::NpcCharacter)
    + sizeof(ecs::SquadName)          // имя анкеты (ход 2, вердикт 3)
    + sizeof(ecs::NpcTraits) + sizeof(ecs::Pools)   // NpcLevel умер: M-246а
    + sizeof(ecs::MacroNpcRuntime) + sizeof(SpellBook)
    + sizeof(ecs::SquadGoal)          // цель {куда,что,сколько,чем стать} (M-1)
    + sizeof(ecs::SquadUpkeep)
    + sizeof(Wellbeing)               // благополучие анкеты (M-90 флип)
    + sizeof(Interests)               // связи любых сквадов (M-90 флип)
    + sizeof(ecs::NpcInventory)
    + sizeof(CharacterSheet) + sizeof(ecs::SquadOrders)
    + sizeof(ecs::BodyEquipment) + sizeof(ecs::DesignCharacterTag)
    + sizeof(std::uint8_t)            // playerFlag — ОДИН бит игрока: `on`
                                      // («кем я на карте», 5б). Второй,
                                      // `home` («кто оригинал», M-255),
                                      // снесён ломтём 7б M-421 вместе с
                                      // родом «дом»: 2 Б → 1 Б на слот.
                                      // Ширина названа байтами, а не `sizeof
                                      // (PlayerFlag)`: сходимость с типом
                                      // держит ассерт ниже, в этом же файле.
    + sizeof(std::uint8_t)            // dead — байт судьбы
    + sizeof(std::uint8_t)            // alive — занятость
    + sizeof(std::uint16_t)           // freeSlots — стек свободных
                                      // (generation умерла с M-220:
                                      // протухание судит spawnId)
    + sizeof(std::uint32_t)           // ordKey — ключ справочника
                                      // идентичности (M-271): ординал →
                                      // слот бинарным поиском вместо скана
                                      // всех 16384 слотов
    + sizeof(std::uint16_t)           // ordSlot — его же слот
    + sizeof(std::uint16_t)           // deadRows — ведомость павших (M-376):
                                      // свип мёртвых за O(павших), не сканом
    + sizeof(std::uint8_t);           // deadListed — флаг строки ведомости
                                      // (дубликат невыразим)

// И ШОВ МЕЖДУ ПРОЗОЙ ПЕРЕПИСИ И ПРАВДОЙ СТРУКТУРЫ — ЗДЕСЬ, РЯДОМ С ТЕРМОМ.
// Добавил колонку только в стор — красный ассерт назовёт забытую строку
// переписи выше; поправил только перепись — он же назовёт ложь в ней.
// Хвост 24 Б — шесть счётчиков (`freeCount`, `aliveCount`, эмитент
// `nextSpawnId`, `ordCount`, `deadRowCount` и выравнивание структуры до
// align 8) — единственное, что не умножается на кап.
static_assert(sizeof(MacroStore)
                  == kMacroStoreRowBytes * kUnifiedCap
                         + sizeof(std::uint32_t) * 6u,
              "перепись штабелей и гладкая память разъехались: цена слота "
              "kMacroStoreRowBytes больше не равна колонкам MacroStore");

// СКОЛЬКО РЯДОВ РЕАЛЬНО ВЫДЕЛЯЮТ СВОЁ ПОЛЕ ШРАМОВ. Не пять: ряд-НОСИТЕЛЬ
// держит живое состояние в своём контейнере, и allocate_world_fields его
// пропускает (`if (carrierRead) continue`). Носителей ЧЕТЫРЕ — лес
// (TreeLayer), ЖИЛА (производный DepositLayer + залежи шахт в числе фич,
// «жилы единые» 2026-10-22), с 2026-10-12 СТАДО (контейнер — поле чисел фич,
// M-258) и с 2026-11-02 ЗВЕРЬ (своё хранимое поле `GameState::faunaField`,
// M-371 — шрам фауны мёртв по вердикту «звери это просто поле»). Значит
// шрам держит ОДИН ряд — пашня (M-91); четыре вечно пустых заголовка массива
// `resourceScarCells` снесены в v157, поле теперь одно — `wheatScars`.
inline constexpr std::size_t kScarRows = 1u;

// ── СТОРОЖ (1): РАЗМЕР СТРОКИ ────────────────────────────────────────────
// Каждое число выведено из формы строки, а не замерено «как вышло». Разъехался
// вывод с правдой — компилятор говорит об этом здесь, а не проза где-то.
static_assert(sizeof(ecs::MacroNpcRuntime) == 44,
              "строка марша: 44 Б × 16384 = 0.69 МиБ (M-425: колонка темпа картинки уехала в кадровый кэш глаз) (ломоть 4 M-72: "
              "`errandObject` −4 Б, выравнивание отдало ещё 4 — объект "
              "поручения был вторым носителем `SquadGoal::what`)");
static_assert(sizeof(ecs::Pools) == 36, "строка полос");
static_assert(sizeof(ecs::CellSub) == 2, "доля клетки (M-244)");
static_assert(sizeof(ecs::NpcCharacter) == 4,
              "строка лица: 12 → 8 → 4 Б (M-430 снёс `visualSeed`; M-246б — `nameIdx` стал локалью рождения, тинты были сиротами)");
static_assert(sizeof(ecs::NpcInventory) == 41024,
              "инвентарь сущности: 1024 стака по 40 Б (единый контейнер "
              "32×32, шаг А слияния 2026-09-24) плюс сводка 64 Б — одна "
              "кэш-линия на 40 КиБ слотов, M-296");
static_assert(sizeof(ecs::SquadUpkeep) == 80,
              "содержание = счёт харча и платы над единым контейнером (M-71): "
              "харч 68 (17 товаров: +медь/золото 2026-10-23) + пад 4 + плата 8; "
              "существа живут в NpcInventory");
// 2026-11-10, M-180: слои мира перестали быть ЗАГОЛОВКАМИ векторов и стали
// плоскими массивами под капом клеток — их `sizeof` теперь и есть их память
// (72 Б → 2 097 168; 40 Б → 2 097 164), кучи за ними нет.
static_assert(sizeof(ResourceGrid) == 16u + 2u * kWorldCells,
              "поле над миром: шапка 16 Б + u16 на клетку капа");
// 2026-11-10, M-456: слой фич перестал быть заголовком вектора (32 Б) на
// оболочке приложения и лёг плоским массивом в тело состояния мира.
// 2026-11-10, M-248 / M-457 п.7: шапка 8 → 16 Б — счётчик правок (4 Б), по
// которому текстура карты догоняет поле в живой игре, и названный хвост
// выравнивания (4 Б): без него состояние мира получало безымянную дыру.
static_assert(sizeof(FeatureLayer) == 16u + kWorldCells,
              "слой фич: шапка 16 Б + байт на клетку капа");
static_assert(sizeof(TreeLayer) == 12u + 2u * kWorldCells,
              "слой леса: шапка 12 Б + u16 на клетку капа");
static_assert(sizeof(KnowledgeLayer) == 12u + kWorldCells,
              "слой знания: шапка 12 Б + байт на клетку капа");
// 2026-11-10, ломоть 3 сейв-эпика: поле владения землёй и список меток карты
// перестали быть заголовками векторов (по 24 Б) и стали плоскими.
static_assert(sizeof(CellOwnerField) == kWorldCells,
              "поле владения: байт на клетку капа, без шапки");
static_assert(sizeof(MarkerList) == 4u + kMaxMarkers * sizeof(Marker),
              "список меток: счёт 4 Б + записи по 68 Б под капом");
// 2026-11-10, ломоть 4 сейв-эпика: последние заголовки векторов и строки
// состояния мира стали плоскими — поле следов, летопись, журнал и имя игрока.
static_assert(sizeof(ScentField)
                  == 8u + 2u * 2u * std::size_t(kMaxFactions) * kWorldCells,
              "поле следов: шапка 8 Б + два канала u16 на клетку капа "
              "каждого плана под потолком фракций");
// 2026-11-10, M-423: кольцо летописи (2^16 записей по 32 Б с головами цепочек
// в состоянии) стало дописываемым логом (2^22 записей по 28 Б), а головы и
// ссылки цепочек ушли из состояния в выводной индекс; журнал игрока (2^20
// копий записей) снесён — его история есть цепочка его сквада.
static_assert(sizeof(Chronicle)
                  == 16u + std::size_t(kChronicleFactsCap) * sizeof(WorldFact),
              "летопись: шапка 16 Б + лог записей под капом");
static_assert(sizeof(PlayerState) == 16u,
              "состояние игрока: 16 Б без дыр (кодекс 8, возраст 4 и четыре "
              "названных байта выравнивания; ячейка имени 32 Б снесена "
              "вердиктом В3 — имя есть колонка анкеты сквада; журнал копий "
              "фактов снесён M-423 — история игрока есть цепочка его сквада)");

// ── СТОРОЖ (2): РАЗМЕР КОНТЕЙНЕРА — ЛОВУШКА НА КОСТЫЛЬ ───────────────────
// Пришитое к этим структурам поле двигает sizeof, и сборка краснеет. Именно
// так нарушение инварианта становится ВИДНЫМ, а не обнаруживается через год.
// 2026-09-24, слияние M-71: пул дезертиров стал единым контейнером
// (SoldierSquad 3076 → Inventory 40960), отсюда 11576 → 49456
// (−4: с SoldierSquad ушёл его хвостовой счётчик с паддингом).
// 2026-09-26, снос мёртвой таблицы энкаунтеров: из `GameSubState` ушли три
// колонки без читателя — `eventId` и `enemyId` (по 24 Б, `std::string`) и
// `pendingEncounterIdx` (4 Б), итого 52 Б плюс 4 Б выравнивания = −56,
// отсюда 49456 → 49400. Сторож сработал ровно как задуман: снос колонки
// покраснел здесь, а не всплыл через год (§8 ЗАКОН НУЛЕВОЙ п.6 — лучшая
// форма свидетеля есть нарушение, которое невозможно собрать).
// 2026-09-29, M-106 1е кластер 5: +8 Б — игрок стал двумя packed-хэндлами
// мира (`playerSquadBits`/`playerFlagBits`, по 4 Б без паддинга: соседние
// u32); с 5б оба поля — КЭШИ колонок анкеты (playerFlag, spawnId).
// 2026-09-30, M-37: −8 Б — `nextLandmarkOrdinal` умер (u32 + 4 Б
// выравнивания): ординалы мест выдаёт ЕДИНЫЙ эмитент субъектов
// `nextMacroSpawnOrdinal`, выдача с 1, 0 навсегда «никто» (закон
// нуля-ординала, AGENTS ЗАКОН СЛОВАРЯ И ОРДИНАЛА п.6).
// 2026-09-30, ход 2 ломтик C: РОД 6 стал строками — RelationMatrix (5696)
// умер в FactionState (793096: 64 строки по 104 + пул феодальных рёбер
// 32768×24 + счёт и штамп), 49400 → 836800. Пул — на месте трёх колонок
// дани КАЖДОГО места (закон «дань — система фракций»).
