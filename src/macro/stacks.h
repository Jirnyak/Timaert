// ПЕРЕПИСЬ ШТАБЕЛЕЙ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ НАПИСАНО, ИЗ ЧЕГО СДЕЛАН МИР.
//
// ИНВАРИАНТ ШТАБЕЛЯ (владелец, 2026-09-22). Состояние мира есть набор
// ШТАБЕЛЕЙ — непрерывных массивов ОДИНАКОВЫХ структур, адресуемых ординалом.
// Легальных форм ровно три, и все три — один и тот же штабель под разными
// именами:
//
//   ПО КЛЕТКЕ    — поле над миром: буквально число в каждой клетке тора;
//   ПО ОРДИНАЛУ  — сущности: сквады, существа, предметы;
//   КАТАЛОГ      — строки законов: спеллы, скиллы, рецепты, рода, ресурсные
//                  ряды. Неизменяемый штабель, известный на сборке.
//
// Плюс ровно одно исключение, названное вслух: СКАЛЯРЫ МИРА — день, сид,
// размер карты, счётчики-выдатчики ординалов. Их один явный блок, и он тоже
// числится здесь.
//
// ДОБАВЛЕНИЕ КОНТЕНТА РАЗРЕШЕНО ДВУМЯ ХОДАМИ И НИКАКИМИ ДРУГИМИ:
//   1) новая СТРОКА в существующий штабель (новое существо, спелл, рецепт);
//   2) новый ШТАБЕЛЬ той же формы (новый ресурс = новое поле над миром).
// Служебный вектор, хеш, одиночное число сбоку, поле, пришитое к чужой
// структуре, — НАРУШЕНИЕ. Владелец дословно: «если я захочу новый ресурс оно
// не сможет никак его добавить кроме как новое поле потому что другое сразу
// сломает ИНВАРИАНТ».
//
// ── ПОЧЕМУ ЭТО ФАЙЛ КОДА, А НЕ РАЗДЕЛ ДОКУМЕНТА ──────────────────────────
// Потому что документ не ловит. Здесь стоят ДВА рода сторожей, и оба
// компиляторные:
//
//   (1) РАЗМЕР СТРОКИ каждого штабеля закреплён `static_assert`. Раздулась
//       строка — красная сборка, и картина памяти не может разойтись с прозой
//       молча (она уже расходилась: шапка обещала «~36 bytes», правда была 96).
//
//   (2) РАЗМЕР САМОГО КОНТЕЙНЕРА закреплён тоже. Это и есть ловушка на
//       костыль: пришил служебный вектор к `GameState` — `sizeof` уехал,
//       сборка красная, и прятать это некуда. Ни один костыль не может
//       встать молча.
//
// Меняешь форму сознательно — правишь число ЗДЕСЬ, и правка видна в дифе
// отдельной строкой. Это и есть «полный контроль, что делаем».
//
// Картина мира словами живёт в SKELETON.md; здесь — та же картина числами,
// которые проверяет компилятор.
