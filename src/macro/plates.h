// ПЛИТЫ — ГРУБАЯ МАКРОЗАТРАВКА МИРА, И ТОЛЬКО ОНА.
//
// Владелец, дословно (2026-10-03): «это МАКРО как затравка и потом всё поверх
// генерится процедурно случайно шумно органично естественно агностично»;
// «это будет очень грубая макро затравка, не надо эти числа прям отслеживать,
// это буквально на глаз обозначить — вот тут море (чёрное), тут плато (белое),
// тут пустыня/долина (серое)».
//
// Значит плита есть ОДИН ПИКСЕЛЬ той серой карты. Сегодня её рисует сид;
// завтра пришлёт дизайнер, и ни одна строка потребителя не изменится —
// меняется только дверь рождения (`make_plates`).
//
// ── ПОЧЕМУ «ПЛИТА», А НЕ «ЗОНА» ─────────────────────────────────────────────
// Слово «зона» в этом проекте ЗАНЯТО: `ZoneLayer@src/macro/zones.h` — поле
// СЛОЖНОСТИ, байт опасности на клетку, род 3 канонического фрейма. Завести
// второе значение одного слова значило бы ровно второй словарь (ЗАКОН СЛОВАРЯ).
// В разговоре с владельцем это «карта зон»; в коде — карта плит.
//
// ── ОТСУТСТВИЕ КАРТЫ ЕСТЬ ЗНАЧЕНИЕ, А НЕ ОТСУТСТВИЕ ─────────────────────────
// Владелец, дословно: «все системы должны работать, и если дизайнер не прислал
// — то есть из обычного шума; дизайн-зоны получатся в этой системе частным
// случаем». Здесь это исполнено ПО ПОСТРОЕНИЮ, а не дисциплиной: «дизайнер не
// прислал» тождественно «прислал ровно серое», то есть `levelBias` ноль у всех
// строк. Поэтому ветки «а есть ли карта» не существует и завести её нельзя —
// путь один, и авторская карта лишь заполняет столбец, который и так есть.
// Это тот же закон, по которому у способности мгновенность есть восстановление
// 0, а бесплатность — цена 0 (ЗАКОН СПОСОБНОСТИ п.2).
//
// И гряды от карты НЕ ЗАВИСЯТ вовсе: их ставит дрейф плит, который приходит из
// сида. Мир без дизайнера — полноценный мир, а не обеднённый.
//
// ── ЧТО ЭТО НЕ ЕСТЬ ─────────────────────────────────────────────────────────
// Это НЕ климат. Влажность и температура остаются независимым шумом и высоту
// не читают; биом собирает каскад `biome_classify@src/macro/map_generator.h` —
// вода по плоскости моря, гора по высоте, остальное по климату. Плиты в этот
// каскад не входят ни одной строкой (вердикт владельца 2026-10-03: «лучше чтобы
// климат отработал агностично эмерджентно… не надо переплетать системы»).
//
// Это НЕ система воды. Море, залив и озеро остаются тем, чем были: любой
// рельеф ниже плоскости моря (`TerrainData::is_water`). Плита умеет лишь
// ОПУСТИТЬ округу своим сдвигом, а нальёт туда воду всё та же плоскость —
// агностично, без строки «здесь море».
//
// ── ДВА СЛЕДСТВИЯ ИЗ ОДНОЙ ГЕОМЕТРИИ ────────────────────────────────────────
// Вес плиты спадает от ближайшей за `kPlateEdgeCells`:
//     w = max(0, 1 − (d − d_min) / край)
// Внутри плиты ненулевой вес РОВНО ОДИН, у шва их два-три, на тройном стыке
// три — поэтому ни одного прямого реза по биссектрисе не возникает. Из этого
// же веса выходят оба ответа, и третьего механизма заводить не нужно:
//   · СДВИГ УРОВНЯ — взвешенное среднее столбцов (плавно, без ступеней);
//   · ШОВ — ИЗБЫТОК веса `Σw − 1`: ноль внутри плиты, максимум на шве.
//
// ЗАМЕР, КУПИВШИЙ ЭТУ ФОРМУ (прототип, 2026-10-03, инструмент вопроса снесён).
// Сперва пробовалось «плита несёт свой УРОВЕНЬ» — кусочно-постоянное поле над
// мозаикой Вороного. Числа хвалили (доля суши, с которой видно плоский передний
// план и стену в 10–50 км: 5.2 % → 29.5 %), а КАРТИНКА показала СОТЫ: ступень
// на каждом шве видна в рельефе всегда, и отбор «какие швы горные» её не
// прячет — проверено отбором по перепаду уровней. Поэтому плита уровень не
// задаёт, а СДВИГАЕТ, и сегодня сдвиг равен нулю у всех: мир рождается ровно
// как прежде, плюс гряды на швах.
#pragma once

#include <cstdint>
#include <vector>

namespace sm {

// ── ПРОЛЁТ ПЛИТЫ — ОН ЖЕ РАЗРЕШЕНИЕ АВТОРСКОГО ХОЛСТА ───────────────────────
// 64 клетки = 64 км, то есть карта 16×16 пикселей на мире 1024. Число назвал
// владелец (2026-10-03, дословно: «16×16 уже точно минимум, так 8×8 слишком
// мало деталей получится сделать») — это ТРЕБОВАНИЕ К ХОЛСТУ, и оно старше
// вида: систему под числа не подгоняют, но холст здесь и есть система.
//
// Вид при этом не проигран, и это замерено прототипом на том же сиде: доля
// суши, с которой видно плоский передний план и стену выше 1500 м в 10–50 км,
// при пролёте 64 равна 18.9 %, при 128 — 15.6 %, при 256 — 8.3 %. Картинка
// уклонов говорит ровно то же другими словами: при 64 выходят горные УЗЛЫ с
// отрогами и равнины между ними, при 128 — длинные линейные цепи, при 256 —
// одинокие валы, до которых из долины не досмотреть.
//
// Котловина между швами до 64 км ⇒ из её середины стена стоит не дальше 32 км,
// то есть внутри охвата дальней лестницы (98.3 км,
// `far_ladder_half_span_m@src/sub/far_mesh.h`) и видна целиком.
//
// По-двойка здесь ПОКУПАЕТ, а не украшает: сторона мира — степень двойки
// (ЗАКОН АДРЕСА), значит решётка целая при любом законном мире, остатка нет по
// построению, а заворот решётки есть маска.
inline constexpr int kPlateSpanCells = 64;

// ШИРИНА ШВА — сколько клеток занимает переход между плитами, он же ширина
// горного фронта. 32 клетки = 32 км на всю ступень, то есть по 16 км на склон:
// подъём от подножия к гребню идёт шестнадцать клеток, а не обрывом в одну.
// Замер прототипа при пролёте 64: ±16 клеток дают сомкнутые массивы с
// отрогами, ±10 — рассыпанную паутину коротких трещин.
inline constexpr int kPlateEdgeCells = 32;

// КРИВИЗНА ШВА — СВОЙСТВО РЕШЁТКИ, А НЕ ПРИКАЗ ЗВОНЯЩЕМУ. Шов спрямлён по
// природе (это граница ячейки Вороного), и прямая линия в рельефе читается
// рукотворной, поэтому запрос к плитам искривляют. Искривляет ЗВОНЯЩИЙ своим
// полем — у синтеза высоты оно уже посчитано, и нового шума не заводится;
// здесь published лишь ПРЕДЕЛ: 8 клеток есть 1/8 пролёта плиты, при котором
// шов гуляет заметно, а соседство плит не перемешивается, то есть топология
// авторского холста цела.
inline constexpr int kPlateWarpCells = 8;

// ── ЧТО ЗНАЧИТ ПОЛНОСТЬЮ БЕЛЫЙ (И ПОЛНОСТЬЮ ЧЁРНЫЙ) ПИКСЕЛЬ ─────────────────
// Шкала авторского холста в единицах поля высот, и она выведена из двух
// требований владельца к карте, а не выбрана:
//   · ЧЁРНОЕ ОБЯЗАНО ТОНУТЬ. Медиана суши стоит на 0.55 поля, плоскость моря
//     на 0.40 — значит чёрный пиксель обязан уметь опустить обычную равнину
//     НИЖЕ воды, то есть сдвиг не меньше 0.15.
//   · БЕЛОЕ ОБЯЗАНО СТАНОВИТЬСЯ НАГОРЬЕМ. Горная линия стоит на 0.625
//     (`kMountainBiomeLevel`), значит белый обязан поднять ту же равнину выше
//     неё, то есть не меньше 0.08.
// 0.20 покрывает оба с запасом: чёрное уводит медианную равнину на 0.35 (под
// воду), белое — на 0.75 (высокое нагорье). Величина БАЛАНСНАЯ: двигается
// свободно, когда дизайнер скажет, что холст говорит слишком тихо или слишком
// громко.
inline constexpr float kPlateBiasFullScale = 0.20f;

// ЗАТРАВКА ПЛИТЫ СМЕЩЕНА ВНУТРИ СВОЕЙ ЯЧЕЙКИ — иначе решётка правильная и
// швы встают сеткой. Доля ячейки, полный диапазон дрожи.
inline constexpr float kPlateJitter = 1.0f;

// ── ОРДИНАЛ ПЛИТЫ — `uint16`, И ЭТО СЧЁТ, А НЕ ПРИВЫЧКА ─────────────────────
// Кап = плит на мир = (сторона / пролёт)². Байт сюда НЕ ВЛЕЗАЕТ, и промах был
// ровно на одну единицу: мир 1024 при пролёте 64 даёт решётку 16×16 = **256**
// плит, то есть ординалы 0…255, а 255 уже занято под «никого» — последняя
// плита назвалась бы пустотой молча. Мир 4096 даёт 4096 плит и разносит байт
// вовсе. Слово держит решётку до 255×255, то есть сторону до 16320 клеток —
// запас назван, а не предположен. Цена — 2 МиБ на поле вместо 1 при 1024²
// (DOD п.2: «десятки и даже сотни мегабайт бесплатны»).
//
// «Нет плиты» — ПОСЛЕДНЕЕ значение типа, а не −1 (ЗАКОН УЗКОГО ИНДЕКСА): слот
// 0 есть законная плита, поэтому ноль здесь занять нельзя.
using PlateOrdinal = std::uint16_t;
inline constexpr PlateOrdinal kNoPlate = 65535u;
// Сколько плит помещается в тип — кап стоит РЯДОМ, под компилятором, а не под
// комментарием.
inline constexpr int kMaxPlates = int(kNoPlate);

// СТРОКА ПЛИТЫ — ОДИН ПИКСЕЛЬ АВТОРСКОЙ КАРТЫ.
//
// Колонки названы по правилу DOD п.9 — «кто читает и зачем»:
//   · u, v      — где стоит затравка плиты, в долях тора. Читает
//                 `plate_sample`: вес плиты есть функция расстояния до неё.
//   · drift     — КУДА ПЛИТА ИДЁТ, радианы. Читает `plate_sample`, чтобы
//                 ответить «сходятся ли плиты здесь»: гряда встаёт только на
//                 сходящемся шве, иначе горы встают на КАЖДОМ шве и мир
//                 вырождается в соты (замерено картинкой, см. шапку).
//   · levelBias — ЕДИНСТВЕННЫЙ АВТОРСКИЙ СТОЛБЕЦ: насколько эта плита тянет
//                 округу вверх или вниз, в единицах поля высот. Чёрный пиксель
//                 карты = минус (утонет под плоскостью моря), белый = плюс
//                 (плато), серый = ноль. Читает `plate_sample`. СЕГОДНЯ У ВСЕХ
//                 ПЛИТ НОЛЬ — столбец заложен, а не включён.
struct PlateRow {
    float u = 0.0f;
    float v = 0.0f;
    float drift = 0.0f;
    float levelBias = 0.0f;
};

// ОТВЕТ ПЛИТ ОДНОЙ ТОЧКЕ МИРА. Три числа, и все три выведены из одного веса.
struct PlateSample {
    // Гладкий сдвиг уровня в единицах поля высот. Ноль, пока карта пуста.
    float levelBias = 0.0f;
    // 0 в глубине плиты, 1 на шве. Это и есть «где стоит гряда».
    float seam = 0.0f;
    // Сходимость: насколько плиты ДАВЯТ в эту точку. Больше нуля — сжатие
    // (горы), меньше — растяжение (гор нет). Непрерывно по построению.
    float squeeze = 0.0f;
    // Ординал ближайшей плиты — та, «чья это клетка».
    PlateOrdinal nearest = kNoPlate;
};

// КАРТА ПЛИТ — КАРКАС МАКРОМИРА.
//
// `rows` — строки плит, `lattice²` штук. `cell` — ПОЛЕ ординала плиты над
// клетками, один байт на клетку (вердикт владельца 2026-10-03: каркас обязан
// быть полем, а не только функцией). Форма та же, что у `TerrainData::biome`,
// и закон тот же: РОЖДЕНИЕ считает, ЖИВОЙ МИР читает.
//
// ПИШЕТ `cell` РОВНО ОДНО МЕСТО — поклеточный проход синтеза высоты, тем же
// `plate_sample`, которым он берёт шов. Отдельной двери выпечки здесь НЕТ
// намеренно: синтез уже искривляет запрос своим полем, и вторая дверь пекла бы
// ординал по НЕискривлённому — два ответа на «чья это клетка», расходящиеся на
// ширину искривления.
//
// ЧЕСТНО О ЧИТАТЕЛЕ ПОЛЯ: сегодня `cell` читают прибор `height_census` (пишет
// карту плит картинкой — ею и судится вид) и свидетель. Живой мир его ещё не
// спрашивает: это ЗАДЕЛ под дизайн-эпик и под родины фракций, заказанный
// владельцем прямо, и так он и назван здесь, чтобы следующий не принял его за
// забытую колонку (DOD п.9).
//
// В сейв не едет: терраин не хранится вовсе, мир пересобирается из сида.
struct PlateMap {
    int lattice = 0;                   // плит по стороне мира
    std::vector<PlateRow> rows;        // lattice² строк
    std::vector<PlateOrdinal> cell;    // ординал плиты на клетку

    bool valid() const {
        return lattice > 0
            && rows.size() == std::size_t(lattice) * std::size_t(lattice);
    }
};

// Размер строки назван — значит закреплён (DOD п.10). Четыре числа и ни байта
// воздуха: 16 Б × 256 плит = 4 КиБ на мир 1024.
static_assert(sizeof(PlateRow) == 4 * sizeof(float),
              "строка плиты — четыре числа подряд, без дыр выравнивания");

// РОЖДЕНИЕ КАРКАСА — ОДНА ДВЕРЬ. Сегодня строки заполняет сид; дверь для
// авторской карты встанет РЯДОМ и вернёт тот же `PlateMap`, поэтому ни
// `plate_sample`, ни синтез высоты о подмене не узнают.
//
// `side` — сторона мира в клетках (степень двойки, ЗАКОН АДРЕСА). Мир меньше
// одного пролёта плиты отдаёт пустую карту: каркас из одной плиты швов не
// имеет, и это честный отказ, а не выдуманная решётка.
PlateMap make_plates(int side, std::uint32_t seed);

// ЧТО ПЛИТЫ ОТВЕЧАЮТ ТОЧКЕ (u, v) ∈ [0,1)² — долям тора, а не клетке:
// синтез высоты спрашивает в непрерывных координатах, и квантовать вопрос до
// клетки здесь нельзя. ЗАМЕРЕНО: расстояние до шва, взятое по клеткам, кладёт
// на фланги хребтов полосчатую рябь изолиний (прототип, картинка уклонов).
//
// `seamWidthScale` — ВО СКОЛЬКО РАЗ ШОВ ЗДЕСЬ ШИРЕ ОБЫЧНОГО. Ширина горного
// фронта не постоянна, и постоянная читается штампованной: ровная кривая
// подножия обнажает фаски Вороного. ЧЕМ её модулировать — дело звонящего, а не
// плит (ЗАКОН АГНОСТИЧНОСТИ: фундаментальная система не знает, кто и зачем её
// позовёт); синтез высоты подаёт сюда своё поле детали, которое всё равно уже
// посчитано. Единица — ровный шов.
PlateSample plate_sample(const PlateMap& map, float u, float v,
                         float seamWidthScale);

} // namespace sm
