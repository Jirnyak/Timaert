// СУД ГРАНИЦЫ СЕЗОНА — ОДНА ДВЕРЬ НА ВСЯКИЙ СЧЁТ СОДЕРЖАНИЯ В МИРЕ.
//
// CANON S4 («гарнизон = ростер ландмарка, армия = ростер, артель = ростер;
// одна система, одна арифметика пищи, ОДИН СУД ГРАНИЦЫ») и S10 («у всякого,
// кто кормит, есть счёт»). До 2026-09-21 этот суд был написан ДВАЖДЫ —
// `garrison_upkeep_` для мест и `squad_season_window` для сквадов, — и обе
// копии делали одно и то же в три шага: взыскать прошлый счёт пропорционально,
// перевыставить по составу после убыли, погасить чем есть.
//
// СЧЁТ ТОЖЕ ЖИВЁТ ЗДЕСЬ — И ЭТО ПРАВКА 2026-09-22, ОТМЕНЯЮЩАЯ ПРЕЖНЮЮ ЗАПИСЬ.
// Здесь стояло: «дверь не считает СЧЁТ — его приносят; цена содержания
// зависит от контекста (дома ли состав, чей фуражир его ведёт), и это
// законные различия КОНТЕКСТА». Вердикт владельца 2026-09-22 снял оба
// различия («один закон без исключений»), и довод вместе с ними: полцены
// дома было хардкодом `>> 1` без вывода (почему половина, а не треть?), а
// скидка фуражира — вторым ответом на «сколько ест состав». Контекста не
// осталось — значит счёт не параметр, а ЗАКОН, и место закона здесь.
//
// ЧТО ЭТИМ СНЕСЕНО, ПОИМЁННО: шаблонный параметр `BillFn`, две лямбды в двух
// вызовах, `squad_season_needs`/`SquadSeasonNeeds` (npc_ai) и расхождение
// «кто считается ртом» — у места ели ВСЕ головы, у сквада только строки с
// `upkeepGoldPerDay >= 0`, то есть зверьё в поле не ело вовсе. Теперь рот —
// это строка существа и её колонка рациона (npc.h `npc_board_per_day`).
#pragma once

#include "macro/currency.h"   // pay_value_dense / inventory_value — плата стоимостью
#include "macro/econ_day.h"   // econ_pay_debt, hunger_commodity_ordinal, EconFactSink
#include "tables/npc.h"        // npc_board_per_day / soldier_upkeep — счёт по строкам
#include "macro/upkeep.h"
#include "macro/world_row.h"  // область существ единого контейнера (M-71)

#include <algorithm>

namespace sm {

// СЧЁТ, ВЫСТАВЛЕННЫЙ КОНТЕЙНЕРУ НА СЕЗОН. Две строки, и у каждой свой исход
// (CANON S4 «ХАРЧ — СМЕРТЬ, ПЛАТА — УХОД»).
struct UpkeepBill {
    int          board = 0;   // харч: единиц голодной строки на сезон
    std::int64_t wage  = 0;   // жалованье: стоимостью
};

// ОДИН ПРОХОД НА ОБЕ СТРОКИ СЧЁТА, И ОБЕ — ПО ТАБЛИЦЕ СУЩЕСТВ.
// Считает по СЛОТАМ области существ ЕДИНОГО контейнера (M-71), а не по
// душам: тысячная деревня — это два-три слота (генерики стоят стопкой),
// поэтому цена двери не зависит от размера контейнера.
inline UpkeepBill upkeep_bill(const Inventory& container) {
    int boardDay = 0;
    int wageDay  = 0;
    for (int i = container.creature_first(); i < kMaxInventorySlots; ++i) {
        const ItemRef& s = container.slots[std::size_t(i)];
        const std::uint16_t kind =
            std::uint16_t(creature_of_world_row(s.def));
        // Обе колонки спрашиваются у ОДНОЙ строки, своими дверьми:
        // `npc_board_per_day` — рацион, `soldier_upkeep` — плата (она же
        // читает `kNpcUpkeepNone` как ноль, поэтому зверь ест, но не
        // получает, и это сказано данными, а не веткой).
        boardDay += npc_board_per_day(soldier_npc_type(kind)) * s.count;
        wageDay  += soldier_upkeep(kind, s.level) * s.count;
    }
    return UpkeepBill{boardDay * kDaysPerSeason,
                      std::int64_t(wageDay) * kDaysPerSeason};
}

struct UpkeepWindowOutcome {
    // ДВЕ ПРИЧИНЫ — ДВА ЧИСЛА, потому что это два РАЗНЫХ события мира
    // (M-232). Здесь стояло одно `walked` и ярлык `byWage` «какая строка
    // победила» — форма, в которой «мир потерял душу» и «душа сменила
    // хозяина» были одним исходом с биркой.
    int starved = 0;      // душ УМЕРЛО за непокрытый ХАРЧ — ушли из мира
    int walked  = 0;      // душ УШЛО в пул за непокрытую ПЛАТУ
};

// Один суд, три шага. Счёт берётся ДВАЖДЫ одной и той же дверью: до убыли —
// как знаменатель доли неоплаченного, после — как новая недоимка.
// `store` — ЕДИНЫЙ контейнер владельца (M-71): его область существ и есть
// контейнер, его предметная область и есть склад; суд читает обе.
inline UpkeepWindowOutcome upkeep_season_window(Upkeep& r, Inventory& store,
                                                Inventory& pool,
                                                std::int64_t& burnedValue,
                                                EconFactSink sink,
                                                void* user) {
    UpkeepWindowOutcome out{};
    const int boardOrd = hunger_commodity_ordinal();
    if (boardOrd < 0) return out;   // мир без голодной строки не судит никого
    const UpkeepBill lastBill = upkeep_bill(store);

    // ── 1. ВЗЫСКАНИЕ ПРОШЛОГО СЧЁТА — ПРОПОРЦИОНАЛЬНО ────────────────────
    // Доля НЕОПЛАЧЕННОГО и есть доля ушедших: зеркало закона мест
    // (econ_debt_boundary). Кромка «покрыто ЦЕЛИКОМ или не списывается»,
    // доля 1/8 и пол «хотя бы одна душа» умерли 2026-09-21 — все три были
    // одним дефектом: контейнер из трёх душ терял треть вместо восьмой, а
    // покрывший 99 % нужды терял столько же, сколько не покрывший ничего.
    // ── ДВЕ НУЖДЫ — ДВА ИСХОДА, И ДОЛИ ПРИМЕНЯЮТСЯ НЕЗАВИСИМО ───────────
    // Вердикт владельца 2026-09-22, дословно: «еда голод смерть
    // пропорционально / неуплата дезертирство пропорционально»; про еду
    // отдельно: «еда просто умирают… технически просто пропадают
    // пропорционально из ростера» — из мира они уходят СОВСЕМ, а не в пул.
    // И 2026-09-21: «согласен харч смерть неоплата денег уход».
    //
    // ЗДЕСЬ СТОЯЛА «ХУДШАЯ ИЗ ДВУХ ДОЛЕЙ», И ТОТ ЖЕ ВЕРДИКТ ОТМЕНИЛ ЕЁ
    // ПРЯМО: она давала ОДИН исход на две разные причины и тем стирала
    // разницу между «мир потерял душу» и «душа сменила хозяина». Код прожил
    // с отменённой формулой две недели, а комментарий на этом месте её
    // ЗАЩИЩАЛ — и шапка файла при этом объявляла «у каждой строки свой
    // исход». Проза обещала закон, которого под ней не было.
    //
    // ОЧЕРЁДНОСТИ У ДОЛЕЙ НЕТ (владелец, там же: «в приоритете что дезертиры
    // нет — но и то не обязательно, если проще агностично, делай
    // агностично»). Обе берутся от ОДНОГО знаменателя — состава ДО убыли, —
    // поэтому «кто первым» не влияет на числа: не кормленная доля и не
    // плаченная доля считаются от одного и того же `souls`. Один и тот же
    // человек может быть и не кормлен, и не плачен; суммы долей это не
    // смешивает, а кламп ниже держит их в границах состава — он СТРАЖ
    // области определения, а не коридор поведения (ЗАКОН КЛАМПА).
    const int souls = creature_count(store);
    float unfedShare = 0.0f;
    if (lastBill.board > 0 && r.needDebt[boardOrd] > 0) {
        unfedShare = float(r.needDebt[boardOrd]) / float(lastBill.board);
    }
    float unpaidShare = 0.0f;
    if (lastBill.wage > 0 && r.wageDebt > 0) {
        unpaidShare = float(r.wageDebt) / float(lastBill.wage);
    }
    if (unfedShare  > 1.0f) unfedShare  = 1.0f;
    if (unpaidShare > 1.0f) unpaidShare = 1.0f;

    // ПОРЯДОК ИМЕЕТ ЗНАЧЕНИЕ РОВНО В ОДНОМ СЛУЧАЕ, И ОН НАЗВАН ВСЛУХ: когда
    // обе доли равны единице, независимость физически невозможна — у одного
    // тела не бывает двух судеб. Первой идёт СМЕРТЬ, потому что умерший не
    // может потом уйти: мёртвый не дезертирует. Это не очерёдность законов, а
    // разрешение ничьей, и она разрешается в пользу более сильного события.
    //
    // ХАРЧ — СМЕРТЬ. Душа снимается тем же `creatures_pop_back`, что у
    // ухода, и НИКУДА не кладётся: приёмника у смерти нет, значит нет и
    // отказа — в этом она противоположность уходу ниже, который пул может
    // не принять. Форма та же, что у павших сквадов (M-228,
    // `creatures_kill_all@src/macro/world_row.h`), только доля, а не всё.
    int dying = int(float(souls) * unfedShare);
    while (dying-- > 0 && !creatures_empty(store)) {
        SoldierRecord dead{};
        if (!creatures_pop_back(store, dead)) break;
        ++out.starved;
    }
    // ПЛАТА — УХОД. Пул МОЖЕТ отказать (свой кап слотов), и тогда человек
    // возвращается в состав: никто не уничтожается за то, что стоял за
    // капом (CANON S26). Голодная смерть выше этого права не имеет и не
    // нуждается в нём.
    int walkers = int(float(souls) * unpaidShare);
    while (walkers-- > 0 && !creatures_empty(store)) {
        SoldierRecord walker{};
        if (!creatures_pop_back(store, walker)) break;
        if (!creatures_push(pool, walker)) {
            creatures_push(store, walker);   // пул полон: человек остаётся
            break;
        }
        ++out.walked;
    }

    // ── 2. НОВЫЙ СЧЁТ по составу ПОСЛЕ убыли, ПЕРЕЗАПИСЬЮ ────────────────
    // Старая недоимка не переносится: взыскали — выставили новый. Поэтому
    // хранить исходную сумму не нужно, она пересчитывается из состава.
    const UpkeepBill next = upkeep_bill(store);
    r.needDebt[boardOrd] = std::int32_t(next.board);
    r.wageDebt = next.wage;
    if (creatures_empty(store)) {
        r.needDebt[boardOrd] = 0;
        r.wageDebt = 0;
        return out;
    }

    // ── 3. НЕМЕДЛЕННОЕ ГАШЕНИЕ, И ОНО ЧАСТИЧНОЕ ──────────────────────────
    // Харч — той же дверью, что у населения этого же склада: что лежит, то
    // и съедено сейчас, остальное остаётся долгом и гасится приходом весь
    // сезон. Плата — стоимостью, монеты первыми по плотности value/kg;
    // уплаченное СГОРАЕТ в пул лута («жалование сгорает естественно»).
    if (r.needDebt[boardOrd] > 0) {
        econ_pay_debt(store, r.needDebt, sink, user);
    }
    if (r.wageDebt > 0) {
        const std::int64_t canPay =
            std::min<std::int64_t>(r.wageDebt, inventory_value(store));
        if (canPay > 0) {
            burnedValue += pay_value_dense(store, int(canPay));
            r.wageDebt -= canPay;
        }
    }
    return out;
}

} // namespace sm
