// ПОДБОР КЛЕТКИ ПОД СТРУКТУРУ — ОДНА ДВЕРЬ НА ВЕСЬ МИР И НА «РЯДОМ С X» (M-248).
//
// ТРЕБОВАНИЕ ВЛАДЕЛЬЦА (2026-11-10, дословно): «если будет создан модуль дизайн
// данжа то должно быть возмондо системно постаивть его в любую точку мира»;
// «прост оложит ьпо индексу клетки и генератор лкально в ней вызывает
// генераицю модуля структуры субмира это должно работать ганотсично системно».
//
// Поставить структуру — два шага, и оба теперь двери, а не арифметика автора:
//   1. НАЗВАТЬ КЛЕТКУ — `pick_site` ниже отвечает ОДНИМ ЧИСЛОМ, индексом клетки
//      (ЗАКОН АДРЕСА: адрес клетки есть индекс);
//   2. ПОЛОЖИТЬ БАЙТ — `feature_put@src/macro/features.h`. Дальше работает то,
//      что стоит давно: байт едет в сейве членом состояния, а субмир на этой
//      клетке зовёт модуль строкой таблицы по байту
//      (`kFeatureGenRows@src/sub/gens/dispatch.cpp`).
//
// ЧТО ЗДЕСЬ СТОЯЛО ДО ДВЕРИ: руины и шпили несли КАЖДЫЙ СВОЮ копию одного и
// того же цикла — «розыгрыш клетки, отбор, счёт до ближайшей уже поставленной,
// лучшая из N» — с частными `bestX/bestY/bestScore` (`src/macro/ruins.cpp`,
// `src/macro/spires.cpp`). Третья структура означала третью копию, а вопрос
// «рядом с городом» не имел формы вовсе.
//
// ФОРМА ОДНА, ЧИСЛА РАЗНЫЕ. Область розыгрыша — прямоугольник на торе.
// «Весь мир» есть прямоугольник (0, 0, сторона, сторона); «рядом с X в
// радиусе r» — прямоугольник (x−r, y−r, 2r+1, 2r+1). Арифметика розыгрыша одна
// и та же, поэтому путь «рядом с X» есть тот же код, по которому каждый день
// рождения мира ходят руины и шпили, а не спящая ветка рядом с ним.
//
// ПОТОК СЛУЧАЙНЫХ ЧИСЕЛ СОХРАНЁН БИТ В БИТ: на каждую попытку ровно два
// розыгрыша (x, затем y) — до отбора, как в обоих прежних циклах. Миры сидов
// от переезда на дверь не сдвинулись ни на клетку.
//
// ГЕНЕРАЦИЯ ИЛИ ЖИВОЙ МИР — ДВЕРИ ВСЁ РАВНО. Она не держит состояния, читает
// только то, что ей дали, и пишет только в поток звонящего. В тике её цена —
// `tries` вызовов отбора и `tries × apart.size()` расстояний; звонящий из
// живого мира платит её за событие («квест выдан»), не за кадр.
#pragma once
#include "core/rng.h"
#include "core/torus.h"
#include "macro/features.h"
#include "macro/map_generator.h"

#include <algorithm>
#include <cstdint>
#include <span>

namespace sm {

// «Клетки нет»: область не дала ни одной клетки, прошедшей отбор. Не ноль —
// клетка 0 есть честная клетка мира.
inline constexpr std::uint32_t kNoSite = 0xFFFFFFFFu;

// Область розыгрыша — прямоугольник на торе: левый верхний угол (может лежать
// за краем мира — заворот делает адресная дверь) и стороны в клетках.
struct SiteArea {
    int x0 = 0, y0 = 0;
    // ПРОЛЁТ РОЗЫГРЫША по каждой оси, в клетках, — НЕ сторона мира: у области
    // «рядом с X» он равен 2r+1 и степенью двойки не является. Остаток по
    // нему ниже сужает случайное число до пролёта и клетку мира НЕ
    // сворачивает: заворот адреса делает маска `cell_of` (ЗАКОН АДРЕСА).
    int spanX = 0, spanY = 0;
};

// Весь мир.
inline SiteArea site_area_world(int side) { return {0, 0, side, side}; }

// Квадрат радиуса `radius` клеток (метрика Чебышёва) вокруг клетки `anchor`.
// Радиус, при котором квадрат шире мира, даёт весь мир вокруг якоря — на торе
// «дальше половины стороны» не существует, и клетка не должна разыгрываться
// дважды чаще соседней из-за заворота.
inline SiteArea site_area_near(std::uint32_t anchor, int radius, int side) {
    const int r = radius < 0 ? 0 : radius;
    const int span = (r >= side / 2) ? side : 2 * r + 1;
    const int half = span / 2;
    return {cell_x(anchor, side) - half, cell_y(anchor, side) - half,
            span, span};
}

// ОБЩИЙ ОТБОР «ЗДЕСЬ МОЖЕТ ВСТАТЬ СТРУКТУРА»: суша, и клетка ещё не занята
// фичей, у которой есть свой род места. ЗАНЯТА ЛИ КЛЕТКА — ВОПРОС К ФИЧЕ, А НЕ
// К СКВАДУ (вердикт владельца 2026-10-26: «МЕСТ НЕТ! … ФИЧИ ПРОСТО ЕСТЬ В
// МИРЕ»): клетка разрабатывается ровно одним способом (ЗАКОН ПОЛЯ п.3), и
// отвечает об этом БАЙТ. Этот вопрос стоял двумя одинаковыми функциями
// `cell_taken` в двух генераторах; скан стора сквадов, стоявший до них,
// после сноса сквадов руины и шпиля (M-320) отвечал бы «свободно» про клетку,
// на которой фича уже стоит.
inline bool site_open_for_structure(const FeatureLayer& features,
                                    const TerrainData& terrain,
                                    std::uint32_t cell) {
    if (terrain.is_water(cell)) return false;
    return rooted_kind_of_feature(features.at(cell)) == SquadType::None;
}

// ЛУЧШАЯ ИЗ `tries` (Mitchell best-candidate): среди разыгранных клеток
// области, прошедших `admit(cell)`, берётся та, что ДАЛЬШЕ ВСЕХ от клеток
// `apart` — ровный разброс без подобранной константы разноса. Пустой `apart`
// — побеждает первая прошедшая. Возвращает индекс клетки либо `kNoSite`.
//
// `side` — сторона мира (мир квадратен и степень двойки, ЗАКОН АДРЕСА);
// незаконный мир и пустая область отвечают `kNoSite`, не розыгрышем.
// `admit` — отбор звонящего: `bool(std::uint32_t cell)`. Он зовётся ПОСЛЕ
// обоих розыгрышей попытки, поэтому поток не зависит от его ответа.
template <typename Admit>
std::uint32_t pick_site(Rng& rng, int side, const SiteArea& area, int tries,
                        std::span<const std::uint32_t> apart, Admit&& admit) {
    if (!world_shape_ok(side, side) || area.spanX <= 0 || area.spanY <= 0)
        return kNoSite;
    std::uint32_t best = kNoSite;
    int bestScore = -1;
    for (int t = 0; t < tries; ++t) {
        const int dx = int(rng.next_u32() % std::uint32_t(area.spanX));
        const int dy = int(rng.next_u32() % std::uint32_t(area.spanY));
        const std::uint32_t cell = cell_of(area.x0 + dx, area.y0 + dy, side);
        if (!admit(cell)) continue;
        const int x = cell_x(cell, side);
        const int y = cell_y(cell, side);
        int score = side + side;   // мерить не от чего: любая клетка годится
        for (const std::uint32_t c : apart)
            score = std::min(score, torus_cheb_cells(
                x, y, cell_x(c, side), cell_y(c, side), side));
        if (score > bestScore) {
            bestScore = score;
            best = cell;
        }
    }
    return best;
}

} // namespace sm
