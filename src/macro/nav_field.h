// НАВИГАЦИЯ РЕЙСОВ — ОКРУГИ, ПОРТАЛЫ, ГРАФ (CANON S7, владелец 2026-09-02).
// Обобщение комнатной схемы (samosbor-maze: комнаты → поля дверей → таблица
// комнат; «персонаж читает число и шагает в меньшее») на макромир:
//
//   · ОКРУГА = зона тяготения ландмарка: одна мультиисточниковая Дейкстра
//     от ВСЕХ ландмарков по цене марша замощает весь тор — «отошёл от
//     ландмарка — там уже поле другого» (владелец). Радиуса нет: границы
//     эмерджентны, из любой глуши ты в чьей-то округе.
//   · ПОРТАЛ = лучший переход связного СЕГМЕНТА границы двух округ. Именно
//     по сегментам, не по парам: на торе две округи могут касаться двумя
//     несвязными отрезками, и один портал на пару резал бы цикл — миниатюра
//     шов-бага остовного дерева (gigahrush2 nav.md «Torus rules»: никогда
//     дерево — только циклический граф).
//   · ГРАФ ОКРУГ: узлы = ландмарки, рёбра = порталы (все, включая
//     пересекающие разрез — они существуют по построению, разреза в
//     пайплайне нет). Таблица next/dist — Дейкстра ПО ГРАФУ на узел.
//   · ПЛАНЫ ПОЛЕЙ ПОРТАЛОВ — приём статьи: поле портала обрезано своей
//     округой, поля разных округ не пересекаются и живут в одной плоскости;
//     плоскостей — по максимуму порталов одной округи.
//
// Походка = ТРИ ЧТЕНИЯ (nav_step): своя округа → цепочка родителей к цели /
// спуск к ландмарку; чужая → next-округа из таблицы → спуск по плану её
// портала. Ни волны, ни A* в горячем цикле. Сквад — читатель полей (S5).
//
// Всё derived: В СЕЙВ НЕ ЕДЕТ, перепекается честно при загрузке и по
// редким событиям (рождение/смерть ландмарка, мост — владелец: «создание и
// смерть ландмарка такое редкое событие, что ради него можно разок всё
// перепекать»). Цена шага — та же, что платит марш (PathCostData + climb);
// предикат стояния один (nav_can_stand).
#pragma once

#include <cstdint>
#include <vector>

#include "macro/macro_world.h"

namespace sm {

// Радиус РУК артелей (гейт труда, не навигации): рабочая зона добытчика =
// своя округа ∩ этот бокс. Равенство с kGathererReach охраняет
// static_assert в npc_ai.cpp.
inline constexpr int kNavHandReach = 16;

inline constexpr std::uint16_t kNavNoRegion  = 0xFFFF;
inline constexpr std::uint16_t kNavUnreached = 0xFFFF;
inline constexpr std::uint32_t kNavFar       = 0xFFFFFFFFu;
inline constexpr std::uint8_t  kNavNoStep    = 0xFF;

// Кап порталов ОДНОЙ округи (= потолок числа плоскостей планов; план — поле
// размером с карту, слоты × клетки × 2 байта, так что кап = потолок памяти
// планов: 64 × 1024² × 2 ≈ 128 МиБ худшего случая, фактических плоскостей
// столько, сколько нужно худшей округе). От чего зависит: от ГЕОМЕТРИИ
// границ одной округи — числа соседей и связных сегментов (изрезанность
// берега, водные зоны; мост добавляет сегмент). С числом ландмарков МИРА не
// растёт: округ больше — каждая мельче, соседей у одной примерно столько же.
// Измеренный максимум: 32 (сид 7, R=1649, с водным ярусом; кап 16 молча
// резал ВОДНЫЕ рёбра у 31 округи, и морская таблица рвала маршруты
// анклавов). 64 = запас ×2 (владелец, 2026-09-02: «на всякий случай»).
// Переполнение говорит вслух (stderr) И считается (portalOverflows ниже —
// грабля «кричит в stderr, grep не ловит» убита механизмом: тест читает
// счётчик), срез держит ДЕШЕВЕЙШИЕ переходы.
inline constexpr int kNavMaxPortalsPerRegion = 64;

// Прайсер моря: вода — мощёная дорога корабля («корабль делает воду
// дешёвой» — владелец; профиль движения, не свойство мира).
inline constexpr float kNavSeaWeight = 1.0f;

// Восемь направлений шага — один порядок для parent-байта и походки.
inline constexpr int kNavDX[8] = {0, 1, 1, 1, 0, -1, -1, -1};
inline constexpr int kNavDY[8] = {-1, -1, 0, 1, 1, 1, 0, -1};

struct NavPortal {
    std::int32_t  cellFrom = -1;   // клетка своей округи (индекс y*W+x)
    std::int32_t  cellTo   = -1;   // клетка соседней округи за переходом
    std::uint16_t toRegion = kNavNoRegion;
    std::uint8_t  plane    = 0;    // слот плана в своей округе
    // СТИХИЯ ребра (CANON S10, владелец 2026-09-02: «корабль делает воду
    // дешёвой» — универсально): 0 = сухое, 1 = водное. Водное ребро —
    // переправа берег→берег любой ширины; пеший профиль проходит его
    // только С НОСИТЕЛЕМ (корпус в счётчике порта / свой dock / верфь) —
    // условие сервиса, не свойство мира. Новая стихия (рельсы, воздух) =
    // новый класс ребра + строка профиля, походка не меняется.
    std::uint8_t  water = 0;
};

struct NavWorld {
    int mapW = 0, mapH = 0;
    // Свежесть: мир тот же (сид), ландмарки те же (число), мосты те же
    // (счётчик мостовых Built) — иначе перепёк.
    std::uint32_t bakedSeed = 0;
    std::uint32_t bakedLandmarks = 0;
    std::uint64_t bakedBridgeBuilts = 0;
    std::uint64_t seenBuiltCount = 0;   // хвост builtFeatures, уже просмотренный
    // Срезы капа порталов за последнее запекание: 0 = ни одна округа не
    // потеряла переход. Тест читает ЭТО, не stderr (грабля grep убита).
    std::uint32_t portalOverflows = 0;

    // ── Разбиение (по клеткам) ───────────────────────────────────────────
    std::vector<std::uint16_t> regionOf;   // округа клетки; kNavNoRegion = вода/недостижимо
    std::vector<std::uint16_t> distHome;   // цена пути до СВОЕГО ландмарка, кванты 1/16 (сатурируется)
    std::vector<std::uint8_t>  stepHome;   // шаг К СВОЕМУ ландмарку (0-7); kNavNoStep у самого ландмарка

    // ── ВОДНЫЙ ЯРУС (CANON S10 «ярус на стихию», владелец 2026-09-02) ────
    // «Чья вода» = продолжение сухих округ от их берегов (сиды СТАБИЛЬНЫ:
    // береговая география, не порты-сервисы — иначе вечный перепёк). Тем же
    // механизмом, прайсером моря: спуск по водному полю ведёт корабль по
    // фьордам так же надёжно, как пешего — суша.
    std::vector<std::uint16_t> waterRegionOf;   // чья вода; kNavNoRegion = суша/не залито
    std::vector<std::uint16_t> waterDist;       // цена до берега СВОЕЙ округи
    std::vector<std::uint8_t>  waterStep;       // шаг К БЕРЕГУ своей округи

    // ── Округа → ландмарк ────────────────────────────────────────────────
    std::vector<std::int32_t> regionLandmarkId;   // ординал ландмарка округи
    std::vector<std::int32_t> regionCell;         // клетка ландмарка

    // ── Порталы и планы ──────────────────────────────────────────────────
    std::vector<NavPortal>     portals;       // сгруппированы по округе
    std::vector<std::uint32_t> portalBegin;   // округа → [begin, begin+count)
    std::vector<std::uint8_t>  portalCount;
    int planeCount = 0;
    // planeCount × cells; значение клетки = цена до портала её слота,
    // обрезано округой (поля разных округ делят плоскость — приём статьи).
    std::vector<std::uint16_t> planes;

    // ── Граф округ, таблицы ПО ПРОФИЛЯМ (CANON S10) ──────────────────────
    // R×R: цена маршрута и ПЕРВАЯ округа шага к цели (как next[64][64]
    // gigahrush2). Циклы сохранены — короткая сторона тора честна.
    // routeNext/Dist — ПЕШИЙ профиль (только сухие рёбра); routeNextSea —
    // МОРСКОЙ (все рёбра): «агент в курсе» = читает таблицу своего профиля.
    std::vector<std::uint32_t> routeDist;
    std::vector<std::uint16_t> routeNext;
    std::vector<std::uint32_t> routeDistSea;
    std::vector<std::uint16_t> routeNextSea;

    // ── ПОЛЕ УГРОЗЫ (CANON S10 «хемотаксис по графу округ», 2026-09-02) ──
    // Скаляр threat НА ОКРУГУ, в ДЕНЬГАХ (стоимость погибших душ по строке
    // найма/жалованья — macro/threat_field.h, единственный писатель). Живёт
    // при графе, потому что делит его судьбу: перепёк перенумеровывает
    // округи, и threat_field_daily видит несовпадение размера и реплеит
    // свежую летопись заново. DERIVED — в сейв не едет, как весь NavWorld.
    std::vector<std::uint32_t> threat;
    std::uint32_t threatSeenSeq = 0;   // хвост летописи, уже влитый в поле

    bool baked() const { return mapW > 0 && !regionOf.empty(); }
    std::size_t cell(int x, int y) const;   // завёрнутый индекс
};

// ЕДИНЫЙ предикат стояния (CANON S7, владелец 2026-08-30): клетка, где
// нельзя встать лагерем, — не клетка для пешего автомата. Один закон, два
// читателя: марш (npc_ai can_stand_at делегирует) и запекание.
bool nav_can_stand(const MacroWorld& mw, int x, int y);

// Честное перепекание всего: разбиение → порталы по сегментам → планы →
// граф. Секунды на мир 1024²; зовётся редко (см. nav_ensure).
void nav_bake(const MacroWorld& mw, NavWorld& nv);

// Ленивая свежесть: перепечь, если мир/ландмарки/мосты изменились. Чужие
// Built (распашка, шахты) проходимость не меняют — поле живо. Возвращает
// готовность (false = нет gs/слоёв).
bool nav_ensure(const MacroWorld& mw, NavWorld& nv);

// ПОХОДКА — три чтения: следующий шаг из (x, y) к цели (tx, ty).
// false = система маршрута не знает (цель в воде, ходок в воде, мир не
// запечён) — вызывающий падает в жадный шаг.
bool nav_step(const NavWorld& nv, int x, int y, int tx, int ty,
              int& sdx, int& sdy);

// Округа клетки (kNavNoRegion, если не запечено/вода).
std::uint16_t nav_region_at(const NavWorld& nv, int x, int y);

} // namespace sm
