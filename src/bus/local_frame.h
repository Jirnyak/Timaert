// ЛОКАЛЬНЫЙ ФРЕЙМ — буфер ТОГО ЖЕ формата, что мир, охватом окна (ЗАКОН
// КАНОНИЧЕСКОГО ФРЕЙМА: «LocalContext — локальный буфер того же формата,
// размером 3×3 или размером данжа»). Пакетов ПЯТЬ (вердикт владельца
// 2026-10-15 «да 5 без фракций имел ввиду»): клетки · сквады-анкеты · поля ·
// мировые переменные · события/факты; род 6 придёт строкой, когда очередь
// дойдёт до фракций, — места под него не оставлено.
//
// ПАКЕТ — РАСКЛАДКА ПАМЯТИ, НЕ ПОСЫЛКА: «отправить» значит заполнить этот
// буфер, «получить» — прочитать его. Очередей, брокеров и каналов доставки
// не существует. Заполняет МАКРО-сторона (fill_local_frame@src/macro/) на
// границе макро-тика и на ре-центре (пересинхронизация ПЛАНОВАЯ); субмир
// читает. Форма агностична и не знает имён модулей: данж видит тот же буфер
// и волен не смотреть в него вовсе («у данжа нет окна» — про потребление).
//
// АНКЕТЫ ЕДУТ АДРЕСОМ, НЕ КОПИЕЙ (вердикт 2026-10-15 «ИСТИНА ВСЕГДА В
// МАКРОМИРЕ»): род 2 — хэндлы MacroHandle, тело субмира — воплощение, не
// владелец; дверь чтения состояния записи — зеркало (sub/record.h).
#pragma once
#include "bus/cell_row.h"
#include "bus/fact.h"
#include "core/caps.h"          // kUnifiedCap — единый кап сквадов макромира
#include "core/macro_handle.h"
#include <array>
#include <cstdint>
#include <type_traits>

namespace sm {

// ОХВАТ КЛЕТОК — 5×5 (вердикт владельца 2026-10-17, дословно в M-171: «ну
// если шире фрейм лучше то давай 5х5 … если надо больше то это нормально»).
// Снято с живого читателя: генерация клетки окна спрашивает её соседей, и
// кольцо плейсхолдеров шва читает ровно 5×5 вокруг центра. АРЕНДА и сквады
// остаются законом 3×3 — центр плюс восемь румбов (lease, M-226).
inline constexpr int kFrameSpan = 5;
inline constexpr int kFrameCells = kFrameSpan * kFrameSpan;   // 25

// РЯДЫ ПОЛЕЙ РОДА 3. Число обязано равняться счёту реестра полей
// (ResourceFieldId::Count); bus не включает macro/, поэтому равенство прибито
// static_assert-ом в сборщике — у единственного места, где оба числа видны
// (ЗАКОН СЛОВАРЯ п.3: пин законен только под static_assert).
inline constexpr int kFrameFieldRows = 5;

// КАП ОКНА ФАКТОВ РОДА 5. Вывод: летопись считает пик СВОЕГО дня колонкой
// factsPeak (контракт M-254) на ВЕСЬ мир в сотни строк; окно 25 клеток несёт
// хвост интереса локально, и 256 строк — порядок выше замеренного локального
// пика. Переполнение — честный срез новейшими (сборщик пишет новые первыми).
inline constexpr std::uint32_t kFrameFactsCap = 256;

// «Аренды нет» — сентинел рода 4; равенство с носителем мира
// (kNoWindowLease@src/macro/state.h) прибито static_assert-ом в сборщике.
inline constexpr std::uint32_t kFrameNoLease = 0xFFFFFFFFu;

struct LocalContext {
    // ── РОД 4 — МИРОВЫЕ ПЕРЕМЕННЫЕ («актор — сам мир») ────────────────────
    std::uint64_t worldTick = 0;   // мировое время, тиками (сутки = 8192)
    std::int32_t  worldDay = 0;    // производный день — его спрашивают факты
    std::uint32_t worldSeed = 0;   // сид сессии
    std::int32_t  side = 0;        // форма мира: сторона тора (степень двойки)
    std::int32_t  seaLevel16 = 0;  // плоскость моря (u16-домен терраина)
    std::uint32_t leasedWindow = kFrameNoLease;  // аренда: клетка-центр
    std::uint32_t centerCell = 0;  // клетка-центр ЭТОГО фрейма (адрес окна)
    // Хэндлы игрока — «кем играем» и «кто оригинал» (род 2-скаляры).
    MacroHandle playerFlag{};
    MacroHandle playerSquad{};

    // ── РОД 1 — КЛЕТКИ: 5×5 строк, ряды с северо-запада, центр = cells[12] ─
    std::array<CellFacts, kFrameCells> cells{};

    // ── РОД 3 — ПОЛЯ: запас ряда реестра на тех же клетках ────────────────
    // stock[ряд * kFrameCells + клетка]; порядок клеток тот же, что у cells.
    std::array<std::int32_t, std::size_t(kFrameFieldRows) * kFrameCells>
        stock{};

    // ── РОД 2 — СКВАДЫ клеток фрейма, АДРЕСОМ ─────────────────────────────
    // Кап — тот же kUnifiedCap, что у глобального фрейма (вердикт: кап один,
    // оплачен пустотой). Без инициализатора: кап-массив в заголовке с NSDMI
    // платил бы каждый включивший (AGENTS §5 п.13).
    std::uint32_t squadCount = 0;
    std::array<MacroHandle, kUnifiedCap> squads;

    // ── РОД 5 — СОБЫТИЯ/ФАКТЫ клеток фрейма (окно копией, вердикт Q3) ─────
    std::uint32_t factCount = 0;
    std::array<WorldFact, kFrameFactsCap> facts;
};
static_assert(std::is_trivially_copyable_v<LocalContext>,
              "пакет тривиально копируем (ФРЕЙМ п.7)");
// Цена названа (DOD п.10): 25 строк клеток по 72 Б + 25×10 запасов полей +
// 16384 хэндла (128 КиБ — кап оплачен пустотой, вердикт) + окно фактов
// 256×32 Б + скаляры = 142 120 Б ≈ 139 КиБ, один экземпляр у приложения.
static_assert(sizeof(LocalContext) == 141624,
              "локальный фрейм — 139 КиБ плоских родов; новая колонка = "
              "новая цена, названная вслух (DOD п.10)");

} // namespace sm
