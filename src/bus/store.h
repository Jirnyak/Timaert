// ── FOLD ЗАХВАТА — ТРЕТЬЯ ДВЕРЬ CellSub, ТЕПЕРЬ КЛЕТКА+ДОЛЯ (ЗАКОН ШВА,
// обобщение fold — ломоть 1 эпика M-419) ─────────────────────────────────
// Вниз клетка РАЗВОРАЧИВАЕТСЯ в континуум, вверх континуум СВОРАЧИВАЕТСЯ в
// числа клетки, и свёртку пишет СЦЕНА — с ЗАХВАТА для КАЖДОГО захваченного
// сквада окна, не только для того, которым играют (прежняя дверь
// `squad_set_sub` писала одну ДОЛЮ одному ФЛАЖКУ и умерла в эту; поправка
// 2026-10-26 «у прочих субмир положения не пишет вовсе» снята ЗАХВАТОМ).
// Клетка и доля — ОДНОЙ операцией на границе макро-тика. Смена клетки —
// честный румб входа: тело ПРОШЛО границу ногами, это не прыжок, поэтому
// доля НЕ зануляется (анти-`squad_jump_to_cell`), а часы думки не трогаются.
// Дверь, а не прямая запись колонки, по той же причине, что у
// `macro_mark_dead`: писателей колонки мира обязано быть видно поимённо.
// Протухший хэндл — no-op: позиция не ложится поверх нового жильца слота.
inline void squad_fold_pos(MacroStore& st, MacroHandle h, int x, int y,
                           std::int32_t side, ecs::CellSub sub) {
    if (!st.valid(h)) return;
    auto& rt = st.runtime[h.slot];
    auto& cell = st.cell[h.slot];
    const std::uint32_t newIdx = ecs::cell_index(x, y, side);
    if (newIdx != cell.idx) {
        // Румб — маской тора (ЗАКОН АДРЕСА: заворот — маска, не деление).
        // Fold зовут на границе КАЖДОГО макро-тика, тело окна не уходит
        // дальше соседа за тик, значит шаг оси ∈ {-1, 0, +1} по построению;
        // свёртка через половину стороны — на случай торового шва.
        const std::uint32_t mask = std::uint32_t(side) - 1u;
        const auto axis_step = [mask, side](int from, int to) {
            const int w = int((std::uint32_t(to) - std::uint32_t(from)) & mask);
            const int d = w > side / 2 ? w - side : w;
            return d < 0 ? -1 : (d > 0 ? 1 : 0);
        };
        rt.entryDir = pack_entry_dir(
            axis_step(cell_x(cell.idx, side), x),
            axis_step(cell_y(cell.idx, side), y));
        rt.entryTicks = 0;
        cell.idx = newIdx;
    }
    rt.sub = sub;
}

// THE macro jump (escape teleport, console goto, subworld exit door): set
// the holder's cell and erase the entry edge (a jump is not a walk —
// SubworldEngine::enter must fall back to the centre). The map EYE is left
// to the one glide cache on purpose (owner 2026-09-10: «универсально
// без игрокового кода»).
// (Тело переехало из macro/player_entity.h ломтём 5 M-171: прыжок — операция
// над колонками рода 2 по хэндлу, мира в ней нет; `side` приходит параметром
// — сторона мира у звонящего (gs.mapW наверху). player_jump_to_cell остался
// тонкой переадресацией — один закон, одно тело.)
inline void squad_jump_to_cell(MacroStore& st, MacroHandle h, int x, int y,
                               std::int32_t side) {
    if (!st.valid(h)) return;
    st.cell[h.slot] = ecs::MacroCell{ecs::cell_index(x, y, side)};
    // A jump is not a walk: no entry edge for the next subworld enter, and
    // the think cadence restarts (the accumulator doubles as the player's
    // entry-tick clock — same kAiTicks law as every squad's think).
    auto& rt = st.runtime[h.slot];
    rt.entryDir = kEntryDirNone;
    rt.entryTicks = 0;
    rt.tickAccum = 0;
    rt.sub = {};   // прыжок — центр клетки (M-244)
}

// «Я СРАЖАЮСЬ» — ОДНА операция боя субмира наверх (ЗАХВАТ п.3 ЗАКОНА ШВА;
// вердикт владельца: «если ктото из сквада вступает в файт В СУБМИРЕ!! …
// на макромир переходит смена сосотояния что он сражается (а это уже от
// модуля)»). Штамп-срок, не флаг: `fighting` взводится на `kFightThinks`
// думок и угасает САМ одной точкой драйвера — снятие снизу было бы ВТОРОЙ
// операцией (разбор — у kFightThinks в squad_row.h). Эмитент ОДИН — дверь
// урона (`apply_damage`, ДО смягчения: в бой втягивает само НАПАДЕНИЕ),
// сквад жертвы называет лестница `slot_squad_of@src/sub/record.h`;
// нападающий втягивается ответным ударом сам. Сквад ИГРОКА штампуется КАК
// ВСЕ — тело флажка несёт бэклинк (ступень 1 лестницы; стенд 2026-11-08
// опроверг прежнее «не штампуется по построению»), а угасает он у ЧАСОВ
// ФЛАЖКА (`advance_flag_clock@src/macro/npc_ai.h`, прецедент M-412д) —
// свип думок игрока не водит никогда.
// Род 2 пишется в момент события по построению (bus/delta.h) — это не
// новая нитка «по ходу». Читает состояние МОДУЛЬ сквада, НИКОГДА гейт ног
// (стопер `squad_mark_halted` снесён шагом 0 ЗАХВАТА; дверь чтения
// `squad_fighting` умерла ещё M-412). Протухший хэндл и мёртвый сквад —
// no-op, как у `squad_fold_pos` выше.
inline void squad_mark_fighting(MacroStore& st, MacroHandle h) {
    if (!st.valid(h) || st.dead[h.slot] != 0) return;
    st.runtime[h.slot].fighting = ecs::kFightThinks;
}

// Судьба макро-сквада — байт колонки (труп стоит до слива, AI-2); тело
// сцены отвечает тегом ecs::Dead своим путём (кластер 4). Протухший хэндл
// отвечает «мёртв» — fail-closed чтение: жилец слота сменился, и
// спрашивать о нём больше нечего.
inline bool macro_dead(const MacroStore& s, MacroHandle h) {
    return !s.valid(h) || s.dead[h.slot] != 0;
}
// Приписка в ведомость павших (M-376). Отдельной дверью, а не телом
// macro_mark_dead, ровно для одного второго писателя: ЗАГРУЗКА восстанавливает
// байт судьбы прямой колонкой (macro_snapshot.cpp) и обязана кормить ведомость
// той же строкой — иначе свип слеп к загруженным трупам.
inline void dead_ledger_append(MacroStore& s, std::uint16_t slot) {
    if (s.deadListed[slot] != 0) return;   // дубликат невыразим (шапка стора)
    s.deadListed[slot] = 1;
    s.deadRows[s.deadRowCount++] = slot;
}

// Компакция ведомости: снять флаги, переписать годных (живой слот с байтом
// судьбы). Сироты — слоты, перерождённые или уничтоженные, — исчезают за
// O(строк). Зовёт её свип трупов (destroy_dead_macro_squads) — единственный,
// кто строки ведомости СНИМАЕТ.
inline void dead_ledger_compact(MacroStore& s) {
    const std::uint32_t n = s.deadRowCount;
    for (std::uint32_t i = 0; i < n; ++i) s.deadListed[s.deadRows[i]] = 0;
    std::uint32_t kept = 0;
    for (std::uint32_t i = 0; i < n; ++i) {
        const std::uint16_t slot = s.deadRows[i];
        if (s.alive[slot] == 0 || s.dead[slot] == 0) continue;
        if (s.deadListed[slot] != 0) continue;
        s.deadListed[slot] = 1;
        s.deadRows[kept++] = slot;
    }
    s.deadRowCount = kept;
}

// Смерть по хэндлу: протухший хэндл — no-op (жилец уже сменился, мертвить
// некого); та же fail-closed пара к macro_dead выше. Уже мёртвый — тоже
// no-op: ведомость кормится ровно флипом судьбы 0 → 1.
inline void macro_mark_dead(MacroStore& s, MacroHandle h) {
    if (!s.valid(h) || s.dead[h.slot] != 0) return;
    s.dead[h.slot] = 1;
    dead_ledger_append(s, h.slot);
}

