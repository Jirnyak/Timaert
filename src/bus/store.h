//
// ФОРМА — `std::array<T, кап>` в ОДНОЙ heap-структуре, не векторы (вердикт
// владельца 2026-09-25): тип физически не умеет ресайзиться (инвариант в
// ТИПЕ, а не в дисциплине), sizeof закреплён ассертом целиком, смещения
