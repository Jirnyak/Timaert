inline void transfer_player_flag(MacroStore& st, MacroHandle& flagRef,
                                 MacroHandle to) {
    if (!st.valid(to)) return;
    if (st.valid(flagRef)) st.playerFlag[flagRef.slot].on = 0;
    st.playerFlag[to.slot].on = 1;
    flagRef = to;
}

