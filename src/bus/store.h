// Звонящих мало и это ПО ПРИРОДЕ ВОПРОСА: дом ставится один раз рождением
// игрока (macro/player_entity.cpp) и пересобирается резолвом загрузки. Он
// НЕ движется вселением — в этом вся разница с флажком, и ровно поэтому
