//
// СПИСОК КОЛОНОК — ОДИН ИСТОЧНИК (ЗАКОН СЛОВАРЯ п.3): X-macro ниже рождает
// и члены, и обнуление слота при рождении — забытая при переиспользовании
// колонка (призрак мёртвого) невозможна ПО ПОСТРОЕНИЮ, а не по памяти
// ревьюера. Условных компонент нет: CharacterSheet, SquadOrders,
// BodyEquipment, DesignCharacterTag — колонки ВСЕХ слотов (вердикт
// 2026-09-25: «полностью пользоваться анкетой своего сквада» — лорд НОСИТ
// артефактный меч, и авто-бой судит его тем же листом).
//
// ЭМИТЕНТ ОРДИНАЛОВ — ЗДЕСЬ, У СТОРА (M-220, арена-форма SubObjects::alloc):
// рождение ВЫДАЁТ идентичность само (nextSpawnId++, с 1 — закон
// нуля-ординала), и валидность ссылки судит ОНА: протухание = «spawnId
// слота не совпал с id ссылки». Монотонность — ЧЕРЕЗ ПЕРЕРОЖДЕНИЕ МИРА
// (store_reset счётчик НЕ трогает, как nextId арены): хэндл прошлого мира
// не совпадёт с новым жильцом ПО ПОСТРОЕНИЮ. До M-220 эмитент жил у
// GameState (nextMacroSpawnOrdinal) и при новой игре стартовал с 1 — суд
// по ID был бы ложен; роль протухания несла колонка generation, умершая
// этим шагом. ЗАКОН АГНОСТИЧНОСТИ цел: счётчик не знает, кто и зачем
// рождает, — он лишь не выдаёт одно имя дважды.
//
// ЧЕГО ЗДЕСЬ НЕТ, СОЗНАТЕЛЬНО:
//  · ПОРЯДКА ОБХОДА — закон порядка (squad_walk.h) живёт НАД хранилищем:
//    слоты переиспользуются, потому «по слотам» ≠ «по ординалу». Не путать
