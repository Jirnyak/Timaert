// Близнец двери выше и ровно та же форма: истина — КОЛОНКА playerFlag.home
// (род 2 фрейма), `homeRef` — КЭШ GameState (playerSquadRef). Ровно-один
// держит сама дверь тем же приёмом: старый носитель известен из кэша, запись
// нового срывает старый, O(1), скана нет.
