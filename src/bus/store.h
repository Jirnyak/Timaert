inline void mark_player_home(MacroStore& st, MacroHandle& homeRef,
                             MacroHandle to) {
    if (!st.valid(to)) return;
    if (st.valid(homeRef)) st.playerFlag[homeRef.slot].home = 0;
    st.playerFlag[to.slot].home = 1;
    homeRef = to;
}

