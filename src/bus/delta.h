// ДЕЛЬТА — обратный поток шва: строки-ОПЕРАЦИИ тех же родов, никогда снимки
// (ЗАКОН ШВА: операция коммутирует с фоновой симуляцией, снимок затирает).
// Премиса подтверждена владельцем 2026-10-16: буфер живёт ПАМЯТЬЮ СУБМИРА,
// копится, применяется операциями в ОДНОЙ точке на границе макро-тика;
// «каждая операция сразу в макро посреди тика» — отвергнутая форма.
//
// БУФЕРЯТСЯ РОДА 3 И 5 (вердикт владельца 2026-10-17): счётчики полей и
// факты летописи. РОД 2 НЕ буферится — раны/опыт/лут пишутся в запись в
// момент события сквозь дверь зеркала (sub/record.h; вердикты 2026-09-25 и
// 2026-10-15): зеркало копирует запись→тело каждый тик, и буфер ран разъехал
// бы две памяти — шрам раздетого лорда. Аренда и клетка игрока — протокол
// самого обмена, они immediate по построению.
#pragma once
#include "bus/fact.h"
#include <array>
#include <cstdint>
#include <type_traits>

namespace sm {

// ── РОД 3 — ОПЕРАЦИЯ НАД СЧЁТЧИКОМ ПОЛЯ/СТОКА ──────────────────────────────
// Операнды — ровно те, что несут двери стока сегодня (перепись 2026-10-17:
// macro_stock_apply и расписка MacroDebt): род стока, субъект (ординал
// сквада/места; 0 = клеточный ряд), клетка ОДНИМ числом (ЗАКОН АДРЕСА — у
// MacroDebt здесь пара координат, и это названное расхождение, которое
// строка дельты не повторяет), величина и две колонки детали (род и уровень
// головы — расписка существа контейнера).
struct StockOp {
    std::uint32_t cell = 0;        // клетка операции (одно число)
    std::int32_t  subject = 0;     // ординал субъекта; 0 = «никто» (клетка)
    std::int32_t  amount = 0;      // знаковая величина операции
    std::int32_t  detail = 0;      // деталь расписки (ординал головы и т.п.)
    std::uint16_t detailKind = 0;  // род детали
    std::int16_t  detailLevel = 0; // уровень детали
    std::uint8_t  stock = 0;       // ординал MacroStock (ряд/сток)
    std::uint8_t  door = 0;        // которой из трёх дверей применять
                                   //   (core/subtract.h: sat / spend / drain)
    std::uint8_t  pad[2] = {};     // явный хвост до кратности 4
};
static_assert(sizeof(StockOp) == 24, "строка операции стока — 24 Б, без дыр");

// Капы — операции ЗА ОДИН МАКРО-ТИК (буфер сливается каждый тик по
// построению, не за вылазку — M-98); переполнение — честный громкий отказ
// сборщика строк, не молчаливый дроп. Числа v1, калибруются замером.
inline constexpr std::uint32_t kDeltaStockCap = 1024;
inline constexpr std::uint32_t kDeltaFactCap = 256;

struct DeltaBuffer {
    std::uint32_t stockCount = 0;
    std::uint32_t factCount = 0;
    // Громкий счёт отказов: строка, не влезшая в кап, НЕ исчезает молча —
    // точка применения обязана назвать потерю (ЗАКОН ДВУХ ТЕМПОВ п.3).
    std::uint32_t droppedOps = 0;
    std::array<StockOp, kDeltaStockCap> stockOps;
    // Род 5 — факт целиком строкой WorldFact (операция «подшей факт»).
    std::array<WorldFact, kDeltaFactCap> factOps;
};
static_assert(std::is_trivially_copyable_v<DeltaBuffer>,
              "дельта — плоские строки, тривиально копируема");
// 1024×24 + 256×32 + три счёта = 32 780 Б ≈ 32 КиБ, член движка субмира.
static_assert(sizeof(DeltaBuffer) == 32780,
              "дельта-буфер — 32 КиБ строк-операций (DOD п.10)");

} // namespace sm
