// ── ФИКСТУРА РОЖДАЕТ СВОЁ ПРЕДУСЛОВИЕ САМА (§8 п.11) ─────────────────────
// Ни одно утверждение ниже не надеется, что генератор на каком-то сиде даст
// нужное место: мир здесь пуст, и всё, что судится, поставлено руками.
struct World {
    std::unique_ptr<sm::GameState> gsOwn = sm::make_game_state();
    sm::GameState& gs = *gsOwn;
    std::unique_ptr<sm::MacroStore> store = sm::make_macro_store();

    World() {
        // Сторона — степень двойки и квадрат (ЗАКОН АДРЕСА); мир крошечный,
        // потому что судится арифметика пары, а не размер тора.
        gs.mapW = 64;
        gs.mapH = 64;
    }

    sm::MacroWorld envelope() {
        return sm::MacroWorld{.gs = &gs, .store = store.get()};
    }
};

// Место с ПАСТВОЙ: `settle_souls` — единственная дверь появления души, и она
// пишет ОБА носителя, поэтому фикстура согласована по построению.
std::uint16_t born_rooted(World& w, sm::SquadType kind, int x, int y,
                         int souls) {
    const sm::MacroHandle h =
        sm::birth_squad(w.gs, nullptr, *w.store, kind, x, y, 0, "Fixture");
    sm::settle_souls(w.gs, *w.store, h.slot, souls);
    return h.slot;
}

int flock_of(World& w, std::uint16_t slot) {
    return cell_number_at(w.gs, *w.store, slot);
}
int folk_of(World& w, std::uint16_t slot) {
    return sm::count_human_souls(w.store->inventory[slot].inv);
}

// ── ДНЕВНОЙ ПРОХОД МОДУЛЯ МЕСТА (M-325) ──────────────────────────────────
// Число поля под местом ведёт ЕГО МОДУЛЬ и сводит раз в день; шов и прочие
// двери его не пишут вовсе (ЗАКОН КОНТЕЙНЕРА п.3 в редакции 2026-10-27: «ВСЁ
// ЧТО В СКВАДЕ ЕСТЬ ЭТО ЕГО ИНВЕНТАРЬ, всё остальное… регулируется через его
// модуль»). Поэтому свидетель обязан ДАТЬ МОДУЛЮ ХОД, а не ждать мгновенной
// пары: отставание ≤ суток законно прямо (ЗАКОН ДВУХ ТЕМПОВ «размазывается
// фоном»). Утверждение при этом НЕ ослаблено — мир по-прежнему не смеет
// числить людей, которых у него нет; изменилась только КАДЕНЦИЯ.
void rooted_module_day(World& w) {
    std::vector<std::int32_t> buf(sm::kUnifiedCap, 0);
    sm::reconcile_rooted_flock(w.gs, *w.store, buf.data());
}

// ── 1. СЕЗОННАЯ ДВЕРЬ: ГОЛОД СНИМАЕТ ОБА НОСИТЕЛЯ ────────────────────────
// Это тот самый путь, что давал 51 322 призрака за границу. Недоимка
// выставляется ПРЯМО — это ВХОД судимой функции, и другого способа получить
// ЧАСТИЧНУЮ долю у двери нет: её рождает только наполовину оплаченный сезон.
void test_the_season_window_pays_the_flock() {
    World w;
    const std::uint16_t slot = born_rooted(w, sm::SquadType::City, 10, 10, 8);
    CHECK(flock_of(w, slot) == 8 && folk_of(w, slot) == 8,
          "фикстура: оба носителя согласны — паства 8 и голов 8");

    const int boardOrd = sm::hunger_commodity_ordinal();
    CHECK(boardOrd >= 0, "фикстура: у мира есть голодная строка");
    const sm::UpkeepBill bill =
        sm::upkeep_bill(w.store->inventory[slot].inv);
    CHECK(bill.board > 0,
          "фикстура: состав из людей несёт рацион — без этого доля голода "
          "неразличима по построению");
    // Половина харча не покрыта ⇒ половина состава обязана умереть.
    w.store->upkeep[slot].needDebt[boardOrd] = std::int32_t(bill.board / 2);

    // (Конверт мира сезонной двери больше не нужен: она отвязана от
    // entt-реестра и просит ровно `gs` и `st` — M-233.)
    // День ГРАНИЦЫ: окно гейтится `season_boundary`, и вне её оно no-op.
    const int day = 1 + sm::kDaysPerSeason;
    CHECK(sm::season_boundary(day), "фикстура: день 33 есть граница сезона");
    sm::squad_season_window(w.gs, *w.store, day);

    const int folkAfter = folk_of(w, slot);
    const int flockAfter = flock_of(w, slot);
    CHECK(folkAfter == 4,
          "половина непокрытого харча = половина состава умерла (8 × 1/2)");
    CHECK(flockAfter == folkAfter,
          "ЗАКОН ПАРЫ: паства упала РОВНО на умерших — оба носителя сошлись");
    // НЕГАТИВНЫЙ КОНТРОЛЬ ДЕФЕКТА, КОТОРЫЙ ЭТОТ ФАЙЛ ЗАКРЫВАЕТ: до починки
    // паства не падала вовсе, то есть осталась бы восьмёркой при четырёх
    // головах. Утверждение названо отдельно от равенства выше, чтобы провал
    // печатал ИМЕННО эту болезнь, а не «числа не равны».
    CHECK(flockAfter != 8,
          "паства, не упавшая на границе ни на одну душу, и есть дефект "
          "51 322 призраков — мир кормил бы людей, которых нет");
}

// ── 2. КВИТАНЦИЯ БОЯ: ТА ЖЕ ПАРА У СТРОКИ `Creatures` ────────────────────
// Строка субъекта не фильтрует род, и квитанции авто-боя приходят на
// поселения: набег на деревню снимал головы и паству не трогал.
void test_the_creature_receipt_pays_the_flock() {
    World w;
    const std::uint16_t slot = born_rooted(w, sm::SquadType::Village, 20, 20, 5);
    const int id = int(w.store->spawnId[slot].index);
    CHECK(flock_of(w, slot) == 5 && folk_of(w, slot) == 5,
          "фикстура: паства 5 и голов 5");

    sm::MacroWorld mw = w.envelope();
    // Генерик называется ПАРОЙ {род, уровень} — у стака нет entityId.
    sm::MacroStockKey key{id, 0, 0, -1,
                          std::uint16_t(sm::NPCType::Peasant),
                          std::int16_t(sm::npc_def(sm::NPCType::Peasant).baseLevel)};
    sm::macro_stock_apply(mw, sm::MacroStock::Creatures, key, -2);

    CHECK(folk_of(w, slot) == 3, "квитанция на двоих сняла ровно двоих");
    // ШОВ ЧИСЛА НЕ ТРОГАЕТ — И ЭТО УТВЕРЖДАЕТСЯ ПРЯМО, а не подразумевается:
    // до хода модуля число обязано стоять там, где его оставил генезис.
    CHECK(flock_of(w, slot) == 5,
          "квитанция сняла ГОЛОВУ и только её: число — частность модуля, и "
          "снизу его не пишет никто (M-325)");
    rooted_module_day(w);
    CHECK(flock_of(w, slot) == 3,
          "ЗАКОН ПАРЫ: в СВОЁМ дневном проходе модуль свёл число к тем же "
          "троим, что остались в контейнере");
}

// ── 2б. «ДОМ + ВСЕ ЕГО АРТЕЛИ» — ВТОРАЯ ПОЛОВИНА ЗАКОНА (M-325) ──────────
// Владелец, дословно 2026-10-27: «это дом + все его артели да естественно -
// и это число управляется через модуль города который на этой фиче стоит».
//
// ПОЧЕМУ ЭТОТ СВИДЕТЕЛЬ ЗАВЕДЁН: без него половина закона стояла НЕОХРАНЯЕМОЙ,
// и это доказано мутацией, а не предположением — свод, считающий ТОЛЬКО дом
// («если родитель не я сам, пропусти»), прошёл ЗЕЛЁНЫМ сквозь оба прежних
// прибора (15 и 67 проверок). Душа, ушедшая в артель, дома больше не лежит,
// поэтому «число == голов ДОМА» на такой мутации сходится — и врёт ровно на
// тех, кто в поле.
void test_the_flock_counts_the_artels_too() {
    World w;
    const std::uint16_t rooted = born_rooted(w, sm::SquadType::Village, 30, 30, 9);
    const int rootedId = int(w.store->spawnId[rooted].index);
    rooted_module_day(w);
    CHECK(flock_of(w, rooted) == 9, "фикстура: девять душ, все дома");

    // АРТЕЛЬ — СКВАД, ЧЕЙ РОДИТЕЛЬ ЭТО МЕСТО. Головы в неё ПЕРЕНОСЯТСЯ, а не
    // рождаются: общее число семьи от выхода в поле не меняется, и ровно это
    // и судится.
    const sm::MacroHandle art = sm::store_birth(*w.store);
    CHECK_OR_RETURN(w.store->valid(art), "фикстура: артель родилась слотом");
    sm::set_relation(*w.store, int(w.store->spawnId[art.slot].index),
                     rootedId, sm::Stance::Parent);
    const int moved = 4;
    sm::bleed_flock(w.store->inventory[rooted].inv, moved);
    CHECK(sm::creatures_push_stack(
              w.store->inventory[art.slot].inv, sm::NPCType::Peasant,
              sm::npc_def(sm::NPCType::Peasant).baseLevel, moved),
          "фикстура: четверо встали в артель");
    CHECK(folk_of(w, rooted) == 5, "дома осталось пятеро");

    rooted_module_day(w);
    // ЯКОРЬ, А НЕ ПЕРЕСЧЁТ ФОРМУЛЫ (§8 п.6): утверждается ОТНОШЕНИЕ к
    // независимо известному факту мира — семья не поредела, четверо просто
    // вышли в поле, значит число обязано остаться девятью.
    CHECK(flock_of(w, rooted) == 9,
          "ЗАКОН: число места есть ДОМ + ВСЕ ЕГО АРТЕЛИ — выход в поле семью "
          "не уменьшает");
    CHECK(flock_of(w, rooted) != folk_of(w, rooted),
          "негативный контроль: число НЕ равно счёту голов дома, иначе "
          "свод, забывший артели, прошёл бы незамеченным");

    // И ОБРАТНО: смерть В АРТЕЛИ обязана убавить число её дома.
    sm::bleed_flock(w.store->inventory[art.slot].inv, 2);
    rooted_module_day(w);
    CHECK(flock_of(w, rooted) == 7,
          "двое павших в поле сошли с числа своего дома");
}

// ── 3. КОНЬ — ИМУЩЕСТВО, А НЕ ДУША ───────────────────────────────────────
// Вторая половина дефекта, и она про ЧИСЛО, а не про наличие записи: до
// починки из паствы вычиталась ЛЮБАЯ павшая голова, потому что счёт шёл
// `creature_count`/`starvedPop`, а приход в паству идёт строкой Peasant.
// Сегодня латентно — табун у мест нулевой, — поэтому свидетель ставит его
// себе сам.
void test_a_dead_horse_is_not_a_dead_soul() {
    World w;
    const std::uint16_t slot = born_rooted(w, sm::SquadType::Village, 30, 30, 4);
    sm::Inventory& inv = w.store->inventory[slot].inv;
    CHECK(sm::creatures_push_stack(inv, sm::NPCType::Horse,
                                   sm::npc_def(sm::NPCType::Horse).baseLevel, 3),
          "фикстура: в стойле места стоят три коня");
    CHECK(flock_of(w, slot) == 4 && sm::creature_count(inv) == 7,
          "фикстура: паства людская (4), а голов в контейнере семь");

    sm::MacroWorld mw = w.envelope();
    const int id = int(w.store->spawnId[slot].index);
    sm::MacroStockKey horseKey{id, 0, 0, -1,
                               std::uint16_t(sm::NPCType::Horse),
                               std::int16_t(sm::npc_def(sm::NPCType::Horse).baseLevel)};
    sm::macro_stock_apply(mw, sm::MacroStock::Creatures, horseKey, -3);

    CHECK(sm::creature_count(inv) == 4, "три коня сняты с контейнера");
    CHECK(flock_of(w, slot) == 4,
          "падёж табуна человеческую паству не трогает: конь — имущество, "
          "и в число фичи его никогда не вносили");
}

// ── 4. ЗДЕСЬ СТОЯЛ `test_a_dungeon_has_no_second_carrier`, И ОН УМЕР ────
//
// M-320, вердикт владельца «снести колонки целиком». Свидетель утверждал: у
// данжа пары «число + голова» нет, потому что число фичи под клеткой входа занято
// ЧУЖИМ числом (под `FT_Spire` живёт спелл), и дверь пары уходит оттуда
// пустой по колонке `bornPopBase`. Колонка снесена, а её предмет — СКВАД
// рода `Spire`, которого рождала фикстура, — исчез: руина и шпиль стали
// ФИЧАМИ (сквадами они и не были по замыслу, а данж — тем более: он
// карманный субмир, не актор макромира).
//
// ЖИВАЯ ПОЛОВИНА ЗАКОНА ОСТАЛАСЬ И ДЕРЖИТСЯ ТЕПЕРЬ ПОСТРОЕНИЕМ, А НЕ
// КОЛОНКОЙ: двери паствы пишут число фичи по КЛЕТКЕ ЖИВОГО СЛОТА, а живого
// слота на клетке со спеллом не бывает — у руины и шпиля слотов нет вовсе,
// а чужой сквад на их клетку не встаёт (`cell_taken@src/macro/spires.cpp`
// и `cell_taken_@src/macro/ruins.cpp` ветируют занятую клетку по байту, и
// фичи ставятся ПОСЛЕ поселений). Спелл недостижим для дверей паствы ПО
// ПОСТРОЕНИЮ.
//
// СТРАЖ У ЭТОГО ПОСТРОЕНИЯ ПОЯВИЛСЯ 2026-10-30 (M-329), И ЖИВЁТ ОН НЕ ЗДЕСЬ:
// `test_no_live_slot_stands_on_a_spell_cell@tests/spire_generation_test.cpp`.
// Дыра была названа честно — утверждение «ни один живой слот не стоит на
// клетке со спеллом» адреса в коде не имеет и требует СВОЕГО теста (§0 п.2), —
// и закрыта там, а не тут, по причине, которая важнее удобства: закон есть
// свойство ПОРЯДКА ГЕНЕРАЦИИ (фичи ставятся ПОСЛЕ поселений, занятую клетку
// ветирует байт), а фикстура ЭТОГО прибора — пустой мир 64×64, поставленный
// руками, и порядок генерации она доказать не может в принципе. Там мир
// поднимается генераторами, деревни занимают ПОЛОВИНУ единственной пригодной
// земли, и снятие вето роняет прибор дважды с адресами слотов.

// ── 5. ОТКАЗ ПРИЁМНИКА — ЗАКОН УМЕР ВМЕСТЕ С ПРИЁМНИКОМ (2026-10-11) ─────
// Здесь стоял `test_a_refused_walker_stays_in_the_flock`: ходок, которого пул
// дезертиров не принял (своя область существ забита доверху), ВОЗВРАЩАЛСЯ в
// состав — «за капом никого не уничтожают» (CANON S26), а паства читала ФАКТ
// исхода, не намерение.
//
// Свидетель снят не как плохой, а как ОСИРОТЕВШИЙ (AGENTS §5 п.6): колонка
// `GameState::deserterPool` уничтожена вердиктом владельца по переписи сирот
// — у неё не было НИ ОДНОГО читателя, то есть из пула никто никогда не
// нанимал. Приёмника больше нет, значит отказ приёмника НЕВЫРАЗИМ: фикстура
// не может набить то, чего не существует, и «пул отказал» перестало быть
// состоянием мира. Это не значит, что закон CANON S26 отменён — он остаётся
// верен и будет проверяться снова, когда аукцион найма заведёт настоящий
// приёмник (наряд M-206). Пока приёмника нет, честнее не иметь свидетеля,
// чем иметь зелёного.

