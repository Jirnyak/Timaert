// ЛЕСТНИЦА ОБЪЕКТА — СВИДЕТЕЛЬ ОТРЕЗКОВ И ВОПЛОЩАЕМОСТИ (наряд M-295).
//
// Что здесь охраняется (AGENTS §3 ЗАКОН ЛЕСТНИЦЫ ОБЪЕКТА / CANON S29):
//   1) «все строки архетипа» есть НЕПРЕРЫВНЫЙ ДИАПАЗОН ординалов строки мира,
//      а не фильтр по колонке — на ВСЕХ 91 строке обеих половин;
//   2) ВОПЛОЩАЕМОСТЬ и АДРЕС отвечают одно и то же, и это их единственное
//      законное пересечение: адрес говорит «какая из двух авторских таблиц»,
//      лестница — «встаёт ли это телом», и разъезд двух ответов был бы молчащим
//      дефектом (поэтому он проверяется поштучно, а не на выборке);
//   3) у выведенных величин есть ЯКОРЯ — независимо известные факты мира, а не
//      пересчёт продакшен-формулы.
//
// ── ПОЧЕМУ ЗДЕСЬ ЕСТЬ ЯКОРЯ, А НЕ ТОЛЬКО ТОЖДЕСТВО (AGENTS §8 п.6, ШЕСТАЯ
// ФОРМА СЛЕПОТЫ, куплена M-296) ───────────────────────────────────────────────
// Сверка «новый предикат == старому ответу» СЛЕПА, если обе её стороны считает
// одна формула: ошибка внутри формулы сходится сама с собой, и прибор зелен.
// Шрам назван числом: сводка контейнера сверялась с полным пересчётом 42 раза
// без расхождений ПОВЕРХ живого дефекта (страж пустоты спрашивал `def == 0`, а
// ординал 0 есть МЕДЯК), и поймал его только якорь «сто монет весят РОВНО 1000
// граммов». Поэтому ниже у каждого утверждения о лестнице стоит независимый
// факт: имя типа, счёт строк в группе, конкретная строка в конкретном
// архетипе — то, что можно проверить, не умея считать отрезки.
//
// ── ТАБЛИЦА «МУТАЦИЯ → ИСХОД», ОБЕ ПОЛЯРНОСТИ (AGENTS §8 п.6) ────────────────
// ПРОГНАНА, А НЕ ЗАЯВЛЕНА: все десять мутаций ниже реально собраны и
// запущены (2026-10-20), и записан ФАКТИЧЕСКИЙ исход каждой — затем, чтобы
// следующий агент мог повторить, а не верил на слово. Снимок дерева на время
// мутации делается КОПИЕЙ ФАЙЛА: `git checkout <файл>` в грязном дереве
// сносит всю несохранённую работу в нём, и в этой же сессии он её снёс.
//
//   ОБЯЗАНЫ КРАСНИТЬ — и покраснели:
//   · М1 строка каталога уехала в чужую группу (`wagon` → тип `statue`):
//     СБОРКА КРАСНАЯ, `catalog_rows_grouped_by_type@src/tables/items.cpp`;
//   · М2 род существа уехал в чужую группу (`Horse` → тип `canine`):
//     СБОРКА КРАСНАЯ, `npc_rows_grouped_by_type@src/tables/npc.h`;
//   · М3 вещь назвала ВОПЛОЩАЕМЫЙ архетип (`misc_gem` → тип `peasant`):
//     СБОРКА КРАСНАЯ, `catalog_is_all_things` — и заметь, что отрезки при этой
//     мутации ЦЕЛЫ (самоцвет последняя строка, монотонность не нарушена),
//     значит страж ловит именно разъезд лестницы с адресом, а не порядок;
//   · М4 существо назвало архетип ВЕЩИ (`Peasant` → тип `gem`):
//     СБОРКА КРАСНАЯ, `npc_rows_are_all_embodied`;
//   · М5 `Misc` переставлен из конца вещей в середину оси (Vehicle 7↔Misc 8):
//     СБОРКА КРАСНАЯ, `static_assert` в `object_archetype.h` (Misc == 8);
//   · М6 тип приписан чужому архетипу (`coin` → `Weapon` в `kObjectTypes`):
//     СБОРКА КРАСНАЯ, `object_types_sorted_by_archetype`;
//   · М7 `is_folk_kind` начал считать народом монстров: СБОРКА ОК, а ЭТОТ
//     ПРИБОР КРАСНЫЙ — «и НИ ОДНОГО народа больше» (строка 233). Именно эта
//     мутация и есть живой сдвиг мира: гоблины стали бы населением мест.
//
//   ОБЯЗАНЫ МОЛЧАТЬ (детектор, краснеющий на всё, — не детектор) — и молчали,
//   все три с ровно 42 проверками:
//   · М8 перестановка двух строк ВНУТРИ одного типа (`coin_empire_copper` ↔
//     `coin_barbar_gold`): отрезки целы, порядок внутри типа лестница не судит;
//   · М9 балансное число строки (цена `statue` 320 → 300);
//   · М10 балансное число колонки (спина коня `haulMult` 8 → 7).
//
// ── ЧТО ЭТОТ ПРИБОР НЕ ПРОВЕРЯЕТ, СКАЗАНО ВСЛУХ ─────────────────────────────
// Он НЕ судит, правильно ли КОНКРЕТНАЯ строка отнесена к своему архетипу по
// смыслу: «гоблин разумен, а кролик нет» есть КОНТЕНТ и вердикт владельца, а не
// закон формы. Якоря ниже закрепляют лишь те отнесения, которые владелец назвал
// дословно (гоблин → Monster, конь → Livestock, лич → Void), потому что на них
// стоят ЖИВЫЕ законы мира: народность решает, кто считается населением.

#include "check.h"

#include "tables/world_row.h"

#include <cstdint>

using namespace sm;

namespace {

// Архетип строки мира, собранный ЧЕРЕЗ АДРЕС и затем через лестницу своей
// половины. Это НЕ продакшен-дверь: единой двери «архетип строки мира» в
// дереве нет, и она не заводится до своего первого читателя (таблица
// объект-модулей, M-296) — колонка без читателя запрещена (DOD п.9). Прибор
// вправе ходить обеими половинами, потому что проверяет именно их согласие.
ObjectArchetype archetype_of_row(std::uint16_t row) {
    if (world_row_is_item(row)) {
        const ItemDef* d = item_def_at(int(row));
        return d ? item_archetype(*d) : ObjectArchetype::Misc;
    }
    return npc_archetype(creature_of_world_row(row));
}

} // namespace

int main() {
    const std::uint16_t items = world_item_rows();
    const std::uint16_t total = world_row_count();

    // ЯКОРЬ РАЗМЕРА: 44 предметные строки и 47 существных. Число названо
    // ВСЛУХ, потому что наряд M-295 пришёл с чужим числом («97 предметных»), и
    // перепись его опровергла — пусть следующий читатель спорит с прибором, а
    // не с прозой.
    CHECK(items == 44, "предметных строк мира — 44");
    CHECK(total == 91, "строк мира всего — 91 (44 предметных + 47 существных)");

    // ── 1. ТОЖДЕСТВО АДРЕСА И ВОПЛОЩАЕМОСТИ, ПОШТУЧНО ──────────────────────
    // Адрес отвечает «какая из двух авторских таблиц», лестница — «встаёт ли
    // телом». Два ответа на ОДНО подмножество мира, и разъехаться им нечем
    // только пока это проверено на каждой строке: выборка здесь не годится,
    // потому что дефект был бы ровно в одной забытой строке.
    int embodiedRows = 0, thingRows = 0, agree = 0;
    for (std::uint16_t row = 0; row < total; ++row) {
        const bool byLadder = object_embodied(archetype_of_row(row));
        const bool byAddress = world_row_is_creature(row);
        if (byLadder == byAddress) ++agree;
        if (byLadder) ++embodiedRows; else ++thingRows;
    }
    CHECK(agree == int(total),
          "воплощаемость по лестнице совпадает с адресом на ВСЕХ строках мира");
    CHECK(thingRows == 44 && embodiedRows == 47,
          "вещей 44, воплощаемых 47 — и это ДВА независимых счёта, "
          "сошедшихся на тех же числах");

    // ── 2. ОТРЕЗОК АРХЕТИПА ЕСТЬ ДИАПАЗОН, А НЕ ФИЛЬТР ─────────────────────
    // Проверяется прямо: пройди мир по порядку, и ординал архетипа не должен
    // НИ РАЗУ убыть. Этого достаточно и необходимо — непрерывность каждой
    // группы следует из монотонности, а дыра в группе её нарушает.
    int drops = 0, steps = 0;
    for (std::uint16_t row = 1; row < total; ++row) {
        const int prev = int(archetype_of_row(std::uint16_t(row - 1)));
        const int cur = int(archetype_of_row(row));
        ++steps;
        if (cur < prev) ++drops;
    }
    CHECK(steps == int(total) - 1, "прибор прошёл все стыки строк мира");
    CHECK(drops == 0,
          "архетип не убывает по пространству строк — значит «все строки "
          "архетипа» есть ДИАПАЗОН");

    // ...и то же для ТИПА, ступенью ниже: тип тоже обязан быть диапазоном,
    // иначе отрезок архетипа цел, а отрезок типа (ключ объект-модуля) порван.
    int typeDrops = 0;
    for (std::uint16_t row = 1; row < total; ++row) {
        const auto typeOf = [](std::uint16_t r) -> int {
            if (world_row_is_item(r)) {
                const ItemDef* d = item_def_at(int(r));
                return d ? int(d->type) : -1;
            }
            return int(npc_type_of(creature_of_world_row(r)));
        };
        if (typeOf(row) < typeOf(std::uint16_t(row - 1))) ++typeDrops;
    }
    CHECK(typeDrops == 0, "тип не убывает по пространству строк — ключ "
                          "объект-модуля тоже ДИАПАЗОН");

    // ── 3. ЯКОРЯ: НЕЗАВИСИМО ИЗВЕСТНЫЕ ФАКТЫ МИРА ──────────────────────────
    // Каждый — отношение или названный владельцем факт, НЕ пересчёт формулы.

    // ЯКОРЬ А: счёт строк в группах. Числа взяты из переписи каталога, а не из
    // той же суммы, которой считает код: если отрезки поедут, поедут и они.
    int perArch[int(ObjectArchetype::Count)] = {};
    for (std::uint16_t row = 0; row < total; ++row) {
        ++perArch[int(archetype_of_row(row))];
    }
    CHECK(perArch[int(ObjectArchetype::Weapon)] == 7, "оружейных строк 7");
    CHECK(perArch[int(ObjectArchetype::Currency)] == 12,
          "монетных строк 12 — четыре державы по три номинала");
    CHECK(perArch[int(ObjectArchetype::Vehicle)] == 1,
          "повозочная строка ровно одна — `wagon`, и она УЖЕ есть в каталоге");
    CHECK(perArch[int(ObjectArchetype::Misc)] == 1, "свалочная строка одна");
    CHECK(perArch[int(ObjectArchetype::Folk)] == 10, "родов народа 10");
    CHECK(perArch[int(ObjectArchetype::Monster)] == 8, "разумных тварей 8");
    CHECK(perArch[int(ObjectArchetype::Animal)] == 16, "животных 16");
    CHECK(perArch[int(ObjectArchetype::Livestock)] == 3,
          "скота 3 — конь, овца, коза");
    CHECK(perArch[int(ObjectArchetype::Void)] == 10, "хтони и демонов 10");

    // ЯКОРЬ Б: ВЕСЬ мир разложен по архетипам без остатка. Независим от
    // счётов выше: он ловит архетип, в который не попала ни одна строка, и
    // строку, попавшую в архетип вне оси.
    int sum = 0;
    for (int a = 0; a < int(ObjectArchetype::Count); ++a) sum += perArch[a];
    CHECK(sum == int(total), "сумма по архетипам равна числу строк мира");
    int emptyArchetypes = 0;
    for (int a = 0; a < int(ObjectArchetype::Count); ++a) {
        if (perArch[a] == 0) ++emptyArchetypes;
    }
    CHECK(emptyArchetypes == 0,
          "ни один архетип оси не пуст — пустой был бы либо преждевременным, "
          "либо лишним (DOD п.9)");

    // ЯКОРЬ В: ОТНЕСЕНИЯ, НАЗВАННЫЕ ВЛАДЕЛЬЦЕМ ДОСЛОВНО (2026-10-20). На них
    // стоят ЖИВЫЕ законы мира, поэтому они прибиты, а не оставлены контентом:
    // народность решает, кто считается населением места и размножается.
    CHECK(npc_archetype(NPCType::Goblin) == ObjectArchetype::Monster
              && npc_archetype(NPCType::Orc) == ObjectArchetype::Monster
              && npc_archetype(NPCType::Dragon) == ObjectArchetype::Monster,
          "«все орки в монстер», «монстры они обладают разумом (огры троли "
          "гоблины драконы)» — ось по РАЗУМУ, а не по рукам");
    CHECK(npc_archetype(NPCType::Rabbit) == ObjectArchetype::Animal
              && npc_archetype(NPCType::Wolf) == ObjectArchetype::Animal,
          "«дефолт животные нашего мира кролики волки»");
    CHECK(npc_archetype(NPCType::Horse) == ObjectArchetype::Livestock
              && npc_archetype(NPCType::Sheep) == ObjectArchetype::Livestock
              && npc_archetype(NPCType::Goat) == ObjectArchetype::Livestock,
          "«скот и ваще любые домашние животные»");
    CHECK(npc_archetype(NPCType::Lich) == ObjectArchetype::Void
              && npc_archetype(NPCType::Imp) == ObjectArchetype::Void,
          "«воид это как раз демоны», «для всякой хтони»");
    CHECK(npc_archetype(NPCType::Cultist) == ObjectArchetype::Folk,
          "культист — народ, и своим типом: «да культисты отдельный тип», "
          "«они точно не маги»");
    CHECK(npc_type_of(NPCType::Cultist) != npc_type_of(NPCType::Witch),
          "...и тип у него НЕ магический");
    CHECK(npc_type_of(NPCType::Witch) == npc_type_of(NPCType::Sorceress),
          "ведьма и сорка — один тип: обе кастуют спеллом из одной таблицы");

    // ЯКОРЬ Г: ЖИВОЙ ЗАКОН НАРОДНОСТИ НЕ СДВИНУЛСЯ. Это главный якорь наряда:
    // перекладка оси обязана была сохранить РОВНО тот же набор народа, иначе
    // гоблины и орки стали бы населением мест, начали размножаться и попали бы
    // в `folkHeads` сводки контейнера. Набор назван ПОИМЁННО, а не счётом:
    // счёт сошёлся бы и при обмене двух родов местами.
    const NPCType folk[] = {NPCType::Peasant, NPCType::Merchant,
                            NPCType::Bandit,  NPCType::RoadAmbusher,
                            NPCType::Guard,   NPCType::Witch,
                            NPCType::Sorceress, NPCType::Cultist,
                            NPCType::Adventurer, NPCType::TaxCollector};
    int folkSeen = 0;
    for (NPCType t : folk) {
        CHECK(is_folk_kind(std::uint16_t(t)), "этот род — народ, как и был");
        ++folkSeen;
    }
    CHECK(folkSeen == 10, "прибор прошёл все десять родов народа");
    int folkTotal = 0;
    for (int t = 0; t < int(NPCType::Count); ++t) {
        if (is_folk_kind(std::uint16_t(t))) ++folkTotal;
    }
    CHECK(folkTotal == 10,
          "и НИ ОДНОГО народа больше: перекладка оси не сделала населением "
          "ни гоблина, ни коня, ни нежить");

    // ── 4. СЕНТИНЕЛ «ТИПА НЕТ» РАЗВЕДЁН СО СВАЛКОЙ ─────────────────────────
    // Прежде `catalog_type_of` отдавала `Misc` на id, которого в каталоге нет
    // вовсе: один знак на два вопроса мира, и второй ответ был немым.
    CHECK(kObjectTypeNone != ObjectType::Gem,
          "«строки нет» и «свалочная вещь» — РАЗНЫЕ значения");
    CHECK(int(kObjectTypeNone) == 0xFF,
          "«типа нет» есть ПОСЛЕДНЕЕ значение типа (DOD «Закон узкого "
          "индекса»), а не −1");
    CHECK(object_type_archetype(kObjectTypeNone) == ObjectArchetype::Misc
              && !object_embodied(object_type_archetype(kObjectTypeNone)),
          "сентинел отвечает fail-closed свалкой и воплощаемым не бывает");

    // ── 5. ВОПЛОЩАЕМОСТЬ — ЭТО НЕ «ЖИВОЙ» ─────────────────────────────────
    // Названо отдельным утверждением, потому что это самая вероятная ошибка
    // следующего читателя: нежить воплощается телом и считается головой ровно
    // как крестьянин, и отрезок обязан её включать.
    CHECK(object_embodied(ObjectArchetype::Void),
          "нежить ВОПЛОЩАЕТСЯ — предикат про тело и голову, а не про жизнь");
    CHECK(!is_folk_kind(std::uint16_t(NPCType::Skeleton)),
          "...но народом не является: это два РАЗНЫХ вопроса");

    return sm::test::report("object_ladder_test");
}
