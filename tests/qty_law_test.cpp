// ВТОРАЯ ПОЛОВИНА ЗАКОНА ТРЁХ ДВЕРЕЙ — СТЕНА ПОД КОМПИЛЯТОРОМ (`Qty`).
//
// Закон (AGENTS §3, четыре инженерных закона, №2) называет ДВЕ формы голого
// вычитания — `a -= b` и `a - b`, — а машинный сторож судил одну, текстом.
// Текстовая мера типа не видит по построению: бинарных `a - b` в слоях
// симуляции 1747 вхождений на 1515 строках, и почти все законны (int/float).
// Вердикт владельца 2026-11-08: «надо универсльно для всеъ безнаковых
// вычитаний проверку разрешон ли заворот если да то норм если запрещон то
// получается нижний кламп или что там» и «но както надо обобщенно системно
// сделать наиболее в духе проекта».
//
// Форма — ТИП: `Qty<T>` носит беззнаковую величину симуляции и не имеет
// минуса вовсе. Вычесть можно только дверью.
//
// ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ И ПОЧЕМУ ИМЕННО `static_assert`. Лучшая форма
// свидетеля есть нарушение, которое НЕВОЗМОЖНО СОБРАТЬ (§8 п.6), — но такое
// нарушение обычным тестом не проверишь: код, который не компилируется,
// нельзя написать в тесте. `requires` это решает: он спрашивает компилятор
// «а собралось бы?» и отвечает НЕ СОБИРАЯ. Поэтому стена здесь не описана
// прозой и не проверена прогоном — она УТВЕРЖДЕНА тем же компилятором,
// который её и держит.
//
// МУТАЦИЯ → ИСХОД (обе полярности прогнаны 2026-11-08, см. таблицу у каждого
// блока ниже). Главная из них отвечает на вопрос «а не вакуумны ли эти
// `!requires`»: отмени удаление минуса — и они обязаны покраснеть. Без этой
// мутации `static_assert(!requires ...)` есть самый коварный род тавтологии:
// он зелен и когда стена стоит, и когда проверка просто опечатана.
#include "check.h"

#include "core/subtract.h"

#include <cstdint>
#include <type_traits>

namespace {

using Wood = sm::Qty<std::uint16_t>;
using Coin = sm::Qty<std::uint32_t>;

// ── 1. ФОРМА: POD, И ЦЕНА РАВНА НУЛЮ ──────────────────────────────────────
// Величина мира, одетая в `Qty`, обязана ложиться в сейв теми же байтами и не
// раздувать раскладку: иначе «одеть величину» стало бы решением о памяти, а
// оно решение о ЗАКОНЕ.
static_assert(sizeof(Wood) == sizeof(std::uint16_t),
              "`Qty` не стоит ни бита: обёртка над величиной, а не контейнер");
static_assert(sizeof(Coin) == sizeof(std::uint32_t), "то же для u32");
static_assert(std::is_trivially_copyable_v<Wood>,
              "величина мира обязана пережить memcpy — сейв есть дамп (§10)");
static_assert(std::is_standard_layout_v<Wood>,
              "стандартная раскладка: байты величины лежат там, где лежали");

// ── 2. СТЕНА: ГОЛОЕ ВЫЧИТАНИЕ НЕСОБИРАЕМО ─────────────────────────────────
// МУТАЦИЯ → ИСХОД:
//   добавить `Qty` рабочий `operator-`                → КРАСНЫЙ (сборка):
//     (вернуть заворот — главный случай:                 оба `!requires` ниже
//      стена, подменённая дырой)                         становятся ложью
//   добавить неявное приведение к `T`                 → КРАСНЫЙ (сборка):
//     (чёрный ход к встроенному минусу)                  подхватится ВСТРОЕННЫЙ
//                                                        оператор, и стены не
//                                                        станет при целом типе
//   добавить `Qty` постороннюю `is_zero()`            → ЗЕЛЁНЫЙ 5/5: детектор
//                                                        молчит на правке, не
//                                                        трогающей стену
//   (НЕГОДНЫЙ КОНТРОЛЬ, записан честно: «сменить ширину u16 → u32» КРАСНЫЙ —
//    но ломает он ДРУГОЙ закон, `sizeof(Wood) == sizeof(u16)` выше, то есть
//    мутация негодна как контроль стены, а не стена плоха. Записано затем,
//    что незаписанный негодный выбор следующий агент сделает заново.)
// Спрашивается КОНЦЕПТОМ, а не голым `requires` в `static_assert`: тело
// концепта есть несомненный SFINAE-контекст, и неудача там — «не
// удовлетворено», тогда как то же требование, написанное прямо в
// `static_assert`, clang диагностирует ТВЁРДОЙ ошибкой и свидетель не
// собирается вовсе. Прибор, который нельзя собрать, стену не утверждает.
template <class Q> concept BareMinus    = requires(Q a, Q b) { a - b; };
template <class Q> concept BareMinusEq  = requires(Q a, Q b) { a -= b; };
template <class Q> concept BarePlus     = requires(Q a, Q b) { a + b; };
template <class Q> concept Comparable   = requires(Q a, Q b) { a < b; };
template <class Q> concept DoorWorks    = requires(Q a, Q b) { sm::sub_sat(a, b); };

static_assert(!BareMinus<Wood>,
              "голое `a - b` над величиной симуляции НЕСОБИРАЕМО — в этом вся "
              "стена; собралось бы — закон держался бы прозой, как до 2026-11-08");
static_assert(!BareMinusEq<Wood>,
              "и голое `a -= b` тоже: дюп из воздуха невыразим обеими формами");

// И КОНТРОЛЬ ПРОТИВ ТАВТОЛОГИИ САМИХ `!requires`: ровно те же выражения,
// которые ОБЯЗАНЫ собираться, проверены тем же механизмом. Детектор,
// отвечающий «не собирается» на всё подряд, — не детектор (§8 п.6).
static_assert(BarePlus<Wood>,
              "рост законен голым: против заворота ВНИЗ стоит тип, а потолок "
              "типа есть вопрос ШИРИНЫ (ЗАКОН ТИПА п.1)");
static_assert(Comparable<Wood>,
              "сравнения законны — иначе величиной нельзя было бы пользоваться");
static_assert(DoorWorks<Wood>,
              "а ДВЕРЬ собирается: вычитание не запрещено, запрещено ГОЛОЕ");
// И ТОТ ЖЕ ДЕТЕКТОР НА СЫРОМ ТИПЕ — ОТВЕЧАЕТ «СОБИРАЕТСЯ». Без этой строки
// `!BareMinus<Wood>` мог бы быть зелен просто потому, что концепт опечатан.
static_assert(BareMinus<std::uint16_t> && BareMinusEq<std::uint16_t>,
              "контроль детектора: у СЫРОГО u16 минус есть — значит концепт "
              "видит минус, и его молчание на `Qty` говорит о СТЕНЕ, а не о "
              "сломанном детекторе");

// ── 3. НЕЯВНОГО ПРИВЕДЕНИЯ НЕТ — ЭТО ЕДИНСТВЕННОЕ, ЧТО УБИЛО БЫ СТЕНУ ──────
// Умей `Qty` сам превращаться в `uint16`, и `a - b` снова собрался бы через
// чёрный ход, а мы имели бы стену, которой нет, при полной уверенности, что
// она есть. Утверждается обеими сторонами: наружу неявно нельзя, внутрь тоже.
static_assert(!std::is_convertible_v<Wood, std::uint16_t>,
              "наружу неявно НЕЛЬЗЯ: иначе голый минус вернулся бы чёрным ходом");
static_assert(!std::is_convertible_v<std::uint16_t, Wood>,
              "и внутрь: сырое число не становится величиной мира молча");
static_assert(std::is_constructible_v<Wood, std::uint16_t>,
              "но ЯВНО — можно: `Qty<T>{raw}` есть названный акт автора");

// ── 4. ДВА НОСИТЕЛЯ ОДНОГО ЗАКОНА НЕ РАЗЪЕЗЖАЮТСЯ ─────────────────────────
// Двери для `Qty` — перегрузки, чьё тело есть вызов сырого близнеца, поэтому
// разойтись им невыразимо. Утверждается это НЕ пересчётом формулы (§8 п.5),
// а тождеством двух исполнений на одной паре чисел.
constexpr bool doors_agree(std::uint16_t a, std::uint16_t b) {
    std::uint16_t raw = a;
    Wood wrapped{a};
    if (sm::sub_sat(a, b) != sm::sub_sat(wrapped, Wood{b}).get()) return false;
    const bool rawOk = sm::try_spend(raw, b);
    Wood spendMe{a};
    if (rawOk != sm::try_spend(spendMe, Wood{b})) return false;
    if (raw != spendMe.get()) return false;
    std::uint16_t drainRaw = a;
    Wood drainMe{a};
    if (sm::drain(drainRaw, b) != sm::drain(drainMe, Wood{b}).get()) return false;
    return drainRaw == drainMe.get();
}

}  // namespace

int main() {
    using namespace sm::test;

    // ── ЗАКОН КАЖДОЙ ДВЕРИ, НА ТОМ САМОМ ЧИСЛЕ ИЗ ШАПКИ ЗАКОНА ────────────
    // «uint16 wood = 5; wood -= 10;` кладёт на склад 65 531 дерева» — вот эти
    // 5 и 10, и вот три законных ответа вместо заворота.
    {
        Wood износ{5};
        CHECK(sm::sub_sat(износ, Wood{10}).get() == 0,
              "sub_sat: ниже нуля не бывает — 5 минус 10 есть 0, а не 65531");
    }
    {
        Wood кошель{5};
        const bool paid = sm::try_spend(кошель, Wood{10});
        CHECK(!paid && кошель.get() == 5,
              "try_spend: полуплатёж есть ЛОЖЬ — при нехватке баланс НЕ тронут");
        Wood хватает{10};
        CHECK(sm::try_spend(хватает, Wood{10}) && хватает.get() == 0,
              "и он же платит целиком, когда хватает");
    }
    {
        Wood делянка{5};
        const Wood взято = sm::drain(делянка, Wood{10});
        CHECK(взято.get() == 5 && делянка.get() == 0,
              "drain: мир отдаёт остаток и ГОВОРИТ сколько — 5, а не 10");
    }

    // ── ТОЖДЕСТВО ДВУХ НОСИТЕЛЕЙ, И ОНО СЧИТАЕТСЯ ────────────────────────
    // Цикл, который меряет, обязан утверждать, что ПОМЕРИЛ (§8 п.3).
    {
        int samples = 0, mismatches = 0;
        for (std::uint16_t a = 0; a < 64; ++a) {
            for (std::uint16_t b = 0; b < 64; ++b) {
                ++samples;
                if (!doors_agree(a, b)) ++mismatches;
            }
        }
        CHECK(samples == 64 * 64 && mismatches == 0,
              "одетая дверь и сырая отвечают ОДНО на всей сетке 64×64");
    }

    // ЗНАКОВОЙ ВЕЛИЧИНЕ ЭТОТ ТИП НЕ НАДЕВАЕТСЯ, и утверждать это здесь
    // НЕЧЕМ — сознательно. `Qty<std::int32_t>` не «не удовлетворяет
    // требованию», а роняет СБОРКУ своим `static_assert` (ЗАКОН ТИПА п.2: у
    // знаковой минус законен голым, и одеть её значило бы запретить ей её же
    // закон). Твёрдая ошибка в `requires` не ловится, поэтому свидетель этой
    // половины — мутация, а не строка: подставь `std::int32_t` в `Wood` выше
    // и сборка краснеет на `subtract.h`. Прогнано 2026-11-08.

    char scope[160];
    std::snprintf(scope, sizeof(scope),
                  "стена утверждена компилятором · носитель %zu Б = сырой · "
                  "неявных приведений 0",
                  sizeof(Wood));
    return report("qty_law_test", scope);
}
