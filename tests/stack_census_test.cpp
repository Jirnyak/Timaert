// СВИДЕТЕЛЬ ИНВАРИАНТА ШТАБЕЛЯ (владелец, 2026-09-22).
//
// Сторожа РАЗМЕРОВ живут в самой переписи (core/stacks.h) и краснеют на
// сборке. Этот свидетель сторожит то, чего компилятор увидеть не может: что
// перепись описывает МИР, а не себя — что потолки настоящие, что род у каждого
// штабеля назван, и что картина памяти сходится числом.
//
// И он ПЕЧАТАЕТ картину памяти. По AGENTS п.10 она рисуется ДО кода; печать
// здесь — чтобы её не приходилось выводить заново на каждой сессии.
//
// С 2026-10-01 он ЕЩЁ И ГЕЙТИТ ЕЁ (`budget.h`). До этого дня картина
// печаталась и не судилась ничем: число росло, прибор послушно его сообщал, и
// ни одна строка дерева не возражала. Три потолка ниже — не вкус, у каждого
// вывод из инварианта мира, и каждый защищает НАЗВАННЫЙ закон.
//
// ЧЕГО ЭТОТ СВИДЕТЕЛЬ СОЗНАТЕЛЬНО НЕ БЮДЖЕТИРУЕТ, И ПОЧЕМУ. Пропуск, названный
// вслух, есть известная дыра; неназванный — упущение, которое следующий читает
// как «проверено всё».
//
//  · РЕЗИДЕНТНУЮ ПАМЯТЬ. Этот прибор читает ТАБЛИЦУ переписи и не рождает мир
//    ни разу — значит про физические страницы он не знает ничего и соврал бы
//    первым же числом. Вопрос «сколько из капов реально тронуто» решается
//    прогоном игры, а не свидетелем над `core/stacks.h`.
//  · ИТОГ ПО КАПАМ. Он ПЕЧАТАЕТСЯ и едет в вердикте, но потолка не несёт: 76 %
//    его держит одно семейство (цена и шаг маршрута, кап 2^30), чьи капы не
//    материализуются все никогда, то есть итог есть ПРОЕКЦИЯ. Потолок над
//    проекцией гейтил бы проекцию, а вывода из инварианта у такого числа нет —
//    значит это было бы число с потолка (ЗАКОН КОНСТАНТ).
//  · ЦЕНУ ОДНОЙ СТРОКИ ШТАБЕЛЯ. Её уже судит компилятор там, где она
//    объявлена (`static_assert` на `sizeof` и на сумму колонок); второй ответ
//    на тот же вопрос запрещён (DOD п.6).
#include "core/stacks.h"
#include "budget.h"
#include "check.h"

#include <cstdio>

namespace {

// ШИРИНА ПОЛЯ СЧИТАЕТСЯ В ЗНАКАХ, А НЕ В БАЙТАХ. `%-30s` меряет байты, и на
// кириллице (2 байта на знак в UTF-8) картина памяти печаталась лесенкой —
// то есть прибор, поставленный ради того, чтобы картину было ВИДНО, её
// разваливал. Считаем кодовые точки: продолжение UTF-8 (10xxxxxx) не знак.
std::size_t glyphs(const char* s) {
    std::size_t n = 0;
    for (const char* p = s; *p; ++p) {
        if ((static_cast<unsigned char>(*p) & 0xC0u) != 0x80u) ++n;
    }
    return n;
}

void pad_to(const char* s, std::size_t width) {
    std::printf("%s", s);
    for (std::size_t g = glyphs(s); g < width; ++g) std::printf(" ");
}

const char* kind_name(sm::StackKind k) {
    switch (k) {
        case sm::StackKind::ByCell:    return "ПО КЛЕТКЕ";
        case sm::StackKind::ByOrdinal: return "ПО ОРДИНАЛУ";
        case sm::StackKind::Catalog:   return "КАТАЛОГ";
        case sm::StackKind::Scalars:   return "СКАЛЯРЫ";
    }
    return "?";
}

} // namespace

int main() {
    using namespace sm;

    std::printf("\n=== ШТАБЕЛЯ МИРА ===\n");
    pad_to("штабель", 48);
    pad_to("строка", 28);
    std::printf("%8s %12s %10s\n", "Б/стр", "строк", "МиБ");
    double totalMiB = 0.0;
    // ПОДЫТОГ НА РОД — ЧАСТЬ КАРТИНЫ, А НЕ УКРАШЕНИЕ: без него итог говорит
    // «шестнадцать гигабайт» и не говорит, ЧТО именно их держит.
    double kindMiB[4] = {0.0, 0.0, 0.0, 0.0};
    // Байты на КЛЕТКУ МИРА — величина, в которой поле и измеряется: сумма по
    // всем полям и максимум по одному. Считаются здесь же, чтобы не обходить
    // перепись второй раз (и чтобы «самое толстое поле» нельзя было потерять
    // при правке печати).
    double byCellBytes = 0.0, fattestFieldBytes = 0.0;
    const char* fattestField = "";
    for (std::size_t i = 0; i < kStackCount; ++i) {
        const StackRow& r = kStacks[i];
        const double bytes = double(r.rowBytes) * double(r.cap);
        const double miB = bytes / (1024.0 * 1024.0);
        totalMiB += miB;
        kindMiB[std::size_t(r.kind)] += miB;
        if (r.kind == StackKind::ByCell) {
            byCellBytes += bytes;
            if (bytes > fattestFieldBytes) {
                fattestFieldBytes = bytes;
                fattestField = r.name;
            }
        }
        pad_to(r.name, 48);
        pad_to(r.rowType, 28);
        std::printf("%8zu %12zu %10.1f\n", r.rowBytes, r.cap, miB);
    }
    std::printf("\n");
    for (std::size_t k = 0; k < 4; ++k) {
        pad_to("  из них ", 10);
        pad_to(kind_name(StackKind(k)), 14);
        std::printf("%10.1f МиБ\n", kindMiB[k]);
    }
    pad_to("ИТОГО ПО КАПАМ", 24);
    std::printf("%10.1f МиБ\n\n", totalMiB);

    CHECK(kStackCount > 0, "перепись не бывает пустой");

    // ── ТРИ ПОТОЛКА, У КАЖДОГО ВЫВОД И СВОЙ ОХРАНЯЕМЫЙ ЗАКОН ────────────────
    std::printf("=== БЮДЖЕТЫ КАРТИНЫ ПАМЯТИ ===\n");

    // 1) КИЛОБАЙТ НА КЛЕТКУ МИРА. Вывод: клетка связного тора есть ОДНА
    //    запись мира, и вся сумма чисел, которые мир о ней помнит, обязана
    //    укладываться в килобайт. Это не про экономию (десятки и сотни
    //    мегабайт бесплатны, DOD п.2) — это про ФОРМУ: за килобайтом на клетку
    //    в клетке лежит уже не набор полей, а вложенная структура, то есть
    //    ЗАКОН ПОЛЯ перестал исполняться. Запас двукратный от замера 482 Б.
    CHECK_BUDGET("байт мира на клетку", byCellBytes / double(kWorldCells),
                 1024.0, "Б/клетка");

    // 2) САМОЕ ТОЛСТОЕ ОДНО ПОЛЕ. Вывод: поле есть ЧИСЛО на клетку (ЗАКОН
    //    ПОЛЯ). Поле на 256 Б в клетке несёт не число, а таблицу на клетку —
    //    законная вещь (планы порталов, след), но такая, которая обязана быть
    //    названа вслух и одобрена, а не прокрасться ростом одной строки
    //    переписи. Замер 128 Б/клетку, потолок 256 — ровно одно удвоение, то
    //    есть следующий шаг этого рода требует решения, а не правки.
    CHECK_BUDGET("байт на клетку в толстейшем поле",
                 fattestFieldBytes / double(kWorldCells), 256.0, "Б/клетка");

    // 3) БЛОК СКАЛЯРОВ МИРА. Вывод: род 4 фрейма — «мировые факты, где актор
    //    сам мир» (сид, время, форма мира, плоскость моря, казна, сезон), то
    //    есть горсть величин и небольшие фиксированные таблицы при них. Это
    //    ЕДИНСТВЕННЫЙ блок, который резидентен всегда и целиком, и он же —
    //    самое соблазнительное место, куда «пока положить» штабель. Мегабайты
    //    здесь означают именно это; замер 0.8 МиБ, потолок 2 МиБ.
    CHECK_BUDGET("блок скаляров мира", kindMiB[std::size_t(StackKind::Scalars)],
                 2.0, "МиБ");
    std::printf("  толстейшее поле: %s\n\n", fattestField);

    // ПОТОЛОК ЕСТЬ У КАЖДОГО ШТАБЕЛЯ. Штабель без потолка — это вектор,
    // который растёт, куда захочет, то есть ровно то, что инвариант запрещает.
    bool everyCapped = true, everyRowSized = true, everyNamed = true;
    for (std::size_t i = 0; i < kStackCount; ++i) {
        if (kStacks[i].cap == 0) everyCapped = false;
        if (kStacks[i].rowBytes == 0) everyRowSized = false;
        if (!kStacks[i].name || !kStacks[i].rowType
            || kStacks[i].name[0] == '\0') {
            everyNamed = false;
        }
    }
    CHECK(everyCapped, "у КАЖДОГО штабеля есть потолок строк");
    CHECK(everyRowSized, "у КАЖДОГО штабеля строка имеет размер");
    CHECK(everyNamed, "КАЖДЫЙ штабель назван и знает тип своей строки");

    // ПОТОЛКИ — НАСТОЯЩИЕ, А НЕ ВЫДУМАННЫЕ ПЕРЕПИСЬЮ. Мир есть тор
    // 1024×1024 (SKELETON слой 0), сквадов в нём 16384.
    CHECK(kWorldCells == 1024u * 1024u,
          "потолок клеток = связный тор 1024x1024, слой 0 скелета");
    CHECK(kWorldSquads == 16384u, "потолок сквадов мира");

    // ПОЛЕ НАД МИРОМ ПОКРЫВАЕТ ВЕСЬ МИР — иначе это не поле, а список с
    // дырами, и «число в каждой клетке» перестаёт быть правдой.
    bool cellStacksCoverWorld = true;
    for (std::size_t i = 0; i < kStackCount; ++i) {
        if (kStacks[i].kind != StackKind::ByCell) continue;
        if (kStacks[i].cap % kWorldCells != 0) cellStacksCoverWorld = false;
    }
    CHECK(cellStacksCoverWorld,
          "штабель ПО КЛЕТКЕ кратен миру: число есть в КАЖДОЙ клетке");

    // ОБЪЯВЛЕННЫЙ РОД БЕЗ ЖИЛЬЦОВ — КОЛОНКА-СИРОТА (AGENTS DOD п.9). Род
    // `Catalog` был объявлен 2026-09-22 и простоял с нулём строк: перепись
    // умела назвать каталоги и молчала о них, а комментарий `StackRow::cap`
    // это молчание ОБЪЯСНЯЛ («0 = каталог») — объяснял ровно то, что сам
    // свидетель ниже запрещает. Проверка стоит здесь, чтобы род либо жил,
    // либо был снесён, но не числился пустым.
    int catalogRows = 0;
    for (std::size_t i = 0; i < kStackCount; ++i) {
        if (kStacks[i].kind == StackKind::Catalog) ++catalogRows;
    }
    CHECK(catalogRows > 0,
          "род КАТАЛОГ объявлен — значит у него есть строки");

    // У ГРАФА ОКРУГ НЕТ СВОЕГО ЧИСЛА, И ЭТО СКАЗАНО ВСЛУХ. Округа рождается
    // на каждое живое место, поэтому потолок графа ЗАИМСТВОВАН у мест.
    // Появится здесь отдельная константа — значит кто-то завёл второй ответ
    // на вопрос «сколько в мире мест» (DOD п.6), и упадёт эта строка.
    CHECK(kNavRegionCap == kWorldLandmarks,
          "потолок округ навигации заимствован у мест, а не выдуман свой");

    // СКАЛЯРЫ — ИСКЛЮЧЕНИЕ, И ОНО РОВНО ОДНО. Два блока скаляров означали бы,
    // что «состояние мира» снова расползлось по коду.
    int scalarBlocks = 0;
    for (std::size_t i = 0; i < kStackCount; ++i) {
        if (kStacks[i].kind == StackKind::Scalars) ++scalarBlocks;
    }
    CHECK(scalarBlocks == 1,
          "блок скаляров мира РОВНО ОДИН — названное исключение инварианта");

    // ГРАНИЦА ЕДЕТ В ВЕРДИКТЕ (check.h, третий закон): «штабелей» и «по капам»
    // меняются только решением, поэтому пинятся точно; «резидентное» стоит
    // словом, чтобы PASS нельзя было прочесть как «память проверена».
    //
    // И ЭТО СЛОВО ОСТАЁТСЯ ПРАВДОЙ ПОСЛЕ M-204 (2026-10-01). Резидентное
    // замерили ОДИН раз зондом в `balance_run` — 1333.1 МиБ стора за 201 мс
    // при рождении мира, 58 живых слотов после генерации, 11 711 на плато, —
    // и зонд снесли как инструмент вопроса, а не жильца. Прибора на
    // резидентное в дереве НЕТ; числа живут в реестре M-204 и в шапке
    // `make_macro_store@src/macro/store.h`. Заведётся прибор — это слово
    // станет ложью, и переписать его надо будет тем же коммитом.
    char scope[160];
    std::snprintf(scope, sizeof(scope),
                  "штабелей %zu · по капам %.0f МиБ · резидентное НЕ судит",
                  kStackCount, totalMiB);
    return sm::test::report("stack_census_test", scope);
}
