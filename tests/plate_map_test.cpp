// каждый пункт ниже — утверждение о мире, которое обязано пережить любую
// перекалибровку пролёта, ширины шва и кривизны (ЗАКОН НУЛЕВОЙ п.5).
//
// ── ТАБЛИЦА МУТАЦИЙ: ЧТО ЭТИ ПРОВЕРКИ ЛОВЯТ, А ЧТО ОБЯЗАНЫ ПРОПУСТИТЬ ───────
// Прогнано 2026-10-03 поштучно; числа записаны, потому что прогнанный и не
// записанный контроль доказывает работу детектора ОДИН раз, в голове автора
// (§8 п.6).
//
//   МУТАЦИЯ                                   ИСХОД (прогнан, числа печатные)
//   М1. представитель плиты берётся без       КРАСНЫЙ, 2 из 21. §1: худшее
//       сдвига копии тора (`px = row.u*L`     расхождение 2.085 при допуске
//       вместо `+ (cx - wx)`)                 1e-03, срывов ординала 512 из 512
//   М2. шов без вычитания единицы             КРАСНЫЙ, 2 из 21. §2: глубина
//       (`wSum` вместо `wSum − 1`)            плиты 14.5 % → 0.0 %, сильный шов
//                                             61.1 % → 100 % (мир стал сплошным
//                                             швом); §5: узкий и широкий шов
//                                             сравнялись, 1024.0 против 1024.0
//   М3. сходимость по ПАРЕ (вес только у      КРАСНЫЙ, 1 из 21. §3: скачок за
//       ближайшей плиты) вместо гладкого      клетку 0.0142 → 1.4972 при пороге
//       ядра                                  0.25 — это и есть прямые резы от
//                                             тройных стыков, которые нашла
//                                             картинка уклонов
//   М4. ординал сужен до байта (`uint8`)      КРАСНЫЙ, 6 из 21. Гейт капа в
//                                             `make_plates` отказывает В ТОЧКЕ
//                                             РОЖДЕНИЯ (256 плит не влезают в
//                                             255), каркас не родился вовсе —
//                                             и дальше по цепочке
//   К1. пролёт плиты 64 → 128                 ЗЕЛЁНЫЙ, 21 — и обязан:
//       (ПЕРЕКАЛИБРОВКА)                      ни один закон не прибит к пролёту
//   К2. ширина шва 32 → 24                    ЗЕЛЁНЫЙ, 21 — тоже обязан
//       (ПЕРЕКАЛИБРОВКА)
//
// К1 и К2 стоят в таблице нарочно: детектор, краснеющий на всё, детектором не
// является.
#include "macro/plates.h"
#include "check.h"

#include <cmath>
#include <cstdio>
#include <vector>

using namespace sm;

namespace {

constexpr int kSide = 1024;
constexpr std::uint32_t kSeed = 12345u;

// Единица ровного шва — та, что подаёт синтез, когда модулировать нечем.
constexpr float kPlainSeam = 1.0f;

float sample_seam(const PlateMap& m, float u, float v) {
    return plate_sample(m, u, v, kPlainSeam).seam;
}

} // namespace

int main() {
    const PlateMap map = make_plates(kSide, kSeed);
    // Доля глубины плиты едет в вердикт (см. границу прибора в конце).
    float flatShare = 0.0f;

    // ── §0. КАРКАС РОДИЛСЯ, И ЕГО ФОРМА ВЫВЕДЕНА ИЗ МИРА ──────────────────
    CHECK(map.valid(), "каркас плит родился на законном мире");
    CHECK(map.lattice == kSide / kPlateSpanCells,
                    "решётка есть сторона мира, делённая на пролёт плиты");
    CHECK(int(map.rows.size()) == map.lattice * map.lattice,
                    "строк ровно решётка в квадрате");

    // ── §0b. МИР МЕНЬШЕ ПРОЛЁТА ОТКАЗЫВАЕТ В ТОЧКЕ РОЖДЕНИЯ ───────────────
    // Отказ вслух, а не выдуманная решётка из одной плиты (§5 п.3).
    CHECK(!make_plates(kPlateSpanCells / 2, kSeed).valid(),
                    "мир меньше пролёта плиты каркаса не имеет");

    // ── §0c. АВТОРСКИЙ СТОЛБЕЦ ПУСТ, И ЭТО ЗНАЧЕНИЕ ──────────────────────
    // «Дизайнер не прислал» тождественно «прислал ровно серое». Если этот
    // закон однажды сломают, мир поедет вверх-вниз без единой правки карты.
    {
        int nonZero = 0;
        for (const PlateRow& r : map.rows)
            if (r.levelBias != 0.0f) ++nonZero;
        CHECK(nonZero == 0,
                        "сдвиг уровня у всех плит ноль, пока карты нет");
    }

    // ── §1. КАРКАС ТОЧНО ПЕРИОДИЧЕН ПО ТОРУ ──────────────────────────────
    // Мир — связный тор (ЗАКОН АДРЕСА), и это утверждение ТОЧНОЕ, а не
    // «меняется мало»: точка u и точка u+1 есть ОДНА точка мира, значит ответ
    // обязан совпасть до бита. Порога здесь нет и быть не должно — первая
    // редакция свидетеля его завела (2/kPlateEdgeCells) и была НЕПРАВА: вывод
    // годился для случая двух плит, а у тройного стыка вкладчиков три, и
    // законная разница там больше. Точное тождество этой дыры не имеет.
    // ОРДИНАЛ сравнивается ТОЧНО — это целое, и дрогнуть ему нечем. У двух
    // непрерывных величин допуск есть цена ПРЕДСТАВЛЕНИЯ, а не поведения:
    // `u + 1.0f` меняет экспоненту, и последние биты произведения `u·L`
    // расходятся. Замерено на 2048 пробах: худшее |Δшов| 1.6e-05, |Δсжатие|
    // 1.3e-06, расхождений ординала ноль. Допуск 1e-3 — шестьдесят таких
    // ошибок, и при этом на три порядка ниже настоящего разрыва: снятый сдвиг
    // копии тора даёт 0.9 (таблица мутаций в шапке).
    {
        constexpr float kRoundingSlack = 1e-3f;
        int samples = 0, loose = 0, ordinalBreaks = 0;
        float worst = 0.0f;
        for (int i = 0; i < 512; ++i) {
            const float u = (float(i % 32) + 0.31f) / 32.0f;
            const float v = (float(i / 32) + 0.67f) / 16.0f;
            const PlateSample c  = plate_sample(map, u, v, kPlainSeam);
            const PlateSample wu = plate_sample(map, u + 1.0f, v, kPlainSeam);
            const PlateSample wv = plate_sample(map, u, v + 1.0f, kPlainSeam);
            const float d = std::max(
                std::max(std::fabs(c.seam - wu.seam), std::fabs(c.seam - wv.seam)),
                std::max(std::fabs(c.squeeze - wu.squeeze),
                         std::fabs(c.squeeze - wv.squeeze)));
            worst = std::max(worst, d);
            if (d > kRoundingSlack) ++loose;
            if (c.nearest != wu.nearest || c.nearest != wv.nearest)
                ++ordinalBreaks;
            ++samples;
        }
        CHECK(samples == 512, "периодичность промерена");
        CHECK(ordinalBreaks == 0,
              "чья клетка — тот же ответ на обеих копиях тора, точно");
        CHECK(loose == 0,
              "каркас замкнут по тору: u и u+1 — одна точка мира");
        std::printf("  [тор] проб %d, худшее расхождение %.3e при допуске %.0e,"
                    " срывов ординала %d\n",
                    samples, double(worst), double(kRoundingSlack),
                    ordinalBreaks);
    }

    // ── §2. ОБЕ ПОЛОВИНЫ ЗАКОНА СУЩЕСТВУЮТ, И ШОВ УБЫВАЕТ С УДАЛЕНИЕМ ────
    // Каркас обещает ровно две вещи, и обе здесь: ГЛУБИНА плиты, где шва нет
    // вовсе (без неё у долины нет плоского дна), и ШОВ во всю силу, где стене
    // есть где встать. Третье — что между ними поле идёт МОНОТОННО, то есть
    // подножие одно, а не гребёнка.
    //
    // ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: закона «шов — меньшинство карты». Первая
    // редакция его утверждала и была НЕПРАВА по адресу: в соты вырождается не
    // шов, а шов, ОТОБРАННЫЙ СЖАТИЕМ, и отбор живёт у потребителя (синтез
    // высоты), а не у плит. Судить его здесь значило бы переписать формулу
    // потребителя в свидетеля (§8 п.5). Доля печатается как замер, не как
    // вердикт.
    //
    // (Та же редакция требовала «в затравке плиты шва нет» и тоже была
    // неправа: у мелкой зажатой плиты сосед стоит ближе ширины шва, и она вся
    // margin — свойство каркаса, а не дефект.)
    {
        int flat = 0, strong = 0, samples = 0;
        float strongest = 0.0f;
        for (int i = 0; i < 16384; ++i) {
            const float u = (float(i % 128) + 0.5f) / 128.0f;
            const float v = (float(i / 128) + 0.5f) / 128.0f;
            const float s = sample_seam(map, u, v);
            if (s <= 0.0f) ++flat;
            if (s > 0.5f) ++strong;
            strongest = std::max(strongest, s);
            ++samples;
        }
        flatShare = 100.0f * float(flat) / float(samples);
        CHECK(samples == 16384, "карта промерена на долю шва");
        CHECK(flat > 0, "плоское дно существует: есть клетки без шва");
        CHECK(strongest > 0.5f, "шов существует: стене есть где встать");
        std::printf("  [доля шва] глубина плиты %.1f %%, сильный шов %.1f %%, "
                    "сильнейший %.4f\n",
                    100.0 * double(flat) / double(samples),
                    100.0 * double(strong) / double(samples),
                    double(strongest));
    }

    // ── §2b. ШОВ УБЫВАЕТ, КОГДА УХОДИШЬ ВГЛУБЬ СВОЕЙ ПЛИТЫ ───────────────
    // Свидетель СТРОИТ СЕБЕ ПРЕДУСЛОВИЕ (§8 п.11): берёт середину между двумя
    // соседними затравками — это заведомо шов — и идёт к одной из них. Поле
    // обязано падать по дороге, иначе у гряды два подножия и провал посередине.
    //
    // ПУТЬ ЗАСЧИТЫВАЕТСЯ, ТОЛЬКО ПОКА ХОЗЯИН ОДИН. Первая редакция этого не
    // требовала и краснела на 11 путях из 240; замер разобрал их поимённо —
    // ВСЕ ОДИННАДЦАТЬ со сменой хозяина, без смены ноль. То есть путь уходил
    // на территорию третьей плиты и честно пересекал ДРУГОЙ шов: закон был
    // верен, небрежно было предусловие. Это не ослабление вердикта, а его
    // адрес.
    {
        int paths = 0, nonMonotone = 0, skipped = 0;
        for (int gy = 0; gy < map.lattice; ++gy) {
            for (int gx = 0; gx + 1 < map.lattice; ++gx) {
                const PlateRow& a = map.rows[std::size_t(gy) * map.lattice + gx];
                const PlateRow& b = map.rows[std::size_t(gy) * map.lattice + gx + 1];
                const float mu = 0.5f * (a.u + b.u), mv = 0.5f * (a.v + b.v);
                const PlateSample start = plate_sample(map, mu, mv, kPlainSeam);
                float prev = start.seam;
                bool rose = false, leftHome = false;
                for (int k = 1; k <= 8; ++k) {
                    const float t = float(k) / 8.0f;
                    const PlateSample s = plate_sample(map,
                        mu + (a.u - mu) * t, mv + (a.v - mv) * t, kPlainSeam);
                    if (s.nearest != start.nearest) { leftHome = true; break; }
                    // Допуск тот же, что у §1, и по той же причине.
                    if (s.seam > prev + 1e-3f) rose = true;
                    prev = s.seam;
                }
                if (leftHome) { ++skipped; continue; }
                if (rose) ++nonMonotone;
                ++paths;
            }
        }
        // Пустой вердикт был бы зелёным молча (§8 п.2): путей обязано остаться
        // большинство, иначе предусловие съело предмет.
        CHECK(paths > skipped,
              "путей вглубь своей плиты больше, чем отброшенных");
        CHECK(nonMonotone == 0,
              "шов убывает к затравке: у гряды одно подножие, а не гребёнка");
        std::printf("  [монотонность] путей %d, немонотонных %d, отброшено "
                    "(ушли к третьей плите) %d\n", paths, nonMonotone, skipped);
    }

    // ── §3. СХОДИМОСТЬ НЕПРЕРЫВНА ────────────────────────────────────────
    // ЭТО ГЛАВНЫЙ ЗАКОН МОДУЛЯ, и куплен он картинкой, а не числом: пока
    // сходимость считалась по ПАРЕ ближайших плит, она прыгала на биссектрисе
    // второго и третьего соседа и резала хребты прямыми линиями от каждого
    // тройного стыка. Непрерывность здесь не стиль — она и есть отсутствие
    // этих резов.
    {
        float worst = 0.0f;
        int samples = 0;
        const float step = 1.0f / float(kSide);
        for (int i = 0; i < 4096; ++i) {
            // Решётка проб, намеренно НЕ выровненная по решётке плит: ровная
            // сетка могла бы лечь мимо стыков, то есть мимо предмета.
            const float u = (float(i % 64) + 0.37f) / 64.0f;
            const float v = (float(i / 64) + 0.61f) / 64.0f;
            const float c = plate_sample(map, u, v, kPlainSeam).squeeze;
            const float r = plate_sample(map, u + step, v, kPlainSeam).squeeze;
            const float d = plate_sample(map, u, v + step, kPlainSeam).squeeze;
            worst = std::max(worst, std::max(std::fabs(r - c), std::fabs(d - c)));
            ++samples;
        }
        // Законный предел выводится из ядра, а не из наблюдения: ядро шириной
        // в ячейку решётки, шаг пробы — одна клетка, то есть 1/64 ячейки,
        // поэтому поле за шаг меняться на четверть размаха не может.
        CHECK(samples == 4096, "сходимость промерена по всей карте");
        CHECK(worst < 0.25f,
                        "сходимость непрерывна: за клетку поле не прыгает");
        std::printf("  [сходимость] худший скачок за клетку %.4f при пороге 0.25\n",
                    double(worst));
    }

    // ── §4. ОРДИНАЛ НАЗЫВАЕТ ЛИЧНОСТЬ, А НЕ ПУСТОТУ ──────────────────────
    // Промах на единицу, пойманный до сборки: при холсте 16×16 плит ровно 256,
    // и в байте последняя назвалась бы «никем».
    static_assert(kMaxPlates > 0, "кап плит положителен");
    {
        int named = 0, noPlate = 0, outOfRange = 0, samples = 0;
        for (int i = 0; i < 4096; ++i) {
            const float u = (float(i % 64) + 0.5f) / 64.0f;
            const float v = (float(i / 64) + 0.5f) / 64.0f;
            const PlateOrdinal o = plate_sample(map, u, v, kPlainSeam).nearest;
            if (o == kNoPlate) ++noPlate; else ++named;
            // Утверждение ОДНО на весь цикл: проверка внутри сдвинула бы счёт
            // вердикта на тысячи и сделала бы пин бессмысленным.
            if (o != kNoPlate && int(o) >= int(map.rows.size())) ++outOfRange;
            ++samples;
        }
        CHECK(samples == 4096, "ординал промерен по всей карте");
        CHECK(noPlate == 0,
              "у каждой точки законного мира есть своя плита");
        CHECK(outOfRange == 0, "ординал плиты лежит в строках карты");
        CHECK(int(map.rows.size()) <= kMaxPlates,
                        "плит не больше, чем вмещает ординал");
        std::printf("  [ординал] плит %zu, названо %d, «никем» %d, кап %d\n",
                    map.rows.size(), named, noPlate, kMaxPlates);
    }

    // ── §5. ШИРЕ ШОВ — ШИРЕ ГРЯДА, И ЭТО ОТНОШЕНИЕ, А НЕ ЧИСЛО ───────────
    // Утверждается не величина, а монотонность: модулятор обязан работать в
    // ту сторону, в какую назван. Прибитое число здесь сломалось бы на первой
    // же перекалибровке (§8 п.4).
    {
        float narrowSum = 0.0f, wideSum = 0.0f;
        int samples = 0;
        for (int i = 0; i < 1024; ++i) {
            const float u = (float(i % 32) + 0.23f) / 32.0f;
            const float v = (float(i / 32) + 0.71f) / 32.0f;
            narrowSum += plate_sample(map, u, v, 0.5f).seam;
            wideSum   += plate_sample(map, u, v, 2.0f).seam;
            ++samples;
        }
        CHECK(samples == 1024, "ширина шва промерена");
        CHECK(wideSum > narrowSum * 1.5f,
                        "вдвое более широкий шов накрывает заметно больше карты");
        std::printf("  [ширина] узкий шов %.1f, широкий %.1f (сумма по пробам)\n",
                    double(narrowSum), double(wideSum));
    }

    // ГРАНИЦА ПРИБОРА ЕДЕТ В ЕГО ВЕРДИКТЕ. Зелёный гейт читается как
    // «проверено всё», а проверен КАРКАС: отбор, какие швы становятся грядами,
    // делает потребитель (синтез высоты), и судить его здесь нечем.
    char scope[160];
    std::snprintf(scope, sizeof(scope),
                  "плит %zu · глубина плиты %.1f %% · отбор гряд сжатием НЕ судится",
                  map.rows.size(), double(flatShare));
    return sm::test::report("plate_map_test", scope);
}
