// ХРАПОВИК ОСТАТКОВ РЕЕСТРА (M-337) — «НЕСДЕЛАННОЕ НЕ ПРОПАДАЕТ».
//
// Мандат владельца 2026-10-28, дословно: «когжа жопус/фейбл поработал и говорит
// что не сделал и почему и тд что не сделал честно это не должно пропадать типа
// ок не сделал бывает но раз не сделал то проблемы остались? это знание не
// долджно пропать и надо системно это решить».
//
// МЕХАНИЗМ ДЫРЫ ЗАМЕРЕН, И ОН НЕ В ЗАБЫВЧИВОСТИ. Знание «что не сделано»
// рождается В КОНЦЕ сессии и оседает в ряду, который та же сессия ЗАКРЫВАЕТ, —
// то есть становится невидимым ровно в момент своего появления. Гигиена M-337
// нашла так **47 остатков** реестра (плюс СВОЙ, 48-й и 49-й токен), висевших
// СЛОВАМИ («ждёт», «уедет», «не покрыто», «отложено»), и у **21** из них не
// было дома ни одного.
//
// ЧТО СУДИТ ЭТОТ ПРИБОР — ДВА ПЛЕЧА, И ОБА НАЗВАНЫ ВЛАДЕЛЬЦЕМ:
//   ПЛЕЧО 1 — закрытый ряд со СЛОВОМ-МАРКЕРОМ обязан высказаться: либо нести
//             токен `**ОСТАТОК:**`, либо сказать `**ОСТАТКА НЕТ`. Молчать нельзя:
//             молчание и есть тот способ, которым остаток исчезает;
//   ПЛЕЧО 2 — у токена обязан быть ДОМ `→ **M-NNN**`, дом обязан СУЩЕСТВОВАТЬ,
//             быть ОТКРЫТЫМ и нести ОБРАТНУЮ ССЫЛКУ. Закрытый дом хоронит
//             остаток заново; дом без обратной ссылки делает остаток видимым
//             только из закрытой строки, то есть не делает ничего.
// Пин — **0** и только убывает (вердикт владельца: «сначала разобрать все 73
// руками», поэтому тающего белого списка здесь нет вовсе).
//
// ПОЧЕМУ ТОКЕН ИМЕННО `**ОСТАТОК:**` (ЖИРНЫЙ) — ЭТО ЗАМЕР, А НЕ ВКУС. Голый
// `ОСТАТОК:` детектором быть НЕ МОЖЕТ: на базе `561ef2a4` он давал 6 строк, и
// ДВЕ из них ложные — заголовок наряда `M-57` («Б-6 ОСТАТОК: `ai_trader`…») и
// самоописание формы внутри ряда `M-337`. Детектор, краснеющий на заголовке, не
// детектор (§8 п.6). Жирность отсекает оба, потому что ни одно из двух жирным не
// было. Та же ловушка сработала ВТОРОЙ раз уже внутри этой работы: обратная
// ссылка, которую прибор требует, сперва цитировала токен словами «Токен
// `**ОСТАТОК:**` в том ряду…» и подняла 20 ложных рядов — поэтому обратная
// ссылка о токене говорит ПРОЗОЙ, без жирной формы.
//
// ЧТО ПРИБОР НЕ СУДИТ, И ЭТО ГРАНИЦА, НЕ НЕДОДЕЛКА. Он утверждает СВЯЗНОСТЬ
// ведомости долгов (высказался / дом есть / дом жив / дом знает), и ничего
// больше. ГОДНОСТЬ остатка — верно ли назван предмет, та ли причина — остаётся
// за чтением: ряд может нести честный токен с глупым домом, и строка этого не
// отличит. Ровно так же `law_carrier_test` судит существование носителя, а не
// его качество.
//
// ТАБЛИЦА «МУТАЦИЯ → ИСХОД», ОБЕ ПОЛЯРНОСТИ, СНЯТАЯ НА `macro-registry.md` ПОСЛЕ
// РАЗБОРА M-337 (§8 п.6; реестр после каждой мутации восстанавливался `cp` и
// сверялся `cmp` ПОБАЙТОВО). БАЗА: код 0, дефектов 0.
// ОБЯЗАНЫ КРАСНИТЬ — и краснят:
//   снять стрелку дома у остатка `M-12` (`→ **M-340**` → `M-340`)
//                                                → без дома 1,      код 1
//   зачеркнуть номер дома `M-346` в первой колонке → дом закрыт 1,   код 1
//   выписать обратную ссылку из `M-72`             → дом молчит 2,   код 1
//   переписать дом `M-12` на `M-999`               → дома нет 1,     код 1
//   снять токен у закрытого `M-93`                 → ПОЛ ТОКЕНОВ,    код 1
// ОБЯЗАНЫ МОЛЧАТЬ — и молчат (детектор, краснеющий на всё, судьёй быть не может):
//   завести ряд БЕЗ остатка                        → дефектов 0,     код 0
//   написать голый `ОСТАТОК:` в ЗАГОЛОВКЕ ряда      → дефектов 0,     код 0
//   закрыть ряд, у которого остатка нет вовсе (`M-240`)
//                                                → дефектов 0,     код 0
//   процитировать `M-NNN` в теле БЕЗ стрелки `→`    → дефектов 0,     код 0
//
// ДВЕ МУТАЦИИ ПЕРВОГО ПРОГОНА ПРОШЛИ ЗЕЛЁНЫМИ, И ОБЕ ЗАПИСАНЫ, ПОТОМУ ЧТО ОДНА
// ОКАЗАЛАСЬ ДЫРОЙ ПРИБОРА, А НЕ ОШИБКОЙ МУТАЦИИ:
//   (а) снятие ОДНОГО дома у `M-90` → зелено, и это ПРАВИЛЬНО: у того остатка
//       ДВА дома (`→ **M-342**` и `→ **M-98**`), второй остался. Мутация была
//       выбрана неудачно — у неё не было наблюдаемого эффекта, ровно тот класс
//       слепоты, против которого §8 п.6 и требует ЗАПИСАННОЕ ЧИСЛО;
//   (б) снятие токена у закрытого ряда → зелено, и это БЫЛА ДЫРА: плечо 1 ловит
//       лишь ряд, чья проза говорит одним из слов-маркеров, а `M-93` молчал о
//       своём остатке другими словами. Дыра закрыта ПОЛОМ `kTokensFloor`, и
//       мутация после этого краснеет. Словарь маркеров не расширялся: остаток
//       выразим любыми словами, и гнаться за ними — проигранная гонка.
#include "check.h"

#include <cstdio>
#include <fstream>
#include <algorithm>
#include <map>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

#ifndef TIMAERT_SOURCE_DIR
#error "TIMAERT_SOURCE_DIR must name the repo root - see CMakeLists.txt"
#endif

namespace {

constexpr const char* kRegistry = TIMAERT_SOURCE_DIR "/macro-registry.md";

// Токен остатка — ЖИРНЫЙ, и это замер (см. шапку). Пометка «остатка нет» —
// префикс, потому что у неё есть хвост с причиной.
constexpr std::string_view kToken   = "**ОСТАТОК:**";
constexpr std::string_view kNoDebt  = "**ОСТАТКА НЕТ";

// ХРАПОВИК СЧЁТА, И ОН ЗАВЕДЁН ПОТОМУ, ЧТО МУТАЦИЯ НАШЛА ДЫРУ В ПЛЕЧЕ 1.
// Плечо 1 ловит только ряд, чья проза говорит одним из слов-маркеров ниже;
// снятый токен у ряда, который о своём остатке молчал ИНЫМИ словами, проходил
// ЗЕЛЁНЫМ — замерено на закрытом `M-93` (снятие токена → 0 дефектов, код 0).
// Словарь маркеров расширять бессмысленно: остаток можно описать любыми словами.
// Поэтому вторая защита — ЧИСЛО: токенов в ведомости не может стать МЕНЬШЕ, чем
// было после разбора, потому что остаток не исчезает сам. Пол поднимается
// ТОЛЬКО правкой этой строки, то есть осознанно и видимо в дифе.
constexpr int kTokensFloor = 49;   // замер разбора M-337, 2026-10-28 (48 остатков реестра + свой)

// Слова, которыми остаток живёт в прозе, когда у него нет формы. Перечень
// закрыт ЗАМЕРОМ: на базе разбора ими и только ими говорили все 47 найденных
// остатков. Новое слово — новая строка здесь, и это осознанно ручной список:
// угадывать остаток по смыслу прибор не умеет и не должен.
constexpr std::string_view kMarkers[] = {
    "ждёт", "ждет", "уедет", "не покрыт", "отложен",
};

struct Row {
    std::string num;
    int         line = 0;
    bool        closed = false;
    bool        token = false;
    bool        noDebt = false;
    bool        backRef = false;
    bool        marker = false;
    std::vector<std::string> homes;
};

bool contains(const std::string& hay, std::string_view needle) {
    return hay.find(needle) != std::string::npos;
}

// Номер наряда ЖИВЁТ В ПЕРВОЙ КОЛОНКЕ, и мера именно такая. Прежний замер этой
// же гигиены читал `~~` ГДЕ УГОДНО в ряду и назвал закрытыми 12 рядов, которые
// лишь ЦИТИРОВАЛИ зачёркнутый номер соседа (`M-82`, `M-258`, `M-218`…). Число
// без границы — не число (§5 п.4).
std::string first_cell_number(const std::string& row, bool& closedOut) {
    const std::size_t a = row.find('|');
    if (a == std::string::npos) return {};
    const std::size_t b = row.find('|', a + 1);
    if (b == std::string::npos) return {};
    const std::string cell = row.substr(a + 1, b - a - 1);
    const std::size_t m = cell.find("M-");
    if (m == std::string::npos) return {};
    std::size_t e = m + 2;
    while (e < cell.size() && cell[e] >= '0' && cell[e] <= '9') ++e;
    if (e == m + 2) return {};
    closedOut = contains(cell, "~~") || contains(cell, "ЗАКРЫТ")
             || contains(cell, "ИСПОЛНЕН") || contains(cell, "ПРОТУХ")
             || contains(cell, "ОПРОВЕРГНУТ");
    return cell.substr(m, e - m);
}

// ОБРАТНАЯ ССЫЛКА — ЛЮБАЯ ЛЕВАЯ СТРЕЛКА, НАЗЫВАЮЩАЯ НОМЕР, И ДВЕ ФОРМЫ ТУТ
// РАВНОПРАВНЫ СОЗНАТЕЛЬНО: ряд-дом, заведённый ПОД остаток, называет источник
// («← **M-236**»), а ряд, которому остаток лишь ПРИПИСАН, перечисляет своих
// («← ОСТАТКИ, ЧЕЙ ДОМ ЗДЕСЬ: …»). Требовать одну форму значило бы требовать
// переписать вторую без выигрыша; прибор судит НАЛИЧИЕ обратного ребра.
// Этот разъезд нашёл сам прибор на первом же прогоне — 22 дома из 49 несли
// форму, которой он не знал, и покраснел правильно.
bool has_back_ref(const std::string& row) {
    if (contains(row, "← ОСТАТКИ")) return true;
    const std::string arrow = "←";
    std::size_t p = 0;
    while ((p = row.find(arrow, p)) != std::string::npos) {
        const std::size_t end = std::min(row.size(), p + arrow.size() + 24);
        const std::size_t m = row.find("M-", p);
        if (m != std::string::npos && m < end && m + 2 < row.size()
            && row[m + 2] >= '0' && row[m + 2] <= '9')
            return true;
        p += arrow.size();
    }
    return false;
}

// Дом — это `→ **M-NNN**`. Стрелка ОБЯЗАТЕЛЬНА: без неё всякое упоминание
// соседнего наряда в теле читалось бы домом, и ряд, просто сославшийся на
// родню, получал бы дом, которого не назначал.
std::vector<std::string> homes_of(const std::string& row) {
    std::vector<std::string> out;
    const std::string arrow = "→ **M-";
    std::size_t p = 0;
    while ((p = row.find(arrow, p)) != std::string::npos) {
        std::size_t s = p + arrow.size() - 2;   // на 'M'
        std::size_t e = s + 2;
        while (e < row.size() && row[e] >= '0' && row[e] <= '9') ++e;
        if (e > s + 2 && row.compare(e, 2, "**") == 0) out.push_back(row.substr(s, e - s));
        p = e;
    }
    return out;
}

} // namespace

int main() {
    std::ifstream in(kRegistry, std::ios::binary);
    std::ostringstream ss;
    ss << in.rdbuf();
    const std::string text = ss.str();
    CHECK(!text.empty(), "реестр читается — без него прибор не высказывание, а молчание");
    if (text.empty()) return sm::test::report("registry_debt_test", "реестр не прочитан");

    std::vector<Row> rows;
    std::map<std::string, std::vector<std::size_t>> byNum;
    {
        std::istringstream lines(text);
        std::string line;
        int n = 0;
        while (std::getline(lines, line)) {
            ++n;
            if (line.empty() || line[0] != '|') continue;
            bool closed = false;
            const std::string num = first_cell_number(line, closed);
            if (num.empty()) continue;
            Row r;
            r.num = num;
            r.line = n;
            r.closed = closed;
            r.token = contains(line, kToken);
            r.noDebt = contains(line, kNoDebt);
            r.backRef = has_back_ref(line);
            for (const std::string_view m : kMarkers)
                if (contains(line, m)) { r.marker = true; break; }
            r.homes = homes_of(line);
            byNum[num].push_back(rows.size());
            rows.push_back(std::move(r));
        }
    }
    CHECK(rows.size() > 300,
          "рядов наряда найдено больше трёхсот — иначе разбор парсера съехал "
          "и ноль дефектов ниже означал бы ноль РЯДОВ, а не чистую ведомость");

    int silent = 0, noHome = 0, deadHome = 0, closedHome = 0, muteHome = 0;
    int tokens = 0, debts = 0;

    for (const Row& r : rows) {
        // ПЛЕЧО 1: закрытый ряд со словом-маркером обязан ВЫСКАЗАТЬСЯ.
        if (r.closed && r.marker && !r.token && !r.noDebt) {
            ++silent;
            std::fprintf(stderr,
                         "  МОЛЧИТ %s (стр %d): ряд закрыт и несёт слово остатка, "
                         "но не сказал ни «ОСТАТОК», ни «ОСТАТКА НЕТ»\n",
                         r.num.c_str(), r.line);
        }
        if (!r.token) continue;
        ++tokens;

        // ПЛЕЧО 2: у токена обязан быть дом.
        if (r.homes.empty()) {
            ++noHome;
            std::fprintf(stderr,
                         "  БЕЗ ДОМА %s (стр %d): токен остатка не называет "
                         "`→ **M-NNN**`\n", r.num.c_str(), r.line);
            continue;
        }
        for (const std::string& h : r.homes) {
            ++debts;
            const auto it = byNum.find(h);
            if (it == byNum.end()) {
                ++deadHome;
                std::fprintf(stderr, "  ДОМА НЕТ %s (стр %d): названный дом %s "
                                     "рядом не является\n",
                             r.num.c_str(), r.line, h.c_str());
                continue;
            }
            bool anyOpen = false, anyBack = false;
            for (const std::size_t idx : it->second) {
                if (!rows[idx].closed) anyOpen = true;
                if (rows[idx].backRef) anyBack = true;
            }
            if (!anyOpen) {
                ++closedHome;
                std::fprintf(stderr, "  ДОМ ЗАКРЫТ %s (стр %d) → %s: остаток "
                                     "похоронен заново\n",
                             r.num.c_str(), r.line, h.c_str());
            }
            if (!anyBack) {
                ++muteHome;
                std::fprintf(stderr, "  ДОМ МОЛЧИТ %s (стр %d) → %s: нет "
                                     "обратной ссылки, остаток виден только "
                                     "из закрытой строки\n",
                             r.num.c_str(), r.line, h.c_str());
            }
        }
    }

    CHECK(tokens >= kTokensFloor,
          "токенов остатка не стало МЕНЬШЕ, чем после разбора: остаток не "
          "исчезает сам, и снятый токен есть регресс, а не уборка");
    CHECK(silent == 0,
          "ни один закрытый ряд со словом остатка не молчит: он либо несёт "
          "токен, либо прямо говорит, что остатка нет");
    CHECK(noHome == 0,
          "у каждого токена остатка есть ДОМ — живой ряд, который его доделает");
    CHECK(deadHome == 0,
          "каждый названный дом существует рядом реестра");
    CHECK(closedHome == 0,
          "каждый названный дом ОТКРЫТ — закрытый дом хоронит остаток заново");
    CHECK(muteHome == 0,
          "каждый названный дом несёт ОБРАТНУЮ ссылку — иначе остаток виден "
          "только из закрытой строки");

    std::printf("registry_debt: рядов %zu · токенов %d · остатков с домом %d\n",
                rows.size(), tokens, debts);

    char scope[512];
    std::snprintf(scope, sizeof(scope),
                  "рядов %zu · токенов остатка %d · домов названо %d · "
                  "молчащих %d · без дома %d · дом не найден %d · дом закрыт %d · "
                  "дом без обратной ссылки %d — прибор судит СВЯЗНОСТЬ ведомости "
                  "долгов, не годность остатка",
                  rows.size(), tokens, debts, silent, noHome, deadHome,
                  closedHome, muteHome);
    return sm::test::report("registry_debt_test", scope);
}
