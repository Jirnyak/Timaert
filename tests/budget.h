// ПОЧЕМУ ЭТО ЗАВЕДЕНО, ЧИСЛОМ. AGENTS DOD п.10 требует картину памяти ДО кода и
// «итог в мегабайтах, оба: по капам и по реальному миру». Картина РИСУЕТСЯ —
// `stack_census_test` печатает её каждым прогоном, — но до этого файла ни один
// свидетель в дереве не утверждал НИ ОДНОГО БАЙТА: сто с лишним тестов судили
// ПОВЕДЕНИЕ и ни один не судил ЦЕНУ. Перепись, которую никто не гейтит, есть
// бумага: она сообщает число тому, кто и так пришёл его прочесть, и молчит
// ровно в том случае, ради которого заводилась — когда число выросло, а никто
// не смотрел.
//
// ДВА ЗАКОНА ФОРМЫ, И ОБА КУПЛЕНЫ ЧУЖИМИ ШРАМАМИ.
//
//  1. ЧИСЛО ПЕЧАТАЕТСЯ ВСЕГДА — зелёным и красным. Молча зелёный бюджет
//     отнимает у следующей сессии ТРЕНД: она видит «ok» и не видит, что запас
//     съеден с двукратного до пяти процентов. Печать и есть главный продукт
//     прибора; гейт — его страховка.
//
//  2. ПРЕДЕЛ — ПОТОЛОК С ЗАПАСОМ, НИКОГДА СЕГОДНЯШНИЙ ЗАМЕР. Предел, прибитый
//     к текущему числу, краснеет на КАЖДОМ улучшении и воспитывает ровно один
//     рефлекс — перенабрать литерал до зелени, то есть подгонку, запрещённую
//     §8 ЗАКОНОМ НУЛЕВЫМ п.4. Потолок обязан пережить и рост по делу, и
//     падение по делу.
//
// И ТРЕТИЙ ЗАКОН — НАШ, ИЗ ЗАКОНА КОНСТАНТ: У ПОТОЛКА ЕСТЬ ВЫВОД ИЗ ИНВАРИАНТА
// ИГРЫ, и он написан В ТОЧКЕ ВЫЗОВА. «Текущее плюс половина» выводом не
// является — это то же число с потолка, размазанное в запас. Потолок без
// вывода запрещён здесь так же, как константа без вывода в коде мира: потолок
// и есть константа, просто живущая в свидетеле.
//
// ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ. Он не меряет — меряет вызывающий. Прибор берёт
// готовое число и судит его потолком, поэтому он агностичен к тому, что
// считают: байты, строки, штуки, доли. Единица приходит строкой и печатается,
// чтобы «482» нельзя было прочесть как мегабайты.
#pragma once
#include "check.h"

namespace sm::test {

// Одна дверь бюджета. `file`/`line` приходят от компилятора в точке ВЫЗОВА:
// провал обязан указывать на потолок, который не держится, а не на эту строку.
inline void check_budget(const char* name, double measured, double limit,
                         const char* unit, const char* file, int line) {
    const bool ok = measured <= limit;
    std::printf("  [бюджет] %-34s %10.1f %-12s потолок %10.1f  %s\n",
                name, measured, unit, limit, ok ? "ok" : "ВЫШЕ ПОТОЛКА");
    check(ok, name, file, line);
}

} // namespace sm::test

// Бюджет как проверка. Сообщение провала — ИМЯ бюджета: оно и есть нарушенное
// обещание, а числа уже напечатаны строкой выше.
#define CHECK_BUDGET(name, measured, limit, unit)                              \
    ::sm::test::check_budget((name), double(measured), double(limit), (unit),   \
                             __FILE__, __LINE__)
