// ЗАКОН СЦЕНИЧЕСКОЙ ВРАЖДЫ — СВИДЕТЕЛЬ НОСИТЕЛЯ (M-422, 2026-11-09).
//
// ЗАЧЕМ ЗАВЁЛСЯ: у вопроса «кто мне враг В ЭТОЙ СЦЕНЕ» в `tests/` не было
// свидетеля НИ ОДНОГО — перепись по всем именам прежней формы
// (`kObjTempHostile`, `maybe_flip_temp_hostile`, `playerExtraMask`,
// `player_stance`, `hostile_to_player_slot`) дала в `tests/` РОВНО НОЛЬ, и
// снос трёх несогласованных путей прошёл бы под зелёной сюитой целиком. Это
// была дыра, а не удобство (§8 п.6), и закрывается она здесь.
//
// ЧТО СУДИТСЯ: ЗАКОН, а не сегодняшнее поведение. Сценическая вражда есть
// отношение ДВУХ ФРАКЦИЙ, живущее ровно одну сцену; отсюда пять утверждений,
// и каждое — про закон, названный вслух в AGENTS/CANON:
//  1) СИММЕТРИЯ (ФРЕЙМ, род 6: «у фракций все равны и чистая симметрия» —
//     одна дверь пишет обе стороны, невзаимной вражды народов не бывает);
//  2) ДИАГОНАЛЬ НЕВЫРАЗИМА (своей фракции не враг никогда — тот же закон, что
//     держит `relation_of`/`set_relation@src/macro/factions.h`);
//  3) ОРДИНАЛ ВНЕ РЕЕСТРА НЕЙТРАЛЕН (fail-closed обеих дверей);
//  4) КОНЕЦ СЦЕНЫ ЗАБЫВАЕТ (вердикт владельца: «если ты ушол … это
//     забывается просто по построению … существует как и сцена в 3х3 только
//     локально»);
//  5) СМЕРТЬ ТЕЛА НЕ ПРОЩАЕТ — и это ровно та разница, которой новый закон
//     отличается от мёртвого бита `kObjTempHostile`: тот гас вместе со слотом,
//     то есть «прощение» покупалось смертью обиженного.
//
// ТАБЛИЦА МУТАЦИЙ (обе полярности) — в теле коммита M-422.
#include "check.h"

#include "sub/objects.h"
#include "scene_objects_fixture.h"   // арена сцены фикстурам (§8 п.11)

namespace {

using sm::FactionSlot;
using sm::kMaxFactions;
using sm::kNoFactionSlot;

// ФОРМА — ПОД КОМПИЛЯТОРОМ (§8 п.6: лучший свидетель есть несобираемое
// нарушение). Строк столько же, сколько народов, а ШИРИНА строки есть ширина
// маски враждебности — не совпадение, а один и тот же вывод
// (`kMaxFactions@src/tables/faction.h` под своим ассертом). Разъехаться молча
// они не могут: мир шире маски потерял бы последние народа БЕЗ диагностики.
using FeudCol = decltype(sm::sub::SubObjects::feud);
static_assert(std::tuple_size_v<FeudCol> == std::size_t(kMaxFactions),
              "строк вражды столько же, сколько народов в мире");
static_assert(sizeof(FeudCol::value_type) * 8 == std::size_t(kMaxFactions),
              "строка вражды — ровно маска фракций: 64 бита на 64 народа");

// Две произвольные РАЗНЫЕ фракции и третья, ни при чём: номера здесь — адреса
// строк реестра, а не баланс, поэтому берутся краями и серединой оси.
constexpr FactionSlot kA = 0;
constexpr FactionSlot kB = 3;
constexpr FactionSlot kC = 7;
constexpr FactionSlot kLast = kMaxFactions - 1;

} // namespace

int main() {
    using namespace sm;
    auto arena = sm::test::make_scene_arena();
    sub::SubObjects& scene = *arena;

    // ── 1. РОЖДЁННАЯ СЦЕНА НЕ ВОЮЕТ НИ С КЕМ ────────────────────────────
    // Счёт обязателен: пустой цикл иначе отчитался бы успехом (§8 п.3).
    {
        int samples = 0;
        int warring = 0;
        for (FactionSlot a = 0; a < kMaxFactions; ++a) {
            for (FactionSlot b = 0; b < kMaxFactions; ++b) {
                ++samples;
                if (scene.at_feud(a, b)) ++warring;
            }
        }
        CHECK(samples == kMaxFactions * kMaxFactions, "перебор пар состоялся целиком");
        CHECK(warring == 0, "рождённая сцена не несёт ни одной вражды");
    }

    // ── 2. ОДНА ДВЕРЬ ПИШЕТ ОБЕ СТОРОНЫ ─────────────────────────────────
    // «Обидчик втягивается ОТВЕТКОЙ, а не второй записью» (вердикт): зов РОВНО
    // один, и спрошенная с другого конца пара обязана ответить то же.
    scene.declare_feud(kA, kB);
    CHECK(scene.at_feud(kA, kB), "жертва не терпит обидчика");
    CHECK(scene.at_feud(kB, kA), "и обидчик втянут — вражда народов взаимна по закону");
    // Та же симметрия В КОЛОНКЕ, а не только в ответе двери: страж против
    // «читатель чинит то, чего писатель не написал» (шрам «свидетель над
    // стражем» — утверждать надо сам носитель).
    CHECK(
        ((scene.feud[std::size_t(kA)] >> kB) & 1ull) != 0ull
            && ((scene.feud[std::size_t(kB)] >> kA) & 1ull) != 0ull, "обе строки колонки несут бит — симметрия в ХРАНЕНИИ");

    // Третья фракция войной не задета: вражда адресуется ПАРОЙ, а не сценой.
    CHECK(!scene.at_feud(kA, kC) && !scene.at_feud(kB, kC), "посторонний народ в чужую войну не втянут");

    // ── 3. ДИАГОНАЛЬ НЕВЫРАЗИМА ─────────────────────────────────────────
    // Своей фракции не враг никогда, и держит это МАТРИЦА, а не гейт
    // поступка: иначе один дружественный огонь поднял бы весь народ сам на
    // себя — сцена целиком в гражданской войне с одного промаха.
    const std::uint64_t beforeDiag = scene.feud[std::size_t(kC)];
    scene.declare_feud(kC, kC);
    CHECK(!scene.at_feud(kC, kC), "сам себе враг — невыразимо");
    CHECK(scene.feud[std::size_t(kC)] == beforeDiag, "диагональный зов не написал в колонку ничего");

    // ── 4. ОРДИНАЛ ВНЕ РЕЕСТРА НЕЙТРАЛЕН (обе двери fail-closed) ────────
    scene.declare_feud(kNoFactionSlot, kA);
    scene.declare_feud(kA, kMaxFactions);
    scene.declare_feud(kMaxFactions + 9, kB);
    CHECK(!scene.at_feud(kNoFactionSlot, kA)
                        && !scene.at_feud(kA, kMaxFactions)
                        && !scene.at_feud(kMaxFactions + 9, kB), "безымянный ординал нейтрален, а не враждебен");
    CHECK(scene.at_feud(kA, kB), "и отвергнутые зовы не затёрли объявленную войну");

    // Край оси выразим: 64-я строка — такой же народ, как первая (иначе маска
    // молча теряла бы последнюю фракцию мира).
    scene.declare_feud(kLast, kA);
    CHECK(scene.at_feud(kA, kLast) && scene.at_feud(kLast, kA), "последняя фракция оси воюет наравне с первой");

    // ── 5. СМЕРТЬ ТЕЛА НЕ ПРОЩАЕТ ───────────────────────────────────────
    // НЕГАТИВНЫЙ КОНТРОЛЬ НА РАЗНИЦУ ДВУХ ЗАКОНОВ: прежний носитель был битом
    // СЛОТА и умирал вместе с ним, поэтому убитый обиженный «прощал». Теперь
    // вражда — отношение народов, и тела ей не ровня: свидетель сам рожает
    // своё предусловие (§8 п.11) и сам его убивает.
    const int body = sm::test::give_body(scene);
    CHECK(body >= 0, "тело фикстуры родилось — предусловие своё");
    CHECK(scene.at_feud(kA, kB), "рождение тела войны не меняет");
    scene.free(body);
    CHECK(scene.at_feud(kA, kB), "смерть тела войну НЕ прощает — обида не свойство тела");
    CHECK(scene.count == 0, "тел в сцене не осталось ни одного");
    CHECK(scene.at_feud(kA, kB), "и опустевшая сцена всё ещё воюет: война у народов");

    // ── 6. КОНЕЦ СЦЕНЫ ЗАБЫВАЕТ — И ЭТО ОДНА ДВЕРЬ ──────────────────────
    // `clear()` есть документированная смерть записи сцены, и все концы сцены
    // (подъём наверх, смена этажа данжа, выход из данжа, смерть мира) приходят
    // к ней. Поэтому забвение проверяется ЗДЕСЬ, у носителя, а не у каждого из
    // четырёх путей порознь.
    scene.clear();
    {
        int samples = 0;
        int warring = 0;
        for (FactionSlot a = 0; a < kMaxFactions; ++a) {
            for (FactionSlot b = 0; b < kMaxFactions; ++b) {
                ++samples;
                if (scene.at_feud(a, b)) ++warring;
            }
        }
        CHECK(samples == kMaxFactions * kMaxFactions, "перебор пар после смерти сцены состоялся целиком");
        CHECK(warring == 0, "конец сцены забыл вражду ЦЕЛИКОМ, не выборочно");
    }

    // И новая сцена начинается с чистого листа — объявленная заново война
    // ложится, то есть забвение не сломало сам носитель.
    scene.declare_feud(kA, kB);
    CHECK(scene.at_feud(kA, kB), "сцена после забвения снова умеет объявлять вражду");

    return sm::test::report("scene_feud_law_test");
}
