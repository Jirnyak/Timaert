// СВИДЕТЕЛЬ ТРЁХ ДВЕРЕЙ ВЫЧИТАНИЯ (`core/subtract.h`, M-243 п.2).
//
// Что охраняется: контракт каждой двери — насыщение (sub_sat), всё-или-
// ничего с нетронутым балансом при нехватке (try_spend), факт взятого
// (drain) — на границах диапазона и на узких типах, где integer promotion
// охотнее всего врёт. Опасность, которую двери убивают, показана живьём:
// голый `-=` на uint16 ДЕЙСТВИТЕЛЬНО кладёт 65 531 дерева из воздуха.
//
// Чего здесь НЕТ и почему: стена «знаковый тип не собирается» — это
// static_assert в самой двери, его нельзя показать зелёному бинарнику;
// её полярности прогоняются МУТАЦИЕЙ (таблица в теле коммита: инстанс
// sub_sat<int> обязан не собраться).
#include "check.h"

#include "core/subtract.h"

#include <cstdint>
#include <limits>

int main() {
    using sm::drain;
    using sm::sub_sat;
    using sm::try_spend;

    // ── sub_sat: насыщение в ноль, и ни байтом ниже ──────────────────────
    static_assert(sub_sat<std::uint16_t>(5u, 10u) == 0u,
                  "недостача насыщается в ноль, не заворачивается");
    static_assert(sub_sat<std::uint16_t>(10u, 3u) == 7u, "обычная убыль");
    CHECK(sub_sat<std::uint8_t>(200u, 100u) == 100u,
          "узкий тип: промоушен в int не меняет ответа");
    CHECK(sub_sat<std::uint8_t>(0u, 255u) == 0u, "ноль минус всё — ноль");
    CHECK(sub_sat<std::uint32_t>(std::numeric_limits<std::uint32_t>::max(),
                                 std::numeric_limits<std::uint32_t>::max())
              == 0u,
          "максимум минус максимум — ноль, без заворота");

    // ── try_spend: всё или ничего ────────────────────────────────────────
    {
        std::uint16_t gold = 30u;
        CHECK(!try_spend<std::uint16_t>(gold, 31u) && gold == 30u,
              "нехватка: отказ, баланс НЕ тронут — полуплатёж есть ложь");
        CHECK(try_spend<std::uint16_t>(gold, 30u) && gold == 0u,
              "точный платёж проходит в ноль");
        CHECK(try_spend<std::uint16_t>(gold, 0u) && gold == 0u,
              "нулевая цена — значение, а не отсутствие (ЗАКОН СПОСОБНОСТИ)");
    }

    // ── drain: взять сколько есть и вернуть ФАКТ ─────────────────────────
    {
        std::uint16_t trees = 4u;
        CHECK(drain<std::uint16_t>(trees, 3u) == 3u && trees == 1u,
              "хватает — взято сколько просили");
        CHECK(drain<std::uint16_t>(trees, 3u) == 1u && trees == 0u,
              "срубили 3, осталось 1 — взято 1, и это ФАКТ, а не просьба");
        CHECK(drain<std::uint16_t>(trees, 3u) == 0u && trees == 0u,
              "пустой склад отдаёт ноль и остаётся пустым");
    }

    // ── Опасность, которую двери убивают, — живьём ───────────────────────
    // Негативный контроль закона, а не двери: ГОЛОЕ вычитание на том же
    // типе и тех же числах заворачивает — дюп из воздуха существует,
    // детектору R7 (arch_guard) есть что ловить.
    {
        std::uint16_t wood = 5u;
        wood = std::uint16_t(wood - 10u);
        CHECK(wood == 65531u,
              "голый минус на uint16: 5 − 10 = 65 531 дерева из воздуха — "
              "ровно шрам, купивший закон");
        std::uint16_t wood2 = 5u;
        CHECK(drain<std::uint16_t>(wood2, 10u) == 5u && wood2 == 0u,
              "та же недостача дверью: взято 5, склад честно пуст");
    }

    return sm::test::report("subtract_doors_test");
}
