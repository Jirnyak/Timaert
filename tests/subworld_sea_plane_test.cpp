// subworld_sea_plane_test — МИКРОМИР НАСЛЕДУЕТ ПЛОСКОСТЬ МОРЯ (M-109, П-6).
//
// Вердикт владельца (2026-09-27, дословно): «у нас фиксированная плоскость
// УРОВЕНЬ моря на весь макромир и микромир её наследует».
//
// Макро-половина закона уже под свидетелем (`tests/water_answer_test.cpp`: одно
// число мира определяет, какая клетка вода, и определяет одинаково для всех).
// Здесь охраняется ВТОРАЯ половина — что субмир этой плоскости СЛЕДУЕТ, а не
// помнит свою:
//   1. дефолты двух миров не могут разъехаться — это проверяется КОМПИЛЯТОРОМ;
//   2. словарь слова (`field_word_of`/`field01_of`) переживает круг
//      «float → слово → float» ровно на дефолтной плоскости, поэтому картинка
//      дефолтного мира обязана быть побитово той же после этой правки;
//   3. ремап высоты, мокрая кромка и датум метров — функции ПЕРЕДАННОЙ
//      плоскости, а не константы;
//   4. у биома нет колонки воды: одиннадцать копий одного числа колонкой не
//      являются (DOD п.9), и её отсутствие прибито `sizeof`;
//   5. данж — третий род: его плоскость 0 и от мира не зависит.
//
// НЕГАТИВНЫЕ КОНТРОЛИ (AGENTS §8 п.6) — каждый обязан ПАДАТЬ, если закон
// нарушен, и каждый утверждается как контроль, а не подразумевается:
//   · та же фикстура, отремапленная про ЗАХАРДКОЖЕННУЮ 0.40 вместо своей 0.60,
//     ОБЯЗАНА положить дно водной клетки ВЫШЕ рисуемой плоскости — это
//     арифметика доклада владельца со стенда «воды вообще не видно», и она
//     здесь воспроизводится числом. Пропадёт — значит мера неверна;
//   · плоскость обязана ДВИГАТЬ землю: два разных уровня моря на одной фикстуре
//     не смеют дать один и тот же рельеф, иначе наследование ничего не несёт.
//
// МУТАЦИЯ → ИСХОД для свипа по шкале плоскости (обе его петли были
// ТАВТОЛОГИЯМИ до 2026-11-08: ни одна не звала `generate_heightmap` ни разу,
// а «встречный контроль против тавтологии» был ВТОРОЙ тавтологией той же
// формы со сменённым знаком — его собственный комментарий это и признавал):
//   Q1  `remapped[i] = mh * 0.5f` в base_generator.cpp    → КРАСНЫЙ 2 из 13.
//       (генератор топит всё подряд — ровно тот класс       СТАРАЯ редакция
//        дефекта, ради которого контроль и существует)      под ТОЙ ЖЕ
//                                                           мутацией: 1 из 12,
//                                                           и падал НЕ
//                                                           контроль, а
//                                                           детектор — то есть
//                                                           контроль был слеп
//   Q2  сдвинуть `kWetH`/`kDryH` фикстуры на 0.01          → ЗЕЛЁНЫЙ 13/13:
//                                                           свип от них не
//                                                           зависит, ложной
//                                                           тревоги нет
#include <cmath>
#include <cstdio>
#include <vector>

#include "check.h"
#include "macro/map_generator.h"
#include "sub/base_generator.h"
#include "sub/height.h"
#include "sub/map_data.h"

using namespace sm;
using namespace sm::sub;

namespace {

// ── 1. ДВА МИРА, ОДИН ДЕФОЛТ — ПОД КОМПИЛЯТОРОМ ───────────────────────────
// Лучшая форма свидетеля есть нарушение, которое невозможно собрать (ЗАКОН
// НУЛЕВОЙ п.6). Субмировой `WATER_LEVEL` остался ровно одним: дефолтом для
// харнессов без макромира — и если чей-то дефолт сдвинут, красным становится
// СБОРКА, а не прогон.
static_assert(WATER_LEVEL == kDefaultSeaLevel,
              "дефолтная плоскость субмира и дефолт редактора макромира — одно "
              "число; разъехаться им нельзя даже на бит");

// Порог живёт в СЛОВАРЕ СЛОВА высоты (`field_word_of`/`field01_of`, наряд B3),
// потому что мир судит воду словом канала. Круг «float → слово → float» на
// ДЕФОЛТНОЙ плоскости точен (26214/65535 = 0.4 ровно, ровно как до B3 было
// 102/255), и именно это делает обещание «при дефолте картинка не меняется»
// доказуемым, а не вежливым.
static_assert(field01_of(field_word_of(kDefaultSeaLevel)) == WATER_LEVEL,
              "круг дефолтной плоскости через словарь карты обязан быть точным "
              "— иначе «при дефолте всё то же» есть мнение, а не факт");

// ── 4. У БИОМА НЕТ НИ КОЛОНКИ ВОДЫ, НИ ФЛАГОВ СВОЕЙ ФАКТУРЫ ───────────────
// Одиннадцать строк `kConfigs` держали колонку воды с одним и тем же
// `WATER_LEVEL` и НУЛЁМ читателей. Размер строки — то, что ловит её возврат
// молча: плотность, шаг, две границы высоты кроны, масштаб высоты.
//
// ЧИСЛО УПАЛО 24 → 20 ВМЕСТЕ С ДВУМЯ ФЛАГАМИ (`swampPools`, `duneNoise`), и
// это не послабление пина, а его расширение: флаги существовали затем, чтобы
// БАЗА знала, какую чужую фактуру ей подмешать: мочажины болота и барханы
// пустыни стояли внутри `generate_heightmap`. Фактура уехала в собственные
// модули биомов (`gens/swamp.cpp`, `gens/open.cpp`), а модулю флаг не нужен —
// ему хватает `nbBiome[i] == Biome::Swamp`. Колонка без читателя не живёт
// (DOD п.9), и теперь строка биома не умеет говорить про рельеф вовсе.
static_assert(sizeof(BiomeConfig) == 20,
              "в строке биома нет ни колонки воды, ни флагов чужой фактуры: "
              "где стоит сея и какой рельеф у биома, решают мир и модуль "
              "биома, а не эта строка (DOD п.9)");

// Фикстура — СОГЛАСОВАННЫЙ мир: при плоскости 0.60 центр (0.45) ниже порога,
// значит он законно вода; кольцо (0.75) выше, значит законно суша. Проверено
// тем же СЛОВОМ, которым судит макромир, чтобы фикстура не описывала мир,
// которого не бывает.
constexpr float kPlane   = 0.60f;
constexpr float kWetH    = 0.45f;
constexpr float kDryH    = 0.75f;
constexpr int   kCS      = 64;

bool macro_calls_water(float h01, float plane) {
    // Ровно то сравнение, которым судит `TerrainData::is_water`: слово канала
    // против слова плоскости, и оба — через единственную дверь записи.
    return field_word_of(h01) < field_word_of(plane);
}

// Один прогон настоящего генератора — БЕЗ GameState, без макро-слоёв, без
// рендерера: плоскость входит аргументом, и это и есть проверяемая узость
// канала.
// Высоты — ПАРАМЕТРЫ, а не константы файла, и это не удобство: свидетель
// внизу обязан гонять генератор по ВСЕЙ законной шкале плоскости, а
// фиксированная пара (0.45 / 0.75) при плоскости 0.40 описывает мир, которого
// не бывает — там 0.45 уже не вода. Законность каждой пробы судится тем же
// словом, что у макромира (`macro_calls_water`).
std::vector<float> build_cell(float plane, float wetH, float dryH) {
    float nbH[9];
    Biome nbB[9];
    for (int i = 0; i < 9; ++i) { nbH[i] = dryH; nbB[i] = Biome::Meadow; }
    nbH[4] = wetH;
    nbB[4] = Biome::Water;
    std::vector<float> out;
    generate_heightmap(out, kCS, nbH, nbB, /*nbBiome5*/nullptr, Biome::Water,
                       /*globalOffsetX*/0, /*globalOffsetY*/0,
                       plane);
    return out;
}

std::vector<float> build_cell(float plane) {
    return build_cell(plane, kWetH, kDryH);
}

// ЗЕРКАЛЬНАЯ ПРОБА: клетка СУШИ на той же плоскости — центр над порогом, биом
// не водный. Нужна встречному контролю: он обязан показать, что мера умеет
// вернуть «над плоскостью», иначе «дно всегда под ней» нечем отличить от
// генератора, который топит всё подряд.
std::vector<float> build_dry_cell(float plane, float dryH) {
    float nbH[9];
    Biome nbB[9];
    for (int i = 0; i < 9; ++i) { nbH[i] = dryH; nbB[i] = Biome::Meadow; }
    std::vector<float> out;
    generate_heightmap(out, kCS, nbH, nbB, /*nbBiome5*/nullptr, Biome::Meadow,
                       /*globalOffsetX*/0, /*globalOffsetY*/0,
                       plane);
    return out;
}

float centre_h(const std::vector<float>& hm) {
    return hm[std::size_t(kCS / 2) * kCS + kCS / 2];
}

} // namespace

int main() {
    // Фикстура обязана быть ЗАКОННЫМ миром, иначе всё ниже меряет фантазию.
    CHECK(macro_calls_water(kWetH, kPlane),
          "фикстура согласована: центр при плоскости 0.60 есть вода для "
          "макромира");
    CHECK(!macro_calls_water(kDryH, kPlane),
          "фикстура согласована: кольцо при плоскости 0.60 есть суша для "
          "макромира");

    // ── 3. РЕМАП ЕСТЬ ФУНКЦИЯ ПЕРЕДАННОЙ ПЛОСКОСТИ ────────────────────────
    const std::vector<float> inherited = build_cell(kPlane);
    const float wetGround = centre_h(inherited);
    CHECK(wetGround < kPlane,
          "дно водной клетки лежит ПОД своей плоскостью — вода видна");

    int dryTiles = 0, drowned = 0;
    for (int y = 0; y < kCS; ++y) {
        for (int x = 0; x < kCS; ++x) {
            // Угол клетки — там бы билинейка ни разу не тянула центральную
            // водную колонку: это чистая суша кольца.
            if (x > 2 || y > 2) continue;
            ++dryTiles;
            if (inherited[std::size_t(y) * kCS + x] < kPlane) ++drowned;
        }
    }
    CHECK(dryTiles > 0 && drowned == 0,
          "суша при плоскости 0.60 стоит НАД водой, а не утоплена");

    // Мокрая кромка и датум метров — тоже функции плоскости, не константы.
    // Разность берётся с допуском, потому что `plane + width − plane` во float
    // не обязано вернуть ровно `width` — утверждается ОТНОШЕНИЕ (кромка выше
    // своей плоскости ровно на ширину), а не битовое равенство суммы.
    CHECK(wet_edge_top(kPlane) > kPlane
              && std::fabs((wet_edge_top(kPlane) - kPlane) - kWetEdgeWidth)
                     < 1e-6f
              && wet_edge_top(kPlane) > wet_edge_top(WATER_LEVEL),
          "мокрая кромка есть плоскость плюс ШИРИНА: ширина своя, основание "
          "наследуется");
    CHECK(sea_level_m(kPlane) == height_m(kPlane)
              && sea_level_m(kPlane) > default_sea_level_m(),
          "датум метров следует сцене (вердикт владельца 2026-09-27), иначе "
          "мост лёг бы на 300 м под своей рекой; и он идёт ОДНОЙ дверью "
          "height_m, а не вторым умножением");
    CHECK(!is_dry_footing(sea_level_m(kPlane) - 1.0f, sea_level_m(kPlane))
              && is_dry_footing(sea_level_m(kPlane) + 1.0f,
                                sea_level_m(kPlane)),
          "сухая опора судится плоскостью ЭТОЙ сцены");

    // ── ДНО ПОД ПЛОСКОСТЬЮ — ТЕПЕРЬ ПО ПОСТРОЕНИЮ, А НЕ ПО НАСТРОЙКЕ ──────
    // Два негативных контроля стояли здесь и оба спрашивали про РЕМАП: что
    // ремап про чужую 0.40 задирает дно, и что две разных плоскости дают
    // разный рельеф. Оба умерли вместе с ремапом (вердикт владельца
    // 2026-09-30: «уровень моря это буквально где будет вода начинаться в
    // макромире биом и где плоскость воды в микромире и всё»; «рельеф… он
    // агностичен»). Рельеф субмира есть поле макромира, и плоскость его не
    // гнёт — значит «две плоскости дают разный рельеф» стало утверждением,
    // ПРОТИВОПОЛОЖНЫМ закону, а свидетель, охраняющий снесённый механизм,
    // охраняет случай, а не закон (AGENTS §8 п.5).
    //
    // Болезнь, ради которой они писались, при этом не осталась без сторожа —
    // она стала НЕВЫРАЗИМОЙ, и вот утверждение об этом. Водная клетка есть
    // клетка, чья макро-высота ниже плоскости (macro/map_generator.h
    // is_water), а её высота в субмире И ЕСТЬ эта макро-высота; значит дно
    // под плоскостью при ЛЮБОМ её положении, а не при удачном. Проверено по
    // всей законной шкале ползунка (0.10..0.80), потому что доклад со стенда
    // пришёл именно со сдвинутой плоскости.
    //
    // И МЕРЯЕТСЯ ЭТО ГЕНЕРАТОРОМ, А НЕ АРИФМЕТИКОЙ НАД ЛИТЕРАЛАМИ. До
    // 2026-11-08 обе петли ниже сравнивали выражение с самим собой: «дно»
    // было `h = macroH; if (h > plane)` при `macroH = plane·q/8 ≤ plane`, а
    // «встречный контроль против тавтологии» — `macroH = plane + (1−plane)·q/8`
    // против `plane`, то есть ВТОРАЯ тавтология той же формы со сменённым
    // знаком (её собственный комментарий признавал: «тождество (дверь
    // снесена)»). Ни одна из них не звала `generate_heightmap` ни разу, так
    // что «сторож на возврат ремапа» сторожил ровно ничего: вернись кривая
    // между полем и землёй — обе петли остались бы зелёными, потому что
    // генератора в них не было.
    //
    // Теперь каждая проба — ПРОГОН НАСТОЯЩЕГО ГЕНЕРАТОРА на своём законном
    // мире: высоты воды и суши едут вместе с плоскостью (фиксированная пара
    // при плоскости 0.40 описывала бы мир, которого не бывает), законность
    // каждой судится словом макромира, и обе половины — дно и суша — читаются
    // из одного и того же выданного рельефа.
    {
        int planes = 0, cases = 0, breaches = 0, sunken = 0;
        float worst = 0.0f, worstPlane = 0.0f;
        for (int p = 1; p <= 8; ++p) {
            const float plane = 0.10f * float(p);
            ++planes;
            for (int q = 1; q <= 8; ++q) {
                // Законная вода — строго ПОД плоскостью; законная суша — над.
                const float wetH = plane * float(q) / 9.0f;
                const float dryH = plane + (1.0f - plane) * float(q) / 9.0f;
                // Фикстура обязана быть миром, который макромир и правда так
                // называет, иначе проба меряет фантазию.
                if (!macro_calls_water(wetH, plane)) continue;
                if (macro_calls_water(dryH, plane)) continue;
                ++cases;
                const std::vector<float> hm = build_cell(plane, wetH, dryH);
                const float floorH = centre_h(hm);
                if (floorH > plane) {
                    ++breaches;
                    if (floorH - plane > worst) {
                        worst = floorH - plane;
                        worstPlane = plane;
                    }
                }
                // ВСТРЕЧНЫЙ КОНТРОЛЬ — ТОТ ЖЕ ГЕНЕРАТОР, ЗЕРКАЛЬНЫЙ ВХОД.
                // Клетка СУШИ на той же плоскости обязана дать дно НАД ней.
                // Без этого «дно всегда под плоскостью» неотличимо от
                // генератора, который топит всё подряд, — а это ровно тот
                // класс дефекта, который контроль обязан исключить.
                //
                // Мерить тут УГОЛ водной клетки (как стояло до 2026-11-08)
                // нельзя: угол есть БЛЕНД, и центральная водная колонка в него
                // входит — при суше, едва возвышающейся над плоскостью, он
                // честно уходит под неё (зонд: плоскость 0.40, суша 0.4667,
                // угол 0.3710). Прежний комментарий обещал «билинейка ни разу
                // не тянет туда водную колонку», и это неправда: старая проба
                // проходила ЗАПАСОМ фикстуры (0.75 против 0.60), а не по
                // построению.
                if (centre_h(build_dry_cell(plane, dryH)) < plane) ++sunken;
            }
        }
        if (breaches > 0) {
            std::fprintf(stderr,
                         "  дно вылезло над плоскостью %d раз, худший раз на "
                         "%.4f при плоскости %.2f\n",
                         breaches, double(worst), double(worstPlane));
        }
        CHECK(planes == 8,
              "проверена вся законная шкала плоскости, а не одно значение");
        CHECK(cases >= 56,
              "и каждая проба — ЗАКОННЫЙ мир, прогнанный через настоящий "
              "generate_heightmap, а не арифметика над литералами");
        CHECK(breaches == 0,
              "дно водной клетки под плоскостью при ЛЮБОМ её положении — "
              "доклад «воды вообще не видно» стал невыразим, а не починен");
        CHECK(sunken == 0,
              "и суша над плоскостью при любом её положении (встречный "
              "контроль: утверждение выше не тавтология)");
    }

    // ── 5. ДАНЖ — ТРЕТИЙ РОД, ЕГО ПЛОСКОСТЬ НЕ ОТ МИРА ───────────────────
    // Свидетель РОЖДАЕТ своё предусловие (AGENTS §8 п.11): сцена собирается
    // здесь, а не выпрашивается у сида.
    SubworldMapData interior{};
    interior.waterLevel = 0.0f;         // как это делает каждый dgn/*
    CHECK(interior.waterLevel == 0.0f && sea_level_m(interior.waterLevel) == 0.0f,
          "у интерьера моря нет, и ноль лежит ниже любого возможного пола — "
          "третий род не наследует плоскость мира (ЗАКОН ДВУХ МИРОВ п.4)");
    SubworldMapData bare{};
    CHECK(bare.waterLevel == WATER_LEVEL,
          "сцена без мира за спиной отвечает ДЕФОЛТНОЙ плоскостью, а не нулём: "
          "«моря нет» и «мира нет» — разные утверждения");

    std::printf("  плоскость %.2f: дно воды %.4f — под ней, и под любой "
                "другой: рельеф плоскости не читает\n",
                double(kPlane), double(wetGround));
    return sm::test::report("subworld_sea_plane_test");
}
