// ── ПРИБОР НА СКАЧОК ВРЕМЕНИ TU (наряд M-127) ─────────────────────────────
//
// ЧТО ЭТО. Ninja сама ведёт журнал стоимости сборки: `build/.ninja_log` хранит
// время КАЖДОГО выхода и читается БЕЗ сборки. Прибор сравнивает свежее время
// `.o` С ЕГО ЖЕ ПРОШЛЫМ и называет те, что подорожали в разы.
//
// ПОЧЕМУ ЭТО ЕСТЬ. 2026-09-25 одна строка в заголовке (`make_macro_store`,
// `src/macro/store.h`) сделала 161 TU дороже медианой в 248 раз, и сборка при
// этом осталась ЗЕЛЁНОЙ: ни ошибки, ни предупреждения, `.o` байт в байт того
// же размера (1344 Б). Диагноз занял 18 часов и семь смертей машины. Пара
// 8.1 → 124.5 с лежала в `.ninja_log` через 14 минут после коммита-виновника.
// Прибор ловит НЕ ЭТОТ механизм, а ЛЮБОЕ подорожание TU против себя же —
// следующий механизм мы не знаем и знать не обязаны (AGENTS §5 п.13).
//
// ПОЧЕМУ У ПРИБОРА СВОЯ БАЗА, А НЕ ОДИН ЖУРНАЛ. Ninja СЖИМАЕТ `.ninja_log`:
// когда записей втрое больше, чем выходов, она схлопывает историю до последней
// строки на выход. Замерено 2026-09-26 на этом же дереве: 1291 TU в журнале и
// история — У НУЛЯ. Прибор на одном журнале в такой момент печатает «скачков
// нет», а значит это не «чисто», а «сравнивать не с чем» — ровно тот род
// зелёного, ради которого проект держит §8 п.2. Поэтому лучшее время каждого
// TU прибор записывает СВОЕЙ ведомостью (`tu_time_baseline.tsv`) и берёт базой
// МИНИМУМ из своей ведомости и уцелевшей истории журнала. Минимум, а не
// последнее: регресс, попавший в базу, иначе объявил бы себя нормой.
//
// ГРАНИЦА: прибор судит ВРЕМЯ, а не память. Память заголовка судит стена
// `header_cost_test` — замером, не логом. Два прибора, каждый по своей оси.
//
// Строки здесь законны: журнал сборки — ГРАНИЦА МИРА, не тик (ЗАКОН СЛОВАРЯ
// п.1). Тела — в `.cpp`: заголовок платит каждый включивший (AGENTS §5 п.13).
#pragma once

#include <string>
#include <vector>

namespace sm::build {

// Один скачок: TU стал дороже САМОГО СЕБЯ.
struct TuJump {
    std::string output;        // путь выхода, как его пишет ninja
    double baselineSec = 0.0;  // лучшее известное прошлое этого TU
    double latestSec = 0.0;    // свежая запись
    double ratio = 0.0;        // latestSec / baselineSec
};

// Строка ведомости прибора: лучшее время, какое этот TU когда-либо показывал.
struct TuBest {
    std::string output;
    double bestSec = 0.0;
};

struct TuTimeReport {
    int tuCount = 0;          // сколько `.o` встретилось в журнале
    int comparable = 0;       // у скольких есть прошлое — есть с чем сравнивать
    int fresh = 0;            // сколько видим впервые (их судить нечем, и это
                              // говорится вслух, а не проглатывается)
    double medianSec = 0.0;   // медиана СВЕЖИХ времён — пол шума, см. ниже
    double slowestSec = 0.0;  // самый дорогой TU свежей записи
    std::string slowest;      // и кто он
    std::vector<TuJump> jumps;  // виновные, от худшего к меньшему
    std::vector<TuBest> best;   // ведомость после прогона, готовая к записи
};

// ПОРОГ — ОТНОСИТЕЛЬНЫЙ, И ОН ВЫВЕДЕН ИЗ ДВУХ ЗАМЕРЕННЫХ НАСЕЛЕНИЙ, а не
// выбран (ЗАКОН КОНСТАНТ). Считано по журналам этой машины 2026-09-26:
//   · ШУМ (та же сборка, разная загрузка машины и -j): худшее подорожание TU
//     против себя же — 3.26× (`journal_test.cpp.o`, 1.31 → 4.26 с,
//     `build-reldeb/.ninja_log`); основная масса пар ≤ 2.5×;
//   · ДЕФЕКТ: 8.1 → 124.5 с = 15.4× (пара, которую прибор ОБЯЗАН поймать).
// Порог — геометрическая середина между ними: √(3.26 × 15.4) = 7.09 → 7.
// Запас в обе стороны примерно двукратный и симметричен по построению:
// сдвинешь порог к шуму — начнёшь глушить прибор, сдвинешь к дефекту —
// пропустишь половину силы регресса.
constexpr double kJumpRatio = 7.0;

// Ninja пишет миллисекундами, поэтому 0 мс значит «дешевле разрешения
// журнала», а не «бесплатно»: базой в этом случае служит само разрешение,
// иначе 0 → 200 с не имело бы отношения и молчало бы.
constexpr double kLogResolutionSec = 0.001;

// Разбор журнала — чистая функция над текстом и ведомостью: прибор проверяется
// ФИКСТУРОЙ, а не тем, что лежит в build/ у запустившего.
TuTimeReport scan_ninja_log(const std::string& logText,
                            const std::vector<TuBest>& baseline);

bool read_text_file(const char* path, std::string& out);

// Ведомость: `<выход>\t<лучшее время, с>` построчно. Нет файла — пустая
// ведомость, это законное состояние первого прогона.
std::vector<TuBest> load_baseline(const char* path);
bool save_baseline(const char* path, const std::vector<TuBest>& best);

} // namespace sm::build
